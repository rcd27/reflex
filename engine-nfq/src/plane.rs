/// КЛЮЧ ЦЕЛИ ТАК, КАК ЕГО ВИДИТ ПЛОСКОСТЬ: имя — сужённое `narrow`, безымянная ветвь — ТОЧНЫЙ
/// адрес (`host_of`), а не сеть. Ширина здесь у ДЕЙСТВИЯ: лечить /24 значило бы применить знание к
/// 256 хозяевам — та же беда, что именное знание по общему адресу, уровнем выше. Запись строки
/// человеку берёт ту же алгебру с другой шириной (`net_of`), и расхождение ловит компилятор.
type Key = TargetKey<Box<str>>;

use crate::parse::{Datagram, Head, Wire};
use crate::talk::{Named, Talks};
use reflex_instrument::wire::Reading;

pub const CURSORS: usize = 8192;
pub const TARGETS: usize = 4096;
pub const SIGHTINGS: usize = 4096;
const SWEEP_EVERY: u64 = 4096;
/// СКОЛЬКО ЗАПИСЕЙ УБОРКА СМОТРИТ ЗА ОДИН РАЗ. Без потолка она обходила карту ЦЕЛИКОМ, то есть
/// делала работу, пропорциональную числу целей, — амортизированно на каждый пакет. Ровно та
/// болезнь, которой невод 1 сжигал ядро под нагрузкой, только спрятанная в редком шаге.
pub const SWEEP_BUDGET: usize = 256;
/// ЭПОХА ЦЕЛИ, О КОТОРОЙ ДВИЖОК ЕЩЁ НЕ УЧИЛ. Строго ниже всякой настоящей (`teach` начинает с
/// первой). Промах несёт её, а не живой счётчик: разговор, промахнувшийся в окне между сдвигом
/// эпохи и вписью плана, иначе унёс бы эпоху, которой метится и настоящий план, — и остался бы
/// «свежим» на мёртвом маршруте навсегда (шов `split`, инвариант `BorneIsEndorsed`).
const NO_KNOWLEDGE: Epoch = Epoch(0);

/// СКОЛЬКО ГОРИЗОНТОВ ПОМНИМ ЗАКРЫТЫЙ РАЗГОВОР.
///
/// Память о закрытом держится не ради него самого, а ради ХВОСТА: последний `ACK` и
/// ретрансмиссия приходят уже после прощания, и ответить им «не видели» значило бы соврать про
/// разговор, по которому мы выносили вердикт.
///
/// Величина названа здесь, а не выведена из числа проходов уборки: срок жизни хвоста есть
/// свойство транспорта, а частота уборки — наше удобство, и связывать их значило бы менять
/// первое, настраивая второе.
pub const RETENTION_HORIZONS: u64 = 2;

/// ЧТО ВЫШЛО ИЗ ОДНОГО ПАКЕТА. `opened` отделяет НОВЫЙ разговор от продолжения: они стоят разного
/// (тысячи наносекунд против сотен — две вставки в карты против поиска), и смешивать их значит
/// мерить состав трафика, а не плоскость.
/// `Copy` СНЯТ вместе с приходом наблюдения: `SeenTcp` его не имеет и не должен — у сброса есть
/// автор, у имени длина, и дешёвое побитовое копирование тут было бы обещанием, которого тип не
/// даёт. Потребителей это не задело: `Fed` берут по значению один раз, сразу после `feed`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Fed {
    pub act: Act,
    pub opened: bool,
    /// ЧТО ЭТОТ ПАКЕТ ПОКАЗАЛ — наблюдение в словаре приборов, из ТОГО ЖЕ разбора, которым выдан
    /// вердикт. Прежде разбор шёл трижды: здесь, в другом крейте и заново в каждом
    /// питателе; две независимые памяти о разговоре расходятся молча — оплачено 1136 флоу из
    /// 1136 мимо памяти.
    ///
    /// `None` значит «пакет наблюдения не дал» (чистый `ACK`), и это НЕ то же самое, что «ничего
    /// не случилось»: тишина видна тиком времени, а не выдуманным событием. Разница та же, что
    /// между `Naming::Silent` и `Naming::Awaited`.
    ///
    /// Показание с НАЗВАННЫМ протоколом: `Option<SeenTcp>` фиксировал бы TCP в подписи, и
    /// датаграмму в такую сигнатуру не положить.
    pub seen: Option<reflex_instrument::wire::Reading>,
    /// Выпускать ли разговор в ядро. Считает плоскость: только она знает все три величины
    /// (личность, вердикт, интерес), и оболочке нечего сводить.
    pub watch: Watch,
}

pub struct Plane {
    /// ЗНАНИЕ О ЦЕЛИ (#317) — ОДНА карта на обе ветви алгебры (#300). Прежде их было две, а между
    /// ними ветвился `Option<Box<str>>`, у которого `None` значил две разные вещи: «имени не
    /// будет» и «имени ещё нет». Одно понятие, записанное дважды, расходится молча.
    ///
    /// Именованная ветвь применяется в момент, когда цель назвалась, и потому не зависит от того,
    /// на какой из адресов цели лёг разговор. Безымянная законна ровно там, где имени не будет.
    plans: BTreeMap<Key, Plan>,
    /// ЧЕМ СУЖАЕТСЯ ИМЯ ДО КЛЮЧА. Приходит СНАРУЖИ и не имеет умолчания намеренно: ключ,
    /// добываемый на каждой стороне своим способом, расходится молча — оплачено 1136 флоу из 1136
    /// мимо памяти. Указатель на функцию, а не `dyn`: у знания о ширине ключа есть имя.
    narrow: fn(&str) -> &str,
    fallback: Programme,
    epoch: Epoch,
    cursors: HashMap<FlowKey, Cursor>,
    /// ПАМЯТЬ РАДИ НАБЛЮДЕНИЯ — граница клиента и выданные головы. Убирается той же уборкой, что
    /// и курсоры: иначе карта росла бы на каждый разговор, то есть работа стала бы
    /// пропорциональна числу целей — та болезнь, которой невод 1 сжигал ядро под нагрузкой.
    ///
    /// ТОТ ЖЕ ТИП, ЧТО У КРАЯ (#320, задача 6). Перевод пакета в показание жил здесь телом
    /// плоскости, и взять его мог только тот, кто берёт плоскость целиком, — то есть край не мог
    /// и написал свой. Теперь предмет один, и расходиться нечему.
    talks: Talks,
    seen_at: BTreeMap<FlowKey, Tick>,
    targets: BTreeMap<Addr, Target>,
    ring: Ring,
    tally: Tally,
    sightings: Vec<Noted>,
    dropped_sightings: u64,
    evicted_cursors: u64,
    evicted_targets: u64,
    unapplied: BTreeMap<&'static str, u64>,
    names: BTreeMap<String, u64>,
    /// ЧТО ИЗВЕСТНО О ЛИЧНОСТИ ЦЕЛИ В ЭТОМ РАЗГОВОРЕ. Ключ — ФЛОУ, а не адрес: имя, добытое из
    /// `ClientHello`, принадлежит соединению, и только соединению. Отсюда и точность: на общем
    /// адресе CDN каждый разговор носит СВОЁ имя, а не имя того, кто говорил последним.
    ///
    /// ТРЁХ СОСТОЯНИЙ, А НЕ ДВУХ (#300): «приветствие прошло, имени в нём не было» (`Silent`) и
    /// «приветствие ещё впереди» (`Awaited`) — разные факты, и первый есть ЗНАМЕНАТЕЛЬ СЛЕПОЙ
    /// ЗОНЫ именного ключа, который #317 требует печатать числом. Хранить его сводным счётчиком
    /// (`unnamed_hellos`) значило бы знать долю по коробке и не знать по разговору.
    flow_names: BTreeMap<FlowKey, Naming<Box<str>>>,
    /// КАК ЗОВУТ ЦЕЛЬ ПО ЭТОМУ АДРЕСУ (#302, срез 3). Отдельно от `names`, потому что там счётчик
    /// имён (сколько раз видели), а здесь — соответствие, без которого беда, наблюдённая по
    /// адресу, не ложится на знание, ключёванное именем.
    ///
    /// ЦЕНА НАЗВАНА: одна запись на цель сверх `targets`, тот же потолок и то же вытеснение —
    /// иначе карта росла бы вместе с числом виденных адресов, а не с числом наблюдаемых целей.
    named: BTreeMap<Addr, Box<str>>,
    /// СКОЛЬКО РАЗ ПО ОДНОМУ АДРЕСУ ГОВОРИЛО ДРУГОЕ ИМЯ. До этого счётчика перезапись молчала, а
    /// частота её была НЕИЗВЕСТНА — то есть подсказка врала, и мы не знали, как часто. Прибор
    /// заведён прежде, чем спорить о том, годна ли подсказка вообще.
    name_collisions: u64,
    /// СКОЛЬКО РАЗ ОДИН РАЗГОВОР НАЗВАЛСЯ ДВУМЯ РАЗНЫМИ ИМЕНАМИ (#300).
    ///
    /// В полной решётке это ⊤ — противоречие: у соединения одна цель, и два имени значат либо
    /// чужой split-hello, либо наш промах разбора. Типа под ⊤ здесь нет НАМЕРЕННО: частота явления
    /// не замерена, а тип, заведённый под неизмеренное, потом не снимается. Сперва число.
    ///
    /// Отличается от `name_collisions`: тот про АДРЕС (двое за одной подсказкой), этот про РАЗГОВОР
    /// (одно соединение, два имени) — разные беды с разным лечением.
    name_conflicts: u64,
    /// СКОЛЬКО РАЗГОВОРОВ ЧЕМ КОНЧИЛИСЬ ПО ЛИЧНОСТИ — знаменатель слепой зоны именного ключа,
    /// который #317 требует печатать числом с первого дня.
    ///
    /// Счётчики НАКОПИТЕЛЬНЫЕ, а не по живым флоу: разговор закрывается и уходит из карт, и доля,
    /// считанная по живым, мерила бы состав трафика В МОМЕНТ ОПРОСА. Доля безымянных — свойство
    /// потока, а не мгновения.
    ///
    /// Переход `Silent → Spoken` законен (знание растёт join'ом), и тогда разговор ПЕРЕЕЗЖАЕТ:
    /// иначе сумма превысила бы число разговоров, и «доля» перестала бы быть долей.
    flows_spoken: u64,
    flows_silent: u64,
    unnamed_hellos: u64,
    offered: u64,
    unparsed: u64,
    marked: BTreeSet<Addr>,
    /// СКОЛЬКО ПАКЕТОВ МЫ ПОМЕТИЛИ И КАКОЙ МЕТКОЙ. Множество целей отвечает «кого», счётчик —
    /// «сколько раз», и без второго «плоскость не пометила» неотличимо от «пометила, а ядро не
    /// увело»: две совершенно разные поломки с одним симптомом на счётчике ядра.
    ///
    /// ПО МЕТКАМ, А НЕ ОДНИМ ЧИСЛОМ: метки ведут в РАЗНЫЕ места (слот страты, общий контур), и
    /// сумма по ним не сверяется ни с одним счётчиком ядра — сверять её было бы сложением
    /// килограммов с метрами. Сверяется величина ПО СВОЕЙ метке.
    marked_packets: BTreeMap<u32, u64>,
    /// С какого места продолжить обход в следующий раз — иначе потолок смотрел бы вечно одни
    /// и те же первые записи, а хвост карты не убирался бы никогда.
    sweep_from: FlowKey,
    sweep_from_target: Addr,
    swept: u64,
    sweeps: u64,
    /// Сколько записей осталось за пределами бюджета на последнем проходе.
    backlog: usize,
}

/// Различитель без имени — то, что нужно ядру.
fn said_of(naming: &Naming<Box<str>>) -> Said {
    match naming {
        Naming::Spoken(_) => Naming::Spoken(()),
        Naming::Silent => Naming::Silent,
        Naming::Awaited => Naming::Awaited,
    }
}

impl Plane {
    /// `narrow` — чем имя с провода сужается до ключа знания (eTLD+1 у продукта, тождество там,
    /// где ширину выбирает вызывающий). Отдельным аргументом, потому что ширина ключа есть
    /// ПОЛИТИКА: молчаливое умолчание завело бы вторую правду о ней.
    pub fn new(fallback: Programme, narrow: fn(&str) -> &str) -> Plane {
        Plane {
            plans: BTreeMap::new(),
            narrow,
            fallback,
            epoch: NO_KNOWLEDGE,
            cursors: HashMap::with_capacity(CURSORS),
            talks: Talks::new(),
            seen_at: BTreeMap::new(),
            targets: BTreeMap::new(),
            ring: empty_ring(),
            tally: Tally {
                up_bytes: 0,
                down_bytes: 0,
                packets: 0,
                flows_opened: 0,
                flows_lost: 0,
                since: Tick(0),
            },
            sightings: Vec::with_capacity(SIGHTINGS),
            dropped_sightings: 0,
            evicted_cursors: 0,
            evicted_targets: 0,
            unapplied: BTreeMap::new(),
            names: BTreeMap::new(),
            flow_names: BTreeMap::new(),
            named: BTreeMap::new(),
            name_collisions: 0,
            name_conflicts: 0,
            flows_spoken: 0,
            flows_silent: 0,
            unnamed_hellos: 0,
            offered: 0,
            unparsed: 0,
            marked: BTreeSet::new(),
            marked_packets: BTreeMap::new(),
            sweep_from: FlowKey(0),
            sweep_from_target: Addr(0),
            swept: 0,
            sweeps: 0,
            backlog: 0,
        }
    }

    /// НАУЧИТЬ ПРО ИМЕНОВАННУЮ ЦЕЛЬ. Имя сужается ТЕМ ЖЕ `narrow`, каким сужается наблюдённое с
    /// провода: иначе движок учил бы под одним ключом, а плоскость искала бы под другим.
    pub fn teach_name(
        &mut self,
        name: &str,
        programme: Programme,
        basis: Basis,
        interest: Interest,
    ) {
        self.epoch = Epoch(self.epoch.0 + 1);
        self.plans.insert(
            TargetKey::Named((self.narrow)(name).into()),
            Plan {
                programme,
                epoch: self.epoch,
                basis,
                interest,
            },
        );
    }

    /// НАУЧИТЬ ПРО БЕЗЫМЯННУЮ ЦЕЛЬ — адресом, и это законно ровно там, где имени не будет: прямой
    /// коннект по IP, MTProto, синтетический засев замера. Для цели, у которой имя есть, тот же
    /// вызов был бы применением знания ко всем её соседям по адресу.
    pub fn teach_unnamed(
        &mut self,
        dst: Addr,
        programme: Programme,
        basis: Basis,
        interest: Interest,
    ) {
        self.epoch = Epoch(self.epoch.0 + 1);
        self.plans.insert(
            TargetKey::Unnamed(host_of(dst)),
            Plan {
                programme,
                epoch: self.epoch,
                basis,
                interest,
            },
        );
    }

    /// Цель, о которой не учили. Интереса нет — и это ЦЕНА, названная в `WatchedInstrument`:
    /// беда на незнакомой цели видна только до решения о выпуске.
    fn unknown(&self) -> Plan {
        Plan {
            programme: self.fallback,
            epoch: NO_KNOWLEDGE,
            basis: Basis::Default,
            interest: Interest::Idle,
        }
    }

    /// ПЛАН ПО КЛЮЧУ — один вход на обе ветви алгебры. Разошлись бы они здесь на два метода, и
    /// вызывающему снова пришлось бы ветвиться самому.
    fn plan_by(&self, key: &Key) -> Plan {
        match self.plans.get(key) {
            Some(known) => *known,
            None => self.unknown(),
        }
    }

    pub fn feed(&mut self, wire: Wire<'_>, now: Tick) -> Fed {
        // ЛИЧНОСТЬ ЧИТАЕТСЯ ДО ШАГА, А НЕ ПОСЛЕ. Прежде она записывалась следом за вердиктом, то
        // есть решение о ЭТОМ пакете принималось, ещё не зная, кто цель, — и `ClientHello`,
        // единственный пакет, которому страта нужна, уходил по плану, взятому на SYN по адресу.
        // ОТКРЫТИЕ СТИРАЕТ ИМЯ ПРОШЛОГО РАЗГОВОРА НА ЭТОЙ ЖЕ ЧЕТВЁРКЕ. Карта имён ключуется флоу,
        // а флоу — четвёркой, и она переиспользуется: без стирания новый разговор носил бы чужую
        // личность, и решение по нему принималось бы за него. С выпуском по состоянию это значит
        // выпустить его НА SYN — приветствие новой цели до нас не доедет вовсе. Оплачено
        // `lift-leak.sh`: 59 КБ ушли мимо userspace под именем предыдущего разговора.
        match wire.opens {
            true => {
                self.flow_names.remove(&wire.flow);
                // ПАМЯТЬ НАБЛЮДЕНИЯ СТИРАЕТСЯ ВМЕСТЕ С ИМЕНЕМ И ПО ТОЙ ЖЕ ПРИЧИНЕ: четвёрка
                // переиспользуется, и граница прошлого разговора объявила бы повтором первый
                // сегмент нового.
                self.talks.forget(wire.flow);
            }
            false => (),
        };
        // НАБЛЮДЕНИЕ СНИМАЕТСЯ ДО ВЕРДИКТА И ИЗ ТОГО ЖЕ РАЗБОРА. Порядок важен: `advance` ниже
        // двигает курсор и может выселить разговор, а показание относится к пакету, который
        // ПРИШЁЛ, а не к состоянию, которое из него получилось.
        // ПРОТОКОЛ НАЗЫВАЕТСЯ ЗДЕСЬ, а не в переводчике: `Fed::seen` складывает показания обоих
        // транспортов в одно поле, и имя протокола на нём — часть контракта поля.
        let reading = self.talks.read(&wire).map(Reading::Tcp);
        let said = self.note_name(&wire);
        let known = match self.flow_names.get(&wire.flow) {
            Some(held) => held.clone(),
            None => Naming::Awaited,
        };
        // ЗНАНИЕ РАСТЁТ JOIN'ОМ, А РЕШЕНИЕ ЗАМОРАЖИВАЕТСЯ СНИМКОМ — это РАЗНЫЕ величины (#300).
        // Здесь первое: что известно о личности разговора. Оно обязано только расти и не зависеть
        // от порядка прихода. Снимок «на чём стоял план» живёт в ядре (`stood_on`) и от порядка
        // зависит по определению — мы действовали тем, что пришло первым.
        let says = said_of(&said);
        let was = said_of(&known);
        let naming = self.joined_named(known, said);
        self.note_naming(was, said_of(&naming));
        match naming == Naming::Awaited {
            true => (),
            false => {
                self.flow_names.insert(wire.flow, naming.clone());
            }
        };

        let key = keyed(naming.clone(), wire.dst, host_of);
        let plan = self.plan_by(&key);
        // УСТАРЕВАНИЕ СВЕРЯЕТСЯ С ТЕМ ПЛАНОМ, КОТОРЫЙ СЕЙЧАС В СИЛЕ ДЛЯ ЭТОГО РАЗГОВОРА, а не с
        // планом адреса: у именованного флоу знание живёт под именем, и сверка с адресом
        // объявляла бы устаревшим то, что никогда не менялось.
        let epoch = plan.epoch;
        let cursor = match self.cursors.get(&wire.flow) {
            Some(held) => *held,
            None => Cursor::Fresh,
        };
        let packet = Packet {
            flow: wire.flow,
            dst: wire.dst,
            dir: wire.dir,
            opens: wire.opens,
            closes: wire.closes,
            resets: wire.resets,
            payload_len: wire.payload.len(),
            says,
        };

        let advanced = advance(
            |held, seen, at| step(|_asked: &Packet| plan, epoch, held, seen, at),
            counted,
            cursor,
            self.tally,
            packet,
            now,
        );

        self.tally = advanced.tally;
        self.note_marked(&advanced.act, wire.dst, wire.dir);
        self.remember(wire.flow, advanced.cursor, now);
        self.charge_channel(wire.dir, wire.payload.len() as u64, now);
        self.charge_target(&wire, now);
        let opened = matches!(
            advanced.sighting.map(|noted| noted.what),
            Some(Noticed::Talk(Sighting::Opened { .. }))
        );
        // КЛЮЧ БОЛЬШЕ НЕ ПРИДЕЛЫВАЕТСЯ СНАРУЖИ. Прежде край брал голое наблюдение и приписывал
        // ему `wire.flow` сам — то есть связь «наблюдение ↔ разговор» существовала ровно в этом
        // крейте, и всякий второй потребитель двери изобретал бы её заново. Тот же класс, за
        // который уже заплачено ключом памяти, считавшимся на каждой стороне по-своему.
        advanced
            .sighting
            .into_iter()
            .for_each(|told| self.tell(told));
        self.sweep(now);
        Fed {
            act: advanced.act,
            opened,
            seen: reading,
            watch: watched(self.naming_of_flow(wire.flow), advanced.act, plan),
        }
    }

    /// ПОКАЗАНИЕ С ДАТАГРАММЫ. Вердикта здесь нет намеренно: правило очереди сегодня заворачивает
    /// только соединения, и выдавать приговор транспорту, который до нас не доезжает, значило бы
    /// отчитываться о работе, которой не было.
    ///
    /// Словарь у датаграмм ровно общий: ни стука, ни рукопожатия, ни сброса, ни окна приёма — это
    /// свойство транспорта, а не «пока не сделано».
    pub fn watch_datagram(&mut self, datagram: &Datagram<'_>) -> Option<Reading> {
        // ИМЯ ВСЕГДА ЖДЁТСЯ: плоскость QUIC-приветствие не разбирает, и голова датаграммы уходит
        // по потолку терпения, а не по собранному имени. Названная дыра — край на том же типе
        // отвечает `Named::Known`, когда имя у него уже есть.
        self.talks.watch(datagram, Named::Awaited).map(Reading::Udp)
    }

    /// АДРЕС ПОПАДАЕТ В МНОЖЕСТВО ОДИН РАЗ, а не на каждый пакет: запись в ядро идёт в темпе
    /// смены знания, чтение — в темпе пакета, и это и есть вся разница между таблицей и запросом.
    /// СЧИТАЕТСЯ ТОЛЬКО ИСХОДЯЩЕЕ, И ЭТО НЕ ПОЛОВИНА ПРАВДЫ, А УСЛОВИЕ СВЕРКИ. Ядерный счётчик
    /// стоит на пути ВВЕРХ (диспетчер пула на `postrouting`); обратный трафик того же разговора
    /// уводит `ct mark` и мимо него. Считай мы обе стороны — два конца витнеса мерили бы разные
    /// величины и расходились бы СИСТЕМАТИЧЕСКИ, выглядя при этом шумом: замерено 31.08, ядро 15
    /// против плоскости 27 на одном прогоне, и вся разница была направлением.
    fn note_marked(&mut self, act: &Act, dst: Addr, dir: Dir) {
        match act {
            Act::Marked(mark) => {
                match dir {
                    Dir::Up => *self.marked_packets.entry(mark.0).or_insert(0) += 1,
                    Dir::Down => (),
                };
                self.marked.insert(dst);
            }
            // ОБРЫВ НЕ МЕТИТ: он кончает разговор, а не ведёт его. Считать его меченым значило
            // бы завысить наш счёт против ядерного и назвать это расхождением мира.
            Act::Pass | Act::Drop | Act::Sever => (),
        }
    }

    pub fn marked_held(&self) -> usize {
        self.marked.len()
    }

    /// Сколько пакетов плоскость пометила КАЖДОЙ меткой — НАША сторона витнеса доставки.
    pub fn marked_packets(&self) -> Vec<(u32, u64)> {
        self.marked_packets
            .iter()
            .map(|(mark, n)| (*mark, *n))
            .collect()
    }

    /// ЧТО ЭТОТ ПАКЕТ СКАЗАЛ О ЛИЧНОСТИ ЦЕЛИ. Возвращает `Spoken` с КЛЮЧОМ (суженным именем), а
    /// не с тем, что стояло на проводе: под ключом лежит знание, и добывать его дважды разными
    /// способами — известный способ разойтись молча.
    ///
    /// `Silent` возвращается там, где ПРИВЕТСТВИЕ ПРОШЛО, а имени в нём нет: не-TLS, ECH, обрезанный
    /// или нечитаемый SNI. Это факт о ЦЕЛИ. `Awaited` — пакет о личности не сказал ничего, и это
    /// факт о ВРЕМЕНИ. Слить их значило бы потерять знаменатель слепой зоны именного ключа.
    fn note_name(&mut self, wire: &Wire<'_>) -> Naming<Box<str>> {
        match wire.head {
            Head::Opaque => Naming::Awaited,
            Head::HelloWithoutName => {
                self.unnamed_hellos += 1;
                Naming::Silent
            }
            Head::Hello { sni_at, sni_len } => {
                let from = sni_at as usize;
                match wire.payload.get(from..from + sni_len as usize) {
                    None => {
                        self.unnamed_hellos += 1;
                        Naming::Silent
                    }
                    Some(raw) => match std::str::from_utf8(raw) {
                        Err(_not_text) => {
                            self.unnamed_hellos += 1;
                            Naming::Silent
                        }
                        Ok(name) => {
                            *self.names.entry(name.to_string()).or_insert(0) += 1;
                            let key: Box<str> = (self.narrow)(name).into();
                            // КОЛЛИЗИЯ ИМЁН СЧИТАЕТСЯ, А НЕ МОЛЧИТ (#317). Прежде `insert`
                            // перезаписывал молча, и на общем адресе CDN подсказка хранила того,
                            // кто говорил последним, — а таких имён там ≥69. Знать частоту
                            // обязательно раньше, чем решать, годна ли подсказка.
                            match self.named.get(&wire.dst) {
                                Some(before) if before.as_ref() != key.as_ref() => {
                                    self.name_collisions += 1
                                }
                                _same_or_first => (),
                            }
                            // ИМЯ ПИШЕТСЯ ПО АДРЕСУ ТОЛЬКО КОГДА ОНО ЕСТЬ: соединение без hello
                            // (докачка, повторный заход по IP) не должно отбирать знание,
                            // добытое предыдущим, — оттого запись, а не замена на `None`.
                            self.named.insert(wire.dst, key.clone());
                            Naming::Spoken(key)
                        }
                    },
                }
            }
        }
    }

    /// КАК ЗОВУТ ЦЕЛЬ В ЭТОМ РАЗГОВОРЕ — точно, потому что имя добыто из его же `ClientHello`.
    /// `None` — цель не называлась: коннект по чистому IP, докачка, не-TLS. Это знание О НАС.
    /// ЧТО ПЛОСКОСТЬ ЗНАЕТ ОБ ЭТОМ РАЗГОВОРЕ. `Cursor::Fresh` здесь значит «не видели вовсе» —
    /// и это законный, а не пограничный случай: разговор, не дошедший до очереди, существует, и
    /// строка обязана его показать.
    pub fn cursor_of(&self, flow: FlowKey) -> Cursor {
        match self.cursors.get(&flow) {
            Some(held) => *held,
            None => Cursor::Fresh,
        }
    }

    /// ОБОРВАТЬ ЖИВЫЕ РАЗГОВОРЫ С ЭТОЙ ЦЕЛЬЮ. Возвращает, скольким приказ лёг в состояние.
    ///
    /// # ЭТО ПОДЪЁМ ПРИКАЗА С ЦЕЛИ НА ЕЁ РАЗГОВОРЫ (#326)
    ///
    /// Приказ адресован ЦЕЛИ (её маршрут изменился), а рвутся РАЗГОВОРЫ — цель есть база, живые
    /// соединения слой над ней, и двери между ними у плоскости не было вовсе. Оттого
    /// `Ordered::Sever` год не производился ничем: закон обрыва в `step` был выражен целиком, а
    /// поставить приказ было некому.
    ///
    /// # Имя сужается тем же сужением, что и планы
    ///
    /// Разговор помнит имя, которым назвалась цель; знание и планы живут под СУЖЕННЫМ именем
    /// (`Naming::Registrable`). Сравнивай мы их без сужения — приказ о `youtube.com` не нашёл бы
    /// ни одного разговора с `rr3---sn-….googlevideo.com`, и обрыв молча не делал бы ничего.
    ///
    /// # Приказ ложится в СОСТОЯНИЕ, а не исполняется здесь
    ///
    /// Исполнит его следующий пакет разговора — тогда же соберётся RST. Так обрыв остаётся
    /// свойством шага (`step::sever` чистая), а плоскость не заводит себе второго способа
    /// действовать.
    pub fn sever_named(&mut self, name: &str) -> usize {
        let narrowed = (self.narrow)(name);
        let doomed: Vec<FlowKey> = self
            .flow_names
            .iter()
            .filter(|(_, said)| match said {
                Naming::Spoken(held) => (self.narrow)(held) == narrowed,
                Naming::Awaited | Naming::Silent => false,
            })
            .map(|(flow, _)| *flow)
            .collect();

        doomed
            .into_iter()
            .filter(|flow| match self.cursors.get(flow) {
                // РВАТЬ НЕЧЕГО — И ЭТО НЕ ОТКАЗ: приказ мог опоздать ровно на конец разговора.
                None => false,
                Some(cursor) => {
                    let severed = sever(*cursor);
                    let ordered = severed != *cursor;
                    self.cursors.insert(*flow, severed);
                    ordered
                }
            })
            .count()
    }

    /// КОГДА ПЛОСКОСТЬ ВИДЕЛА ЭТОТ РАЗГОВОР В ПОСЛЕДНИЙ РАЗ.
    ///
    /// Нужен строке, и по причине, которой счёт не покрывает: `Sight` меряет слепоту в ПАКЕТАХ и
    /// ловит «до очереди дошло не всё». Второго рода она не ловит — счета сошлись, а наблюдения
    /// прекратились. Живая строка и застывшая выглядят одинаково, то есть «прибор молчит»
    /// неотличимо от «прибор мёртв».
    pub fn seen_at_of(&self, flow: FlowKey) -> Option<Tick> {
        self.seen_at.get(&flow).copied()
    }

    /// КАК ЗОВУТ ЦЕЛЬ В ЭТОМ РАЗГОВОРЕ. `None` значит «имени нет», и ДВЕ его причины различает
    /// `naming_of_flow`: имени не будет либо приветствие впереди. Здесь они слиты намеренно —
    /// вызывающему, которому нужно имя, обе причины одинаковы.
    pub fn name_of_flow(&self, flow: FlowKey) -> Option<&str> {
        match self.flow_names.get(&flow) {
            Some(Naming::Spoken(name)) => Some(name.as_ref()),
            Some(Naming::Silent) | Some(Naming::Awaited) | None => None,
        }
    }

    /// ЧТО ИЗВЕСТНО О ЛИЧНОСТИ ЦЕЛИ В ЭТОМ РАЗГОВОРЕ — все три состояния. Отсюда считается доля
    /// безымянных ПО РАЗГОВОРУ, а не сводным счётчиком по коробке.
    pub fn naming_of_flow(&self, flow: FlowKey) -> Naming<Box<str>> {
        match self.flow_names.get(&flow) {
            Some(known) => known.clone(),
            None => Naming::Awaited,
        }
    }

    /// КАК ЗВАЛИ ТОГО, КТО ГОВОРИЛ ПО ЭТОМУ АДРЕСУ ПОСЛЕДНИМ — ПОДСКАЗКА, А НЕ ОСНОВАНИЕ (#317).
    ///
    /// Годится ровно для безымянного трафика, и явное имя обязано её перебивать: на общем адресе
    /// CDN за одной записью стоят десятки имён, и какое из них вернётся — вопрос очерёдности, а не
    /// правды. Частота расхождения не гадается, а СЧИТАЕТСЯ — `name_collisions`.
    pub fn name_hint_of(&self, dst: Addr) -> Option<&str> {
        self.named.get(&dst).map(|name| name.as_ref())
    }

    /// Сколько раз подсказка по адресу сменила имя на другое.
    pub fn name_collisions(&self) -> u64 {
        self.name_collisions
    }

    /// ПЕРЕЕЗД РАЗГОВОРА ПО ЛИЧНОСТИ. Считается ПЕРЕХОД, а не состояние: разговор, ушедший из
    /// `Silent` в `Spoken`, обязан покинуть первую долю, иначе сумма превысит число разговоров.
    fn note_naming(&mut self, was: Said, now: Said) {
        match (was, now) {
            (Naming::Awaited, Naming::Spoken(())) => self.flows_spoken += 1,
            (Naming::Awaited, Naming::Silent) => self.flows_silent += 1,
            (Naming::Silent, Naming::Spoken(())) => {
                self.flows_silent = self.flows_silent.saturating_sub(1);
                self.flows_spoken += 1;
            }
            _no_move => (),
        }
    }

    /// ДОЛИ ЛИЧНОСТИ ПО РАЗГОВОРАМ: назвались · приветствие без имени · так и не сказали ничего.
    ///
    /// Третье считается вычитанием из числа ОТКРЫТЫХ разговоров — то есть у прибора есть
    /// знаменатель, и «безымянных ноль» отличимо от «мы не смотрели».
    ///
    /// ЦЕНА НАЗВАНА: знаменатель считает разговоры, чей SYN мы ВИДЕЛИ. Разговор, подхваченный с
    /// середины (коробка включилась при живом трафике), в него не попадает, и третья доля тогда
    /// упирается в ноль вместо отрицательного — прибор обязан молчать, а не утверждать
    /// невозможное. Величина этого занижения видна сравнением с `cursors`.
    pub fn naming_shares(&self) -> (u64, u64, u64) {
        let known = self.flows_spoken + self.flows_silent;
        (
            self.flows_spoken,
            self.flows_silent,
            self.tally.flows_opened.saturating_sub(known),
        )
    }

    /// Сколько разговоров назвались двумя разными именами — величина ⊤, которой нет типом.
    pub fn name_conflicts(&self) -> u64 {
        self.name_conflicts
    }

    /// JOIN ЗНАНИЯ О ЛИЧНОСТИ РАЗГОВОРА — тот же порядок по информации, что у ядра
    /// (`Awaited ⊑ Silent ⊑ Spoken`), только с именем в верхнем элементе.
    ///
    /// # ЗАКОН 3 ЗДЕСЬ НЕ ТОТАЛЕН, И ЭТО НАЗВАНО, А НЕ СПРЯТАНО
    ///
    /// Два РАЗНЫХ имени на одном разговоре несравнимы: в полной решётке их соединение есть ⊤
    /// («противоречие»), и коммутативности на этой паре НЕТ — держится пришедшее первым. Значит
    /// правильная формулировка такая: **коммутативно на цепочке; в конфликте — нет, и частота
    /// замеряется** (`name_conflicts`). Сказать «три закона зелёные» было бы overclaim.
    ///
    /// Детерминированный разрешатель (скажем, лексикографически меньшее имя) сделал бы закон
    /// тотальным — и был бы решением, принятым ДО замера: мы молча выбирали бы имя не по времени,
    /// не зная даже, как часто выбор вообще случается. Сперва число.
    fn joined_named(
        &mut self,
        known: Naming<Box<str>>,
        said: Naming<Box<str>>,
    ) -> Naming<Box<str>> {
        match (known, said) {
            (Naming::Spoken(first), Naming::Spoken(other)) => {
                match first.as_ref() == other.as_ref() {
                    true => (),
                    false => self.name_conflicts += 1,
                };
                Naming::Spoken(first)
            }
            (Naming::Spoken(name), _lower) | (_lower, Naming::Spoken(name)) => Naming::Spoken(name),
            (Naming::Silent, _) | (_, Naming::Silent) => Naming::Silent,
            (Naming::Awaited, Naming::Awaited) => Naming::Awaited,
        }
    }

    /// Сколько имён держится сейчас. Публично РАДИ ЗАКОНА О ФОРМЕ РОСТА: без этого числа
    /// утверждение «карта имён ограничена целями» проверялось бы только чтением кода.
    pub fn named_held(&self) -> usize {
        self.named.len()
    }

    pub fn names(&self) -> Vec<(String, u64)> {
        self.names
            .iter()
            .map(|(name, n)| (name.clone(), *n))
            .collect()
    }

    pub fn unnamed_hellos(&self) -> u64 {
        self.unnamed_hellos
    }

    /// ЗАКОНЧЕННЫЙ РАЗГОВОР УХОДИТ В `Lost`, А НЕ В ПУСТОТУ. Освободив запись на `FIN`, оболочка
    /// превращала хвост разрыва в НОВЫЕ разговоры: замер провода дал «открыт 3» при одном флоу,
    /// и движку это пришло бы как три новые цели. Запись держится до подметания по горизонту.
    /// # ПЕРЕВОДА БОЛЬШЕ НЕТ, И ЭТО СНЯТИЕ СОГЛАШЕНИЯ (#320, 03.09)
    ///
    /// Прежде шаг отдавал при закрытии `Cursor::Fresh`, а оболочка переводила его в `Ended` —
    /// то есть у `Fresh` было два смысла, и держались они комментарием в этом файле. Соглашение,
    /// которого не знает тип, однажды не знает и читатель: вместе с ним терялся ответ цели, и
    /// таблица слепла на всё завершённое.
    ///
    /// Теперь шаг называет закрытие сам (`Cursor::Ended(answered)`), и оболочка кладёт то, что
    /// получила. `Fresh` сюда больше не приходит вовсе — а если придёт, это разговор, которого
    /// не было, и запоминать о нём нечего.
    fn remember(&mut self, flow: FlowKey, cursor: Cursor, now: Tick) {
        match cursor {
            Cursor::Fresh => (),
            Cursor::Running(_) | Cursor::Ended(_) | Cursor::Lost => {
                self.cursors.insert(flow, cursor);
                self.seen_at.insert(flow, now);
            }
        }
    }

    fn charge_channel(&mut self, dir: Dir, bytes: u64, now: Tick) {
        match dir {
            Dir::Down => self.ring = applied(self.ring, charge(self.ring.last, now, bytes)),
            Dir::Up => (),
        }
    }

    fn charge_target(&mut self, wire: &Wire<'_>, now: Tick) {
        let held = match self.targets.get(&wire.dst) {
            Some(known) => *known,
            None => fresh_target(now),
        };
        let packet = Packet {
            flow: wire.flow,
            dst: wire.dst,
            dir: wire.dir,
            opens: wire.opens,
            closes: wire.closes,
            resets: wire.resets,
            payload_len: wire.payload.len(),
            // СЧЁТУ БАЙТОВ ЛИЧНОСТЬ ЦЕЛИ БЕЗРАЗЛИЧНА: здесь меряется темп, а не решается план.
            says: Naming::Awaited,
        };
        let charged = charged_target(held, &packet, now);
        self.targets.insert(wire.dst, charged.target);
        match charged.peaked {
            false => (),
            true => self.tell(Noted {
                at: now,
                about: About::Talk(wire.flow),
                // РАЗЛИЧИТЕЛЬ, А НЕ ИМЯ: имя добавит `drain`, одним местом на все наблюдения.
                target: said_of(&self.naming_of_flow(wire.flow)),
                what: Noticed::Talk(Sighting::Peaked {
                    dst: wire.dst,
                    pace: charged.target.best,
                }),
            }),
        }
    }

    fn tell(&mut self, told: Noted) {
        match self.sightings.len() < SIGHTINGS {
            true => self.sightings.push(told),
            false => self.dropped_sightings += 1,
        }
    }

    /// НАБЛЮДЕНИЕ ОТДАЁТСЯ ВМЕСТЕ С РАЗГОВОРОМ, В КОТОРОМ СЛУЧИЛОСЬ (#317). Без этого потребитель
    /// пошёл бы спрашивать имя по адресу — то есть вернул бы карту адрес→имя основанием действия
    /// через заднюю дверь.
    /// # ИМЯ ДОБАВЛЯЕТСЯ ЗДЕСЬ, И ТОЛЬКО ЗДЕСЬ (#320, Т5)
    ///
    /// Ядро имён не знает, потребитель их восстанавливать не вправе — своя карта адрес→имя есть
    /// второй источник правды о цели, и им уже оплачен ключ памяти. Знает их ровно плоскость, и
    /// обогащение стоит на выходе, где знание полное: наблюдение копилось с различителем, а имя
    /// берётся ТЕКУЩЕЕ, на момент выдачи.
    ///
    /// ЦЕНА НАЗВАНА: имя, названное позже наблюдения, приезжает с ним — то есть `Opened`,
    /// снятый на `SYN`, выйдет уже с именем, если разговор назвался до дренажа. Это ВЕРНО для
    /// таблицы (там предмет — цель) и НЕТОЧНО для ленты, где строка утверждает момент. Различить
    /// можно `Sighting::Recognised`: он и есть засечка, когда имя стало известно.
    ///
    /// Клон — только у `Spoken`: у безымянных ветвей копировать нечего.
    ///
    /// # СВОДКА ПО НАБЛЮДЕНИЯМ КОПИТСЯ У ПОКАЗА, А НЕ ЗДЕСЬ — решение названо вслух (#320)
    ///
    /// «Сколько сбросов у этой цели», «когда её видели в последний раз», «сколько разговоров
    /// оборвалось» — всё это СВЁРТКИ потока, и дверь их не считает намеренно. Причина не в
    /// экономии: плоскость отдаёт ВЕЛИЧИНЫ, вывод делает оператор. Заведи она сводку — и у неё
    /// появился бы вердикт, то есть второе суждение рядом с суждением показа, и разошлись бы они
    /// молча.
    ///
    /// Сказано здесь, а не в переписке, ровно затем, чтобы следующий потребитель не завёл свою
    /// вторым способом: копит показ, и копит один.
    pub fn drain(&mut self) -> Vec<Noted<Box<str>>> {
        let names = &self.flow_names;
        self.sightings
            .drain(..)
            .map(|noted| {
                let flow = match noted.about {
                    reflex_engine::About::Talk(flow) => Some(flow),
                    // У наблюдения о ЦЕЛИ разговора нет, и спрашивать имя не у кого: её разговоры
                    // выселены раньше. Подставить сюда подсказку по адресу значило бы вернуть
                    // через заднюю дверь ровно то знание, которое врёт на общем адресе CDN.
                    reflex_engine::About::Target => None,
                };
                noted.named(
                    |said| match (flow.and_then(|flow| names.get(&flow)), said) {
                        (Some(known), _) => known.clone(),
                        // ИМЕНИ У РАЗГОВОРА НЕТ — и различитель ядра говорит, ПОЧЕМУ его нет.
                        // `Silent` («приветствие прошло без имени») переживает потерю карты, `Awaited`
                        // («приветствия ещё не было») — тоже: обе причины установлены ядром.
                        (None, Naming::Silent) => Naming::Silent,
                        (None, Naming::Spoken(())) | (None, Naming::Awaited) => Naming::Awaited,
                    },
                )
            })
            .collect()
    }

    pub fn note_unapplied(&mut self, what: &'static str) {
        *self.unapplied.entry(what).or_insert(0) += 1;
    }

    /// УБОРКА С ПОТОЛКОМ И С МЕСТА, ГДЕ ОСТАНОВИЛИСЬ. Обход карты целиком есть работа,
    /// пропорциональная числу целей; редкость шага её не отменяет, а лишь размазывает по пакетам.
    /// Упорядоченная карта позволяет продолжить с сохранённого ключа — тогда и потолок соблюдён,
    /// и хвост карты рано или поздно осматривается.
    /// ВРЕМЯ ИДЁТ — ЕДИНСТВЕННЫЙ ВХОД, НЕ ТРЕБУЮЩИЙ ПАКЕТА.
    ///
    /// # Что этим чинится
    ///
    /// Всё, чем плоскость судит о ТИШИНЕ, до сих пор двигалось чужим пакетом: `Tick` вычислялся
    /// внутри обработчика, а уборка вдобавок висела на СЧЁТЕ пакетов (`tally.packets %
    /// SWEEP_EVERY`), хотя решает вопрос временной. Нет трафика — время для плоскости стоит, и
    /// `expired`, `Freshness::Silent`, `Sighting::Stale` и [`Lost`] не срабатывают ровно тогда,
    /// когда заводились.
    ///
    /// Мёртвая нога умирает В ТИШИНЕ. Прибор, которого будит чужой пакет, слеп именно к тому
    /// случаю, ради которого существует, — и остаётся при этом честным: `law/Instrument`, клетка
    /// `traffic`, `NoFalseAlarm` зелёный при красном `PainNeverSilent`.
    ///
    /// # Почему `Lost` рождается здесь, а не в шаге закона
    ///
    /// Потеря цели есть событие ОТСУТСТВИЯ, а шаг закона видит только присутствие: он реагирует
    /// на пакет, а здесь пакета нет и не будет. Событий отсутствия не бывает — бывает время, в
    /// которое ничего не произошло, и ровно это время уборка по часам умеет заметить, а реакция
    /// на пакет — нет.
    pub fn tick(&mut self, now: Tick) -> Vec<Noted<Box<str>>> {
        self.wipe(now);
        self.drain()
    }

    fn sweep(&mut self, now: Tick) {
        match self.tally.packets % SWEEP_EVERY == 0 {
            false => (),
            true => self.wipe(now),
        }
    }

    /// Один проход уборки — с потолком и с места, где остановились.
    ///
    /// Отделён от [`Plane::sweep`] ровно тем, что не спрашивает о ПАКЕТАХ: у уборки два повода
    /// (амортизация на горячем пути и ход времени), и условие принадлежит поводу, а не работе.
    fn wipe(&mut self, now: Tick) {
        {
            {
                self.sweeps += 1;

                let looked: Vec<FlowKey> = self
                    .seen_at
                    .range(self.sweep_from..)
                    .take(SWEEP_BUDGET)
                    .map(|(flow, _seen)| *flow)
                    .collect();
                self.swept += looked.len() as u64;
                self.backlog = self.seen_at.len().saturating_sub(looked.len());
                self.sweep_from = match looked.last() {
                    Some(FlowKey(last)) => FlowKey(last.saturating_add(1)),
                    None => FlowKey(0),
                };
                let stale: Vec<FlowKey> = looked
                    .into_iter()
                    .filter(|flow| match self.seen_at.get(flow) {
                        Some(seen) => expired(*seen, now),
                        None => false,
                    })
                    .collect();
                // СЧЁТ `evicted_cursors` — ЗА ЗАБЫВАНИЕМ, И ТОЛЬКО ЗА НИМ.
                //
                // Забывание — это переход `Running → Lost`: состояние снято, и мы больше не знаем,
                // что применяли. Ровно это обещает докблок слова «забыто». Удаление записи по
                // истечении удержания у `Ended` забыванием не является: разговор закрылся штатно,
                // всё было известно, память просто отслужила срок. Удаление уже забытой (`Lost`)
                // тем более не событие — забывание об этом разговоре уже сосчитано раньше.
                //
                // Отсюда и то, чего здесь НЕТ: инкремент не стоит одним числом на факте попадания
                // записи в `stale` (кандидат на пересмотр — не событие, а `Ended` внутри удержания
                // возвращается в кандидаты на каждом проходе) и не стоит на факте удаления —
                // он стоит РОВНО в одной точке, там, где случается само забывание.
                // ВЫСЕЛЕНИЕ ДВУХФАЗНОЕ, И ЭТО НАЙДЕНО ЖИВОЙ ТАБЛИЦЕЙ (#320, 03.09).
                //
                // Прежде первая же фаза УДАЛЯЛА курсор. Дальше `record()` находил запись
                // conntrack, курсора к ней не находил — и ставил `Watched::Never`, то есть «через
                // очередь не шёл». Таблица честно печатала «не видели» про разговор, который мы
                // наблюдали: плоскость видела 37 пакетов на 8 флоу, а все три строки сказали, что
                // слепы.
                //
                // `Never` и `Lost` — РАЗНЫЕ ФАКТЫ: «мы не смотрели» и «смотрели и забыли». Слив их,
                // человек читает нашу забывчивость как нашу слепоту, а доля «не видели» — главное
                // число приёмки — оказывается завышена на все короткие разговоры.
                //
                // ЦЕНА НАЗВАНА: карта держит забытый разговор ещё горизонт, то есть потолок
                // `CURSORS` покрывает вдвое меньше живых. Это дешевле лжи в главном числе, и
                // мерить надо долю `Lost` среди курсоров — она и скажет, тесен ли потолок.
                stale.iter().for_each(|flow| {
                    match self.cursors.get(flow) {
                        // УМЕР МОЛЧА: закрытия не объявлял, состояние снимаем — и честно говорим,
                        // что не знаем, что применяли. Иначе хвостовой пакет получил бы решение,
                        // принятое заново поверх уже применённого.
                        Some(Cursor::Running(_)) => {
                            self.cursors.insert(*flow, Cursor::Lost);
                            self.seen_at.insert(*flow, now);
                            self.evicted_cursors += 1;
                        }
                        // ЗАКРЫЛСЯ БУКВОЙ: знание получено и не устаревает от того, что прошло
                        // время, — `seen_at` тут НЕ двигаем, иначе срок отсчитывался бы от
                        // каждого прохода уборки и не кончался бы никогда. Он отсчитывается от
                        // ЗАКРЫТИЯ, и это удержание — своя величина (`RETENTION_HORIZONS`), а не
                        // горизонт уборки: одно — свойство хвоста на проводе, другое — наше
                        // удобство обхода, и мерить первое вторым значило бы менять первое,
                        // настраивая второе.
                        //
                        // Не истекло — оставляем как есть. Истекло — запись УДАЛЯЕТСЯ, не
                        // разжалуется: дальше о ней честно скажется `Never`, ровно как о
                        // забытом строкой ниже.
                        Some(Cursor::Ended(_)) => {
                            let closed = self.seen_at.get(flow).copied().unwrap_or(now);
                            let held = now.0.saturating_sub(closed.0);
                            match held >= RETENTION_HORIZONS * horizon().0 {
                                false => (),
                                true => {
                                    self.cursors.remove(flow);
                                    self.seen_at.remove(flow);
                                    self.flow_names.remove(flow);
                                }
                            }
                        }
                        // ВТОРАЯ ФАЗА: забытый пережил ещё горизонт — теперь исчезает совсем.
                        // Дальше о нём честно скажется `Never`: столько времени спустя мы и правда
                        // не знаем, шёл ли он через нас.
                        Some(Cursor::Lost) | Some(Cursor::Fresh) | None => {
                            self.cursors.remove(flow);
                            self.seen_at.remove(flow);
                            // ИМЯ РАЗГОВОРА УХОДИТ ВМЕСТЕ С РАЗГОВОРОМ. Переживи оно курсор —
                            // карта имён росла бы числом ВИДЕННЫХ соединений, а не живых, и
                            // потолок перестал бы ограничивать память.
                            self.flow_names.remove(flow);
                        }
                    };
                    // ПАМЯТЬ НАБЛЮДЕНИЯ УХОДИТ НА ПЕРВОЙ ЖЕ ФАЗЕ: граница клиента от прошлого
                    // разговора на переиспользованной четвёрке объявила бы повтором первый же
                    // сегмент нового. Забытый разговор новых показаний не даёт — а если пакет
                    // придёт, `Lost` его и встретит.
                    self.talks.forget(*flow);
                });

                let looked: Vec<Addr> = self
                    .targets
                    .range(self.sweep_from_target..)
                    .take(SWEEP_BUDGET)
                    .map(|(dst, _target)| *dst)
                    .collect();
                self.swept += looked.len() as u64;
                self.sweep_from_target = match looked.last() {
                    Some(Addr(last)) => Addr(last.saturating_add(1)),
                    None => Addr(0),
                };
                let gone: Vec<Addr> = looked
                    .into_iter()
                    .filter(|dst| match self.targets.get(dst) {
                        Some(target) => expired(target.last_seen, now),
                        None => false,
                    })
                    .collect();
                self.evicted_targets += gone.len() as u64;
                gone.iter().for_each(|dst| {
                    self.targets.remove(dst);
                    // ИМЯ УХОДИТ ВМЕСТЕ С ЦЕЛЬЮ. Переживи оно её — карта имён росла бы с числом
                    // ВИДЕННЫХ адресов, а не наблюдаемых целей, и потолок `TARGETS` перестал бы
                    // ограничивать память: та самая утечка, которая выглядит как исправная работа.
                    self.named.remove(dst);
                });
                // ЦЕЛЬ ПОТЕРЯНА — И ОБ ЭТОМ ГОВОРЯТ, А НЕ ТОЛЬКО ЗАБЫВАЮТ.
                //
                // Прежде выселение было чистой уборкой памяти: цель молча исчезала из карт, и
                // единственным следом оставался счётчик `evicted_targets` — число, по которому
                // нельзя сказать НИ ЧТО потеряно, НИ КОГДА. Оттого у `Lost` и не было
                // производителя.
                //
                // РАЗГОВОРА У ЭТОГО НАБЛЮДЕНИЯ НЕТ, и это сказано БУКВОЙ: потеряна ЦЕЛЬ, а не
                // соединение, — её разговоры к этому времени выселены той же уборкой строкой
                // выше. Прежде здесь стоял `FlowKey(0)`, честный по смыслу и неотличимый по типу
                // от настоящего ключа: потребитель обязан был знать соглашение, чтобы не
                // приписать наблюдение разговору номер ноль.
                gone.into_iter().for_each(|dst| {
                    self.tell(Noted {
                        at: now,
                        about: About::Target,
                        // РАЗГОВОРА НЕТ — и различителя личности тоже: цель потеряна целиком, а
                        // её разговоры выселены этой же уборкой. `Awaited` здесь честен: о
                        // личности НЕ СКАЗАНО ничего, потому что сказать больше некому.
                        target: Naming::Awaited,
                        what: Noticed::Loss(Lost { dst }),
                    })
                });
            }
        }
    }

    pub fn swept(&self) -> u64 {
        self.swept
    }

    pub fn sweeps(&self) -> u64 {
        self.sweeps
    }

    /// СКОЛЬКО ЗАПИСЕЙ ОСТАЛОСЬ НЕОСМОТРЕННЫМИ на последнем проходе уборки.
    ///
    /// Растущий остаток значит, что круг удлиняется: тревоги ещё не опаздывают, но начнут. Это
    /// показание, а не счётчик работы, — оно говорит о ЗАПАСЕ, а не о сделанном.
    pub fn backlog(&self) -> usize {
        self.backlog
    }

    pub fn pressure(&self) -> Pressure {
        Pressure {
            held: self.cursors.len() as u32,
            capacity: CURSORS as u32,
            evicted: self.evicted_cursors,
        }
    }

    pub fn channel(&self, back: u8) -> Pace {
        reflex_engine::meter::paced(&self.ring, back)
    }

    pub fn ceiling(&self) -> Pace {
        reflex_engine::meter::ceiling(&self.ring)
    }

    pub fn tally(&self) -> Tally {
        self.tally
    }

    pub fn targets_held(&self) -> usize {
        self.targets.len()
    }

    pub fn dropped_sightings(&self) -> u64 {
        self.dropped_sightings
    }

    pub fn evicted_targets(&self) -> u64 {
        self.evicted_targets
    }

    /// СКОЛЬКО РАЗГОВОРОВ ЗАБЫТО УБОРКОЙ. Едет в снимок показа: без него человек не отличит нашу
    /// СЛЕПОТУ («не смотрели») от нашей ЗАБЫВЧИВОСТИ («смотрели и забыли»), а доля «не видели»
    /// перестаёт что-либо мерить.
    pub fn evicted_cursors(&self) -> u64 {
        self.evicted_cursors
    }

    pub fn unapplied(&self) -> Vec<(&'static str, u64)> {
        self.unapplied.iter().map(|(what, n)| (*what, *n)).collect()
    }

    pub fn offer(&mut self) {
        self.offered += 1;
    }

    pub fn note_unparsed(&mut self) {
        self.unparsed += 1;
    }

    pub fn snapshot(&self) -> String {
        format!(
            "packets={} up={} down={} flows={} cursors={} targets={} ring_1s={} ceiling={} evicted_cursors={} evicted_targets={} dropped_sightings={} named={} unnamed={} offered={} unparsed={} marked={} name_collisions={} name_conflicts={} spoken={} silent={} awaited={}\n",
            self.tally.packets,
            self.tally.up_bytes,
            self.tally.down_bytes,
            self.tally.flows_opened,
            self.cursors.len(),
            self.targets.len(),
            self.channel(7).bytes,
            self.ceiling().bytes,
            self.evicted_cursors,
            self.evicted_targets,
            self.dropped_sightings,
            self.names.len(),
            self.unnamed_hellos,
            self.offered,
            self.unparsed,
            self.marked.len(),
            self.name_collisions,
            self.name_conflicts,
            self.naming_shares().0,
            self.naming_shares().1,
            self.naming_shares().2,
        )
    }

    pub fn horizon_span(&self) -> u64 {
        horizon().0
    }
}

fn counted(tally: Tally, packet: &Packet, now: Tick) -> Tally {
    let size = packet.payload_len as u64;
    Tally {
        up_bytes: match packet.dir {
            Dir::Up => tally.up_bytes + size,
            Dir::Down => tally.up_bytes,
        },
        down_bytes: match packet.dir {
            Dir::Up => tally.down_bytes,
            Dir::Down => tally.down_bytes + size,
        },
        packets: tally.packets + 1,
        flows_opened: tally.flows_opened + u64::from(packet.opens),
        flows_lost: tally.flows_lost,
        since: match tally.packets == 0 {
            true => now,
            false => tally.since,
        },
    }
}
