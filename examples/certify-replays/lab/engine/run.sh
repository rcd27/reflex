#!/bin/sh
# Внутри контейнера: поднять движок с предъявлением §10, погнать боевой трафик, снять ВЕРДИКТ.
# Предмет проверки — не находка детектора, а воспроизводимость: два прогона одного окна ленты
# обязаны сказать одно и то же.
set -u

TARGET=${TARGET:-rutracker.org}
CONTROL=${CONTROL:-vk.com}
QUEUE=200
LOG=/tmp/reflex.log

MUTANT=${MUTANT:-}
echo "[стенд] цель=$TARGET  контроль=$CONTROL  очередь=$QUEUE  мутант=${MUTANT:-нет}"

# 1. Движок на очереди. Правило ставим ПОСЛЕ — очередь без слушателя дропает трафик.
#    MUTANT=1 подсовывает в цепочку прибор со скрытым входом: этим прогоном стенд доказывает, что
#    умеет краснеть. Зелёный вердикт исправной машины без такого доказательства ничего не значит.
certify-replays >"$LOG" 2>&1 &
ENGINE=$!
sleep 1
if ! kill -0 "$ENGINE" 2>/dev/null; then
  echo "[стенд] движок не поднялся:"; cat "$LOG"; exit 2
fi

# 2. Наш :443 — в очередь, обе стороны.
nft add table inet reflex_lab
nft add chain inet reflex_lab out '{ type filter hook output priority -150; policy accept; }'
nft add rule  inet reflex_lab out tcp dport 443 queue num 200
nft add chain inet reflex_lab inp '{ type filter hook input priority -150; policy accept; }'
nft add rule  inet reflex_lab inp tcp sport 443 queue num 200

# 3. Боевой трафик ВОЛНАМИ, а не разово. Молчащее окно (одни узлы сетки, ни одной живой машины)
#    воспроизводится тривиально и свидетельством не считается — под ним однажды прошла мутация
#    «переигровка читает часы», и стенд остался зелёным. Волны держат машины живыми, пока окна
#    закрываются. Мимо любого прокси: иначе движок увидел бы разговор с прокси, а не с целью
#    (урок 09.09: curl через http_proxy молча меняет предмет наблюдения).
i=0
while [ "$i" -lt 6 ]; do
  curl -s4 --noproxy '*' --max-time 10 "https://$TARGET/"  >/dev/null 2>&1 &
  curl -s4 --noproxy '*' --max-time 6  "https://$CONTROL/" >/dev/null 2>&1 &
  sleep 5
  i=$((i + 1))
done

# 4. Дать последним волнам дотикать.
sleep 6

# 5. Прибраться.
nft delete table inet reflex_lab 2>/dev/null
kill "$ENGINE" 2>/dev/null; wait "$ENGINE" 2>/dev/null

echo "─── лог движка ───────────────────────────"
cat "$LOG"
echo "──────────────────────────────────────────"

# 6. ВЕРДИКТ. Нарушение — приговор; отсутствие свидетельства — тоже провал стенда: закон, который
#    не предъявился, не проверен.
# Мутантный прогон ОБЯЗАН покраснеть — иначе стенд слеп, и его зелёный ничего не свидетельствует.
if [ -n "$MUTANT" ]; then
  if grep -q "§10 НАРУШЕН" "$LOG"; then
    echo "[вердикт] стенд ЗРЯЧ: испорченная машина поймана — §10 нарушен, как и должно быть"
    exit 0
  fi
  echo "[вердикт] СТЕНД СЛЕП: скрытый вход не пойман — зелёный на исправной машине ничего не стоит"
  exit 4
fi

if grep -q "§10 НАРУШЕН" "$LOG"; then
  echo "[вердикт] §10 НАРУШЕН — у машины есть вход вне её алфавита"
  exit 1
fi
if grep -q "воспроизведено" "$LOG"; then
  echo "[вердикт] §10 держится: окно ленты воспроизведено на боевом трафике"
  exit 0
fi
# Молчащие окна закон не свидетельствуют: если ВСЕ окна прошли молча, проверено ничего не было.
if grep -q "прошло молча" "$LOG"; then
  echo "[вердикт] ПРОВАЛ СТЕНДА: все окна молчали — машинам нечего было сказать, закон не проверен"
  exit 3
fi
echo "[вердикт] ПРОВАЛ СТЕНДА: закон не предъявился ни разу — окно не закрылось"
exit 3
