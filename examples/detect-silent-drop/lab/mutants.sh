#!/bin/sh
# Оснастка мутантов ЗАМЕРА (Д8, задача 13): «замер без доказанной способности показать ненуль не
# считается» — как зелёный тест без доказанной способности краснеть. Ноль переполнений на боевой
# очереди (задача 4, ~15 п/с) едва не был записан фактом («тревога теоретическая»); свидетель
# нагрузки показал, что переполнение на этом стенде недостижимо ПО ПОСТРОЕНИЮ (движок опережает
# очередь на три порядка) — ноль означал «не измерено», а выглядел как «измерено и пусто».
#
# Способность предъявляется ДВУМЯ мутантами (`linux/src/queue/socket.rs`,
# `tiny_queue_mutant`/`tiny_rcvbuf_mutant`), а не одним: `queue_dropped` («до очереди не дошло») и
# `user_dropped` («мы не забрали») — РАЗНЫЕ оракулы одного и того же алфавита `Overrun`, и мутанты
# расходятся по ним ЗЕРКАЛЬНО (замерено 10.09, соседней сессией, вручную — здесь оснастка, не
# открытие). Один мутант доказал бы способность не того оракула, а второй остался бы «не измерено»
# под чужим именем.
#
# Три прогона ПОДРЯД, как `.certifying()` у §10: два мутанта обязаны показать ненуль ТЕМ ЖЕ
# оракулом, которым потом мерят боевую частоту, — иначе третий прогон опять был бы нулём без
# разрешающей способности.
set -u
cd "$(dirname "$0")"

echo "[мутанты] сборка образа…"
docker compose build engine >/dev/null || { echo "[мутанты] сборка не прошла"; exit 2; }

# Выдёргивает "[метрика] queue_dropped=Q user_dropped=U overrun=O" из лога прогона.
metric() { grep '^\[метрика\]' | tail -1; }
field() { echo "$1" | grep -oE "$2=[0-9?]+" | cut -d= -f2; }

FAIL=0

echo
echo "=== прогон 1/3 — мутант №1: REFLEX_LAB_TINY_QUEUE=2 (queue_dropped обязан уйти от нуля) ==="
OUT1=$(docker compose run --rm -e REFLEX_LAB_TINY_QUEUE=2 engine 2>&1) || true
echo "$OUT1"
M1=$(echo "$OUT1" | metric)
QD1=$(field "$M1" queue_dropped); UD1=$(field "$M1" user_dropped); OV1=$(field "$M1" overrun)
echo "[мутанты] мутант №1: queue_dropped=$QD1 user_dropped=$UD1 overrun=$OV1"
if [ "${QD1:-0}" -gt 0 ] 2>/dev/null && [ "${UD1:-1}" = 0 ] && [ "${OV1:-1}" = 0 ]; then
  echo "[мутанты] мутант №1 ПОКАЗАЛ ненуль в СВОЁМ оракуле (queue_dropped), и только в нём"
else
  echo "[мутанты] мутант №1 НЕ показал ожидаемого зеркального рисунка — способность оракула НЕ доказана"
  FAIL=1
fi

echo
echo "=== прогон 2/3 — мутант №2: REFLEX_LAB_TINY_RCVBUF=1024 (user_dropped обязан уйти от нуля) ==="
OUT2=$(docker compose run --rm -e REFLEX_LAB_TINY_RCVBUF=1024 engine 2>&1) || true
echo "$OUT2"
M2=$(echo "$OUT2" | metric)
QD2=$(field "$M2" queue_dropped); UD2=$(field "$M2" user_dropped); OV2=$(field "$M2" overrun)
echo "[мутанты] мутант №2: queue_dropped=$QD2 user_dropped=$UD2 overrun=$OV2"
# КРИТЕРИЙ СУЖЕН относительно спеки (Д8/прогона 10.09): та цифра «строки Overrun пошли (×8)» была
# снята ДО задачи 8 — тогда `QueueError::Overrun` печатался текстом (`report!("очередь {}: {why:?}")`
# в старом `Running::run`). После переезда (§8/§9.4) `Overrun` стал буквой `DetectorEvent::Torn`,
# и ВСЕ приборы (`instrument/src/{retransmit,detect}.rs`) на ней молча сбрасывают окно — ни один не
# эмитит `Distress`. Текста «Overrun» в логе примера теперь не бывает НИ ПРИ КАКОМ устройстве
# мутанта: это не промах мутанта, а следствие архитектуры после задачи 8/9 (см. отчёт T13, «что не
# сошлось»). Критерий здесь — только счётчик ядра, тот же, которым потом мерят боевую частоту.
if [ "${UD2:-0}" -gt 0 ] 2>/dev/null && [ "${QD2:-1}" = 0 ]; then
  echo "[мутанты] мутант №2 ПОКАЗАЛ ненуль в СВОЁМ оракуле (user_dropped), и только в нём"
  if [ "${OV2:-0}" = 0 ]; then
    echo "[мутанты] ПРИМЕЧАНИЕ: строк Overrun в логе НЕТ (ожидалось брифом) — см. докблок выше и отчёт T13"
  fi
else
  echo "[мутанты] мутант №2 НЕ показал ожидаемого зеркального рисунка — способность оракула НЕ доказана"
  FAIL=1
fi

if [ "$FAIL" != 0 ]; then
  echo
  echo "[мутанты] КРАСНО: способность показать ненуль не доказана — боевой прогон дальше не идёт,"
  echo "[мутанты] его ноль был бы неотличим от «не измерено»"
  exit 1
fi

echo
echo "=== прогон 3/3 — боевой (без мутантов): ноль теперь РЕЗУЛЬТАТ, не недостаток разрешающей способности ==="
OUT3=$(docker compose run --rm engine 2>&1) || true
echo "$OUT3"
M3=$(echo "$OUT3" | metric)
echo "[мутанты] боевой прогон: $M3"
echo "[мутанты] ЗЕЛЕНО: оба оракула доказанно способны показать ненуль (прогоны 1-2); боевая частота — прогон 3"
