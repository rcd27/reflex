#!/bin/sh
# Сверка двух краёв (задача 11): множества «род беды + цель» из логов ct-движка и местного движка
# ОБЯЗАНЫ совпасть — не потому что один переписан по образцу другого, а потому что оба смотрели на
# ОДИН И ТОТ ЖЕ трафик (докблок `run.sh`: `queue num 200`, затем `queue num 201`, одна цепочка) и
# считают ОДИН И ТОТ ЖЕ закон `EdgeView`, каждый своим носителем.
#
# СРАВНИВАЮТСЯ МНОЖЕСТВА, НЕ ПОСЛЕДОВАТЕЛЬНОСТИ. Порядок между двумя процессами не определён — кто
# из них первым дотикал до подтверждения решает планировщик, не закон. Требовать порядка значило бы
# краснеть на планировщике вместо расхождения о мире.
#
# ПОРОГ ПУСТОТЫ — обязателен. Если оба множества пусты, зелёный не засчитывается: стенд согласовал
# два молчания, а не два наблюдения. Цена этой ошибки уже была заплачена однажды («закон был зелен
# на пустом окне», §10) — второй раз не платим: ниже стоит явный отказ, а не тихий `diff` двух
# пустых файлов (у которых разницы, конечно, нет — и зелёный был бы ЛОЖЬЮ).
set -eu

usage() {
  echo "использование: $0 <лог ct-движка> <лог local-движка>" >&2
  exit 2
}
[ "$#" -eq 2 ] || usage

extract() { grep -oE '(подтверждено|подозрение)[^«]*«[^»]+»' "$1" | sort -u; }

extract "$1" >/tmp/ct.set
extract "$2" >/tmp/local.set

if [ ! -s /tmp/ct.set ] && [ ! -s /tmp/local.set ]; then
  echo "ПУСТО С ОБЕИХ СТОРОН — стенд не наблюдал ничего, зелёный этим не считается" >&2
  exit 2
fi

if diff -u /tmp/ct.set /tmp/local.set; then
  echo "совпали: $(wc -l </tmp/ct.set) наблюдений"
else
  echo "РАСХОЖДЕНИЕ краёв — улика против закона EdgeView, а не против стенда" >&2
  exit 1
fi
