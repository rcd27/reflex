#!/bin/sh
# Сверка двух краёв (задача 11) — по СЧЁТУ, не по множеству. Топология nft (почему движки стоят в
# двух отдельных цепочках одного хука, а не в одной) объяснена в `../README.md`, раздел «edges/ —
# дифференциальный стенд (задача 11)»; здесь — только сверка.
#
# МУЛЬТИМНОЖЕСТВО, НЕ МНОЖЕСТВО. Первая редакция сверяла множества (`sort -u`) — порядок между двумя
# процессами и правда не определён (кто из них первым дотикал до подтверждения решает планировщик,
# не закон), но `sort -u` вместе с порядком стёр и КОЛИЧЕСТВО: 20 «подозрений» и 1 «подозрение»
# печатались бы одной и той же строкой, и местный край, потерявший 19 из 20 повторов, дал бы тот же
# зелёный вердикт, что и целый счёт. Порядок снимается СЧЁТОМ вхождений, а не их устранением: счёт,
# как и дедуп, безразличен к порядку (оба сортируют), но, в отличие от дедупа, сохраняет количество.
# Мутант, доказывающий именно эту способность красить (а не только «вид беды исчез целиком»),
# описан в `../README.md` (раздел «Два мутанта») и в отчёте задачи 11 — местный край теряет
# `opened` у каждого второго ПОТОКА, не каждый второй кадр.
#
# ДОПУСК — ЧИСЛОМ, не «на всякий случай». `TOLERANCE` (по умолчанию 0) — максимальная разница
# счётчиков одной пары «род беды, цель» между ct и local, при которой пара ещё считается совпавшей.
# Ноль — это ИЗМЕРЕННОЕ значение, не предположение: несколько живых прогонов исправной машины дали
# счётчики, совпадающие ТОЧНО (число — в отчёте задачи 11, раздел «Живой прогон»), потому что оба
# движка стоят на одном и том же проводе и видят один и тот же пакет — Retransmit читает провод
# напрямую (не через край), а NoBytes/Blackhole у EdgeSilence переходят Suspected→Confirmed РОВНО
# ОДИН раз на поток и дальше молчат (см. `instrument/src/edge_detect.rs`), так что гонки на границе
# прогона (kill в конце `run.sh`) считать было ровно нечего. Если следующий прогон на другой машине
# покажет шум — меняй `TOLERANCE`, но запиши здесь свежий замер, а не старое число.
#
# КЛЮЧ НЕСЁТ РОД БЕДЫ, А НЕ ОДНУ УВЕРЕННОСТЬ. Первая редакция ключевала регуляркой
# `(подтверждено|подозрение)[^«]*«[^»]+»` — она ловит слово ПЕРЕД целью, а род беды в строках
# `edges_main.rs` стоит ПОСЛЕ неё. Четыре рода схлопывались в два ключа: `Retransmit` был неотличим
# от `Diverged`, `NoBytes` от `Blackhole`. Замеренное следствие хуже потери разрешения: счётчики
# складываются, и лишний `Diverged` у одного края КОМПЕНСИРОВАЛ бы недосчёт подозрений у другого —
# стенд остался бы зелёным ровно там, где обязан краснеть. Способность краснеть была у́же заявленной.
#
# ДВА СЛОВА ХВОСТА, не весь хвост: у всех четырёх родов первые два слова после цели различны
# (`отдал запрос,` / `не ответил` / `blackhole —` / `чужая метка`), а с третьего пойдут ЧИСЛА —
# миллисекунды повтора и чужая метка hex'ом. Числа у двух краёв законно разные, и попади они в ключ,
# совпасть не смог бы ни один. Нормализовать их не выйдет: цель бывает БЕЗЫМЯННОЙ и ключуется
# адресом (`TargetKey::Unnamed`), так что `[0-9]+ → N` по всей строке склеил бы разные цели в одну.
#
# Замер на образце всех четырёх строк реакции: старая регулярка даёт для одной цели 2 ключа, новая —
# 4, и два разных безымянных адреса остаются двумя ключами (отчёт финальных правок, раздел I7).
#
# ПОРОГ ПУСТОТЫ — обязателен. Если оба мультимножества пусты, зелёный не засчитывается: стенд
# согласовал два молчания, а не два наблюдения (§10, «закон был зелен на пустом окне»).
set -eu

usage() {
  echo "использование: $0 <лог ct-движка> <лог local-движка>" >&2
  exit 2
}
[ "$#" -eq 2 ] || usage

TOLERANCE=${TOLERANCE:-0}

# Строка "<счёт> <TAB> <уверенность>: «<цель>» <род беды>" — `sort | uniq -c` считает вхождения,
# не убирает их.
extract() {
  grep -oE '(подтверждено|подозрение): «[^»]+» [^ ]+ [^ ]+' "$1" | sort | uniq -c \
    | sed -E 's/^[[:space:]]*([0-9]+)[[:space:]]+/\1\t/'
}

extract "$1" >/tmp/ct.count
extract "$2" >/tmp/local.count

if [ ! -s /tmp/ct.count ] && [ ! -s /tmp/local.count ]; then
  echo "ПУСТО С ОБЕИХ СТОРОН — стенд не наблюдал ничего, зелёный этим не считается" >&2
  exit 2
fi

# Ключуем по «уверенность + цель + род беды», сравниваем счётчики с допуском. Печатаем ВСЕ ключи с обеих сторон
# (не только разошедшиеся) — глазами видно и совпадение, и то, чего не хватило, без второго прогона.
STATUS=0
awk -F'\t' -v tol="$TOLERANCE" '
  NR == FNR { a[$2] = $1; next }
  { b[$2] = $1 }
  END {
    mismatch = 0
    for (k in a) seen[k] = 1
    for (k in b) seen[k] = 1
    for (k in seen) {
      av = (k in a) ? a[k] : 0
      bv = (k in b) ? b[k] : 0
      d = av - bv; if (d < 0) d = -d
      flag = (d > tol) ? "  <-- РАСХОЖДЕНИЕ" : ""
      if (d > tol) mismatch = 1
      printf "  ct=%-4d local=%-4d  %s%s\n", av, bv, k, flag
      total += av
    }
    print "___TOTAL___" total
    exit mismatch
  }
' /tmp/ct.count /tmp/local.count >/tmp/edges.diff || STATUS=$?
grep -v '^___TOTAL___' /tmp/edges.diff
TOTAL=$(grep '^___TOTAL___' /tmp/edges.diff | sed 's/^___TOTAL___//')

if [ "$STATUS" = 0 ]; then
  echo "совпали (допуск ±$TOLERANCE): $TOTAL наблюдений у ct"
else
  echo "РАСХОЖДЕНИЕ краёв — улика против закона EdgeView, а не против стенда" >&2
  exit 1
fi
