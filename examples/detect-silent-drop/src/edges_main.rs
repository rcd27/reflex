//! Дифференциальный стенд (задача 11): ОДНА цепочка `.from(Tcp).extract(Sni).detect(...)`, ДВА
//! носителя `IntoCarrier` — различие ровно то, ради чего носитель и заведён (край и дом), не
//! логика детекции. `CARRIER=ct|local` выбирает `Nfqueue::queue`/`Nfqueue::local`, `QUEUE` — номер
//! очереди netfilter: `lab/edges/run.sh` ставит движки на РАЗНЫЕ цепочки одного хука (соседние
//! приоритеты, по одному `queue num` в каждой — докблок там же называет ЗАМЕР, по которому одна
//! цепочка с двумя `queue num` отвергнута: второе правило той же цепочки недостижимо по построению
//! ядра), так что один и тот же пакет проходит оба движка последовательно, а не похожий трафик
//! по отдельности.
//!
//! ЗАЧЕМ ЭТОТ БИНАРЬ, А НЕ СОСЕД (`edge_main.rs`, задача 10, независимый A/B-свидетель второго
//! пути — трогать не велено, держится решением хозяина). `edge_main.rs` — РУЧНОЙ ядерный путь мимо
//! фасада (свой цикл, `EdgeSilence` напрямую по `CtEdge`), заведённый ДО того, как `Serves`/
//! `Bordered` обобщились по носителю. Этот файл наоборот: он ЦЕЛИКОМ фасадный
//! (`engine(...).from(...).detect(...).on(...).run()`), и его предмет — не «ядерный путь работает»,
//! а «`Nfqueue::queue` и `Nfqueue::local` ВЗАИМОЗАМЕНИМЫ в ОДНОЙ и той же дверце фасада», различие
//! только в аргументе `engine(...)`. Дифференциалу нужен именно это: запускаемый носитель, зовущий
//! `Nfqueue::local` изнутри настоящей цепочки — а витрину (`main.rs`) менять нельзя, её
//! неизменность сама служит замером готовности фасада.
//!
//! Отдельный бинарь этого же пакета — не параметр `main.rs`: этот файл живёт ради стенда в `lab/`
//! и с потребителем не пересекается.
//!
//! Формат реакции — цель в «кавычках-ёлочках»: контракт с `lab/edges/compare.sh`, который вырезает
//! из лога пары «род беды + цель» регулярным выражением `(подтверждено|подозрение)[^«]*«[^»]+»` и
//! сверяет их МНОЖЕСТВАМИ между двумя логами (докблок `compare.sh`).

use reflex::*;

fn react(target: &str, distress: Distress) {
    match distress {
        Distress::Retransmit { after_ms } => {
            report!("подозрение: «{target}» отдал запрос, ответа нет (повтор через {after_ms}мс)")
        }
        Distress::Silence { ms } => report!("подтверждено: «{target}» молчит {ms}мс"),
        Distress::NoBytes => report!("подтверждено: «{target}» не ответил вовсе"),
        // Прочие беды — не этому пайпу: здесь стоят только приборы тишины и повтора (как в main.rs).
        _ => {}
    }
}

fn main() -> Report {
    let queue: u16 = std::env::var("QUEUE")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(200);
    let local = matches!(std::env::var("CARRIER").as_deref(), Ok("local"));
    eprintln!(
        "[edges] носитель={} очередь={queue}",
        if local { "местный" } else { "ct" }
    );

    // Ветки различаются ТОЛЬКО первой строкой (носитель) — остаток цепочки идентичен дословно.
    // Держать это разницей типов (а не парой функций с общим генериком) — самое прямое доказательство
    // тезиса брифа «различие ровно одно»: компилятору без разницы, какой конкретный `IntoCarrier`
    // сюда придёт, у обеих веток общий тип возврата (`Report`), и написаны они рядом, глазами видно.
    if local {
        engine(Nfqueue::local(queue))
            .from(Tcp)
            .extract(Sni)
            .detect(Retransmit::unanswered())
            .detect(Silence::after(secs(5)))
            .on(react)
            .run()
    } else {
        engine(Nfqueue::queue(queue))
            .from(Tcp)
            .extract(Sni)
            .detect(Retransmit::unanswered())
            .detect(Silence::after(secs(5)))
            .on(react)
            .run()
    }
}
