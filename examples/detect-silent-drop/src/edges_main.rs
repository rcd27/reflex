//! Дифференциальный стенд (задача 11): ОДНА цепочка `.from(Tcp).extract(Sni).detect(...)`, ДВА
//! носителя `IntoCarrier` — различие ровно то, ради чего носитель и заведён (край и дом), не
//! логика детекции. `CARRIER=ct|local` выбирает `Nfqueue::queue`/`Nfqueue::local`, `QUEUE` — номер
//! очереди netfilter. КАК движки ставятся рядом на живом трафике (две цепочки nft, а не одна, и
//! почему) — каноническое объяснение и замер живут в `lab/README.md`, раздел «edges/ —
//! дифференциальный стенд (задача 11)», здесь не пересказываются: один предмет — один закон, второй
//! экземпляр молча разошёлся бы с первым при следующей правке.
//!
//! ЗАЧЕМ ЭТОТ БИНАРЬ, А НЕ СОСЕД (`edge_main.rs`, задача 10, независимый A/B-свидетель второго
//! пути — трогать не велено, держится решением хозяина). `edge_main.rs` — РУЧНОЙ ядерный путь мимо
//! фасада (свой цикл, `EdgeSilence` напрямую по `CtEdge`), заведённый ДО того, как `Serves`/
//! `Bordered` обобщились по носителю. Этот файл наоборот: он ЦЕЛИКОМ фасадный
//! (`engine(...).from(...).detect(...).on(...).run()`), и его предмет — не «ядерный путь работает»,
//! а «`Nfqueue::queue` и `Nfqueue::local` ВЗАИМОЗАМЕНИМЫ в ОДНОЙ и той же дверце фасада», различие
//! только в аргументе `engine(...)`. Дифференциалу нужен именно это: запускаемый носитель, зовущий
//! `Nfqueue::local` изнутри настоящей цепочки — а витрину (`main.rs`) менять нельзя, её
//! неизменность сама служит замером готовности фасада.
//!
//! Отдельный бинарь этого же пакета — не параметр `main.rs`: этот файл живёт ради стенда в `lab/`
//! и с потребителем не пересекается.
//!
//! Формат реакции — цель в «кавычках-ёлочках»: контракт с `lab/edges/compare.sh`, который вырезает
//! из лога пары «род беды + цель» регулярным выражением `(подтверждено|подозрение)[^«]*«[^»]+»` и
//! сверяет их МУЛЬТИМНОЖЕСТВАМИ (счётом, не только фактом наличия) между двумя логами — докблок
//! `compare.sh` называет, почему `sort -u` здесь не годится.

use reflex::*;

/// Реакция печатает ВЕСЬ алфавит беды, который эта цепочка (`Retransmit` + `Silence`) способна
/// произвести, ни одной беды не роняя в `_ => {}`. Паттерн «остальное молчит» скопирован из
/// `main.rs` уместно ТАМ (витрина одного use-case, лишние роды беды — шум для потребителя); здесь
/// единственная работа стенда — свидетельствовать о расхождении, и глушить половину алфавита значит
/// заранее сузить собственное свидетельство.
///
/// Особенно важен `Diverged` — сигнал «по нашим битам марки писал ДРУГОЙ АГЕНТ», то есть ровно то,
/// чем стенд с ДВУМЯ одновременными движками мог бы обнаружить их столкновение. Молчаливый
/// `_ => {}` делал бы такое столкновение структурно невидимым, и тогда нечем было бы подтвердить
/// даже то, что движки не сталкиваются, — а это предпосылка всего дифференциала.
///
/// `Rst`/`Throttled`/`Poisoned` эта цепочка произвести не может: здесь нет ни RST-, ни throttle-,
/// ни DNS-детектора (транспорт — TCP, приборы — `Retransmit` и `Silence`). `Distress::Silence{ms}`
/// не производит даже сама `Silence` — её прибор `EdgeSilence` (`instrument/src/edge_detect.rs`)
/// отдаёт только `NoBytes`/`Blackhole`/`Diverged`; имя детектора и имя беды совпадают случайно.
/// Все четыре сведены в одну ветку «не должно случиться» — exhaustive match, чтобы будущий
/// детектор без обновления реакции стал ОШИБКОЙ КОМПИЛЯЦИИ, а не тихим молчанием.
fn react(target: &str, distress: Distress) {
    match distress {
        Distress::Retransmit { after_ms } => {
            report!("подозрение: «{target}» отдал запрос, ответа нет (повтор через {after_ms}мс)")
        }
        Distress::NoBytes => report!("подтверждено: «{target}» не ответил вовсе"),
        Distress::Blackhole { after_ms } => {
            report!("подтверждено: «{target}» blackhole — SYN без ответа ({after_ms}мс)")
        }
        Distress::Diverged { theirs } => report!(
            "подозрение: «{target}» чужая метка 0x{theirs:08x} — возможное столкновение движков"
        ),
        Distress::Silence { .. }
        | Distress::Rst
        | Distress::Throttled { .. }
        | Distress::Poisoned => report!(
            "НЕОЖИДАННО для этой цепочки: «{target}» {distress:?} — детектора, рождающего это, здесь нет"
        ),
    }
}

fn main() -> Report {
    let queue: u16 = std::env::var("QUEUE")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(200);
    let local = matches!(std::env::var("CARRIER").as_deref(), Ok("local"));
    eprintln!(
        "[edges] носитель={} очередь={queue}",
        if local { "местный" } else { "ct" }
    );

    // Ветки различаются ТОЛЬКО первой строкой (носитель) — остаток цепочки идентичен дословно.
    // Держать это разницей типов (а не парой функций с общим генериком) — самое прямое доказательство
    // тезиса брифа «различие ровно одно»: компилятору без разницы, какой конкретный `IntoCarrier`
    // сюда придёт, у обеих веток общий тип возврата (`Report`), и написаны они рядом, глазами видно.
    if local {
        engine(Nfqueue::local(queue))
            .from(Tcp)
            .extract(Sni)
            .detect(Retransmit::unanswered())
            .detect(Silence::after(secs(5)))
            .on(react)
            .run()
    } else {
        engine(Nfqueue::queue(queue))
            .from(Tcp)
            .extract(Sni)
            .detect(Retransmit::unanswered())
            .detect(Silence::after(secs(5)))
            .on(react)
            .run()
    }
}
