//! # Снятая запись — тот же движок, другой мир
//!
//! Носитель называет ПЕРВАЯ строка цепочки, и всё, что ниже, от него не зависит: те же приборы,
//! тот же ключ цели, та же реакция, что в `detect-silent-drop` на живой очереди. Разница в мире, а
//! не в коде — ради этого носитель и сделан параметром.
//!
//! ## Зачем гонять запись, когда есть провод
//!
//! * **Без прав и без сети.** NFQUEUE требует `CAP_NET_ADMIN` и работающего цензора; файл не
//!   требует ничего. Диагностика уезжает туда, где сеть недоступна, — в CI, на чужую машину, в
//!   разбор жалобы пользователя, приславшего дамп.
//! * **Время идёт из файла (§8).** Окно тишины в пять секунд проходит за микросекунды: моменты
//!   букв — штампы записи, а не часы прогона. Час записи разбирается за секунды.
//! * **Один вход — один ответ.** Живой провод не обещает повторимости, запись обещает. Прибор,
//!   который «иногда молчит», на файле молчит всегда или не молчит никогда.
//!
//! ## Чего запись НЕ МОЖЕТ, и это говорит компилятор
//!
//! Записанный разговор не оборвать: `CanSever`/`CanInject` у носителя записи не реализованы, и
//! `.act(…)` с ним не соберётся (§9.1 — способность требуется в точке создания акта). Не «не
//! рекомендуется», а не собирается.
//!
//! ## Запуск
//!
//! ```sh
//! sudo tcpdump -i any -w /tmp/talk.pcap 'tcp port 443'   # снять
//! cargo run -p replay-recording -- /tmp/talk.pcap         # разобрать
//! ```

use reflex::*;

fn main() -> Report {
    // Путь — довод запуска: пример о ЧУЖОЙ записи, и зашитое имя файла сделало бы его витриной
    // одного дампа. Отсутствие довода — не паника: движок отвечает исходом, как и на любую другую
    // несостоявшуюся настройку.
    let path = std::env::args().nth(1).unwrap_or_default();

    pcap(path)
        .from(Tcp)
        .extract(Sni)
        .detect(Retransmit::unanswered()) // быстрое подозрение — по повтору клиента
        .detect(Silence::after(secs(5))) // медленное подтверждение — по возрасту разговора
        .on(|target, distress| match distress {
            Distress::Retransmit { after_ms } => {
                report!("подозрение на тихий дроп: {target} (повтор через {after_ms}мс)")
            }
            Distress::NoBytes => report!("подтверждено: {target} не ответил вовсе"),
            Distress::Blackhole { after_ms } => {
                report!("{target}: соединения не было ({after_ms}мс)")
            }
            _ => {}
        })
        .run()
}
