//! # Свой детектор в ту же дверь — расширение фреймворка
//!
//! Вижн: «описать ВСЕ сценарии через пайпы». Все — значит и те, под которые прибора в парке нет.
//! Потребитель приносит СВОЙ автомат Мили и кладёт его в `.detect(own(...))` рядом с парковыми —
//! фиксированное меню приборов перестаёт быть потолком.
//!
//! Здесь `Impatient` — потребительская переделка тишины со СВОИМ порогом (3с против парковых 5с):
//! часы идут от последнего запроса клиента, сбрасываются ответом цели, повтор их не двигает (тот же
//! урок, что и у паркового прибора: повтор — симптом тишины, не её конец). Автомат читает словарь
//! провода `Seen`; сужение из широкого `Reading` и раздачу тиков/эвикт даёт движок — потребитель
//! пишет только логику.
//!
//! ## Что показывает
//!
//! Машина живёт в ЭТОМ крейте, движок про неё ничего не знал — и всё равно гоняет её на каждый
//! поток, кормит буквами провода и тиками, собирает её слова беды в общую реакцию. Тот же
//! `Distress`, та же дверь `.on`, что и у парка.
//!
//! И тот же копредел: `.about` сводит слова СВОЕГО прибора под ключ цели, как сводил бы парковые.
//! Оси перпендикулярны — «чей автомат» и «о чём слово» друг о друге не знают.
//!
//! ## Запуск
//!
//! ```sh
//! sudo nft 'add table inet reflex_demo'
//! sudo nft 'add chain inet reflex_demo out { type filter hook output priority -150; }'
//! sudo nft 'add rule inet reflex_demo out tcp dport 443 queue num 200'
//! cargo run -p bring-your-own-detector
//! # снять правила: sudo nft 'delete table inet reflex_demo'
//! ```

use std::time::{Duration, Instant};

use reflex::*;

/// Свой порог терпения — короче паркового (5с), чтобы вердикт не спутать с прибором парка.
const PATIENCE: Duration = Duration::from_millis(3000);

/// Потребительский прибор: «цель молчит дольше терпения при живом клиенте». Состояние — момент
/// последнего запроса клиента (пусто — ждать нечего). `Copy`, как требует движок: он сеет свежую
/// копию шаблона на каждый поток.
#[derive(Clone, Copy, Default)]
struct Impatient {
    asked_at: Option<Instant>,
}

impl Mealy for Impatient {
    type In = DetectorEvent<Seen>;
    type Out = SmallVec<[Distress; 2]>;
    type Log = ();

    fn step(mut self, event: DetectorEvent<Seen>) -> (Self, Self::Out, ()) {
        // СНАЧАЛА ЗАКОН СЛЕПОТЫ, потом разбор. Прибор судит по ОТСУТСТВИЮ ответа, а буква может
        // означать, что отсутствие перестало быть свидетельством: дыра носителя (`Torn`) или
        // обрезанный кадр (`Opaque`) — ответ цели мог пройти мимо нас. Окно доказуемой тишины
        // начинается ЗАНОВО, с момента обнаружения дыры: так теряется находка, но не рождается
        // ложная. Обратный порядок — «промолчать о дыре» — выдал бы нашу слепоту за молчание сети.
        //
        // Критерий зовём ПО ИМЕНИ (`hides_observation`), а не перечисляем буквы у себя: закон один
        // на дерево, и своя копия разошлась бы с ним молча — не всякое непонятое прячет наблюдение
        // (чужой протокол виден целиком, обрезанный кадр — нет).
        if event.hides_observation() {
            self.asked_at = self.asked_at.map(|_| event.at());
            return (self, smallvec![], ());
        }
        match event {
            // Клиент попросил — завести/сдвинуть часы (повтор `Resent` сюда не входит: он их не трогает).
            DetectorEvent::Packet {
                input:
                    Seen::Sent { .. }
                    | Seen::Payload {
                        from_client: true, ..
                    },
                at,
            } => self.asked_at = Some(at),

            // Цель ответила или разговор кончился — тишины нет, часы гасим. ПОВТОР ЦЕЛИ тоже
            // гасит: предмет этого прибора — «цель молчит», а повторяющая цель говорит. Что её
            // повтор есть улика другого рода (ответы не доходят) — предмет другого прибора, и
            // компилятор привёл сюда именно затем, чтобы автор это решил, а не проглядел.
            DetectorEvent::Packet {
                input:
                    Seen::Received { .. }
                    | Seen::Restated { .. }
                    | Seen::Payload {
                        from_client: false, ..
                    }
                    | Seen::Closed { .. },
                ..
            } => self.asked_at = None,

            // Тик: ждём при живом запросе — за порогом высказываемся раз и гасим часы.
            DetectorEvent::Tick { at, .. } => {
                if let Some(since) = self.asked_at {
                    if at.duration_since(since) >= PATIENCE {
                        self.asked_at = None;
                        let ms = at.duration_since(since).as_millis() as u32;
                        return (self, smallvec![Distress::Silence { ms }], ());
                    }
                }
            }

            // Повтор в тишину часов не двигает: повтор — симптом тишины, не её конец. Тот же
            // урок, что у паркового прибора, и назван он ОТДЕЛЬНОЙ ветвью, а не заглушкой.
            DetectorEvent::Packet {
                input: Seen::Resent { .. },
                ..
            } => {}

            // Непонятое, не прячущее наблюдения (чужой протокол, чужой порт): кадр виден целиком,
            // просто он не наш. Часы не трогаем — свидетельство цело.
            DetectorEvent::Opaque { .. } => {}

            // Дыра носителя сюда не доходит: её перехватил закон слепоты выше. Ветвь названа,
            // чтобы АЛФАВИТ БЫЛ ЗАКРЫТ ПОЛНОСТЬЮ — заглушки `_` здесь нет нарочно: появится в
            // алфавите пятая буква, и компилятор приведёт автора прибора сюда, вместо того чтобы
            // дать ей молча провалиться в «ничего не делаем».
            DetectorEvent::Torn { .. } => {}
        }
        (self, smallvec![], ())
    }
}

fn main() -> Report {
    engine(Nfqueue::queue(200))
        .from(Tcp)
        .extract(Sni)
        .detect(own(Impatient::default())) // СВОЙ автомат, не из парка — в ту же дверь
        // Копредел не спрашивает, чей автомат сказал слово: он сводит слова РАЗГОВОРОВ под ключ
        // цели, а откуда они взялись — из парка или отсюда — его не касается. Оси перпендикулярны:
        // свой прибор × слово о цели собирается так же, как парковый × слово о цели.
        .about(|words| {
            // Величина у слова о цели — МИНИМУМ по разговорам: столько цель молчит НАВЕРНЯКА.
            // Возьми максимум — и число говорило бы о самом невезучем потоке, а не о цели.
            let waited: Vec<u32> = words
                .iter()
                .map(|distress| match distress {
                    Distress::Silence { ms } => Some(*ms),
                    _ => None,
                })
                .collect::<Option<Vec<u32>>>()?; // хоть одно слово не о тишине — цель не молчит
            waited.into_iter().min().map(|ms| Distress::Silence { ms })
        })
        .on_target(|target, voiced| {
            if voiced.since < secs(1) {
                report!(
                    "свой прибор о ЦЕЛИ: {target} — {}",
                    voiced.distress.detail()
                )
            }
        })
        .on(|target, distress| {
            if let Distress::Silence { ms } = distress {
                report!("свой прибор поймал тишину: {target} молчит {ms}мс (порог 3с)")
            }
        })
        .run()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn asked(at: Instant) -> DetectorEvent<Seen> {
        DetectorEvent::Packet {
            input: Seen::Sent { count: 517 },
            at,
        }
    }

    fn tick(at: Instant) -> DetectorEvent<Seen> {
        DetectorEvent::Tick { node: 1, at }
    }

    /// Половина первая: прибор ВООБЩЕ УМЕЕТ высказаться. Без неё второй тест зелен и на приборе,
    /// который молчит всегда, — а такой прибор проверяет не закон, а собственную немоту.
    #[test]
    fn терпение_кончается_и_прибор_говорит() {
        let t0 = Instant::now();
        let (probe, _, _) = Impatient::default().step(asked(t0));
        let (_, said, _) = probe.step(tick(t0 + Duration::from_millis(3500)));

        assert_eq!(said.as_slice(), [Distress::Silence { ms: 3500 }]);
    }

    /// Половина вторая — ПРЕДМЕТ: между просьбой и порогом носитель объявил дыру. Ответ цели мог
    /// пройти мимо нас, и молчать о собственной слепоте значило бы выдать её за молчание сети.
    /// Окно доказуемой тишины начинается с момента обнаружения дыры, и трёх секунд в нём ещё нет.
    #[test]
    fn дыра_носителя_не_становится_уликой_против_цели() {
        let t0 = Instant::now();
        let (probe, _, _) = Impatient::default().step(asked(t0));
        let (probe, said, _) = probe.step(DetectorEvent::Torn {
            at: t0 + Duration::from_millis(1000),
        });
        assert!(said.is_empty(), "дыра сама по себе уликой не является");

        let (_, said, _) = probe.step(tick(t0 + Duration::from_millis(3500)));

        assert!(
            said.is_empty(),
            "после дыры доказуемой тишины лишь 2.5с — прибор обязан молчать, а сказал {said:?}"
        );
    }
}
