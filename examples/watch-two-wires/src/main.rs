//! # Две цепочки рядом — набор (Опр. 9.8), а не две нити
//!
//! У потребителя редко один провод. TCP 443 и DNS 53 — разные транспорты, разные словари провода,
//! разные очереди ядра: одну очередь двум цепочкам не поделить, а словарь датаграмм не словарь
//! потока. Собрать их можно двумя способами, и они не равны.
//!
//! * **Нить на цепочку.** Два порядка событий, два владельца знания — и замок там, где потребитель
//!   сводит одно с другим. Замер переезда: пятнадцать замков до цепочки, ноль после; набор в
//!   отдельных нитях вернул бы их обратно.
//! * **Набор.** Цепочки крутятся в ОДНОЙ нити по кругу и отдают показания одним потоком. Владелец
//!   знания один, замков нет.
//!
//! Набор — ДРАЙВЕР, а не объект модели (Опр. 9.8): он не композирует машины (композиция проводит
//! влияние, а здесь его нет), не смешивает их слова и своего состояния не имеет. Оттого и
//! предъявимость (§10) остаётся свойством ЦЕПОЧКИ: у набора нет поведения, о котором можно
//! свидетельствовать (Следствие 9.9), и «сколько цепочек сказали за окно» считает тот, кто набор
//! собрал.
//!
//! ## Что этот пример показывает
//!
//! 1. **Отказ одной — значение, а не падение набора.** Цепочка, чей носитель не открылся, лежит в
//!    [`Together::refused`], остальные работают. Смотреть его нужно ДО прогона: проглотишь — и
//!    продукт молча уменьшился, а выглядит он при этом работающим.
//! 2. **Показания всех цепочек одним потоком** — `for note in chorus`.
//! 3. **Ход без показания** (Утв. 9.10) — `within(окно)`. Машина потребителя, которой время нужно
//!    САМО ПО СЕБЕ (досмотреть срок, прочесть ответ, пришедший не проводом), не обязана ждать
//!    пакета: её темп перестаёт быть темпом трафика. Три клетки исхода обитаемы порознь (§7):
//!    `Said` — сказали; `Quiet` — провод молчал, машины живы; `Ended` — источники кончились.
//!    Слить две последние значило бы объявить тишину концом работы.
//!
//! ## Цена, названная числом
//!
//! * **Окно открытия.** `chain` открывает носитель СРАЗУ: отказ обязан стать значением здесь, а не
//!   посреди чужих показаний. Значит первая очередь копит пакеты в ядре, пока открываются
//!   остальные. На редкой очереди незаметно, на плотной — прямая потеря, и видна она счётчиком
//!   ядра, а не нашим.
//! * **Задержка показания.** Оборот соседок — сумма их сроков; показание может подождать столько.
//!   Плата за одну нить и отсутствие замков.
//!
//! ## Чего здесь нет
//!
//! Слова о ЦЕЛИ (`.about(…).on_target(…)`) в общий поток не едут: там слово РАЗГОВОРА, а спуск
//! между слоями не определён (§5, §12.2). Цепочка со свёрткой в набор входит — слово о цели уходит
//! её замыканием, из того же оборота и той же нити.
//!
//! ## Запуск
//!
//! ```sh
//! sudo iptables -I OUTPUT -p tcp --dport 443 -j NFQUEUE --queue-num 250
//! sudo iptables -I OUTPUT -p udp --dport 53  -j NFQUEUE --queue-num 252
//! sudo -E cargo run -p watch-two-wires
//! ```
//!
//! Без прав пример честно откажет обеими цепочками и скажет, чего не хватает, — это и есть
//! пункт 1. Работу набора на сочинённом проводе, без прав и без сети, показывают тесты ниже.

use reflex::*;

/// Сколько ждём хода, прежде чем заняться своими делами. Не сон: показание вернёт раньше.
const TURN: std::time::Duration = std::time::Duration::from_millis(200);

fn main() {
    let together = together()
        .chain(
            engine(Nfqueue::queue(250))
                .from(Tcp)
                .extract(Sni)
                .detect(Silence::after(secs(5))),
        )
        .chain(
            engine(Nfqueue::queue(252))
                .from(Udp)
                .extract(Sni)
                .detect(DnsPoison::injected()),
        );

    // ДО ПРОГОНА, и это не порядок ради порядка: цепочка, не поднявшаяся молча, уменьшает продукт
    // ровно настолько, насколько её предмет был нужен, — а набор при этом выглядит работающим.
    for refused in together.refused() {
        report!(
            "цепочка не поднялась: {}",
            refused.why().unwrap_or("без причины")
        );
    }

    let mut chorus = together.heard();
    // СВОЯ МАШИНА ПОТРЕБИТЕЛЯ — та, ради которой нужен ход без показания. Здесь она простая: ведёт
    // счёт тихих окон. У настоящей на этом месте досмотр срока внеполосной пробы, чтение отметки,
    // разбор ответа, пришедшего не проводом.
    let mut quiet_windows = 0u32;

    loop {
        match chorus.within(TURN) {
            Turned::Said(note) => match note.word {
                Distress::NoBytes => report!("{}: не ответил вовсе", note.target),
                Distress::Silence { ms } => report!("{}: молчит {ms}мс", note.target),
                Distress::Poisoned => report!("{}: отравление DNS", note.target),
                other => report!("{}: {other:?}", note.target),
            },
            // ТИШИНА — НЕ КОНЕЦ. Провод молчал, машины живы; время наше идёт, и своя работа делается
            // ровно здесь. Без этой клетки темп машины равнялся бы темпу трафика.
            Turned::Quiet => {
                quiet_windows += 1;
                if quiet_windows % 25 == 0 {
                    report!("провод молчит {} окон подряд", quiet_windows);
                }
            }
            // КОНЕЦ — ДРУГАЯ ВЕСТЬ: источников больше нет, ждать нечего и некого.
            Turned::Ended => {
                report!(
                    "источники кончились: {} тихих окон за прогон",
                    quiet_windows
                );
                return;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use reflex::scenario::{request, syn, Paper};

    /// ПРЕДМЕТ 1: две цепочки — один поток показаний.
    ///
    /// Сочинённый провод (§11: носитель — голова выражения, всё ниже от него не зависит) — тот же
    /// набор, что в `main`, только мир написан здесь. Ни прав, ни сети: пример проверяем там, где
    /// NFQUEUE недоступна.
    #[test]
    fn two_wires_speak_into_one_stream() {
        let heard: Vec<Note> = together()
            .chain(
                engine(
                    Paper::new()
                        .then_packet(syn(40001))
                        .then_packet(request(40001))
                        .silent_for(secs(6))
                        .then_stop(),
                )
                .from(Tcp)
                .extract(Sni)
                .detect(Silence::after(secs(5))),
            )
            .chain(
                engine(
                    Paper::new()
                        .then_packet(syn(40002))
                        .then_packet(request(40002))
                        .silent_for(secs(6))
                        .then_stop(),
                )
                .from(Tcp)
                .extract(Sni)
                .detect(Silence::after(secs(5))),
            )
            .heard()
            .collect();

        assert!(
            heard.len() >= 2,
            "оба провода молчали дольше порога — сказать обязаны оба, а сказано {}: {heard:?}",
            heard.len()
        );
    }

    /// ПРЕДМЕТ 2: ход возвращается ПО СРОКУ, а не по пакету (Утв. 9.10).
    ///
    /// Провод молчит секунду; окно хода — пятьдесят миллисекунд. Набор обязан вернуть управление
    /// внутри окна и назвать тишину тишиной, а не концом работы: слить `Quiet` с `Ended` значило бы
    /// объявить молчащий провод мёртвым.
    ///
    /// Секунда, а не тридцать: часы бумаги двигаются НА ВЕЛИЧИНУ ОКНА (докблок `Paper::serve` —
    /// срок исполняется движением своих часов, не сном), и молчание длиной в тридцать секунд
    /// потребовало бы полутора тысяч ходов по двадцать миллисекунд, чтобы кончиться.
    #[test]
    fn a_silent_wire_still_gives_the_turn_back() {
        let mut chorus = together()
            .chain(
                engine(Paper::new().silent_for(secs(1)).then_stop())
                    .from(Tcp)
                    .extract(Sni)
                    .detect(Silence::after(secs(5))),
            )
            .heard();

        let turned = chorus.within(std::time::Duration::from_millis(50));

        assert!(
            matches!(turned, Turned::Quiet),
            "провод молчал — обязан быть ход с тишиной, а не удержание потребителя: {turned:?}"
        );

        // ВТОРАЯ ПОЛОВИНА, без которой первая ничего не стоит: дверь, отвечающая «тихо» ВСЕГДА,
        // прошла бы проверку выше и была бы при этом сломана насмерть. Конец обязан наступить и
        // назваться концом.
        let ended = (0..200).any(|_| {
            matches!(
                chorus.within(std::time::Duration::from_millis(20)),
                Turned::Ended
            )
        });

        assert!(
            ended,
            "источник исчерпан — набор обязан сказать `Ended`, а не молчать тишиной вечно"
        );
    }
}
