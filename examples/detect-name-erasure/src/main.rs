//! # Стирание имени: разговор, который кончается ДО транспорта
//!
//! Клиент спросил адрес и получил «такого имени нет». Дальше не происходит НИЧЕГО: `SYN` не
//! отправлен, рукопожатия нет, сбрасывать нечего. Всякий транспортный прибор молчит — и молчит
//! законно, разговора не было, — а человек видит ровно тот же исход, что от сброса или блэкхола:
//! «сайт не открывается».
//!
//! ## Улика — один бит
//!
//! Рекурсор не авторитетен для чужой зоны: не найдя имени, он отвечает `NXDOMAIN` БЕЗ флага `AA`.
//! Подделке на пути нужен ОКОНЧАТЕЛЬНЫЙ ответ (иначе клиент пойдёт спрашивать дальше), и она
//! присваивает себе авторитетность, которой у отвечающего нет. На этом различии и стоит прибор.
//!
//! Оно же объясняет, почему `NXDOMAIN` сам по себе молчит: поиск по суффиксам (`resolv.conf
//! search`) получает его на каждое имя по разу, и прибор, кричащий на всякий отказ, был бы шумом.
//!
//! ## Чем отличается от [`DnsPoison`] (`detect-dns-poisoning`)
//!
//! Предметом. Отравление судит ПАРУ «запрос · ответ» — пришёл ли на просьбу инжект, — и одиночный
//! отказ ему не улика: оракулом там служит ПОВТОР, имя не отвечает никому, сколько ни спрашивай.
//! Здесь судится САМ ОТВЕТ, и одного достаточно. Приборы дополняют друг друга и стоят рядом.
//!
//! ## Слово своё, не `Distress`
//!
//! Цепочка говорит [`Resolved`]: «имя разрешилось честно» бедой не является, и выразить его
//! алфавитом бед нечем. Словарь цепочки берётся от прибора — см. `bring-your-own-detector`.
//!
//! ## Запуск
//!
//! ```sh
//! sudo nft 'add table inet reflex_demo'
//! sudo nft 'add chain inet reflex_demo inp { type filter hook input priority -150; }'
//! sudo nft 'add rule inet reflex_demo inp udp sport 53 queue num 201'
//! sudo nft 'add chain inet reflex_demo out { type filter hook output priority -150; }'
//! sudo nft 'add rule inet reflex_demo out udp dport 53 queue num 201'
//! cargo run -p detect-name-erasure
//! # снять правила: sudo nft 'delete table inet reflex_demo'
//! ```

use reflex::*;

fn main() -> Report {
    engine(Nfqueue::queue(201))
        .from(Udp)
        .extract(Sni)
        .detect(Resolve::names())
        .on(|target, resolved| match resolved {
            // СТИРАНИЕ с уликой: отвечающий присвоил себе авторитетность. Лечить нечего — цели у
            // клиента нет вовсе; продукт обязан хотя бы НАЗВАТЬ причину, потому что человек видит
            // «сайта не существует» и верит этому.
            Resolved::Erased {
                how: Erasure::Denied,
                ..
            } => report!("имя стёрто на пути: {target} — отказ с присвоенной авторитетностью"),
            // Ответ без адреса: цели тоже нет, но вмешательства это не доказывает — у имени может
            // не быть записи `A` честно (только `AAAA`, только `MX`). Слово несёт способ, и
            // разница в силе улики видна прямо здесь, в реакции.
            Resolved::Erased {
                how: Erasure::NoAddress,
                ..
            } => report!("имя не дало адреса: {target} — цели нет, вмешательство не доказано"),
            // Увод: публичное имя разрешилось в частный адрес. Настоящие адреса называются рядом —
            // по ним видно, осталось ли имя достижимым помимо заглушки.
            Resolved::Hijacked { to, alongside, .. } => report!(
                "резолв уведён: {target} → {to:?}, рядом настоящие {alongside:?}"
            ),
            // Честный ответ — не беда, и в отчёт не идёт. Он здесь ради полноты алфавита: цепочка
            // видит ВСЕ исходы разрешения имени, а не только плохие.
            Resolved::Honest { .. } => (),
        })
        .run()
}
