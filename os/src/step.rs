//! Шаг как морфизм с ОБЛАСТЬЮ ОПРЕДЕЛЁННОСТИ (#152).
//!
//! Мы искали примитив, несущий четыре вещи разом: готовность шага, перезапускаемость,
//! обработку ошибок и наблюдение состояния. Это не четыре свойства, а одна известная
//! структура — restriction category (Cockett–Lack, 2002): категория, где каждому
//! морфизму `f` сопоставлен идемпотент `f̄`, его область определённости.
//!
//! Отображение один в один:
//!
//! | требование | структура | здесь |
//! |---|---|---|
//! | готовность | `f̄` | `guard: Level<bool>` |
//! | наблюдаемость | `f̄` вычислим, не выполняя `f` | `ready()` |
//! | ошибки | Клейсли над `Result` | `StepOutcome::Failed` |
//! | перезапускаемость | `f ∘ f = f` | ЗАКОН (property-тест), не флаг |
//!
//! Аксиома `f ∘ f̄ = f` («проверка готовности ничего не меняет») здесь не декорация:
//! именно она разрешает читать готовность в любой момент и печатать её — то есть даёт
//! ответ на вопрос «где мы застряли», которого сегодня в субстрате нет ни у кого.

use crate::Level;
use std::sync::Arc;

/// Исход попытки. ТРИ конструктора, а не два — и это прямая проекция молекулы
/// `model/infra/GuardedRepair`.
///
/// `NotReady` и `Failed` разведены намеренно: **отсутствие успеха не является уликой
/// поломки**. Пока оба случая живут в одном `Err`, страж обязан их спутать — и сожжёт
/// рабочий одноразовый кред, приняв «сети не было» за «идентичность сломана»
/// (контрпример `onstuck`, воспроизводящий штатную загрузку рига). Здесь спутать
/// нельзя: разные конструкторы, exhaustive match.
#[derive(Debug, PartialEq, Eq)]
pub enum StepOutcome<B, E> {
    Advanced(B),
    NotReady,
    Failed(E),
}

/// Шаг: охраняемое действие.
///
/// Внутреннее действие возвращает `StepOutcome`, а НЕ `Result`, и это вскрыла сама
/// композиция: `then` обязан уметь сказать «голова отработала, а хвост не готов», а
/// `Result` такого конструктора не имеет. Тип, в котором это невыразимо, вынуждает
/// либо соврать успехом, либо соврать ошибкой — оба вранья и есть тот дефект, из-за
/// которого страж жжёт рабочий кред.
pub struct Step<A, B, E> {
    guard: Level<bool>,
    run: Arc<dyn Fn(A) -> StepOutcome<B, E> + Send + Sync>,
}

impl<A: 'static, B: 'static, E: 'static> Step<A, B, E> {
    /// Собрать шаг из обычного `Result`-действия: неготовность добавляет охрана.
    pub fn new(
        guard: Level<bool>,
        run: impl Fn(A) -> Result<B, E> + Send + Sync + 'static,
    ) -> Step<A, B, E> {
        Step {
            guard,
            run: Arc::new(move |input| match run(input) {
                Ok(out) => StepOutcome::Advanced(out),
                Err(err) => StepOutcome::Failed(err),
            }),
        }
    }

    /// Готов ли шаг — БЕЗ выполнения. Наблюдение, а не действие.
    pub fn ready(&self) -> bool {
        self.guard.get()
    }

    /// Попытаться продвинуться. Неготовность — не ошибка и ошибкой не притворяется.
    pub fn attempt(&self, input: A) -> StepOutcome<B, E> {
        match self.guard.get() {
            false => StepOutcome::NotReady,
            true => (self.run)(input),
        }
    }

    /// Последовательная композиция.
    ///
    /// Готовность композита — готовность ГОЛОВЫ, а не встреча готовностей, и это не
    /// упрощение, а единственное честное определение. Готовность хвоста вычислима лишь
    /// ПОСЛЕ эффекта головы (в терминах restriction-категории — откат `ḡ` вдоль `f`, а
    /// откатывать, не выполнив `f`, нечем). У нас это не теоретическая тонкость:
    /// `start_dataplane` САМ делает истинной готовность `await_witness`. Объяви мы
    /// встречу — композит не был бы готов никогда.
    ///
    /// Отсюда же требование к голове: если хвост не готов, цикл повторит ВЕСЬ композит,
    /// значит голова обязана быть перезапускаемой (`f ∘ f ≡ f`). Перезапускаемость
    /// перестаёт быть пожеланием и становится условием композиции.
    pub fn then<C: 'static>(self, next: Step<B, C, E>) -> Step<A, C, E> {
        let head = self.run.clone();
        let tail = next.run.clone();
        let tail_guard = next.guard;
        Step {
            guard: self.guard,
            run: Arc::new(move |input| match head(input) {
                StepOutcome::NotReady => StepOutcome::NotReady,
                StepOutcome::Failed(err) => StepOutcome::Failed(err),
                StepOutcome::Advanced(middle) => match tail_guard.get() {
                    false => StepOutcome::NotReady,
                    true => tail(middle),
                },
            }),
        }
    }
}
