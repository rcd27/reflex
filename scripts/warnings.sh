#!/usr/bin/env bash
# Бюджет предупреждений — ОДНА команда, а не три вперемешку.
#
# 10.09.2026 бюджет «9 предупреждений» ни разу не был привязан к конкретной команде: за один день
# его мерили тремя разными способами и получали 9, 5 и 28 — и ни один прогон не включал
# `--all-targets`. Без него не собираются интеграционные тесты (`reflex/tests/*.rs`), а именно там
# жили шестнадцать предупреждений, которые никто не заметил. Счёт без `--all-targets` у́же
# собственного критерия проекта («зелено» значит «весь workspace, включая тесты»), а не просто
# неполон — он МОЛЧА врёт о том, что проверено.
#
# Поэтому здесь ровно одна команда, число при ней и вывод самих строк — следующий не подбирает
# свою.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

# Ожидаемое число ПОСЛЕ уборки 10.09.2026 (задача «малая уборка за собой»): шесть чужих
# предсуществующих предупреждений в тестовых целях `certify_replays`, `edge_word`, `flow_table`,
# `flow_identity` (2 шт.) и нестандартное имя функции в `reflex/tests/own_word.rs` — файле соседней
# сессии, который эта уборка не трогает.
EXPECTED=2

OUT="$(cargo build --workspace --all-targets 2>&1)"

# Настоящее предупреждение — строка вида `warning: <текст>`. Строку-агрегат вида
# "warning: `крейт` (...) generated N warnings" cargo печатает ПОСЛЕ каждой цели с
# предупреждениями — это не отдельное предупреждение, а сводка уже посчитанных, и второй раз
# считать её нельзя.
REAL="$(grep '^warning:' <<<"$OUT" | grep -vc 'generated [0-9]* warning' || true)"

echo "$OUT" | grep '^warning:' | grep -v 'generated [0-9]* warning' || true
echo "---"
echo "предупреждений: $REAL (ожидание: $EXPECTED)"

if [ "$REAL" -ne "$EXPECTED" ]; then
    echo "БЮДЖЕТ РАСХОДИТСЯ с ожиданием — либо завели новое предупреждение, либо убрали старое и забыли поправить EXPECTED в этом скрипте." >&2
    exit 1
fi
