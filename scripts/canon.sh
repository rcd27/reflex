#!/usr/bin/env bash
# СТОРОЖ КАНОНА: утверждения документа о коде — прогоном, а не чтением.
#
# 10.09.2026 канон был пойман на том, что ЦЕНТРАЛЬНЫЙ раздел §1 цитирует трейт `Step` из
# `core/src/step.rs` — ни файла, ни трейта, ни одного из трёх его ассоциированных имён в дереве нет
# (переименование в `Mealy` прошло по коду и до документа не дошло). Вместе с ним нашлись `Alongside`,
# `CanReplay`, `Recording`, `Entangled` — объявленные построенными и отсутствующие.
#
# Ловится это не проверкой, а тем, что кто-то мимо шёл. У докблоков сторож есть — имя в них держит
# компилятор (`deny(rustdoc::broken_intra_doc_links)`), потому что докблок живёт в компиляторе.
# Канон живёт в markdown, где имя есть просто текст. Отсюда этот скрипт.
#
# ЧТО ОН МЕРИТ И ЧЕГО НЕ МЕРИТ. Он проверяет ССЫЛКИ — что названный адрес существует и названное имя
# встречается. Он НЕ проверяет, что утверждение о них верно: «`Entangled` делает закон §4 проверяемым»
# он подтвердит одним вхождением слова. Сторож против мёртвых имён, не против ложных доводов.
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

DOCS="docs/vision"
BAD=0

echo "── адреса файлов (всё, что названо путём с каталогом) ──"
# Многоточие в пути (`linux/.../terminal.rs`) — намеренная краткость канона, не адрес: пропускаем.
grep -ohP '`\K[a-z_0-9-]+(/[a-z_0-9.-]+)+\.(rs|sh|toml|md)(?=[`:])' "$DOCS"/*.md \
  | sort -u | while read -r path; do
    if [ ! -e "$path" ]; then
        echo "  МЁРТВ: $path"
        echo x >> /tmp/canon-bad.$$
    fi
done

echo "── имена, объявленные ПОСТРОЕННЫМИ ──"
# Список явный, а не выведенный: канон полон имён из математики (`Conversation`, `Target`), которых в
# коде нет и быть не должно. Сторож обязан отличать «имя закона» от «имя типа», а вывести это из
# markdown нечем — значит называем руками. Строка сюда добавляется вместе со ссылкой в каноне.
BUILT=(
    "Mealy" "Compose" "Id" "Lift" "MealyExt"          # §1, §3: морфизм и его категория
    "Word" "Base" "Layer" "Descends"                  # §4, §5: область и слово
    "Serves" "Terminal" "Held" "Served"               # §9: функтор носителя
    "CanHold" "CanRefuse" "CanMark" "CanSever" "CanInject" "CanRemember" "CanAsk"  # §9.1
    "Interleave" "DetectorEvent" "FlowTable"          # §2, §7: алфавит и шов
    "replays" "Replayed" "Tape" "TapeLetter"          # §10: предъявимость
    "IntoCarrier" "Distress" "Note" "Heard"           # §11: публичный синтаксис
)
# ИЩЕМ ОБЪЯВЛЕНИЕ, А НЕ УПОМИНАНИЕ. Первая редакция грепала слово целиком — и не краснела на
# мутанте `pub trait Mealy` → `pub trait Mealy2`: слово `Mealy` осталось в докблоках и в `impl … for`,
# греп его находил, сторож молчал. Мерилось УПОМИНАНИЕ, а канон утверждает ПОСТРОЙКУ; между ними
# ровно та разница, из-за которой этот скрипт и заведён.
for name in "${BUILT[@]}"; do
    hits=$(grep -rE --include='*.rs' "^ *pub (trait|struct|enum|fn|type) $name\b" \
        core/src engine/src instrument/src linux/src reflex/src 2>/dev/null | wc -l)
    if [ "$hits" -eq 0 ]; then
        echo "  НЕ ПОСТРОЕНО: $name — канон называет его построенным, объявления в дереве нет"
        echo x >> /tmp/canon-bad.$$
    fi
done

BAD=$( [ -f /tmp/canon-bad.$$ ] && wc -l < /tmp/canon-bad.$$ || echo 0 )
rm -f /tmp/canon-bad.$$
echo "──"
if [ "$BAD" -ne 0 ]; then
    echo "канон расходится с деревом в $BAD месте(ах) — правьте документ или верните имя" >&2
    exit 1
fi
echo "канон и дерево сошлись: мёртвых адресов нет, названное построенным построено"
