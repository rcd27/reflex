#!/usr/bin/env bash
# ПЕРЕНОСИМОСТЬ ФУНДАМЕНТА: крейты, которые пинит потребитель, обязаны собираться там, где НЕТ
# 64-БИТНЫХ АТОМИКОВ. Признак класса именно этот, и никакой другой.
#
# 12.09.2026 релиз потребителя упал на трёх целях из девяти — `mips`, `mipsel`, `powerpc`:
# `cannot find AtomicU64 in atomic`. Держал их `AtomicU64` в `TestClock` — ТЕСТОВОМ ДУБЛЕ, который
# потребитель не исполняет никогда. Модуль `core::clock` публичный (рядом боевой `OsClock`), потому
# дубль компилировался в каждой релизной сборке и отнимал три архитектуры за код, до которого там
# не доходит управление. Для потребителя на роутерах OpenWrt это основная аудитория.
#
# ЧЕГО СТОРОЖ НЕ ЛОВИТ. Он проверяет СБОРКУ, а не поведение: тип, который на 32 битах у́же (скажем,
# `AtomicUsize` вместо `AtomicU64`), соберётся зелёным и переполнится в бою — счётчик наносекунд
# через 4,3 секунды модельного времени. Против такой починки сторожа нет, есть только докблок на
# самом поле.
#
# «32 БИТА» — НЕ ИМЯ ЭТОГО КЛАССА, и первая редакция скрипта звала его так. Замер по девяти целям
# потребителя (12.09.2026, `rustc --print cfg`) показал, что признаки расходятся:
#
#     i586        32 бита  little  атомики64 ЕСТЬ
#     arm         32 бита  little  атомики64 ЕСТЬ
#     mips        32 бита  big     атомики64 НЕТ
#     mipsel      32 бита  little  атомики64 НЕТ
#     ppc         32 бита  big     атомики64 НЕТ
#     mips64      64 бита  big     атомики64 есть
#     x86_64 · arm64 · riscv64      атомики64 есть
#
# Класс, уронивший релиз, — ровно {mips, mipsel, ppc}, и назвать его «32-битными целями» значит
# включить в него i586 и arm, которые здоровы. Цена ошибки не в словах: следующий, кто станет
# менять цель, взял бы «какую-нибудь 32-битную», сторож ослеп бы и остался ЗЕЛЁНЫМ. Тот же сорт
# беды, что `pipefail` ниже.
#
# ПОЧЕМУ `powerpc-unknown-linux-gnu`, а не `mipsel`. У него готовый `rust-std` в rustup — цель
# ставится одной командой и без `-Z build-std`. Представителем класса он годится не разрядностью:
# `mips` и `ppc` совпадают по всем четырём признакам (32 / big-endian / нет 64-битных атомиков /
# один набор ширин), и это измерено, а не предположено.
#
# ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ СВЕРХ УЖЕ СКАЗАННОГО: ПОРЯДОК БАЙТОВ. Он проявляется в ИСПОЛНЕНИИ, а
# не в типах, и `cargo check` его не увидит ни на какой цели. Big-endian у потребителя закрывается
# полной сборкой перед релизом, не здесь.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

TARGET=powerpc-unknown-linux-gnu
# Ровно те крейты, которые пинит потребитель. Носителей (`linux`, `windivert`) здесь нет намеренно:
# они привязаны к своей платформе по существу, и требовать от них 32-битного powerpc бессмысленно.
CRATES="-p reflex-core -p reflex-instrument"

# СТОРОЖ ПРОВЕРЯЕТ СОБСТВЕННУЮ ЗРЯЧЕСТЬ ПЕРВЫМ ДЕЛОМ. Цель обязана ПРИНАДЛЕЖАТЬ классу, ради
# которого он написан, — иначе он зелен и слеп. Проверяется признаком, а не именем цели: имя
# ничего не обещает, `rustc --print cfg` обещает.
if rustc --print cfg --target "$TARGET" 2>/dev/null | grep -q 'target_has_atomic="64"'; then
    echo "СТОРОЖ СЛЕП: у цели $TARGET ЕСТЬ 64-битные атомики." >&2
    echo "  Он написан против класса «атомиков на 64 бита нет» — на такой цели он не проверяет" >&2
    echo "  НИЧЕГО и будет зелен всегда. Возьмите цель, у которой признака нет:" >&2
    echo "  mips-, mipsel-, powerpc-unknown-linux-*." >&2
    exit 2
fi

if ! rustup target list --installed | grep -qx "$TARGET"; then
    echo "ЦЕЛЬ НЕ ПОСТАВЛЕНА: $TARGET" >&2
    echo "  rustup target add $TARGET" >&2
    echo "Сторож НЕ ОТРАБОТАЛ — это не «зелено», это «не проверено»." >&2
    exit 2
fi

echo "── $CRATES под $TARGET ──"

# СУДИМ ПО КОДУ ВОЗВРАТА КОМПИЛЯТОРА, а не по грепу его вывода — и это оплачено ошибкой прямо
# здесь. Первая редакция сторожа стояла так:
#
#     if cargo check … 2>&1 | tee /dev/stderr | grep -q '^error'; then … exit 1; fi
#
# и была ЗЕЛЕНА НА МУТАНТЕ: при `set -o pipefail` статусом конвейера становится ненулевой код
# упавшего `cargo`, даже когда `grep` совпадение НАШЁЛ, — и `if` читает найденную ошибку как «не
# нашлось». Сторож молчал ровно в том случае, ради которого написан. Поймано §10.1: зелёный без
# доказанной способности краснеть не считается, и закон этот держит сторожей тоже.
set +e
OUT="$(cargo check $CRATES --target "$TARGET" 2>&1)"
STATUS=$?
set -e
echo "$OUT"

if [ "$STATUS" -ne 0 ]; then
    echo "──" >&2
    echo "ФУНДАМЕНТ НЕ СОБИРАЕТСЯ НА 32 БИТАХ. Потребитель на роутере потеряет цель." >&2
    exit 1
fi
echo "──"
echo "переносимость держится: фундамент собирается там, где 64-битных атомиков нет"
