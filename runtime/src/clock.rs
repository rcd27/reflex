//! СИСТЕМНЫЕ ЧАСЫ — реализация [`reflex_core::clock::Clock`] на настоящем времени.
//!
//! Живут здесь, а не в `reflex-core`, потому что тикать значит СПАТЬ, а спать умеет только край.
//! Ядро держит контракт и виртуальные часы; рантайм добавляет единственное, чего им не хватает, —
//! будильник.
//!
//! # Зачем это вообще заводилось
//!
//! Замер 03.09.2026: семнадцать мест вне тестов порождали время сами, в пяти разных формах. Ровно
//! то, что док часов записи предсказал буквой: «часы добавляет тот, кто читает провод, и делать
//! это обязан ИСТОЧНИК, иначе всякий потребитель напишет своё, по-разному». Здесь источник один.

use core::time::Duration;
use std::time::Instant;

use futures::Stream;
use reflex_core::clock::{Clock, OsClock, Ticks};

/// ЧАСЫ ОПЕРАЦИОННОЙ СИСТЕМЫ, БУДЯЩИЕ ПОТОК СОБЫТИЙ.
///
/// Не второй тип системных часов, а вторая ФОРМА ОЖИДАНИЯ у тех же самых: `now` делегируется
/// ядерным [`OsClock`], и разойтись показаниям неоткуда. Здесь добавляется единственное, чего
/// ядру взять негде, — асинхронное пробуждение, то есть рантайм.
///
/// Разделение по крейтам следует за этим, а не за вкусом: синхронному потребителю (плоскость)
/// нужен `std::thread::sleep` и ничего больше, и заставлять его тянуть tokio ради одного треда
/// со сном значило бы брать плату за неиспользуемое.
#[derive(Debug, Clone, Copy, Default)]
pub struct SystemClock;

impl Clock for SystemClock {
    fn now(&self) -> Instant {
        OsClock.now()
    }
}

impl Ticks for SystemClock {
    /// ТИКИ ИДУТ ПО СЕТКЕ [`reflex_core::grid`] — ТОЙ ЖЕ, ЧТО У ЗАПИСИ, ТЕСТА И [`Beats`].
    ///
    /// # Прежняя редакция ДВИГАЛА СЕТКУ, и это замерено
    ///
    /// Стоял `tokio::time::interval` с `MissedTickBehavior::Delay`, и он отсчитывает следующий шаг
    /// от ОПОЗДАВШЕГО тика. При шаге 100 мс и заминке потребителя 350 мс узлы приходили на
    /// `0, 100, 450, 550, 650` вместо `0, 100, 200, 300, 400`: сетка уехала на 50 мс и такой
    /// осталась навсегда.
    ///
    /// Прежний док цену называл («окна станут чуть длиннее заказанных»), но следствие шире
    /// названного: [`Ticks`] и [`Beats`] объявлены не двумя часами, а двумя ФОРМАМИ ОЖИДАНИЯ
    /// одних и тех же. Разная сетка делает это объявление ложным — детектор, поверенный на
    /// тестовых часах, под нагрузкой исполнялся по другой.
    ///
    /// # ЧТО ЭТИМ ОБРАЩЕНО, И ЦЕНУ НАЗЫВАЮ Я, а не наследую
    ///
    /// `Delay` выбирался ради того, чтобы пропущенные узлы НЕ выдавались залпом: пачка закрытий
    /// окна с одинаковым смыслом есть ошибка СОБЫТИЙНАЯ и выглядит как настоящая беда. Теперь
    /// отставшие узлы выдаются — но по ОДНОМУ НА ОПРОС, как это уже делает `Beats`: потребитель
    /// сам задаёт темп разбора, и залпа в одном пробуждении не бывает.
    ///
    /// Цена обращения: после долгой заминки потребитель получит очередь наступивших узлов вместо
    /// одного. Взамен два способа ожидания перестают мерить разное, а сетка не уезжает.
    fn ticks(&self, every: Duration) -> impl Stream<Item = Instant> + Unpin {
        let began = Instant::now();
        Box::pin(futures::stream::unfold(
            None::<u64>,
            move |handed| async move {
                match (every.is_zero(), handed) {
                    // ВЫРОЖДЕННАЯ СЕТКА ПУСТА, а не бесконечна: у шага в ноль узлов нет, и выдавать
                    // их значило бы крутиться без сна, выдумывая моменты.
                    (true, _) => None,
                    (false, handed) => {
                        let nth = handed.map_or(0, |already| already + 1);
                        let due = reflex_core::grid::node(began, every, nth);
                        match due.checked_duration_since(Instant::now()) {
                            // Узел уже позади — отдаём без сна: мы отстали, но сетку не двигаем.
                            None => (),
                            Some(left) => tokio::time::sleep(left).await,
                        }
                        Some((due, Some(nth)))
                    }
                }
            },
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use futures::StreamExt;

    /// КОНТРОЛЬ НА РЕАЛЬНЫХ ЧАСАХ — тот самый, без которого виртуальное время лжёт.
    ///
    /// Оплачено #287: три зелёных теста на `tokio::time::pause` не поймали потерянный waker,
    /// потому что виртуальные часы доказывают «сколько прошло», а не «оператор проснулся».
    /// Здесь проверяется именно пробуждение: поток обязан отдать тик САМ, без единого события
    /// извне и без того, чтобы его кто-то подтолкнул.
    #[tokio::test]
    async fn the_stream_wakes_itself_on_a_real_clock() {
        let ticks: Vec<Instant> = SystemClock
            .ticks(Duration::from_millis(10))
            .take(3)
            .collect()
            .await;
        assert_eq!(ticks.len(), 3, "часы не разбудили поток сами");
        assert!(
            ticks[2] > ticks[0],
            "тики пришли с неубывающим временем — часы стоят"
        );
    }

    /// ЗАМИНКА ПОТРЕБИТЕЛЯ НЕ СДВИГАЕТ СЕТКУ.
    ///
    /// `tokio::interval` с `MissedTickBehavior::Delay` отсчитывает следующий шаг от ОПОЗДАВШЕГО
    /// тика и двигает всю сетку вперёд НАВСЕГДА. Замер до правки: при шаге 100 мс и заминке
    /// 350 мс узлы приходили на `0, 100, 450, 550, 650` вместо `0, 100, 200, 300, 400` — сетка
    /// уехала на 50 мс и такой осталась.
    ///
    /// Три другие реализации этих же часов (запись, тестовые, синхронные `Beats`) считают узлы от
    /// начала и не двигают ничего. А `Ticks` и `Beats` объявлены не двумя часами, а двумя ФОРМАМИ
    /// ОЖИДАНИЯ одних и тех же — значит разная сетка делает это объявление ложным.
    ///
    /// # Почему утверждение про ОСТАТОК, а не про момент
    ///
    /// Между `Instant::now()` и внутренними часами tokio есть постоянное смещение эпохи (замерено:
    /// ~24 мкс). Утверждение вида `tick == began + step` краснеет на нём — то есть НЕ НА СВОЮ
    /// причину. Остаток от деления на шаг это смещение снимает: он берётся относительно первого
    /// узла, а не относительно `began`.
    #[tokio::test(start_paused = true)]
    async fn a_stall_does_not_shift_the_grid() {
        let step = Duration::from_millis(100);
        let mut ticks = SystemClock.ticks(step);

        let Some(origin) = ticks.next().await else {
            panic!("часы не отдали первый тик");
        };

        // Потребитель занят: сетка успевает уйти на три с половиной шага вперёд.
        tokio::time::advance(Duration::from_millis(350)).await;

        for nth in 1..=4u32 {
            let Some(at) = ticks.next().await else {
                panic!("часы замолчали после заминки");
            };
            assert_eq!(
                at.saturating_duration_since(origin).as_nanos() % step.as_nanos(),
                0,
                "узел {nth} лёг мимо сетки — она сдвинулась заминкой"
            );
        }
    }

    /// ПЕРВЫЙ ТИК НЕ ЖДЁТ ШАГА. Так устроен `interval` у tokio, и на это опирается всякий, кто
    /// хочет снять состояние сразу после подписки; проверяется, чтобы смена реализации это
    /// сломала громко, а не тихо задержала первое наблюдение на период.
    #[tokio::test]
    async fn the_first_tick_does_not_wait_a_full_step() {
        let began = Instant::now();
        let _first = SystemClock
            .ticks(Duration::from_secs(3600))
            .next()
            .await
            .expect("часы отдали первый тик");
        assert!(
            began.elapsed() < Duration::from_secs(1),
            "первый тик ждал целый шаг — состояние не снять раньше периода"
        );
    }
}
