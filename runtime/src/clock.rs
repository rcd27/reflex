//! СИСТЕМНЫЕ ЧАСЫ — реализация [`reflex_core::clock::Clock`] на настоящем времени.
//!
//! Живут здесь, а не в `reflex-core`, потому что тикать значит СПАТЬ, а спать умеет только край.
//! Ядро держит контракт и виртуальные часы; рантайм добавляет единственное, чего им не хватает, —
//! будильник.
//!
//! # Зачем это вообще заводилось
//!
//! Замер 03.09.2026: семнадцать мест вне тестов порождали время сами, в пяти разных формах. Ровно
//! то, что док часов записи предсказал буквой: «часы добавляет тот, кто читает провод, и делать
//! это обязан ИСТОЧНИК, иначе всякий потребитель напишет своё, по-разному». Здесь источник один.

use core::time::Duration;
use std::time::Instant;

use futures::Stream;
use reflex_core::clock::Clock;

/// ЧАСЫ ОПЕРАЦИОННОЙ СИСТЕМЫ.
///
/// Тип пустой намеренно: у системных часов нет состояния, которое имело бы смысл настраивать, и
/// два экземпляра обязаны показывать одно и то же. Значение существует ради того, чтобы часы
/// ПЕРЕДАВАЛИСЬ, а не брались из воздуха вызовом `Instant::now()` посреди чужой логики: только
/// переданные часы можно подменить в тесте.
#[derive(Debug, Clone, Copy, Default)]
pub struct SystemClock;

impl Clock for SystemClock {
    fn now(&self) -> Instant {
        Instant::now()
    }

    /// ТИКИ ИДУТ ПО СЕТКЕ, А ОТСТАВШИЕ СХЛОПЫВАЮТСЯ.
    ///
    /// `MissedTickBehavior::Delay` выбран, а не унаследован: поведение по умолчанию у tokio —
    /// `Burst`, и оно выдаёт залпом все тики, пропущенные, пока потребитель был занят. Для
    /// прибора это не «наверстать время», а выстрелить пачкой закрытий окна с одинаковым
    /// смыслом — то есть соврать о темпе ровно в тот момент, когда система под нагрузкой и врать
    /// дороже всего.
    ///
    /// ЦЕНА названа: при заминке потребителя сетка сдвигается, и окна станут чуть длиннее
    /// заказанных. Это ошибка ВЕЛИЧИНЫ и она видна; залп же есть ошибка СОБЫТИЙНАЯ, и она
    /// выглядит как настоящая беда.
    fn ticks(&self, every: Duration) -> impl Stream<Item = Instant> + Unpin {
        let mut beat = tokio::time::interval(every);
        beat.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
        Box::pin(futures::stream::unfold(beat, |mut beat| async move {
            let at = beat.tick().await;
            Some((at.into_std(), beat))
        }))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use futures::StreamExt;

    /// КОНТРОЛЬ НА РЕАЛЬНЫХ ЧАСАХ — тот самый, без которого виртуальное время лжёт.
    ///
    /// Оплачено #287: три зелёных теста на `tokio::time::pause` не поймали потерянный waker,
    /// потому что виртуальные часы доказывают «сколько прошло», а не «оператор проснулся».
    /// Здесь проверяется именно пробуждение: поток обязан отдать тик САМ, без единого события
    /// извне и без того, чтобы его кто-то подтолкнул.
    #[tokio::test]
    async fn the_stream_wakes_itself_on_a_real_clock() {
        let ticks: Vec<Instant> = SystemClock
            .ticks(Duration::from_millis(10))
            .take(3)
            .collect()
            .await;
        assert_eq!(ticks.len(), 3, "часы не разбудили поток сами");
        assert!(
            ticks[2] > ticks[0],
            "тики пришли с неубывающим временем — часы стоят"
        );
    }

    /// ПЕРВЫЙ ТИК НЕ ЖДЁТ ШАГА. Так устроен `interval` у tokio, и на это опирается всякий, кто
    /// хочет снять состояние сразу после подписки; проверяется, чтобы смена реализации это
    /// сломала громко, а не тихо задержала первое наблюдение на период.
    #[tokio::test]
    async fn the_first_tick_does_not_wait_a_full_step() {
        let began = Instant::now();
        let _first = SystemClock
            .ticks(Duration::from_secs(3600))
            .next()
            .await
            .expect("часы отдали первый тик");
        assert!(
            began.elapsed() < Duration::from_secs(1),
            "первый тик ждал целый шаг — состояние не снять раньше периода"
        );
    }
}
