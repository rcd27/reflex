//! ЛЕСТНИЦА ПРОБ — ведение множества внеполосных попыток, у которых есть порядок и цена.
//!
//! # Почему это живёт здесь, а не в `core`
//!
//! Машина шага (`core`) живёт в категории обычных функций: `S × In → S × Out`, носитель шага
//! синхронный, и это не бедность, а закон — переигровка (§10) требует, чтобы порядок букв не
//! зависел ни от чего, кроме самих букв. У лестницы гомы НЕСУТ ВРЕМЯ И КОНКУРЕНТНОСТЬ: «идти не
//! более чем n ветвями», «остановиться на первой годной», «пересобрать план» стрелкой в `Set` не
//! записываются вовсе. Это машина над ДРУГИМ ОСНОВАНИЕМ — обогащение, и разрез получает имя:
//! **`core` — шаг, `runtime` — конкурентность**.
//!
//! # Условие, под которым эта ось вообще заводится
//!
//! То же, что у алфавита провода: **исходы тотальны, а незнание обитаемо**. У пробы три разных
//! исхода, и слить любые два значило бы соврать о поиске:
//!
//! * `Established` — проба СОСТОЯЛАСЬ и что-то установила;
//! * `Refused` — мир отказал (сокета нет, права, таймаут): о кандидате мы так ничего и не узнали;
//! * `NotRun` — не запускали вовсе, потому что лестница остановилась раньше.
//!
//! Слей `Established` с `Refused` — и «техника не работает» стало бы неотличимо от «мы не смогли
//! её попробовать»; отчёт сказал бы «перебрали двадцать, не нашли», хотя половина из них не
//! состоялась. Слей `NotRun` с `Established` — и остановка выглядела бы как двадцать неудач.
//!
//! # ДВЕ ОСИ, А НЕ ОДНА: что установлено и лезть ли дальше
//!
//! Первая редакция спрашивала пробу `Result<Option<T>, String>` и тем СЛИВАЛА две независимые
//! вещи: «годен» и «стоп» оказывались одним ответом. Замер потребителя показал, что это неправда о
//! мире, и показал двумя случаями сразу:
//!
//! * цель НЕ БЕРЁТСЯ НИЧЕМ — перебор обязан встать, но это не находка, а приговор ЦЕЛИ. Выразить
//!   его «годной» значит объявить годным кандидата, который ничего не взял, — соврать ровно там,
//!   где отчёт и читают;
//! * кандидат берёт, НО С ПОВТОРАМИ — успех, и перебор всё же продолжается: для оракула присутствия
//!   это «да», для человека — потерянное время, и стоит поискать чище.
//!
//! Оттого оси разведены: проба всегда отдаёт УСТАНОВЛЕННОЕ (`T` — слово потребителя, фреймворк
//! несёт конверт, а не смысл) и отдельно [`Climbing`] — лезть ли дальше.
//!
//! # ГОДНОСТЬ — НЕ НАШЕ СЛОВО
//!
//! Прежняя редакция знала, какой исход «годный», и тем судила за потребителя. Знать этого мы не
//! можем: у одного годность есть «взяло», у другого «взяло без повторов», у третьего «цель ожила».
//! Лестница знает ровно две вещи о чужом знании — что оно УСТАНОВЛЕНО и что перебор на нём ВСТАЛ;
//! всё остальное читается из `T` тем, чьё это `T`.
//!
//! # «До остановки ВКЛЮЧИТЕЛЬНО»
//!
//! Ступень, на которой перебор встал, попадает в отчёт, а не отбрасывается вместе с остановкой.
//! Условие останова здесь — ЗАКОН лестницы, а не проверка внутри цикла: цикл с `break` теряет его
//! при первой же правке соседней строки, и потеря молчалива.
//!
//! # Цена ограниченного параллелизма НАЗВАНА
//!
//! Ширина `n` означает, что в полёте не более `n` проб. Кандидаты сверх ширины ждут; кандидаты
//! после найденной годной не запускаются и получают `NotRun`. Ничего не «теряется молча»: всякий
//! кандидат назван в отчёте своим исходом, и сумма исходов равна числу кандидатов — это и
//! проверяется прогоном.

use std::sync::Arc;

use futures::stream::{FuturesUnordered, StreamExt};

/// ЛЕЗТЬ ЛИ ДАЛЬШЕ — ось, независимая от того, что установлено. Не `bool`: у булева нет адреса, и
/// в позицию слова он не встаёт; читающий `true` заново вспоминает, что оно значило.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Climbing {
    /// Перебор продолжается — даже если проба удалась: удача не всегда конец поиска.
    Onward,
    /// Перебор встаёт. НЕ «нашли»: встать можно и оттого, что дальше искать бессмысленно.
    Halt,
}

/// Чем кончилась одна проба. Алфавит ЗАКРЫТ: заглушки `_ =>` у читателя не будет.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Tried<T> {
    /// Проба состоялась и УСТАНОВИЛА `what`. Что именно значит установленное — дело того, чьё это
    /// `T`; лестница видит лишь `then`: встал на нём перебор или пошёл дальше.
    Established { what: T, then: Climbing },
    /// Мир отказал: попытка не состоялась, и о кандидате мы не узнали НИЧЕГО. Причина несётся с
    /// собой — «не смогли спросить» без «почему» лечится только повтором вслепую.
    Refused(String),
    /// Не запускали: лестница остановилась раньше либо ширина не пустила. Клетка незнания (§7) —
    /// «не смотрели» ≠ «смотрели и пусто».
    NotRun,
}

impl<T> Tried<T> {
    /// Установила ли проба хоть что-нибудь. `Refused`/`NotRun` — нет, и это спрашивают ЗАКОНОМ, а
    /// не перечислением у себя: два перечисления разошлись бы молча.
    pub fn established(&self) -> bool {
        matches!(self, Tried::Established { .. })
    }
}

/// Чем кончился подъём: каждый кандидат и его исход, в порядке ПОДАЧИ.
///
/// Отчёт полный по построению — строк ровно столько, сколько кандидатов подавали. Отчёт, из
/// которого выпадают незапущенные, читается как «перебрали всё», а это ложь ровно в том случае,
/// ради которого лестницу и заводят.
///
/// Найденная годная ОТДЕЛЬНЫМ полем не лежит: один факт живёт в одном месте, и вторая его копия
/// разошлась бы с первой молча. Спрашивают её [`Climbed::good`] — по тому же порядку подачи.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Climbed<K, T> {
    pub tried: Vec<(K, Tried<T>)>,
}

impl<K, T> Climbed<K, T> {
    /// Ступень, НА КОТОРОЙ ПЕРЕБОР ВСТАЛ, — первая по порядку ПОДАЧИ, не по времени ответа. Иначе
    /// две остановки, случившиеся в разном темпе, давали бы разный ответ на одном входе, и
    /// лестница перестала бы быть функцией.
    ///
    /// «Встал» не значит «нашли»: что именно установлено, читается из `T` тем, чьё это `T`.
    pub fn halted(&self) -> Option<(&K, &T)> {
        self.tried.iter().find_map(|(key, tried)| match tried {
            Tried::Established {
                what,
                then: Climbing::Halt,
            } => Some((key, what)),
            Tried::Established {
                then: Climbing::Onward,
                ..
            }
            | Tried::Refused(_)
            | Tried::NotRun => None,
        })
    }

    /// Сколько кандидатов НИЧЕГО НЕ УСТАНОВИЛИ — цена остановки и цена отказов, числом. Не
    /// «сколько потеряли»: потерянного нет, есть неустановленное, и оно названо поимённо.
    pub fn unestablished(&self) -> usize {
        self.tried
            .iter()
            .filter(|(_, tried)| !tried.established())
            .count()
    }
}

/// ПОДНЯТЬСЯ ПО ЛЕСТНИЦЕ: пробовать кандидатов не более чем `width` ветвями сразу, до остановки
/// включительно.
///
/// `probe` отвечает `Result<(T, Climbing), String>`: что установлено И лезть ли дальше — две
/// НЕЗАВИСИМЫЕ вещи (докблок модуля объясняет, почему их нельзя слить), либо `Err(причина)`, если
/// мир отказал и не установлено ничего.
///
/// Уже летящие ветви ДОСЛУШИВАЮТСЯ и после остановки: они состоялись, и выбросить их исход значило
/// бы отчитаться «не запускали» о том, что запускали. Не долитые — не запускаются вовсе и получают
/// `NotRun`.
pub async fn climb<K, T, F, Fut>(candidates: Vec<K>, width: usize, probe: F) -> Climbed<K, T>
where
    K: Clone + Send + 'static,
    T: Send + 'static,
    F: Fn(K) -> Fut + Send + Sync + 'static,
    Fut: std::future::Future<Output = Result<(T, Climbing), String>> + Send,
{
    let probe = Arc::new(probe);
    let mut outcome: Vec<Option<Tried<T>>> = candidates.iter().map(|_| None).collect();
    let mut halt_at: Option<usize> = None;
    let mut next = 0usize;
    let mut flight = FuturesUnordered::new();

    loop {
        // Ширина ноль — не «без ограничения», а вырожденный случай: `max(1)` держит лестницу
        // ходячей. Молчаливое превращение нуля в безграничность запустило бы ВСЁ ровно тогда,
        // когда просили не запускать ничего.
        while halt_at.is_none() && flight.len() < width.max(1) && next < candidates.len() {
            let index = next;
            let candidate = candidates[index].clone();
            let probe = Arc::clone(&probe);
            flight.push(async move { (index, probe(candidate).await) });
            next += 1;
        }

        let Some((index, result)) = flight.next().await else {
            break;
        };

        outcome[index] = Some(match result {
            Ok((what, then)) => {
                if then == Climbing::Halt {
                    halt_at = Some(match halt_at {
                        None => index,
                        Some(earlier) => earlier.min(index),
                    });
                }
                Tried::Established { what, then }
            }
            Err(why) => Tried::Refused(why),
        });
    }

    // НЕЗАПУЩЕННЫЕ НАЗЫВАЮТСЯ, А НЕ ВЫПАДАЮТ. Пустая клетка здесь значит ровно одно: до кандидата
    // не дошли — либо остановились раньше, либо ширина не пустила.
    Climbed {
        tried: candidates
            .into_iter()
            .zip(outcome)
            .map(|(key, tried)| (key, tried.unwrap_or(Tried::NotRun)))
            .collect(),
    }
}
