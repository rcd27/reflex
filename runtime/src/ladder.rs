//! ЛЕСТНИЦА ПРОБ — ведение множества внеполосных попыток, у которых есть порядок и цена.
//!
//! # Почему это живёт здесь, а не в `core`
//!
//! Машина шага (`core`) живёт в категории обычных функций: `S × In → S × Out`, носитель шага
//! синхронный, и это не бедность, а закон — переигровка (§10) требует, чтобы порядок букв не
//! зависел ни от чего, кроме самих букв. У лестницы гомы НЕСУТ ВРЕМЯ И КОНКУРЕНТНОСТЬ: «идти не
//! более чем n ветвями», «остановиться на первой годной», «пересобрать план» стрелкой в `Set` не
//! записываются вовсе. Это машина над ДРУГИМ ОСНОВАНИЕМ — обогащение, и разрез получает имя:
//! **`core` — шаг, `runtime` — конкурентность**.
//!
//! # Условие, под которым эта ось вообще заводится
//!
//! То же, что у алфавита провода: **исходы тотальны, а незнание обитаемо**. У пробы четыре разных
//! исхода, и слить любые два значило бы соврать о поиске:
//!
//! * `Good` — годная, нашли;
//! * `Bad` — проба СОСТОЯЛАСЬ и не годится;
//! * `Refused` — мир отказал (сокета нет, права, таймаут): о кандидате мы так ничего и не узнали;
//! * `NotRun` — не запускали вовсе, потому что лестница остановилась раньше.
//!
//! Слей `Bad` с `Refused` — и «техника не работает» стало бы неотличимо от «мы не смогли её
//! попробовать»; отчёт сказал бы «перебрали двадцать, не нашли», хотя половина из них не состоялась.
//! Слей `NotRun` с `Bad` — и остановка на первой годной выглядела бы как двадцать неудач.
//!
//! # «До первой годной ВКЛЮЧИТЕЛЬНО»
//!
//! Годная попадает в отчёт, а не отбрасывается вместе с остановкой. Условие останова здесь —
//! ЗАКОН лестницы, а не проверка внутри цикла: цикл с `break` теряет его при первой же правке
//! соседней строки, и потеря молчалива.
//!
//! # Цена ограниченного параллелизма НАЗВАНА
//!
//! Ширина `n` означает, что в полёте не более `n` проб. Кандидаты сверх ширины ждут; кандидаты
//! после найденной годной не запускаются и получают `NotRun`. Ничего не «теряется молча»: всякий
//! кандидат назван в отчёте своим исходом, и сумма исходов равна числу кандидатов — это и
//! проверяется прогоном.

use std::sync::Arc;

use futures::stream::{FuturesUnordered, StreamExt};

/// Чем кончилась одна проба. Алфавит ЗАКРЫТ: заглушки `_ =>` у читателя не будет.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Tried<T> {
    /// Годная — то, ради чего лезли.
    Good(T),
    /// Проба состоялась, кандидат не годится. ЗНАНИЕ о кандидате.
    Bad,
    /// Мир отказал: попытка не состоялась, и о кандидате мы ничего не узнали. НЕ «не годится».
    Refused(String),
    /// Не запускали: лестница остановилась раньше. Клетка незнания (§7) — «не смотрели» ≠
    /// «смотрели и пусто».
    NotRun,
}

impl<T> Tried<T> {
    /// Установила ли проба хоть что-нибудь о кандидате. `Refused`/`NotRun` — нет, и это
    /// спрашивают ЗАКОНОМ, а не перечислением у себя: два перечисления разошлись бы молча.
    pub fn established(&self) -> bool {
        matches!(self, Tried::Good(_) | Tried::Bad)
    }
}

/// Чем кончился подъём: каждый кандидат и его исход, в порядке ПОДАЧИ.
///
/// Отчёт полный по построению — строк ровно столько, сколько кандидатов подавали. Отчёт, из
/// которого выпадают незапущенные, читается как «перебрали всё», а это ложь ровно в том случае,
/// ради которого лестницу и заводят.
///
/// Найденная годная ОТДЕЛЬНЫМ полем не лежит: один факт живёт в одном месте, и вторая его копия
/// разошлась бы с первой молча. Спрашивают её [`Climbed::good`] — по тому же порядку подачи.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Climbed<K, T> {
    pub tried: Vec<(K, Tried<T>)>,
}

impl<K, T> Climbed<K, T> {
    /// Первая годная ПО ПОРЯДКУ ПОДАЧИ — не по времени ответа. Иначе две годные, ответившие в
    /// разном темпе, давали бы разный ответ на одном входе, и лестница перестала бы быть функцией.
    pub fn good(&self) -> Option<(&K, &T)> {
        self.tried.iter().find_map(|(key, tried)| match tried {
            Tried::Good(good) => Some((key, good)),
            _ => None,
        })
    }

    /// Сколько кандидатов НИЧЕГО НЕ УСТАНОВИЛИ — цена остановки и цена отказов, числом. Не
    /// «сколько потеряли»: потерянного нет, есть неустановленное, и оно названо поимённо.
    pub fn unestablished(&self) -> usize {
        self.tried
            .iter()
            .filter(|(_, tried)| !tried.established())
            .count()
    }
}

/// ПОДНЯТЬСЯ ПО ЛЕСТНИЦЕ: пробовать кандидатов не более чем `width` ветвями сразу, до первой
/// годной включительно.
///
/// `probe` отвечает `Result<Option<T>, String>`: `Ok(Some)` — годен, `Ok(None)` — не годен, `Err` —
/// мир отказал. Три ответа, а не два, ровно потому, что «не годен» и «не смогли спросить» — разные
/// знания, и слить их значило бы отчитаться «перебрали двадцать», перебрав десять.
///
/// Уже летящие ветви ДОСЛУШИВАЮТСЯ и после находки: они состоялись, и выбросить их исход значило
/// бы отчитаться «не запускали» о том, что запускали. Не долитые — не запускаются вовсе и получают
/// `NotRun`.
pub async fn climb<K, T, F, Fut>(candidates: Vec<K>, width: usize, probe: F) -> Climbed<K, T>
where
    K: Clone + Send + 'static,
    T: Send + 'static,
    F: Fn(K) -> Fut + Send + Sync + 'static,
    Fut: std::future::Future<Output = Result<Option<T>, String>> + Send,
{
    let probe = Arc::new(probe);
    let mut outcome: Vec<Option<Tried<T>>> = candidates.iter().map(|_| None).collect();
    let mut good_at: Option<usize> = None;
    let mut next = 0usize;
    let mut flight = FuturesUnordered::new();

    loop {
        // Ширина ноль — не «без ограничения», а вырожденный случай: `max(1)` держит лестницу
        // ходячей. Молчаливое превращение нуля в безграничность запустило бы ВСЁ ровно тогда,
        // когда просили не запускать ничего.
        while good_at.is_none() && flight.len() < width.max(1) && next < candidates.len() {
            let index = next;
            let candidate = candidates[index].clone();
            let probe = Arc::clone(&probe);
            flight.push(async move { (index, probe(candidate).await) });
            next += 1;
        }

        let Some((index, result)) = flight.next().await else {
            break;
        };

        outcome[index] = Some(match result {
            Ok(Some(good)) => {
                good_at = Some(match good_at {
                    None => index,
                    Some(earlier) => earlier.min(index),
                });
                Tried::Good(good)
            }
            Ok(None) => Tried::Bad,
            Err(why) => Tried::Refused(why),
        });
    }

    // НЕЗАПУЩЕННЫЕ НАЗЫВАЮТСЯ, А НЕ ВЫПАДАЮТ. Пустая клетка здесь значит ровно одно: до кандидата
    // не дошли — либо остановились раньше, либо ширина не пустила.
    Climbed {
        tried: candidates
            .into_iter()
            .zip(outcome)
            .map(|(key, tried)| (key, tried.unwrap_or(Tried::NotRun)))
            .collect(),
    }
}
