//! ЛЕСТНИЦА ПРОБ — внеполосные попытки, у которых есть порядок и цена.
//!
//! ИСХОДЫ ТОТАЛЬНЫ, НЕЗНАНИЕ ОБИТАЕМО (§7): `Established` — проба состоялась и что-то установила;
//! `Refused` — мир отказал, и о кандидате мы не узнали ничего; `NotRun` — не запускали вовсе. Слей
//! `Established` с `Refused` — и «техника не работает» станет неотличимо от «мы не смогли её
//! попробовать»: отчёт скажет «перебрали двадцать, не нашли», хотя половина не состоялась. Слей
//! `NotRun` с `Established` — и остановка прочтётся как двадцать неудач.
//!
//! ДВЕ ОСИ, А НЕ ОДНА: что УСТАНОВЛЕНО и лезть ли ДАЛЬШЕ. `Result<Option<T>, String>` слил бы их в
//! один ответ, а мир опровергает слияние двумя случаями сразу — цель не берётся ничем (перебор
//! встаёт, но это приговор ЦЕЛИ, а не находка) и кандидат берёт, но с повторами (успех, и всё же
//! стоит поискать чище). Годность — не наше слово: у одного она «взяло», у другого «взяло без
//! повторов», у третьего «цель ожила». Лестница знает о чужом знании ровно две вещи — что оно
//! УСТАНОВЛЕНО ([`Tried`]; `T` — слово потребителя, фреймворк несёт конверт, а не смысл) и что
//! перебор на нём ВСТАЛ ([`Climbing`]).
//!
//! ДО ОСТАНОВКИ ВКЛЮЧИТЕЛЬНО: ступень, на которой встали, попадает в отчёт, и всякий кандидат
//! назван в нём своим исходом — сумма исходов равна числу кандидатов. Останов есть ЗАКОН лестницы,
//! а не `break` внутри цикла: `break` теряется при первой же правке соседней строки, молча.
//!
//! Списка кандидатов подъём на ходу не пересобирает: единственный писатель знания об этой цели —
//! сам подъём, и всё узнанное он и так держит в отчёте. Замер темпа: каталог в 12 кандидатов,
//! проба ждёт 6 с, при ширине 4 подъём длится 18 с худшим случаем — а слепок цели меняется за это
//! время ОДИН раз, в конце, нашими же находками. Заведётся кросс-целевое обучение — мера будет
//! другой; строить раньше замера нечего.
//!
//! Почему не в `core`: гомы здесь несут время и конкурентность («идти не более чем n ветвями»,
//! «остановиться на первой годной») — стрелкой в `Set` это не записывается вовсе, а шаг
//! `S × In → S × Out` обязан быть синхронным, иначе порядок букв зависит не от одних букв и
//! переигровка (§10) перестаёт быть переигровкой. Разрез: `core` — шаг, `runtime` — конкурентность.

use futures::stream::{FuturesUnordered, StreamExt};

/// ЛЕЗТЬ ЛИ ДАЛЬШЕ — ось, независимая от того, что установлено. Не `bool`: у булева нет адреса, и
/// в позицию слова он не встаёт; читающий `true` заново вспоминает, что оно значило.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Climbing {
    /// Перебор продолжается — даже если проба удалась: удача не всегда конец поиска.
    Onward,
    /// Перебор встаёт. НЕ «нашли»: встать можно и оттого, что дальше искать бессмысленно.
    Halt,
}

/// Чем кончилась одна проба. Алфавит ЗАКРЫТ: заглушки `_ =>` у читателя не будет.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Tried<T> {
    /// Проба состоялась и УСТАНОВИЛА `what`. Что именно значит установленное — дело того, чьё это
    /// `T`; лестница видит лишь `then`: встал на нём перебор или пошёл дальше.
    Established { what: T, then: Climbing },
    /// Мир отказал: попытка не состоялась, и о кандидате мы не узнали НИЧЕГО. Причина несётся с
    /// собой — «не смогли спросить» без «почему» лечится только повтором вслепую.
    Refused(String),
    /// Не запускали: лестница остановилась раньше либо ширина не пустила. Клетка незнания (§7) —
    /// «не смотрели» ≠ «смотрели и пусто».
    NotRun,
}

impl<T> Tried<T> {
    /// Установила ли проба хоть что-нибудь. `Refused`/`NotRun` — нет, и это спрашивают ЗАКОНОМ, а
    /// не перечислением у себя: два перечисления разошлись бы молча.
    pub fn established(&self) -> bool {
        matches!(self, Tried::Established { .. })
    }
}

/// Чем кончился подъём: каждый кандидат и его исход, в порядке ПОДАЧИ.
///
/// Отчёт полный по построению — строк ровно столько, сколько кандидатов подавали. Отчёт, из
/// которого выпадают незапущенные, читается как «перебрали всё», а это ложь ровно в том случае,
/// ради которого лестницу и заводят.
///
/// Ступень остановки ОТДЕЛЬНЫМ полем не лежит: один факт живёт в одном месте, и вторая его копия
/// разошлась бы с первой молча. Спрашивают её [`Climbed::halted`] — по порядку подачи.
///
/// «Годной» она здесь не названа намеренно: годность — слово потребителя, не лестницы (докблок
/// модуля).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Climbed<K, T> {
    pub tried: Vec<(K, Tried<T>)>,
}

impl<K, T> Climbed<K, T> {
    /// Ступень, НА КОТОРОЙ ПЕРЕБОР ВСТАЛ, — первая по порядку ПОДАЧИ, не по времени ответа. Иначе
    /// две остановки, случившиеся в разном темпе, давали бы разный ответ на одном входе, и
    /// лестница перестала бы быть функцией.
    ///
    /// «Встал» не значит «нашли»: что именно установлено, читается из `T` тем, чьё это `T`.
    pub fn halted(&self) -> Option<(&K, &T)> {
        self.tried.iter().find_map(|(key, tried)| match tried {
            Tried::Established {
                what,
                then: Climbing::Halt,
            } => Some((key, what)),
            Tried::Established {
                then: Climbing::Onward,
                ..
            }
            | Tried::Refused(_)
            | Tried::NotRun => None,
        })
    }

    /// Сколько кандидатов НИЧЕГО НЕ УСТАНОВИЛИ — цена остановки и цена отказов, числом. Не
    /// «сколько потеряли»: потерянного нет, есть неустановленное, и оно названо поимённо.
    pub fn unestablished(&self) -> usize {
        self.tried
            .iter()
            .filter(|(_, tried)| !tried.established())
            .count()
    }
}

/// ПОДНЯТЬСЯ ПО ЛЕСТНИЦЕ: пробовать кандидатов не более чем `width` ветвями сразу, до остановки
/// включительно.
///
/// `probe` отвечает `Result<(T, Climbing), String>`: что установлено И лезть ли дальше — две
/// НЕЗАВИСИМЫЕ вещи (докблок модуля объясняет, почему их нельзя слить), либо `Err(причина)`, если
/// мир отказал и не установлено ничего.
///
/// Уже летящие ветви ДОСЛУШИВАЮТСЯ и после остановки: они состоялись, и выбросить их исход значило
/// бы отчитаться «не запускали» о том, что запускали. Не долитые — не запускаются вовсе и получают
/// `NotRun`.
/// # Почему здесь НЕТ границ `Send`/`Sync`/`'static`
///
/// Потому что лестница НЕ СПАВНИТ. Ветви живут на стеке вызывающего: `FuturesUnordered`
/// опрашивается тут же, в цикле `climb`, и ни одна проба не уезжает в чужой поток. Требовать
/// потокобезопасности, которой оператор не пользуется, — тот же род беды, что «способность
/// заявлена и недостижима» (§9.1), только с обратным знаком: ТРЕБОВАНИЕ ЗАЯВЛЕНО И НЕ НУЖНО.
///
/// Цена этой лишней строгости ложится не на нас, а на вызывающего, и она не косметическая:
/// однопоточная оснастка (провод `Rc<dyn Fn>`, счётчик `Cell<usize>`) под неё не подходит, и
/// автору пришлось бы переписать её на `Arc` и атомики — то есть платить синхронизацией за то,
/// чего не происходит. Замер потребителя: восемь историй поля, в каждой свой провод.
///
/// Начнёт лестница спавнить — границы вернутся ВМЕСТЕ с тем решением и осознанно. Пока не спавнит,
/// их здесь нет, и держит это прогоном тест с `Rc`/`Cell`: верни границы — он не соберётся.
pub async fn climb<K, T, F, Fut>(candidates: Vec<K>, width: usize, probe: F) -> Climbed<K, T>
where
    K: Clone,
    F: Fn(K) -> Fut,
    Fut: std::future::Future<Output = Result<(T, Climbing), String>>,
{
    let mut outcome: Vec<Option<Tried<T>>> = candidates.iter().map(|_| None).collect();
    let mut halt_at: Option<usize> = None;
    let mut next = 0usize;
    let mut flight = FuturesUnordered::new();

    loop {
        // Ширина ноль — не «без ограничения», а вырожденный случай: `max(1)` держит лестницу
        // ходячей. Молчаливое превращение нуля в безграничность запустило бы ВСЁ ровно тогда,
        // когда просили не запускать ничего.
        while halt_at.is_none() && flight.len() < width.max(1) && next < candidates.len() {
            let index = next;
            // Проба зовётся ЗДЕСЬ, а будущее кладётся в полёт: так оно вольно заимствовать у
            // вызывающего (`Rc`, `Cell`, что угодно не-`Send`), и лестница не диктует ему форму.
            let trying = probe(candidates[index].clone());
            flight.push(async move { (index, trying.await) });
            next += 1;
        }

        let Some((index, result)) = flight.next().await else {
            break;
        };

        outcome[index] = Some(match result {
            Ok((what, then)) => {
                if then == Climbing::Halt {
                    halt_at = Some(match halt_at {
                        None => index,
                        Some(earlier) => earlier.min(index),
                    });
                }
                Tried::Established { what, then }
            }
            Err(why) => Tried::Refused(why),
        });
    }

    // НЕЗАПУЩЕННЫЕ НАЗЫВАЮТСЯ, А НЕ ВЫПАДАЮТ. Пустая клетка здесь значит ровно одно: до кандидата
    // не дошли — либо остановились раньше, либо ширина не пустила.
    Climbed {
        tried: candidates
            .into_iter()
            .zip(outcome)
            .map(|(key, tried)| (key, tried.unwrap_or(Tried::NotRun)))
            .collect(),
    }
}
