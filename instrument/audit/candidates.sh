#!/usr/bin/env bash
# СБОР КАНДИДАТОВ В ПРИБОРЫ (#320, срез B, шаг B1).
#
# Критерий СТРУКТУРНЫЙ, не смысловой: прибор даёт СИГНАЛ, сигнал имеет исходы, исходы — варианты
# `enum`. Отбирать «то, что похоже на прибор», значило бы повторить перепись среза 0, которая
# именно на смысловом отборе и соврала трижды.
#
# ЦЕНА КРИТЕРИЯ НАЗВАНА: приборы-величины (`Tempo`, `Envelope`) — это `struct`, и сюда они не
# попадут. По нашей же рамке они ЭЛЕМЕНТЫ (дают величину, не сигнал), так что пропуск ожидаемый;
# но если срез C найдёт среди них сигнал наружу — критерий придётся расширить, и это будет
# находка, а не досада.
#
# Невод 1 (`nevod/`) исключён: deprecated, в парк не поедет.
#
# СМЕРТЬ: кандидаты выводятся механически крейтом приборов (паспорт как трейт) — скрипт снимается.
set -u

CRATES="dataplane dataplane-nfq nevod2 nevod2-runtime zond reflex/core reflex/linux"

for crate_dir in $CRATES; do
  [ -d "$crate_dir/src" ] || continue
  grep -rn --include=*.rs -E "^[[:space:]]*pub enum [A-Za-z_]" "$crate_dir/src" 2>/dev/null \
    | sed -E "s#^([^:]+):([0-9]+):[[:space:]]*pub enum ([A-Za-z_0-9]+).*#${crate_dir}\t\1\t\2\t\3#"
done
