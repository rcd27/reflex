#!/usr/bin/env bash
# ВИТНЕС ИНСТРУМЕНТА ВЗВЕШИВАНИЯ (#320, срез B).
#
# Инструмент переписи САМ есть прибор, и этот прибор уже соврал трижды: объявил `Speaks`
# неподключённым через двое суток после подключения, объявил `health.rs` недостижимым (зовётся
# без `use`), записал `meter::Freshness` прибором с нулём (он элемент). Зелёный прогон без стенда
# неотличим от «не проверял».
#
# Стенд — свой одноразовый cargo-проект: настоящее дерево трогать нельзя, а взвешивание по
# построению правит файлы. Сверки проверяют ПОВЕДЕНИЕ, а не текст команды: «есть ли --bins в
# строке» ловится грепом и потому слабо, «даёт ли инструмент ноль типу, читаемому только из
# тестов» ловит ту же ошибку через результат.
#
# СМЕРТЬ: парк переразмечен и взвешен повторно механически (audit в крейте приборов) — стенд
# переезжает туда вместе с инструментом.
set -u

STAND="$(mktemp -d)"
TOOL="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/weigh.sh"
trap 'rm -rf "$STAND"' EXIT
export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@t GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@t

failed=0
verdict() { # ожидание · факт · имя
  if [ "$1" = "$2" ]; then printf '  ✓ %s\n' "$3"; else printf '  ✖ %s (ждали %s, получили %s)\n' "$3" "$1" "$2"; failed=1; fi
}

# ── ФИКСТУРА: библиотека с четырьмя типами и бинарь-потребитель в ДРУГОМ крейте ────────────────
mkdir -p "$STAND/libx/src" "$STAND/appx/src/bin" "$STAND/appx/tests"
cd "$STAND" || exit 1

cat > libx/Cargo.toml <<'EOF'
[package]
name = "libx"
version = "0.1.0"
edition = "2021"
EOF

# Loud     — читается из бинаря ЧУЖОГО крейта (эталон подключённого прибора)
# Quiet    — читается только внутри своего файла (эталон элемента)
# TestOnly — читается только из tests/ (ложная зелень, если собирать --all-targets)
# Private  — уже приватный: снятие `pub` НЕ применится (свидетель применения)
cat > libx/src/lib.rs <<'EOF'
pub enum Loud {
    A,
    B,
}

pub enum Quiet {
    A,
    B,
}

pub enum TestOnly {
    A,
    B,
}

enum Private {
    A,
    B,
}

// Sibling — определён в одном модуле, читается ДРУГИМ модулем ТОГО ЖЕ файла. Читатель законный:
// он снаружи модуля определения и доступ теряет по-настоящему. Отбросить его как «шум того же
// файла» значило бы объявить подключённый прибор элементом.
pub mod inner {
    pub enum Sibling {
        A,
        B,
    }
}

pub mod sibling_reader {
    use super::inner::Sibling;

    pub fn read() -> u8 {
        match Sibling::A {
            Sibling::A => 1,
            Sibling::B => 2,
        }
    }
}

// Root — определён в КОРНЕ крейта и читается другим ФАЙЛОМ того же крейта. Снятие `pub` его не
// ловит: подмодули суть потомки корня и приватный тип родителя видят. Значит первый проход для
// таких типов меряет только межкрейтовых читателей — а `Told`, `Executor`, `Ordered` в
// `dataplane/src/lib.rs` именно таковы, и их нули без второго прохода неинтерпретируемы.
pub enum Root {
    A,
    B,
}

pub mod other;

pub fn use_quiet(q: Quiet) -> u8 {
    match q {
        Quiet::A => 1,
        Quiet::B => 2,
    }
}

pub fn use_private() -> u8 {
    match Private::A {
        Private::A => 1,
        Private::B => 2,
    }
}
EOF

cat > libx/src/other.rs <<'EOF'
use crate::Root;

pub fn read_root() -> u8 {
    match Root::A {
        Root::A => 1,
        Root::B => 2,
    }
}
EOF

cat > appx/Cargo.toml <<'EOF'
[package]
name = "appx"
version = "0.1.0"
edition = "2021"

[dependencies]
libx = { path = "../libx" }
EOF

cat > appx/src/bin/appx-main.rs <<'EOF'
use libx::Loud;

fn main() {
    let signal = Loud::A;
    let code = match signal {
        Loud::A => 0,
        Loud::B => 1,
    };
    std::process::exit(code);
}
EOF

cat > appx/tests/only_test.rs <<'EOF'
use libx::TestOnly;

#[test]
fn test_only_reader() {
    let value = TestOnly::A;
    assert!(matches!(value, TestOnly::A));
}
EOF

git init -q -b main .
git add -A
git commit -qm fixture

# Кандидаты: крейт · файл · строка определения · имя
: > candidates.tsv
for pair in "pub enum Loud:Loud" "pub enum Quiet:Quiet" "pub enum TestOnly:TestOnly" "enum Private:Private" "    pub enum Sibling:Sibling" "pub enum Root:Root"; do
  pattern="${pair%%:*}"
  name="${pair##*:}"
  # Без якоря конца строки: определение выглядит как `pub enum Loud {`, и `$` не совпал бы —
  # список кандидатов молча оказался бы пустым, а стенд отчитался бы «инструмент отработал».
  line="$(grep -n "^${pattern} " libx/src/lib.rs | head -1 | cut -d: -f1)"
  printf 'libx\tlibx/src/lib.rs\t%s\t%s\n' "$line" "$name" >> candidates.tsv
done

# ── ПРОГОН ────────────────────────────────────────────────────────────────────────────────────
bash "$TOOL" --root "$STAND" --candidates candidates.tsv \
  --manifests libx/Cargo.toml,appx/Cargo.toml > weigh.tsv 2> weigh.log
rc=$?

weight() { awk -v n="$1" -F'\t' '$4 == n { print $5 }' weigh.tsv; }
state()  { awk -v n="$1" -F'\t' '$4 == n { print $8 }' weigh.tsv; }

echo "взвешивание:"
verdict 0 "$rc" "инструмент отработал без ошибки"

# 1. ЭТАЛОН ПОДКЛЮЧЁННОГО. Читатель живёт в ЧУЖОМ крейте: инструмент, собравший только манифест
#    кандидата, дал бы ложный ноль — «крейт в одиночку молчит о потребителях» (176 зелёных тестов
#    зонда при сломанной сборке края).
positive() { case "${1:-}" in ''|*[!0-9]*) return 1 ;; *) [ "$1" -gt 0 ] ;; esac; }

#    Вес сверяется ТОЧНЫМ числом, а не «больше нуля»: у `Loud` ровно один читатель
#    (`appx/src/bin/appx-main.rs`). Слабая форма «> 0» не различала бы 1 и 2, и лишний файл в
#    списке читателей прошёл бы незамеченным — так первая редакция не заметила, что фильтр файла
#    определения молча съедает законного читателя.
verdict 1 "$(weight Loud)" "у подключённого прибора ровно один читатель"

#    ПУТЬ ЧИТАТЕЛЯ — ОТ КОРНЯ, а не от каталога манифеста. Cargo выдаёт `file_name` относительно
#    своего манифеста, и один файл, увиденный двумя манифестами, попадал в список ДВАЖДЫ под
#    разными путями — вес раздувался, а «вне крейта» считалось по обрубку. Найдено пробой на
#    живой репе, где `dataplane-nfq/src/parse.rs` и `src/parse.rs` оказались одним файлом.
readers_of() { awk -v n="$1" -F'\t' '$4 == n { print $7 }' weigh.tsv; }
verdict "appx/src/bin/appx-main.rs" "$(readers_of Loud)" "путь читателя нормализован к корню"

# 2. ЭТАЛОН ЭЛЕМЕНТА. Читается только внутри своего файла — снятие `pub` не красит никого.
verdict 0 "$(weight Quiet)" "у элемента вес = 0"

# 3. ТЕСТЫ НЕ СПАСАЮТ. Читатель только в tests/ ⟹ по живым бинарям вес 0. Проверяется ПОВЕДЕНИЕМ:
#    --all-targets дал бы > 0, и это тот самый корень эпика — ТЕСТ ПОДАЁТ ВХОДЫ САМ.
verdict 0 "$(weight TestOnly)" "читаемое только из тестов весит 0"

# 3b. ЧИТАТЕЛЬ ИЗ ДРУГОГО МОДУЛЯ ТОГО ЖЕ ФАЙЛА НЕ ТЕРЯЕТСЯ. Он снаружи модуля определения и
#     доступ теряет по-настоящему; отбросить его значило бы объявить подключённый прибор
#     элементом. Ровно это делала первая редакция инструмента, и обезоруживание её не поймало —
#     поймал живой rustc.
positive "$(weight Sibling)"
verdict 0 $? "читатель из соседнего модуля того же файла засчитан"

# 3в. ТИП ИЗ КОРНЯ КРЕЙТА. Снятие `pub` его читателей не видит (потомок видит приватное
#      родителя) — их находит ВТОРОЙ проход, переименованием. Без него нули у типов из `lib.rs`
#      («нет читателей вне крейта») читались бы как «нет читателей вовсе», и элемент от мёртвого
#      было бы не отличить. Проверено на живой репе: снятие `pub` у `dataplane::Told` даёт лишь
#      warning `private_interfaces`, при том что читателей в крейте четыре.
renamed() { awk -v n="$1" -F'\t' '$4 == n { print $9 }' weigh.tsv; }
verdict 0 "$(weight Root)"  "тип из корня крейта: первый проход не видит внутрикрейтовых"
verdict 1 "$(renamed Root)" "тип из корня крейта: второй проход находит читателя"

# 3г. СВИДЕТЕЛЬ ПЕРЕСБОРКИ. `cmp` доказывает, что изменился ФАЙЛ; он молчит о том, увидела ли это
#     СБОРКА. Вернись cargo из кеша — ошибок нет, и подключённый прибор получит вес 0. Свидетель
#     обязан стоять на стороне предмета (крейт пересобран), а не на стороне вызова (правку
#     внесли). Улика — `Checking <пакет>` в stderr cargo.
verdict OK "$(state Loud)" "сборка увидела правку (крейт пересобран)"

# 4. СВИДЕТЕЛЬ ПРИМЕНЕНИЯ. У `Private` снимать нечего: правка не применяется. Инструмент обязан
#    сказать NOT_APPLIED, а НЕ записать вес 0 — иначе «не покраснело» неотличимо от «не отключили»
#    (шесть дефектов окружения поверочного стенда за день, каждый выглядел исправной работой).
verdict NOT_APPLIED "$(state Private)" "неприменившаяся правка помечена, а не посчитана нулём"

# 5. ОТКАТ. Дерево фикстуры обязано вернуться в исходное состояние в ЛЮБОМ исходе.
#
#    ПРЕДПОСЫЛКА ДОКАЗЫВАЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ. Первая редакция этой сверки была ВАКУУМНОЙ:
#    при отсутствующем инструменте дерево чисто, и она горела зелёным — то есть не отличала
#    «откатил» от «не запускался». Ровно тот класс, ради которого весь эпик. Поэтому чистота
#    засчитывается только вместе с доказательством, что хоть одна правка применялась.
applied="$(awk -F'\t' '$8 == "OK" { n++ } END { print n + 0 }' weigh.tsv 2>/dev/null)"
positive "$applied"
verdict 0 $? "хотя бы одна правка применялась (предпосылка отката)"
#    Предмет — ИСХОДНИКИ: `Cargo.lock` и `target/` создаёт cargo, инструмент их не трогает, и
#    засчитывать их за неоткаченную правку значило бы судить не то, что делали.
verdict "" "$(git status --porcelain -- '*.rs' | head -1)" "правки исходников откачены после прогона"

# 6. ПОТРЕБИТЕЛЬ ДЕЙСТВИТЕЛЬНО СОБИРАЛСЯ. Ищем строку ЦИКЛА (`<имя>: <манифест> (<файл>)`), а не
#    заголовок с аргументами: первая редакция грепала заголовок и потому не отличала «собрали оба»
#    от «напечатали оба, собрали один». Обезоруживание (слом «только первый манифест») оставило её
#    зелёной — тем и вскрылось.
grep -q ': appx/Cargo.toml (' weigh.log
verdict 0 $? "потребительский манифест реально собирался"

exit "$failed"
