#!/usr/bin/env bash
# ВЗВЕШИВАНИЕ ПРИБОРОВ (#320, срез B). Кто из парка держится ЖИВЫМ кодом, а кто только собой.
#
# # Механизм: снимаем `pub`, а не удаляем тип
#
# Снятие `pub` со строки определения — точный тест на само определение прибора («есть ли читатель
# СНАРУЖИ»): внутренние ссылки не трогаются вовсе, краснеют строго те, кто вне модуля. Удаление
# типа ломало бы и сам модуль; переименование чинило бы часть ссылок молча.
#
# # Почему `--bins` и почему НЕСКОЛЬКО манифестов
#
# `--tests`/`--examples`/`--all-targets` ЗАПРЕЩЕНЫ: `record.rs`, `kernel::*` и `dns` покраснели бы
# из собственных тестов, парк отчитался бы зелёным, и инструмент воспроизвёл бы корень эпика —
# ТЕСТ ПОДАЁТ ВХОДЫ САМ, оттого зелёный тест молчит о том, зовёт ли звено кто-нибудь.
#
# Единого воркспейса в репе НЕТ (`nevod2-runtime`, `zond`, `reflex` — отдельные). Крейт, собранный в
# одиночку, МОЛЧИТ о своих потребителях: оплачено 176 зелёными тестами зонда при сломанной сборке
# края. Поэтому манифестов несколько, и все они обязаны быть в журнале.
#
# # Свидетель применения
#
# Прогон, где правка НЕ применилась, недействителен, а не чист: иначе «не покраснело» неотличимо
# от «не отключили». Оплачено поверочным стендом соседней сессии — шесть дефектов окружения за
# день, каждый выглядел исправной работой (правила в `filter/FORWARD` при прозрачном прокси:
# сценарий не применялся, счётчик 0, отчёт зелёный).
#
# # Вход
#
# TSV без заголовка, 4 колонки: КАТАЛОГ КРЕЙТА · файл (от корня) · строка определения · имя.
# Каталог крейта — путь (`reflex/core`), а не имя пакета (`reflex-core`): по нему считается,
# лежит ли читатель вне крейта.
#
# # Выход
#
# TSV, 8 колонок: каталог крейта · файл · строка · имя · читателей вне файла · читателей вне
# крейта · файлы-читатели через запятую · состояние (OK | NOT_APPLIED | NO_LINE).
#
# СМЕРТЬ: парк переразмечен, и взвешивание переехало в механический `audit` крейта приборов —
# скрипт снимается вместе со стендом.
set -u

ROOT="$PWD"
CANDIDATES=""
MANIFESTS=""

while [ $# -gt 0 ]; do
  case "$1" in
    --root)       ROOT="$2"; shift 2 ;;
    --candidates) CANDIDATES="$2"; shift 2 ;;
    --manifests)  MANIFESTS="$2"; shift 2 ;;
    *) printf 'неизвестный аргумент: %s\n' "$1" >&2; exit 2 ;;
  esac
done

[ -n "$CANDIDATES" ] || { echo "нужен --candidates <tsv>" >&2; exit 2; }
[ -n "$MANIFESTS" ]  || { echo "нужен --manifests <m1,m2,...>" >&2; exit 2; }

cd "$ROOT" || exit 2
[ -f "$CANDIDATES" ] || { printf 'нет файла кандидатов: %s\n' "$CANDIDATES" >&2; exit 2; }

# Ошибки, означающие «читатель потерял доступ». E0603 — private; E0432/E0433 — не разрешился
# импорт/путь; E0412 — тип не найден там, где на него смотрели через `use`.
CODES='E0603 E0432 E0433 E0412'

BACKUP="$(mktemp -d)"
RESTORE_FROM=""
RESTORE_TO=""

restore() { # вернуть файл, даже если нас прервали
  if [ -n "$RESTORE_FROM" ] && [ -f "$RESTORE_FROM" ]; then
    cp "$RESTORE_FROM" "$RESTORE_TO"
    RESTORE_FROM=""
  fi
}
trap 'restore; rm -rf "$BACKUP"' EXIT INT TERM

printf 'манифесты: %s\n' "$MANIFESTS" >&2

while IFS=$'\t' read -r crate_dir file line name; do
  [ -n "${name:-}" ] || continue

  if [ ! -f "$file" ]; then
    printf '%s\t%s\t%s\t%s\t\t\t\tNO_LINE\t\n' "$crate_dir" "$file" "$line" "$name"
    continue
  fi

  # ── снимаем `pub` и ДОКАЗЫВАЕМ, что правка применилась ──────────────────────────────────────
  copy="$BACKUP/$(printf '%s' "$file" | tr '/' '_')"
  cp "$file" "$copy"
  RESTORE_FROM="$copy"; RESTORE_TO="$file"

  # Отступ сохраняется: тип внутри модуля объявлен не с начала строки, и якорь `^pub` его бы не
  # взял — правка молча не применилась бы, а прибор получил бы NOT_APPLIED вместо веса.
  sed -i "${line}s/^\([[:space:]]*\)pub /\1/" "$file"

  if cmp -s "$copy" "$file"; then
    # Снимать было нечего: строка не начиналась с `pub`. Это НЕ «вес 0» — это несостоявшийся
    # замер, и путать их нельзя.
    restore
    printf '%s\t%s\t%s\t%s\t\t\t\tNOT_APPLIED\t\n' "$crate_dir" "$file" "$line" "$name"
    continue
  fi

  # ── собираем живые входы, копим файлы-читатели ──────────────────────────────────────────────
  #
  # ВТОРАЯ ПОЛОВИНА СВИДЕТЕЛЯ. `cmp` выше доказывает, что изменился ФАЙЛ; он ничего не говорит о
  # том, что сборка это УВИДЕЛА. Вернись `cargo` из кеша — ошибок не будет, и подключённый прибор
  # получит вес 0, то есть ложный ноль ровно того класса, ради которого заведён эпик. Свидетель
  # обязан стоять на стороне ПРЕДМЕТА (крейт пересобран), а не на стороне вызова (правку внесли);
  # оплачено соседней сессией дважды — универсальный счётчик считал совпадения не в той таблице и
  # молча врал нулём на шести клетках из десяти.
  #
  # УЛИКА — ДВЕ, и по отдельности каждая слепа именно там, где нужна другая.
  #
  # `fresh == false` у `compiler-artifact` — значение, положительно утверждающее пересборку. Оно
  # сильнее отсутствия следа (кеш-попадание доказывалось бы ОТСУТСТВИЕМ строки, а отсутствие
  # неотличимо от «инструмент не запускался»). Но `compiler-artifact` эмитится ТОЛЬКО для
  # успешно собранных юнитов — а мы сборку ломаем НАМЕРЕННО, и когда читатель живёт в том же
  # крейте, артефакта нет по построению. Проверено: слом `zond::Fooling` даёт ноль артефактов
  # `zond` и при этом `Checking zond` в stderr.
  #
  # Поэтому вторая улика — `Checking <пакет>`: она доказывает ЗАПУСК компиляции независимо от
  # исхода. Свидетель обязан быть не только значением на стороне предмета, но и СОВМЕСТИМЫМ с
  # механизмом наблюдения; более сильный в общем случае оказался слеп ровно там, где живёт наш
  # предмет — в сломанной сборке.
  #
  # Имя цели нормализовано cargo: `reflex-core` → `reflex_core`; в stderr имя пакета как в
  # `Cargo.toml`, с дефисом.
  package_raw="$(sed -n 's/^name *= *"\(.*\)"/\1/p' "$crate_dir/Cargo.toml" 2>/dev/null | head -1)"
  package="$(printf '%s' "$package_raw" | tr '-' '_')"
  rebuilt=0
  readers=""
  for manifest in ${MANIFESTS//,/ }; do
    printf '  %s: %s (%s)\n' "$name" "$manifest" "$file" >&2
    raw="$BACKUP/cargo.json"
    noise="$BACKUP/cargo.err"
    cargo check --manifest-path "$manifest" --bins --message-format=json > "$raw" 2>"$noise"
    spans="$(jq -r --arg codes "$CODES" '
          select(.reason == "compiler-message")
          | .message
          | select(.code.code as $c | ($codes | split(" ")) | index($c))
          | .spans[]?
          | .file_name
        ' "$raw" 2>/dev/null)"

    # Крейт кандидата пересобирался хотя бы одним манифестом — значит правку сборка увидела.
    # ВЫВОДИМ ИМЯ, А НЕ САМО ПОЛЕ, и код возврата jq не используем вовсе: `jq -e` ставит статус
    # ПО ЗНАЧЕНИЮ последнего вывода, а искомое значение здесь — литерал `false`. То есть свидетель
    # находил улику, а инструмент читал это как «не нашёл» — ровно тот класс ошибки, который весь
    # этот скрипт и ловит, только у себя самого.
    if [ -n "${package:-}" ]; then
      found="$(jq -r --arg pkg "$package" '
                 select(.reason == "compiler-artifact")
                 | select(.target.name == $pkg)
                 | select(.fresh == false)
                 | .target.name
               ' "$raw" 2>/dev/null | head -1)"
      [ -n "$found" ] && rebuilt=1
      grep -q "Checking $package_raw " "$noise" 2>/dev/null && rebuilt=1
    fi

    # ПУТИ НОРМАЛИЗУЮТСЯ ЗДЕСЬ, пока известен манифест: cargo выдаёт `file_name` относительно
    # каталога СВОЕГО манифеста, и один файл, увиденный двумя манифестами, попадал в список
    # дважды под разными путями. Вес раздувался, а «вне крейта» считалось по обрубку.
    manifest_dir="$(dirname "$manifest")"
    while IFS= read -r span; do
      [ -n "$span" ] || continue
      case "$span" in
        /*) absolute="$span" ;;
        *)  absolute="$ROOT/$manifest_dir/$span" ;;
      esac
      # Файл может не существовать (путь из внешнего крейта в реестре) — тогда берём как есть.
      if [ -e "$absolute" ]; then
        readers="$readers$(realpath --relative-to="$ROOT" "$absolute")"$'\n'
      else
        readers="$readers$span"$'\n'
      fi
    done <<< "$spans"
  done

  restore

  # ФАЙЛ ОПРЕДЕЛЕНИЯ НЕ ОТБРАСЫВАЕТСЯ, и это решение стоит объяснить: первая редакция его
  # отбрасывала «как шум механизма». Обезоруживание показало, что слом этого фильтра не красит
  # ничего, а проверка на живом rustc объяснила почему:
  #   * приватный тип в публичной сигнатуре даёт `private_interfaces` — WARNING, кода нет в
  #     списке, до фильтра шум не доходит вовсе;
  #   * у `E0603` ровно ОДИН span — на месте использования; на определение rustc его не ставит
  #     (пояснение живёт в `children`, а не в `spans`).
  # Зато фильтр отбрасывал бы ЗАКОННОГО читателя — другой модуль того же файла, который снаружи
  # модуля определения и доступ теряет по-настоящему.
  reader_files="$(printf '%s' "$readers" \
    | sed "s#^$ROOT/##" \
    | grep -v '^[[:space:]]*$' \
    | sort -u)"

  outside_file="$(printf '%s' "$reader_files" | grep -c . || true)"
  outside_crate="$(printf '%s' "$reader_files" | grep -v "^$crate_dir/" | grep -c . || true)"
  joined="$(printf '%s' "$reader_files" | paste -sd, -)"

  # ── ВТОРОЙ ПРОХОД: ПЕРЕИМЕНОВАНИЕ ──────────────────────────────────────────────────────────
  #
  # Снятие `pub` слепо к читателям ВНУТРИ поддерева модуля определения: подмодуль есть потомок и
  # приватный тип родителя видит. Для типа в корне крейта (`lib.rs`) поддерево — весь крейт, и
  # первый проход меряет только межкрейтовых читателей. Проверено на живой репе: у
  # `dataplane::Told` снятие `pub` даёт лишь warning `private_interfaces`, при том что читателей
  # в крейте четыре. Без второго прохода их нули читались бы как «читателей нет вовсе», и
  # ЭЛЕМЕНТ от МЁРТВОГО было бы не отличить — а это разные беды с разным лечением.
  #
  # Переименование внутри файла определения согласованно правит все вхождения в нём, поэтому сам
  # файл не краснеет, а всякий читатель ВНЕ файла — краснеет.
  cp "$file" "$copy"
  RESTORE_FROM="$copy"; RESTORE_TO="$file"
  sed -i "s/\b${name}\b/${name}Corch/g" "$file"

  renamed_readers=""
  for manifest in ${MANIFESTS//,/ }; do
    spans="$(cargo check --manifest-path "$manifest" --bins --message-format=json 2>/dev/null \
      | jq -r --arg codes "$CODES" '
          select(.reason == "compiler-message")
          | .message
          | select(.code.code as $c | ($codes | split(" ")) | index($c))
          | .spans[]?
          | .file_name
        ' 2>/dev/null)"
    manifest_dir="$(dirname "$manifest")"
    while IFS= read -r span; do
      [ -n "$span" ] || continue
      case "$span" in
        /*) absolute="$span" ;;
        *)  absolute="$ROOT/$manifest_dir/$span" ;;
      esac
      if [ -e "$absolute" ]; then
        renamed_readers="$renamed_readers$(realpath --relative-to="$ROOT" "$absolute")"$'\n'
      else
        renamed_readers="$renamed_readers$span"$'\n'
      fi
    done <<< "$spans"
  done

  restore

  by_rename="$(printf '%s' "$renamed_readers" \
    | grep -v '^[[:space:]]*$' \
    | grep -Fxv "$file" \
    | sort -u \
    | grep -c . || true)"

  # NOT_BUILT — не «вес 0», а несостоявшийся замер: сборка правки не заметила, и число ничего не
  # означает. Состояние отдельное намеренно: слить его с нулём значило бы объявить прибор
  # неподключённым на основании того, что мы его не проверили.
  state=OK
  [ "$rebuilt" -eq 1 ] || state=NOT_BUILT

  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$crate_dir" "$file" "$line" "$name" "$outside_file" "$outside_crate" "$joined" "$state" "$by_rename"
done < "$CANDIDATES"
