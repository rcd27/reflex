#!/usr/bin/env bash
# РАЗДЕЛЕНИЕ НУЛЕЙ (#320, срез C, шаг C3). Ноль веса — ДВЕ РАЗНЫЕ БЕДЫ с разным лечением:
#
#   * ЭЛЕМЕНТ — тип потребляется прибором, который сам подключён. Наружу ему высказываться незачем,
#     ноль ему не дефект. Так `meter::Freshness` служит `Sighting`, и перепись среза 0 записала
#     его прибором с нулевой подключённостью ошибочно.
#   * МЁРТВЫЙ — не потребляется никем: ни прибором, ни другим элементом. Кандидат на снос или на
#     провод, и решает это список нужд, а не вес.
#
# Различает их не вес, а ЧИТАТЕЛЬ: в каком файле имя встречается и жив ли тот файл. Регулярное
# выражение смысла не знает — поэтому вывод здесь ПОДСКАЗКА для чтения, а не вердикт, и назван так
# в заголовке колонки.
#
# ЦЕНА НАЗВАНА: греп слеп к принадлежности имени. `Fate` и `Outcome` существуют в репе дважды
# каждый (`zond::fate` против `reflex::Fate`; `domain::pipe` против `zond::lib`), и на них
# подсказка соврёт. Проверять глазами обязательно там, где имя короткое и общее.
#
# СМЕРТЬ: парк переразмечен и переехал в крейт приборов — классификация делается его паспортом.
set -u

WEIGH="${1:-}"
[ -f "$WEIGH" ] || { echo "нужен путь к TSV взвешивания" >&2; exit 2; }

files="$(mktemp)"
trap 'rm -f "$files"' EXIT
git ls-files --recurse-submodules '*.rs' | grep -v '^nevod/' > "$files"

# Файлы, где живёт хотя бы один ПОДКЛЮЧЁННЫЙ прибор (вес по любому из двух проходов > 0).
alive="$(awk -F'\t' '$8 == "OK" && ($5 > 0 || $9 > 0) { print $2 }' "$WEIGH" | sort -u)"

printf 'крейт\tфайл\tимя\tчитателей\tиз них живых\tподсказка\n'

# РАЗБОР ЧЕРЕЗ `cut`, А НЕ `IFS=$'\t' read`: таб есть whitespace, и bash СХЛОПЫВАЕТ подряд идущие
# разделители — строка с пустым полем (у прибора нет читателей) теряет его, и все последующие
# колонки съезжают влево. Инструмент при этом не падает, а молча выдаёт пустой результат.
while IFS= read -r row; do
  crate_dir="$(printf '%s' "$row" | cut -f1)"
  file="$(printf '%s' "$row" | cut -f2)"
  name="$(printf '%s' "$row" | cut -f4)"
  w_pub="$(printf '%s' "$row" | cut -f5)"
  state="$(printf '%s' "$row" | cut -f8)"
  by_rename="$(printf '%s' "$row" | cut -f9)"

  [ "${state:-}" = "OK" ] || continue
  [ "${w_pub:-0}" = "0" ] || continue
  [ "${by_rename:-0}" = "0" ] || continue

  readers="$(grep -l -w "$name" $(cat "$files") 2>/dev/null | grep -Fxv "$file" || true)"
  total="$(printf '%s' "$readers" | grep -c . || true)"

  live=0
  while IFS= read -r reader; do
    [ -n "$reader" ] || continue
    printf '%s\n' "$alive" | grep -Fxq "$reader" && live=$((live + 1))
  done <<< "$readers"

  # ВНУТРИ СВОЕГО ФАЙЛА тип тоже может служить прибору — так `meter::Freshness` служит `Sighting`.
  # Первая редакция исключала файл определения из подсчёта и объявляла такой тип МЁРТВЫМ, тогда
  # как он образцовый ЭЛЕМЕНТ. Ошибка не в счёте, а в имени класса: «нигде» означало «нигде,
  # кроме своего файла», и это разные вещи с противоположным лечением.
  inside="$(grep -c -w "$name" "$file" 2>/dev/null || true)"

  case "$total:$live:$inside" in
    0:*:0|0:*:1) hint="МЁРТВЫЙ — имя встречается только в своём определении" ;;
    0:*:*)       hint="ЭЛЕМЕНТ — служит внутри своего файла, наружу не высказывается" ;;
    *:0:*)       hint="ЧИТАТЬ ГЛАЗАМИ — читатели есть, но ни один не несёт подключённого прибора" ;;
    *)           hint="ЭЛЕМЕНТ — потребляется файлом с подключённым прибором" ;;
  esac

  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$crate_dir" "$file" "$name" "$total" "$live" "$inside" "$hint"
done < "$WEIGH"
