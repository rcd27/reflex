//! СИГНАЛ БЕДЫ — то, что человек почувствовал бы как поломку.
//!
//! # Почему это прибор, а не домен
//!
//! `Distress` описывает МИР: «пришёл сброс», «молчание столько-то», «байты идут так медленно, что
//! это неотличимо от поломки». Ни одно из этих слов не говорит, что мы предпримем, — лечение
//! живёт в `Finding` и в маршруте, и они остались у потребителя.
//!
//! Пока сигнал беды жил в домене, четыре прибора провода (`Rst`, `Silence`, `Throttled`, `Choked`)
//! не могли переехать в общий дом: их показание тянуло домен за собой.

/// СИГНАЛ БЕДЫ. То, что человек почувствовал бы как поломку, если бы мы не увели его в ногу.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Distress {
    /// Пришёл RST. От кого — вопрос расследования, а не догадки.
    Rst,
    /// Молчание дольше названного окна, в миллисекундах.
    Silence { ms: u32 },
    /// Байты идут, но так медленно, что это неотличимо от поломки.
    Throttled { bps: u32 },
    /// Ответ пришёл, но это заглушка «недоступно в вашей стране».
    GeoStub,
    /// Соединение живо, байтов ноль.
    NoBytes,
    /// КЛИЕНТ ПОВТОРИЛ ПРОСЬБУ, а цель не отдала ни байта. Величина — сколько человек ждёт с
    /// первой отправки, в миллисекундах.
    ///
    /// # Почему это отдельная буква, а не ранний [`Distress::NoBytes`]
    ///
    /// Различает их ЧЕЙ ПОРОГ сработал. `NoBytes` наступает по НАШЕМУ терпению (константа кода,
    /// одна на цель за океаном и цель в соседней стойке); повтор наступает по RTO КЛИЕНТСКОГО
    /// ЯДРА, отмеренному под фактический RTT именно этого пути. Слей их в одну букву — и замер,
    /// ради которого повтор заводится («360 мс против 1500»), станет ненаблюдаемым.
    Retransmit { after_ms: u32 },
}

impl Distress {
    /// ИМЯ СИГНАЛА — публичный контракт: он уезжает меткой в метрику и словом в дело (#321).
    /// Тотально и без `Debug`, чей формат стандартом объявлен нестабильным: переименуй кто-нибудь
    /// вариант — компилятор промолчит, а метка сменится, и владелец увидит ноль, неотличимый от
    /// «беды нет».
    pub fn name(&self) -> &'static str {
        match self {
            Distress::Rst => "rst",
            Distress::Silence { .. } => "silence",
            Distress::Throttled { .. } => "throttled",
            Distress::GeoStub => "geo_stub",
            Distress::NoBytes => "no_bytes",
            Distress::Retransmit { .. } => "retransmit",
        }
    }

    /// ТРЕБУЕТ ЛИ ПОКАЗАНИЕ ВНИМАНИЯ — и ответ здесь ОДИН НА ВЕСЬ АЛФАВИТ, потому что таков сам
    /// тип: `Distress` есть «то, что человек почувствовал бы как поломку». Небеспокоящей беды не
    /// бывает, и клетка, где она была бы возможна, в этом типе не выражается.
    ///
    /// # Почему метод, а не константа у потребителя
    ///
    /// До 05.09.2026 это решали ЧЕТЫРЕ прибора, каждый своим `match` по всему алфавиту, и все
    /// четыре возвращали `true` во всех рукавах — то есть четыре разбора, ничего не решающих.
    /// Заведись когда-нибудь буква, которую лечить не надо, — правка нужна здесь одна, а не в
    /// каждом приборе, чей словарь эту букву включает.
    pub const fn alarming(&self) -> bool {
        true
    }

    /// ВЕЛИЧИНА ПОКАЗАНИЯ В ЕДИНИЦЕ ЧЕЛОВЕКА. Пусто — показание есть само событие, и мерить в нём
    /// нечего: сброс либо пришёл, либо нет.
    ///
    /// Отличается от [`Display`] предметом, а не оформлением: `Display` пишет машинную улику в
    /// дело (`silence ms=1500`), а здесь — то, что читает человек. Обе живут в этом файле именно
    /// затем, чтобы сверяться глазом за секунду; разъезжались они, пока лежали в разных.
    pub fn detail(&self) -> String {
        match self {
            Distress::Silence { ms } => format!("{ms} мс без байтов"),
            Distress::Throttled { bps } => format!("{} КБ/с", bps / 1024),
            Distress::Retransmit { after_ms } => format!("повтор через {after_ms} мс"),
            Distress::Rst | Distress::NoBytes | Distress::GeoStub => String::new(),
        }
    }
}

/// УЛИКА СИГНАЛА — имя ПЛЮС величина, которой судит человек (#325).
///
/// «Молчание» без миллисекунд и «стойло» без скорости неразличимы между собой у соседних целей,
/// а различать их — предмет таксономии. Имя открывает строку и совпадает с [`Distress::name`]:
/// два имени одного события лечатся уже не переименованием, а археологией.
impl core::fmt::Display for Distress {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Distress::Rst => f.write_str("rst"),
            Distress::Silence { ms } => write!(f, "silence ms={ms}"),
            Distress::Throttled { bps } => write!(f, "throttled bps={bps}"),
            Distress::GeoStub => f.write_str("geo_stub"),
            Distress::NoBytes => f.write_str("no_bytes"),
            Distress::Retransmit { after_ms } => write!(f, "retransmit after_ms={after_ms}"),
        }
    }
}

#[cfg(test)]
mod tests {
    /// АЛФАВИТ БЕДЫ ПЕРЕЧИСЛЯЕТСЯ РОВНО В ОДНОМ ФАЙЛЕ — закон владельца, заданный 05.09.2026
    /// дословно: «одна беда должна детектиться в одном месте; где можно посмотреть и сказать:
    /// во, RST/silent_drop».
    ///
    /// # Почему это тест, а не договорённость
    ///
    /// Договорённость держится памятью автора и ломается на первой же букве, заводимой в спешке.
    /// Замер 05.09 показал цену: имя беды было записано ДВАЖДЫ (`Distress::name` и
    /// `detect::name_of`, совпадали буква в букву), величина ТРИЖДЫ, тревожность ЧЕТЫРЕЖДЫ — и
    /// каждая копия объясняла в докстринге, что объявлена отдельно, «чтобы не разъехалось».
    /// Заведение одной буквы потребовало правки четырёх мест.
    ///
    /// # Что именно считается
    ///
    /// ФАЙЛЫ, где перечисляется алфавит, а не сами перечисления: `Display` и `name` в одном файле
    /// суть два взгляда на одну таблицу и сверяются глазом за секунду; та же пара в разных файлах
    /// расходится молча. Игла — буква без полей, входящая в КАЖДУЮ полную таблицу.
    ///
    /// Игла собирается `concat!`: целиком в исходнике она не встречается, и самосчёт невозможен
    /// по построению, а не по внимательности (грабля оплачена реестром парка — там счётчик
    /// пополнял собственную выборку).
    #[test]
    fn the_alphabet_of_trouble_is_spelled_out_in_exactly_one_file() {
        let needle = concat!("Distress::", "GeoStub");
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        // Нечитаемый каталог даёт ПУСТОЙ список, а не панику: пустой не равен ожидаемому, и тест
        // покраснеет — то есть «не смогли посмотреть» отличимо от «посмотрели и чисто».
        let spelling: Vec<String> = std::fs::read_dir(&root)
            .into_iter()
            .flatten()
            .filter_map(|entry| entry.ok())
            .filter(|entry| {
                std::fs::read_to_string(entry.path())
                    .map(|text| text.contains(needle))
                    .unwrap_or(false)
            })
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .collect();

        assert_eq!(
            spelling,
            ["distress.rs"],
            "алфавит беды перечислен в {} файлах — имя, величина и тревожность суть свойства \
             БУКВЫ, и всякая копия таблицы разъедется молча",
            spelling.len()
        );
    }
}
