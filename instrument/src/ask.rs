//! ВОПРОСЫ ПРИБОРОВ — атомы, из которых складывается требование к наблюдению.
//!
//! # Почему по одному факту на трейт, а не «контракт прибора» целиком
//!
//! Крупный трейт («дай мне всё, что нужно прибору ухода») ЗАСТЫВАЕТ: добавить вопрос значит
//! сломать всех, кто на него отвечает, и потому дисциплина «не проси лишнего» держится памятью
//! автора. Память — ровно тот способ хранения, который мы лечим у приборов: то, что надо держать
//! в уме, рано или поздно не удерживается.
//!
//! Атомарные вопросы убирают память из уравнения ТИПОМ. Прибор перечисляет свои требования в
//! границе (`S: SeveredByPerson + TargetDelivered`), и три вещи следуют из этого сами:
//!
//! * **лишний вопрос виден** — он стоит в границе, его нельзя «попросить на всякий случай» молча;
//! * **контракт не застывает** — новый вопрос есть НОВЫЙ трейт, и он не ломает существующих
//!   отвечающих: тот, кто его не реализует, просто не годится тому прибору, который его просит;
//! * **вопросы переиспользуются** — «отдала ли цель» спрашивают трое, и отвечает домен ОДИН раз.
//!
//! # Алгебра, а не набор
//!
//! Требование прибора есть ПРОИЗВЕДЕНИЕ вопросов: `A + B` в границе значит «наблюдение, умеющее
//! и то, и другое». Композиция приборов складывает требования по тому же правилу, и потому
//! композит выражается типом, а не соглашением: `S: A + B + C` — это и есть его паспорт входа.
//!
//! Отсюда же следует закон, который мы уже знали числом: **различение композита ≤ различению
//! частей**. Композит не может спросить больше, чем спрашивают его части вместе, — граница
//! попросту не даёт назвать вопрос, которого никто не задал.

/// ОБОРВАЛ ЛИ РАЗГОВОР САМ ЧЕЛОВЕК — закрыл вкладку, перестал ждать, переоткрыл страницу.
///
/// Не «пришёл сброс»: сброс бывает и от цели, и от нас самих, и путать их значило бы обвинять
/// мир в том, что сделали мы (замер 29.08: из 23 сбросов 17 были наши собственные).
pub trait SeveredByPerson {
    fn severed_by_person(&self) -> bool;
}

/// УСПЕЛА ЛИ ЦЕЛЬ ОТДАТЬ ХОТЬ БАЙТ к моменту наблюдения.
///
/// Этим «ушёл ни с чем» отличается от «ушёл, получив своё»: первое есть беда, второе — обычный
/// конец разговора, и лечения у них противоположные.
pub trait TargetDelivered {
    fn target_delivered(&self) -> bool;
}

/// СКОЛЬКО РАЗГОВОРОВ НЕСЁТ НОГА В ЭТОМ ОКНЕ.
///
/// Знаменатель для всякого суждения о ноге: доля застрявших без него не считается, а «два
/// застряло» значит разное при десяти разговорах и при двух.
pub trait Carrying {
    fn carrying(&self) -> usize;
}

/// СКОЛЬКО ИЗ НИХ ЗАСТРЯЛО — не отдают байт при живом спросе.
pub trait Stalled {
    fn stalled(&self) -> usize;
}

/// КОГДА ЭПИЗОД НАЧАЛСЯ. `None` — не начинался вовсе, и это не то же самое, что «начался давно».
pub trait OpenedAt {
    fn opened_at(&self) -> Option<std::time::Instant>;
}

/// КОГДА В НЁМ В ПОСЛЕДНИЙ РАЗ ЧТО-ТО ПРОИСХОДИЛО.
pub trait LastSeen {
    fn last_seen(&self) -> Option<std::time::Instant>;
}

/// ВИДЕЛИ ЛИ УХОД ЧЕЛОВЕКА НА ПРОВОДЕ.
///
/// Отдельно от `SeveredByPerson`: тот про ОДИН разговор, этот — про эпизод целиком. Слить их
/// значило бы объявить эпизод законченным от первой закрытой вкладки.
pub trait PersonLeft {
    fn person_left(&self) -> bool;
}

// ── ССЫЛКА ОТВЕЧАЕТ ТАК ЖЕ, КАК ЗНАЧЕНИЕ ──────────────────────────────────────────────────────
//
// Без этих правил домен, у которого наблюдение под рукой по ссылке, вынужден был бы его
// КЛОНИРОВАТЬ ради вопроса — то есть платить копией за чистоту границы. Копия дешёвая не всегда
// (у окна эпизода внутри вклады), а главное — она лишняя: вопрос читает, а не владеет.
//
// Правила общие (`impl<T: Ask> Ask for &T`), и потому их не придётся дописывать для каждого
// нового вопроса-атома... кроме самих себя: новый вопрос добавляет и своё правило. Цена названа.

impl<T: SeveredByPerson> SeveredByPerson for &T {
    fn severed_by_person(&self) -> bool {
        (*self).severed_by_person()
    }
}

impl<T: TargetDelivered> TargetDelivered for &T {
    fn target_delivered(&self) -> bool {
        (*self).target_delivered()
    }
}

impl<T: Carrying> Carrying for &T {
    fn carrying(&self) -> usize {
        (*self).carrying()
    }
}

impl<T: Stalled> Stalled for &T {
    fn stalled(&self) -> usize {
        (*self).stalled()
    }
}

impl<T: OpenedAt> OpenedAt for &T {
    fn opened_at(&self) -> Option<std::time::Instant> {
        (*self).opened_at()
    }
}

impl<T: LastSeen> LastSeen for &T {
    fn last_seen(&self) -> Option<std::time::Instant> {
        (*self).last_seen()
    }
}

impl<T: PersonLeft> PersonLeft for &T {
    fn person_left(&self) -> bool {
        (*self).person_left()
    }
}

/// НАБЛЮДЕНИЕ, УМЕЮЩЕЕ ОТВЕТИТЬ ТОЛЬКО НА ОДИН ВОПРОС, НЕ ГОДИТСЯ ПРИБОРУ, СПРАШИВАЮЩЕМУ ДВА.
///
/// Это и есть проверка того, что граница не украшение. Пример обязан НЕ КОМПИЛИРОВАТЬСЯ: если он
/// соберётся, значит требование прибора выражено словами, а не типом, и «спросить лишнего» снова
/// стало вопросом дисциплины.
///
/// ```compile_fail
/// use reflex_instrument::ask::SeveredByPerson;
/// use reflex_instrument::departure::DepartureInstrument;
/// use reflex_core::{Detector, DetectorEvent};
///
/// struct Half(bool);
/// impl SeveredByPerson for Half {
///     fn severed_by_person(&self) -> bool { self.0 }
/// }
///
/// // `TargetDelivered` не реализован — прибор не собирается.
/// let _ = DepartureInstrument::<Half>::new().step(DetectorEvent::packet_now(Half(true)));
/// ```
///
/// А с обоими ответами — собирается:
///
/// ```
/// use reflex_instrument::ask::{SeveredByPerson, TargetDelivered};
/// use reflex_instrument::departure::{DepartureInstrument, Left};
/// use reflex_core::{Detector, DetectorEvent};
///
/// struct Whole { severed: bool, delivered: bool }
/// impl SeveredByPerson for Whole {
///     fn severed_by_person(&self) -> bool { self.severed }
/// }
/// impl TargetDelivered for Whole {
///     fn target_delivered(&self) -> bool { self.delivered }
/// }
///
/// let seen = Whole { severed: true, delivered: false };
/// let (_, said) = DepartureInstrument::new().step(DetectorEvent::packet_now(seen));
/// assert_eq!(said.as_slice(), &[Left::Unserved]);
/// ```
/// Константа-носитель примеров: у документации нет иного места, куда их повесить, а сами примеры
/// и есть проверка. Значения не несёт намеренно.
