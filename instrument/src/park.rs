//! РЕЕСТР ПАРКА — паспорт, снятый с типа и ставший ЗНАЧЕНИЕМ (#320, 02.09).
//!
//! # Зачем снимок, если паспорт и так объявлен
//!
//! Паспорт живёт ассоциированными константами трейта, и перебрать их нельзя: типы не значения.
//! Оттого всякий вопрос о ПАРКЕ («сколько приборов отвечает на ступень `Reached`», «есть ли
//! производитель у строки таблицы улик») сегодня задаётся человеком глазами, а ответ на него
//! живёт в чужой голове ровно до следующего прибора.
//!
//! Снимок переводит паспорт в данные, и парк становится тем, о чём можно спросить машину.
//!
//! # ЧТО ЭТИМ ЛЕЧИТСЯ, И ЦЕНА ЭТОГО ЗАМЕРЕНА
//!
//! [`crate::Rung::evidence`] есть ЗАМЕРЕННАЯ таблица: где лежит улика ступени на протоколе, и
//! `None` значит «улики не существует». Таблица оплачена фикстурами, но не исполняется ничем —
//! между ней и парком нет ни одной проверки. Сверка 02.09 дала два расхождения:
//!
//! * `Rung::Reached` объявлен наблюдаемым на любом протоколе, и НИ ОДИН прибор его не отвечает;
//! * `Authentic × Tls` объявлен слепым (`None`), а прибор `trust` эту улику читает — и `None`
//!   там значит [`crate::Silence::Blind`], то есть «чините другим прибором» о приборе, который
//!   уже построен.
//!
//! Оба расхождения — не опечатки, а следствие того, что объявление и парк никогда не сводились.
//!
//! # ГРАНИЦА КРЕЙТА
//!
//! Здесь только СНИМОК и его тип. Самого реестра тут нет и быть не может: приборы живут в трёх
//! крейтах (`instrument` и потребители), и ни один из них не видит остальных целиком. Союз
//! собирается там, где виден весь парк, — и сверяется там же.

/// ПАСПОРТ, СНЯТЫЙ С ТИПА. Ровно те оси переписи, по которым парк спрашивают.
///
/// Полей меньше, чем у трейта, и это намеренно: снимок заводится под ВОПРОС («кто отвечает на
/// ступень», «где лежит улика»), а не как второй способ хранить паспорт. Копия, повторяющая
/// оригинал целиком, разъезжается с ним — это уже оплачено (#320: интерпретация уехала в
/// `instrument`, память осталась в другом крейте, и они разошлись в тот же день).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Passport {
    /// Публичное имя прибора — им же подписаны его показания.
    pub instrument: &'static str,
    /// Уровень, на котором лежит улика.
    pub layer: crate::Layer,
    /// Протоколы, на которых улика существует. Пустой список — улики нет на проводе вовсе.
    pub protocols: &'static [crate::Protocol],
    /// Вопрос, на который прибор отвечает. `None` — прибор не есть детектор ступени.
    pub rung: Option<crate::Rung>,
    /// ПОЛНОЕ ИМЯ ТИПА — `reflex_instrument::detect::RstInstrument` и подобные.
    ///
    /// Публичного имени (`"rst"`) для поиска читателей НЕДОСТАТОЧНО: в коде прибор зовут типом, а
    /// строка `"rst"` встречается в реестрах имён событий и в чужой прозе. Имя типа берётся у
    /// компилятора ([`std::any::type_name`]), а не пишется рядом рукой, — иначе оно разъедется с
    /// типом ровно так же, как разъезжались паспорта.
    ///
    /// У параметризованных приборов сюда попадает и параметр (например, конкретный `L` у
    /// `LinkInstrument<L>`); читателей ищут по части до `<`.
    pub type_path: &'static str,
    /// ЧТО ЗАСТАВЛЯЕТ ПРИБОР ВЫСКАЗАТЬСЯ. Нужен переписи срока: у прибора со своими часами шаг
    /// решётки сравним с терпением человека прямо, у прибора с чужим темпом — нет.
    pub cadence: crate::Cadence,
}

/// Снять паспорт с типа.
///
/// Функция, а не метод: она о ТИПЕ, а не об экземпляре, и звать её на значении незачем — прибор
/// со своим состоянием и его паспорт суть разные вещи.
///
/// # ЗДЕСЬ ЖЕ ПАСПОРТ И ПОВЕРЯЕТСЯ (#320, срез 4)
///
/// `const { … }` — не украшение: блок вычисляется В МОМЕНТ МОНОМОРФИЗАЦИИ, то есть отдельно для
/// каждого прибора, чей паспорт здесь снимают. Расхождение паспорта с таблицей улик становится
/// ошибкой СБОРКИ, а не падением прогона.
///
/// ПЕРВАЯ РЕДАКЦИЯ ССЫЛАЛАСЬ НА АССОЦИИРОВАННУЮ КОНСТАНТУ (`let () = I::PASSPORT_HOLDS;`) и НЕ
/// РАБОТАЛА: ссылка в теле обычной функции её не форсирует, и обезоруживание это показало —
/// заведомо сломанный паспорт собрался молча. Проверка, которую не удалось заставить покраснеть,
/// не в покрытии; здесь она покраснела только после смены механизма.
///
/// # ЦЕНА НАЗВАНА: `cargo check` ЭТОГО НЕ ЛОВИТ
///
/// Мономорфизация — часть кодогенерации, и `const`-блок вычисляется на ней. `cargo check` кода не
/// генерирует, а значит сломанный паспорт пройдёт его МОЛЧА; ловят `cargo build` и `cargo test`.
/// Замерено обезоруживанием 02.09: `check` зелёный, `build` красный на том же дереве.
///
/// Для рабочего цикла это существенно: `check` — самая частая команда, и полагаться на неё как на
/// поверку паспорта нельзя. Оттого тест парка остаётся ВТОРЫМ оракулом, а не наследием.
///
/// Обойти можно только не внеся прибор в реестр — а это ловит счётчик полноты.
/// # ПЕРЕСТАЛА БЫТЬ `const` РАДИ ИМЕНИ ТИПА
///
/// [`std::any::type_name`] в `const`-контексте пока не стабилизирован. Цена уплачена сознательно:
/// имя типа, взятое у компилятора, не разъезжается с типом, а написанное рядом рукой — разъедется,
/// и это уже оплачено паспортами. Поверка паспорта от снятия `const` не пострадала: `const { … }`
/// внутри обычной функции вычисляется при мономорфизации ровно так же.
/// # ГРАНИЦА ПОВТОРЕНА, А НЕ ПОДРАЗУМЕВАЕТСЯ
///
/// Паспорт связывает объявленный сигнал с той буквой пары, где прибор говорит ([`crate::Spoken`]).
/// Границу трейта компилятор в общем коде не выводит сам, и всякий, кто берёт прибор параметром,
/// повторяет её вслух. Плата за то, что связь проверяется, а не описывается.
pub fn of<I: crate::Instrument>() -> Passport
where
    (I::To, I::Notes): crate::Spoken<Signals = smallvec::SmallVec<[I::Signal; 2]>>,
{
    const {
        assert!(
            crate::passport_holds(I::RUNG, I::PROTOCOLS, I::LAYER),
            "паспорт прибора разошёлся с таблицей улик: ступень объявлена там, где улики нет, \
             либо прибор стоит не на том уровне, либо не назван ни один протокол"
        )
    }

    Passport {
        instrument: I::INSTRUMENT,
        layer: I::LAYER,
        protocols: I::PROTOCOLS,
        rung: I::RUNG,
        type_path: std::any::type_name::<I>(),
        cadence: I::CADENCE,
    }
}

/// ПРИБОРЫ ЭТОГО КРЕЙТА, ЧЕЙ ПАСПОРТ ЧИТАЕТСЯ ЗДЕСЬ ЖЕ.
///
/// Список руками, и это НЕ дефект разводки: снять его автоматически нечем — трейт по типам не
/// перебирается. Полнота держится проверкой, а не дисциплиной: тест сверяет длину этого списка с
/// числом реализаций трейта в дереве крейта и краснеет, если прибор заведён и не внесён.
pub fn here() -> Vec<Passport> {
    vec![
        of::<crate::detect::RstInstrument>(),
        of::<crate::detect::SilenceInstrument>(),
        of::<crate::detect::ThrottledInstrument>(),
        of::<crate::detect::ChokedInstrument>(),
        of::<crate::retransmit::RetransmitInstrument>(),
        of::<crate::agreement::AgreementInstrument>(),
        of::<crate::drift::HistoryInstrument>(),
        of::<crate::fate::ObservedInstrument>(),
        of::<crate::pace::PaceInstrument>(),
        of::<crate::resolve::ResolutionInstrument>(),
        of::<crate::sag::SagInstrument>(),
        of::<crate::trust::TrustInstrument>(),
    ]
}

/// ПРИБОРЫ, ЧЕЙ ПАСПОРТ ЗДЕСЬ НЕ ЧИТАЕТСЯ — и это свойство, а не недосмотр.
///
/// Они параметризованы ДОМЕННЫМ типом (`DepartureInstrument<S>`, `EpisodeInstrument<W>`,
/// `LinkInstrument<L>`): параметр говорит «какой угодно, лишь бы отвечал на такие-то вопросы», а
/// сами вопросы задаёт домен. Константы паспорта от параметра не зависят — но прочесть
/// ассоциированную константу без конкретного типа Rust не даёт, а конкретный тип живёт не здесь.
///
/// Список ИМЁН, а не заглушек. Завести здесь пустышку ради чтения паспорта значило бы поселить в
/// продукте тип, существующий только для теста, — и первый же читатель принял бы его за прибор.
/// Паспорта этих троих читает союзный реестр там, где домен виден.
pub const PARAMETERISED: [&str; 3] = ["departure", "episode", "leg"];

#[cfg(test)]
mod tests {
    use super::*;

    /// РЕЕСТР ПОЛОН — иначе всякий вопрос к парку отвечает о ЧАСТИ парка и выглядит как ответ о
    /// парке.
    ///
    /// Считается по дереву, а не по памяти автора: заведённый и не внесённый прибор — ровно тот
    /// класс дефекта, из-за которого прибор доверия оказался в одной ленте и отсутствовал в
    /// другой (#320, четырнадцатый ноль подключённости).
    /// # СВИДЕТЕЛЬ ОБЕЗОРУЖЕН, И ОБА ЕГО ДЕФЕКТА НАЗВАНЫ
    ///
    /// Первая редакция искала `"impl crate::Instrument for"` и дала 12 вместо 14 — сразу две беды
    /// в одном счётчике. **Считал не то:** у параметризованных приборов между `impl` и трейтом
    /// стоит список границ (`impl<W: OpenedAt + …> crate::Instrument for`), и подстрока их не
    /// ловила. **Считал себя:** этот самый файл содержал искомую строку литералом и добавлял
    /// единицу к результату — то есть счётчик пополнял собственную выборку, и две ошибки почти
    /// сошлись, замаскировав друг друга.
    ///
    /// Оттого игла собирается `concat!`: строка целиком в исходнике не встречается ни разу, и
    /// самосчёт невозможен по построению, а не по внимательности.
    #[test]
    fn the_registry_lists_every_instrument_of_this_crate() {
        let needle = concat!("crate::", "Instrument", " for ");
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let declared: usize = std::fs::read_dir(&root)
            .expect("каталог исходников читается")
            .filter_map(|entry| entry.ok())
            .filter_map(|entry| std::fs::read_to_string(entry.path()).ok())
            .map(|text| text.matches(needle).count())
            .sum();

        assert_eq!(
            here().len() + PARAMETERISED.len(),
            declared,
            "приборов в дереве {declared}, в реестре {} плюс {} параметризованных — вопрос к \
             парку ответит о ЧАСТИ парка, оставаясь похожим на ответ о парке",
            here().len(),
            PARAMETERISED.len()
        );
    }

    /// ИМЕНА В РЕЕСТРЕ РАЗЛИЧНЫ. Два прибора под одним именем неразличимы в ленте и в реестре
    /// молчащих: показание одного читалось бы как показание другого.
    #[test]
    fn no_two_instruments_share_a_name() {
        let names: std::collections::BTreeSet<&str> =
            here().iter().map(|passport| passport.instrument).collect();

        assert_eq!(names.len(), here().len(), "имена приборов повторяются");
    }
}
