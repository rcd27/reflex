//! Приборы на величинах КРАЯ, без собственного состояния. Прибор о носителе не знает — читает
//! `EdgeView` (conntrack, карта eBPF, чужая ОС) и марку под своей `Layout`. Собственное `S`
//! вырождено: исход зависит от края и марки, не от прожитого (§ спеки — состояние в ядре).
//!
//! ## Сигнал по БАЙТАМ СВЕРХ ЗАГОЛОВКОВ, порог — по ВОЗРАСТУ (оба оплачены прогоном)
//!
//! Счётчики БАЙТ conntrack считают полный кадр (L3+L4+нагрузка), не нагрузку: у молчащей цели
//! `up.bytes ≈ 60` — её `SYN+ACK` с заголовками, не ноль. Оттого не «байты против нуля», а
//! `up.bytes > up.packets × HDR + FLOOR` — сверх потолка заголовков не меньше `FLOOR`. Та же
//! арифметика, которой прибор мерит просьбу клиента вниз: один предмет — один закон, повёрнутый в
//! обе стороны.
//! * `up.packets == 0` → `Blackhole` — `SYN+ACK` не пришёл, соединения не было;
//! * рукопожатие есть, клиент попросил, а сверх заголовков цель не дала ничего → `NoBytes`;
//! * цель отдала данные → жива → `Released`.
//!
//! ПОЧЕМУ НЕ ПАКЕТАМИ, КАК БЫЛО. Прежде жизнь цели читалась счётом её пакетов (`up.packets >= 2` —
//! жива), и это был вопрос НЕ О ТОМ, о чём слово: подтверждение без данных — тоже пакет. Цель,
//! подтвердившая `ClientHello` и не сказавшая больше ни байта, отпускалась навсегда (`Released`), а
//! проводная половина двери на TCP `NoBytes` не говорит вовсе — слово отдано краю как
//! единственному свидетелю истории. Молчали обе половины, и молчание было КРУГОВЫМ: каждая
//! ссылалась на другую. Замер, которым это оплачено, — дамп с линии Москвы 20.09.2026
//! (`rutracker.org`): рукопожатие, приветствие, подтверждение цели, десять секунд повторов клиента
//! с растущим RTO и ноль байт от цели — ноль показаний двери. Сторож:
//! `a_target_that_acknowledges_without_a_single_byte_is_named` (`reflex/tests/stalled.rs`).
//!
//! КОГДА подтверждать — вопрос времени, не счёта наблюдений. Замер (netns, сервер с ~80 мс RTT
//! отвечает полным `ServerHello`) показал: два наблюдения подряд умещаются в burst рукопожатия —
//! `SYN+ACK` и `ClientHello` уходят встык, ДО ответа. Подтверждать по «второму пакету» — значит
//! кричать дропом на всяком живом сервере, чей ответ отстаёт на RTT. Порог честен только по
//! ВОЗРАСТУ потока (`age`): цель молчит с открытия дольше `after` — вот тогда `NoBytes`/`Blackhole`.
//! Возраст монотонен (не `idle`, что освежается повтором клиента); окно `after` шире обычного RTT,
//! но у́же клиентского терпения — на живом дропе клиент повторяет запрос, и к его повтору возраст
//! перешагивает порог, а живая цель к этому времени давно прислала бы пакет.
//!
//! ## Пределы названы, а не обойдены втихую
//!
//! ОТВЕТ МЕНЬШЕ `FLOOR` БАЙТ сверх заголовков читается как «не дала ничего» — и это уже не
//! молчание о беде, а возможное обвинение живого. Запас неустраним: `HDR` есть ПОТОЛОК заголовка
//! (кадр с опциями весит больше голых сорока), и без запаса поток из одних подтверждений
//! перевешивал бы порог сам собой. Цена ограничена родом трафика, ради которого дверь и стоит:
//! `ServerHello` и всякий HTTP-ответ идут сотнями байт, сотня сверх заголовков их не скрывает.
//!
//! УСТРОЙСТВО, ГОВОРЯЩЕЕ ОТ ИМЕНИ ЦЕЛИ ДАННЫМИ (страница-заглушка вместо ответа), читается как
//! живая цель и дверью пропускается. Это предел НОСИТЕЛЯ: счётчики conntrack различают наличие
//! нагрузки, а её АВТОРСТВО — нет; различитель есть на проводе (TTL, фингерпринт) и сюда не
//! приходит. Прежде в этот предел записывалось и устройство, которое лишь ПОДТВЕРЖДАЕТ, ничего не
//! отдавая, — замер выше показал, что тот случай пределом носителя не был: величина у края была,
//! прибор её не спрашивал. Оттиск памятки (снимок `up.packets` на момент записи) существует РАДИ
//! оставшегося предела: даёт трассе увидеть, растёт ли счётчик ответных пакетов (спуфер) или стоит
//! (чистый дроп). В решении он не участвует — порог держит возраст.
//!
//! ## `Released` — ТЕРМИНАЛ, не круг
//!
//! Ожила цель — `Released`, обратно в подозрение поток не возвращается. Круг потребовал бы сторожить
//! рост `down` вторым оттиском, а в 15 битах марки места ему нет. ПРОПУСКАЕМЫЙ случай назван прямо:
//! «ответила на первый запрос, замолчала на втором» (keep-alive) этот прибор не ловит — и не должен.
//! Это не тишина, а ПОВТОР: работа прибора повтора (`Retransmit`). Один случай, размазанный по двум
//! приборам, был бы хуже отданного тому, чья это буква.

use std::marker::PhantomData;
use std::time::Duration;

use reflex_core::edge::EdgeView;
use reflex_core::mealy::Mealy;
use reflex_core::DetectorEvent;
use smallvec::{smallvec, SmallVec};

use crate::distress::Distress;
use crate::edge::{Layout, Memo, Phase, Recall};
use crate::edge_word::Edged;
use crate::wire::Seen;

/// Потолок ОБЫЧНОГО заголовка IPv4+TCP на пакет. С опциями бывает до 80 — если стенд покажет
/// пограничные случаи, поднимать сюда, но именно как потолок заголовка, не как множитель среднего.
const HDR: u64 = 60;
/// Сколько байт СВЕРХ заголовков считаем реальным запросом. `ClientHello`/HTTP-запрос перекрывают.
const FLOOR: u64 = 100;

/// Что прибор оставляет на пакете: памятку в марку (фазу — `None`, если писать нечего: тик без края
/// или чужой писатель, чьи биты не трогаем) и находки (пусто на переходе без беды).
pub type Verdict = (Option<Memo>, SmallVec<[Distress; 2]>);

/// Тишина по ПАКЕТНЫМ величинам края с порогом по ВОЗРАСТУ, через прогрессию фаз
/// (Quiet→Suspected→Confirmed|Released). Фазу и оттиск читает/пишет через марку — состояния в
/// юзерспейсе не держит. Закон, роль возраста, терминальность `Released` и предел — в докблоке модуля.
pub struct EdgeSilence<V> {
    /// Возраст потока, после которого молчание цели считаем дропом. Шире RTT, у́же терпения клиента.
    after: Duration,
    layout: Layout,
    edge: PhantomData<fn() -> V>,
}

// Copy/Clone без `V`-бонда: носитель в фантоме, экземпляр от `V` не зависит.
impl<V> Clone for EdgeSilence<V> {
    fn clone(&self) -> Self {
        *self
    }
}
impl<V> Copy for EdgeSilence<V> {}

/// Оттиск — младшие 8 бит счётчика ответных ПАКЕТОВ на момент записи. РАДИ трассы предела (растёт ли
/// счётчик = спуфер, или стоит = чистый дроп), в решении не участвует. `None` (край не считает) → 0.
fn imprint_of(up: Option<u64>) -> u8 {
    (up.unwrap_or(0) & 0xFF) as u8
}

/// Отдал ли клиент что-то сверх заголовков. Отдельной функцией, а не выражением в ветке: это
/// ЗАКОН о величинах края, и его проверяют таблицей, а не прогоном автомата целиком.
pub(crate) fn asked_for_something<E: EdgeView>(edge: &E) -> bool {
    match (edge.down_bytes(), edge.down_packets()) {
        (Some(bytes), Some(packets)) => bytes > packets.saturating_mul(HDR) + FLOOR,
        _ => false,
    }
}

/// Отдала ли ЦЕЛЬ что-то сверх заголовков — та же арифметика, обращённая в другую сторону.
///
/// ТРИ ЗНАЧЕНИЯ, не два. `None` — край байт не считает: «не отдала» и «не считали» есть разные
/// утверждения (§7), и сказать `NoBytes` по второму значило бы обвинить цель за собственную
/// слепоту.
///
/// Мерить ответ цели ПАКЕТАМИ нельзя: подтверждение без данных — тоже пакет, и по счёту пакетов
/// цель, подтверждающая приветствие и молчащая, неотличима от цели, ответившей делом. Ровно на
/// этом дверь и промолчала на живом проводе (`reflex/tests/stalled.rs`,
/// `a_target_that_acknowledges_without_a_single_byte_is_named`).
/// СПОСОБЕН ЛИ КРАЙ ВЫНЕСТИ ПРИГОВОР ОБ ИСТОРИИ РАЗГОВОРА — наблюдаемая величина, а не догадка о
/// носителе.
///
/// Объявлена ЗДЕСЬ, рядом с законом, который эти величины и читает: спроси её на другой стороне
/// (проводная половина двери решает по ней, отдавать ли слово) — и два списка предпосылок
/// разошлись бы молча, ровно как разошлись бы две копии всякого закона.
///
/// Чего не хватает чаще всего — ЧАСОВ. Порог здесь держит возраст потока, а возраст даёт ядро
/// меткой времени conntrack (`nf_conntrack_timestamp`); на железе, собранном без неё, ключа нет
/// вовсе. Замер потребителя (NanoPi R2S, OpenWrt 6.12.71, 20.09.2026): счётчики края приходят
/// (`up_packets = 1`, `up_bytes = 60` — цель отдала один `SYN+ACK`), а `age()` — `None`, и фаза
/// никогда не уходит из `Suspected`. Край есть, величины есть, часов нет — и слово, отданное
/// такому свидетелю, не говорит никто.
pub fn can_witness_history<E: EdgeView>(edge: &E) -> bool {
    gave_something(edge).is_some()
        && edge.down_bytes().is_some()
        && edge.down_packets().is_some()
        && edge.age().is_some()
}

/// СКОЛЬКО ЦЕЛЬ ОТДАЛА СВЕРХ ЗАГОЛОВКОВ — величина, на которой стоит весь закон молчания.
///
/// Публична, и это не удобство: тот же вопрос задаёт ПОТРЕБИТЕЛЬ, когда решает, понесла ли страта
/// (nevod3, `Treating::carrying`). Задай он его своей арифметикой — писатель и читатель держали бы
/// два разных закона об одних битах, и разошлись бы молча. Замер, стоящий за этой строкой: потребитель
/// суммировал ОБА направления (`up + down`), то есть засчитывал за лечение собственные байты клиента —
/// `ClientHello` с повторами весит 7614 байт и течёт при ПОЛНОЙ блокировке.
///
/// `None` значит «ядро не считало» — третье значение рядом с нулём и числом (§7).
pub fn gave<E: EdgeView>(edge: &E) -> Option<u64> {
    match (edge.up_bytes(), edge.up_packets()) {
        (Some(bytes), Some(packets)) => Some(bytes.saturating_sub(packets.saturating_mul(HDR))),
        _uncounted => None,
    }
}

/// Отдала ли цель что-то сверх заголовков — `gave` с порогом `FLOOR`.
pub(crate) fn gave_something<E: EdgeView>(edge: &E) -> Option<bool> {
    delivered(edge)
}

/// ЦЕЛЬ ОТДАЛА ДАННЫЕ — отрицание `NoBytes`, то есть снятие его симптома.
///
/// Публична ради ПОТРЕБИТЕЛЯ, который судит, вылечена ли цель (nevod3, свидетель лечения по
/// диагнозу): спроси он «отдала ли» своим порогом — прибор назвал бы молчанием то, что потребитель
/// уже объявил лечением. Ровно так и было: потребитель засчитывал `gave > 0`, прибор судит
/// `gave > FLOOR`, и 4 байта сверх оценки заголовков были лечением для одного и молчанием для
/// другого (канарейка 21.09.2026, 54 рецидива из 54).
pub fn delivered<E: EdgeView>(edge: &E) -> Option<bool> {
    gave(edge).map(|beyond| beyond > FLOOR)
}

/// ЦЕЛЬ ОТВЕТИЛА НА СТУК — отрицание `Blackhole` (`up.packets == 0`): пришёл хоть один её пакет.
///
/// Для беды «на стук не ответила» рукопожатие и есть лечение; для беды «молчит после приветствия»
/// — нет, там снятие симптома — [`delivered`]. Один порог на обе беды врёт в обе стороны.
pub fn answered<E: EdgeView>(edge: &E) -> Option<bool> {
    edge.up_packets().map(|packets| packets >= 1)
}

/// ЦЕЛЬ ОТВЕТИЛА ПОСЛЕ РУКОПОЖАТИЯ — отрицание `HelloDropped`: пакетов цели больше одного.
///
/// Первый пакет цели на разговоре — всегда `SYN+ACK`; всё сверх него — ответ на то, что клиент
/// сказал после рукопожатия: голое подтверждение приветствия, `ServerHello` или оба. Флаги край не
/// хранит, но здесь они и не нужны — различает СЧЁТ. Данных не требует: подтвердившая и режущая
/// позже цель — другая болезнь, и снятие этой о ней не судит.
///
/// ПРЕДЕЛ: повторённый целью `SYN+ACK` (потерялось подтверждение клиента) даст два пакета без
/// ответа на приветствие. Редко, и край этого не различит.
pub fn acknowledged<E: EdgeView>(edge: &E) -> Option<bool> {
    edge.up_packets().map(|packets| packets >= 2)
}

/// ЧЕМ СНИМАЕТСЯ СИМПТОМ — какой из предикатов снятия отвечает беде ([`crate::Distress::relief`]).
///
/// Снятие спрашивается у той же величины, которой беду мерила детекция: один порог на все беды
/// врёт в обе стороны.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Relief {
    /// Цель ответила на стук — [`answered`].
    Answered,
    /// Цель ответила после рукопожатия — [`acknowledged`].
    Acknowledged,
    /// Цель отдала данные сверх порога молчания — [`delivered`].
    Delivered,
    /// Чем снимается, не знаем: снятием такое не объявляется.
    Unknown,
}

impl Relief {
    /// Имя словом — для истории и рассказа. Не `Debug`: его формат нестабилен.
    pub fn word(self) -> &'static str {
        match self {
            Relief::Answered => "answered",
            Relief::Acknowledged => "acknowledged",
            Relief::Delivered => "delivered",
            Relief::Unknown => "unknown",
        }
    }

    /// Снят ли симптом на этом крае — и сколько байт цели за этим стоит.
    pub fn seen<E: EdgeView>(self, edge: &E) -> Option<std::num::NonZeroU64> {
        match self {
            // Ответ на стук — сам кадр ответа: байты с заголовками, данных у него нет.
            Relief::Answered => answered(edge)
                .filter(|answered| *answered)
                .and(edge.up_bytes())
                .and_then(std::num::NonZeroU64::new),
            Relief::Acknowledged => acknowledged(edge)
                .filter(|acknowledged| *acknowledged)
                .and(edge.up_bytes())
                .and_then(std::num::NonZeroU64::new),
            Relief::Delivered => delivered(edge)
                .filter(|delivered| *delivered)
                .and_then(|_delivered| gave(edge))
                .and_then(std::num::NonZeroU64::new),
            Relief::Unknown => None,
        }
    }
}

impl<V: EdgeView> EdgeSilence<V> {
    pub fn new(after: Duration, layout: Layout) -> EdgeSilence<V> {
        EdgeSilence {
            after,
            layout,
            edge: PhantomData,
        }
    }

    /// Памятка: фаза и оттиск ставятся ОДНИМ конструктором — разнести (записать фазу, не обновив
    /// снимок счётчика) нельзя.
    fn memo(&self, phase: Phase, up: Option<u64>) -> Memo {
        Memo::new(self.layout, phase, imprint_of(up))
    }
}

impl<V: EdgeView> Mealy for EdgeSilence<V> {
    /// Край приезжает `Option`: пакет, которого ядро ещё не завело в conntrack (первый `SYN` вне
    /// таблицы), вида не имеет. Это ТРЕТЬЕ значение рядом с «ноль» и «много» (§7): «не считали» —
    /// не «не ответила». Прими прибор непустой `V` — петля роняла бы такие пакеты молча, и разница
    /// между незнанием и наблюдением исчезла бы ещё до прибора.
    type In = DetectorEvent<Edged<Option<Seen>, Option<V>>>;
    type Out = Verdict;
    type Log = ();

    fn step(self, event: Self::In) -> (Self, Self::Out, ()) {
        // Прибор края работает по букве `Packet`: тик марки прочесть не может (ct-вид едет с пакетом).
        let edge = match &event {
            DetectorEvent::Packet { input, .. } => &input.edge,
            // ТОЖДЕСТВО НА ВСЕХ БУКВАХ, КРОМЕ ПАКЕТА, — и обосновано оно ДВУМЯ половинами, потому
            // что довод, верный для одного края, для другого ложен.
            //
            // ПЕРВАЯ: прячущая буква сюда сегодня НЕ ПРИХОДИТ ВОВСЕ. Фасад зовёт краевые приборы
            // только в арме пакета (`Alive::walk`, `reflex/src/lib.rs`), а вне фасада прибор
            // получает то, что ему подаёт зовущий. То есть выбор здесь — о букве, которой в
            // живом потоке нет; будь иначе, он был бы РАЗНЫМ для разных краёв.
            //
            // ВТОРАЯ: что было бы, приди она. На `CtEdge` — ничего: счётчик пакетов и возраст ведёт
            // ЯДРО, независимо от того, дошёл ли кадр до нас, и дыра нашей очереди вида не портит —
            // считает не прибор. Но `EdgeView` этой веткой обобщён, и на краю, который счёт ведёт
            // САМ по дошедшим кадрам (`LocalEdge`, `Local<WinDivertHandle>`), довод переворачивается:
            // пропавший кадр там означает «не досчитали», `up_packets` остаётся нулём, и прибор
            // объявил бы `Blackhole` из собственной слепоты — ровно тот род беды, ради которого
            // `DetectorEvent::hides_observation` и заведён. Придёт сюда прячущая буква — этот арм
            // обязан её разобрать (гасить высказывание либо гасить фазу), и решать это придётся с
            // замером, а не по симметрии с `CtEdge`.
            DetectorEvent::Tick { .. }
            | DetectorEvent::Opaque { .. }
            | DetectorEvent::Torn { .. } => {
                return (self, (None, SmallVec::new()), ());
            }
        };
        // Края нет — судить не о чем, и памятки нет: писать в марку по незнанию значило бы
        // выдумать фазу разговора, которого край ещё не видит.
        let Some(edge) = edge else {
            return (self, (None, SmallVec::new()), ());
        };

        // Чужой писатель (тег не наш, слово непустое) — находка, а не тишина. Его биты НЕ трогаем
        // (памятка `None`): у соседа своя маска, затирать её нам нечем.
        let phase = match self.layout.read(edge.mark()) {
            Recall::Foreign { theirs } => {
                return (self, (None, smallvec![Distress::Diverged { theirs }]), ());
            }
            // Под нашими битами пусто — нетронутый поток. Что лежит ВНЕ маски, прибора не
            // касается: там сосед, и раньше он объявлялся чужим писателем (см. `Recall`).
            Recall::Untouched => Phase::Quiet,
            Recall::Ours(memo) => memo.phase,
        };

        // СУДИТЬ НЕЧЕМ — НЕ СУДИМ, И ФАЗЫ НЕ ВЫДУМЫВАЕМ. Одна дверь на все недостающие величины
        // (`can_witness_history`), и та же, которой проводная половина решает, отдавать ли слово:
        // пока прибор писал `Suspected` в марку на крае без часов, он обещал приговор, который не
        // мог вынести никогда.
        if !can_witness_history(edge) {
            return (self, (None, SmallVec::new()), ());
        }

        let up_pk = edge.up_packets();

        // Жива ли цель (пакетом сверх `SYN+ACK`), состоялось ли рукопожатие, заговорил ли клиент, и
        // перешагнул ли ВОЗРАСТ порог. Возраст — единственные честные часы «сколько молчит с открытия».
        // ЖИВА ЛИ ЦЕЛЬ — по БАЙТАМ сверх заголовков, а не по счёту пакетов: слово `NoBytes`
        // утверждает о байтах, и спрашивать о них надо ту величину, о которой говоришь.
        let gave = gave_something(edge);
        let target_alive = gave == Some(true);
        let gave_nothing = gave == Some(false);
        // Рукопожатие состоялось — цель на стук ответила. Чем именно она ответила дальше, говорят
        // байты; здесь важно лишь, что разговор ОТКРЫТ (иначе беда зовётся `Blackhole`).
        let handshaken = answered(edge) == Some(true);
        let no_synack = answered(edge) == Some(false);
        let client_spoke = asked_for_something(edge);
        let overdue = matches!(edge.age(), Some(age) if age >= self.after);

        let out: Verdict = match phase {
            // Уже сказали — молчим, фазу не трогаем (лежит в марке).
            Phase::Confirmed | Phase::Released => (None, SmallVec::new()),

            // Первое наблюдение. Есть что сторожить — под подозрение, БЕЗ жалобы (порог держит возраст).
            Phase::Quiet => {
                if target_alive || !((client_spoke && handshaken && gave_nothing) || no_synack) {
                    (None, SmallVec::new())
                } else {
                    (Some(self.memo(Phase::Suspected, up_pk)), SmallVec::new())
                }
            }

            // Под подозрением: цель ожила — отпускаем; возраст перешагнул порог при молчании — беда;
            // иначе ждём (возраст ещё мал — живой сервер успеет ответить).
            Phase::Suspected => {
                if target_alive {
                    (Some(self.memo(Phase::Released, up_pk)), SmallVec::new())
                } else if overdue && no_synack {
                    let after_ms = edge.age().map_or(0, |age| age.as_millis() as u32);
                    (
                        Some(self.memo(Phase::Confirmed, up_pk)),
                        smallvec![Distress::Blackhole { after_ms }],
                    )
                } else if overdue && handshaken && client_spoke && gave_nothing {
                    (
                        Some(self.memo(Phase::Confirmed, up_pk)),
                        smallvec![Distress::NoBytes],
                    )
                } else {
                    (Some(self.memo(Phase::Suspected, up_pk)), SmallVec::new())
                }
            }
        };
        (self, out, ())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Край, у которого известны только эти две величины: остальное — «не считали» (§7).
    struct Frames {
        packets: u64,
        bytes: u64,
    }

    impl EdgeView for Frames {
        fn down_packets(&self) -> Option<u64> {
            Some(self.packets)
        }
        fn down_bytes(&self) -> Option<u64> {
            Some(self.bytes)
        }
        fn up_packets(&self) -> Option<u64> {
            None
        }
        fn up_bytes(&self) -> Option<u64> {
            None
        }
        fn idle(&self) -> Option<Duration> {
            None
        }
        fn age(&self) -> Option<Duration> {
            None
        }
        fn mark(&self) -> u32 {
            0
        }
    }

    /// Порог «клиент отдал запрос» считает КАДРЫ, и это контракт, а не совпадение с conntrack.
    /// Считай край нагрузку — порог завысился бы на заголовок каждого пакета, и запрос перестал
    /// бы наблюдаться. Мера: conntrack нагрузки не знает и знать не может.
    #[test]
    fn the_request_threshold_counts_frames_not_payload() {
        // Три пакета вниз, кроме заголовков — ничего: запроса не было.
        assert!(!asked_for_something(&Frames {
            packets: 3,
            bytes: 3 * HDR
        }));
        // Те же три пакета, но сверх заголовков 200 байт: запрос отдан.
        assert!(asked_for_something(&Frames {
            packets: 3,
            bytes: 3 * HDR + 200
        }));
        // Сверх заголовков есть 50 байт, но это меньше FLOOR (100) — ещё не запрос, а, например,
        // случайный ACK с опцией. Без этого случая мутация «убрать FLOOR» осталась бы незамеченной:
        // оба случая выше не зависят от FLOOR (0 и 200 — по разные стороны и нуля, и сотни).
        assert!(!asked_for_something(&Frames {
            packets: 3,
            bytes: 3 * HDR + 50
        }));
    }

    /// Край, отвечающий на вопрос о ЦЕЛИ: встречная половина `Frames`. Две фикстуры, а не одна с
    /// четырьмя полями, — прибор мерит стороны разными законами, и смешать их в одном наборе
    /// величин значило бы дать проверке молча опереться на чужую сторону.
    struct Answering {
        packets: u64,
        bytes: u64,
    }

    impl EdgeView for Answering {
        fn down_packets(&self) -> Option<u64> {
            None
        }
        fn down_bytes(&self) -> Option<u64> {
            None
        }
        fn up_packets(&self) -> Option<u64> {
            Some(self.packets)
        }
        fn up_bytes(&self) -> Option<u64> {
            Some(self.bytes)
        }
        fn idle(&self) -> Option<Duration> {
            None
        }
        fn age(&self) -> Option<Duration> {
            None
        }
        fn mark(&self) -> u32 {
            0
        }
    }

    /// ОТВЕТ ЦЕЛИ МЕРИТСЯ ТОЙ ЖЕ АРИФМЕТИКОЙ, ЧТО И ПРОСЬБА КЛИЕНТА, и это ровно то, чего прибору
    /// недоставало: цель, приславшая одни подтверждения, по счёту ПАКЕТОВ неотличима от ответившей
    /// делом, по байтам сверх заголовков — отличима.
    #[test]
    fn the_answer_threshold_counts_frames_not_payload() {
        // Три кадра вверх, сверх заголовков ничего: `SYN+ACK` и два подтверждения — цель не
        // сказала НИ БАЙТА. Прежний закон (`up.packets >= 2`) звал её живой.
        assert_eq!(
            gave_something(&Answering {
                packets: 3,
                bytes: 3 * HDR
            }),
            Some(false)
        );
        // Те же три кадра, но сверх заголовков 200 байт: цель ответила делом.
        assert_eq!(
            gave_something(&Answering {
                packets: 3,
                bytes: 3 * HDR + 200
            }),
            Some(true)
        );
        // Полсотни байт сверх заголовков — меньше FLOOR, и это НАЗВАННАЯ цена запаса (докблок
        // модуля): ответ короче сотни байт читается как молчание. Без этой строки мутация «убрать
        // FLOOR» прошла бы незамеченной.
        assert_eq!(
            gave_something(&Answering {
                packets: 3,
                bytes: 3 * HDR + 50
            }),
            Some(false)
        );
    }

    /// ПОДТВЕРЖДЕНИЕ СЧИТАЕТСЯ ПАКЕТАМИ — и это не противоречие соседу, а другой вопрос.
    ///
    /// Сосед судит МОЛЧАНИЕ (`NoBytes`), и там пакеты врут: подтверждения без данных — не ответ
    /// делом. Здесь предмет — ПОДТВЕРЖДЕНИЕ приветствия (`HelloDropped`), и его величина именно
    /// пакет сверх `SYN+ACK`: голый ACK ответом делом не является, но приветствие подтверждает.
    #[test]
    fn an_acknowledgement_is_a_frame_beyond_the_handshake() {
        // Только `SYN+ACK` — картина записи `rutracker.org` и счётчиков канарейки (`packets=1`).
        assert_eq!(
            acknowledged(&Answering {
                packets: 1,
                bytes: HDR
            }),
            Some(false)
        );
        // `SYN+ACK` и голое подтверждение: данных ноль, а приветствие подтверждено.
        assert_eq!(
            acknowledged(&Answering {
                packets: 2,
                bytes: 2 * HDR
            }),
            Some(true)
        );
        // Молчание при этом остаётся молчанием: вопросы разные, и законы у них разные.
        assert_eq!(
            gave_something(&Answering {
                packets: 2,
                bytes: 2 * HDR
            }),
            Some(false)
        );
    }

    /// ВЕЛИЧИНА, А НЕ ТОЛЬКО ПОРОГ. `gave` публична, и число её читает потребитель — им он судит,
    /// понесла ли страта. Значит законом стало САМО ЧИСЛО, и охранять один лишь порог мало:
    /// замером проверено, что удвоение величины проходит таблицу порога целиком (все три её
    /// клетки лежат по ту же сторону сотни) — то есть без этой проверки число не сторожил никто.
    ///
    /// Вычитается ПОТОЛОК заголовка, оттого у молчащей цели выходит ноль, а не отрицательное:
    /// реальный кадр легче потолка, и «меньше нуля отдала» — не величина мира.
    #[test]
    fn the_amount_given_is_measured_beyond_the_header_ceiling() {
        assert_eq!(
            gave(&Answering {
                packets: 3,
                bytes: 3 * HDR + 200
            }),
            Some(200)
        );
        // Три кадра по 56 байт — легче потолка втрое; отдала ноль, а не «минус двенадцать».
        assert_eq!(
            gave(&Answering {
                packets: 3,
                bytes: 3 * 56
            }),
            Some(0)
        );
    }

    /// Учёт выключен — не «ноль запроса», а «не считали». Иначе край без учёта выглядел бы как
    /// клиент, не отправивший ничего, и прибор судил бы о мире по собственной слепоте.
    ///
    /// Про ответ ЦЕЛИ это же незнание обязано быть ЗНАЧЕНИЕМ (`None`), а не ложью `false`: слепой
    /// край, сведённый к «не отдала ни байта», превратил бы дверь в обвинителя всякой цели на
    /// машине без учёта conntrack.
    #[test]
    fn an_edge_without_accounting_is_not_an_absent_request() {
        struct Blind;
        impl EdgeView for Blind {
            fn down_packets(&self) -> Option<u64> {
                None
            }
            fn down_bytes(&self) -> Option<u64> {
                None
            }
            fn up_packets(&self) -> Option<u64> {
                None
            }
            fn up_bytes(&self) -> Option<u64> {
                None
            }
            fn idle(&self) -> Option<Duration> {
                None
            }
            fn age(&self) -> Option<Duration> {
                None
            }
            fn mark(&self) -> u32 {
                0
            }
        }
        assert!(!asked_for_something(&Blind));
        assert_eq!(gave_something(&Blind), None);
        assert_eq!(gave(&Blind), None);
    }
}
