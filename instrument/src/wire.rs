//! СЛОВАРЬ ПРОВОДА — что видно на разговоре, в терминах наблюдения.
//!
//! # Почему это переехало в крейт приборов
//!
//! `Seen` есть НАБЛЮДЕНИЕ, а не решение: «пришёл сброс», «цель ответила на стук», «клиент
//! попросил подождать» — всё это про мир, а не про то, что мы предпримем. Пока словарь жил в
//! домене, всякий прибор, читающий провод, тянул домен за собой — и переехать в общий дом не мог
//! ни один.
//!
//! Граница крейта от этого не сдвинулась: сюда переехало знание О МИРЕ, а `Distress`, `Finding` и
//! `Sighting` (что мы считаем бедой и что намерены делать) остаются у потребителя.

/// Наблюдаемое событие. `Idle` здесь НЕТ намеренно: тишина есть отсутствие событий, и
/// обнаруживается она тиком времени, а не выдуманным событием «ничего не произошло».
/// КТО ПОСЛАЛ СБРОС. Три явления в одной сессии, и они лечатся по-разному (#320, вопрос
/// владельца 01.09).
///
/// Булев флаг «сбросил клиент» держал только два и молчал о том, что второй из них — СОСТАВНОЙ:
/// со стороны цели приходит и её собственный отказ, и инжект ТСПУ от её имени. Первое значит
/// «цель не работает, техника бесполезна», второе — «работает, техника нужна». Флаг заставил бы
/// добавлять четвёртое поле рядом с собой, а тип разводит их сразу.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResetBy {
    /// ЧЕЛОВЕК: закрыл вкладку, оборвал ожидание, переоткрыл страницу.
    Person,
    /// ОБОРВАЛИ МЫ САМИ — исполнение приказа `Act::Sever`, а не переживание человека.
    ///
    /// Заведён ДО ТОГО, как понадобился: сегодня `plane-queue` приказ на обрыв не исполняет
    /// (`note_unapplied("Sever")`), и производителя у этого варианта нет. Но в день, когда обрыв
    /// заработает, наш собственный приказ пришёл бы со стороны клиента и был бы прочитан как уход
    /// человека — прибор о человеке начал бы считать наши действия его переживаниями, и МОЛЧА.
    ///
    /// Плоскость от этого защищена своим `Sighting::Severed` с 29.08; край такого различения не
    /// имел. Добавить вариант в мёртвую зону дешевле, чем ловить размытие потом.
    Ourselves,
    /// ПРИШЁЛ СО СТОРОНЫ ЦЕЛИ — и это ВСЁ, что установлено.
    ///
    /// Имя намеренно не `Target`: чей сброс на самом деле, мы не знаем. Различитель существует на
    /// проводе (TTL инжекта, фингерпринт окна и флагов), но не читается ничем — Н10 эпика #320.
    /// Назвать это `Target` значило бы утверждать больше установленного, а под этим утверждением
    /// прячется противоположное лечение.
    TargetSide,
}

/// СЛОВАРЬ ЛЮБОГО ТРАНСПОРТА — буквы, существующие и на соединении, и на датаграммах.
///
/// `Idle` здесь НЕТ намеренно: тишина есть отсутствие событий, и обнаруживается она тиком
/// времени, а не выдуманным событием «ничего не произошло».
///
/// # ПОЧЕМУ АЛФАВИТОВ ДВА (#320, 02.09)
///
/// Словарь был один на оба транспорта, и четыре его буквы из девяти на UDP НЕ СУЩЕСТВУЮТ:
/// рукопожатия у датаграмм нет, сброса нет, окна приёма нет. Склейка была осознанной и для
/// приборов О ЧЕЛОВЕКЕ верной — «как это узнано, домену знать не нужно». Но потребителей у
/// словаря два, и требования у них противоположные: прибор о человеке требует транспорт СТЕРЕТЬ,
/// прибор о проводе — СОХРАНИТЬ. Уровень абстракции был выбран под одного.
///
/// Цена склейки замерена: `nevod2-runtime/src/wire.rs` для датаграммы подставлял `rst = false`,
/// `syn = false`, `window = u16::MAX` — то есть расщепление уже было истинно в коде и невыразимо
/// в типе. Прибор сброса собирался в цепочку над UDP молча, и объявление `PROTOCOL: Tcp` не
/// запрещало ничего.
///
/// # ИМЯ `Seen` ОСТАВЛЕНО ЗА ОБЩИМ, а не за TCP
///
/// Общий алфавит есть утверждение о МИРЕ («человек попросил», «цель отдала», «разговор кончился»),
/// и оно верно независимо от того, каким транспортом шли. Отдать это имя алфавиту TCP значило бы
/// назвать устройство одного транспорта наблюдением вообще — той же ошибкой, которую расщепление
/// и лечит. Алфавит TCP называется [`SeenTcp`] и содержит общий целиком ([`SeenTcp::Anywhere`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Seen {
    /// Клиент ОТПРАВИЛ байты вверх — то есть человек чего-то попросил.
    ///
    /// Направление существенно, и это не педантизм: «цель молчит при живом клиенте» и «молчат
    /// обе стороны» — разные факты с разными лечениями, а без направления они неразличимы.
    Sent { count: u32 },
    /// КЛИЕНТ ПОВТОРИЛ ТО ЖЕ САМОЕ — просьба ушла второй раз, потому что ответа не было.
    ///
    /// ОТДЕЛЬНО ОТ `Sent`, и разница в единице человека: повтор значит, что первая просьба
    /// НЕ ДОШЛА либо ответ на неё пропал. Тишина говорит о том же, но ПОЗЖЕ — она ждёт порога
    /// (полторы секунды), а первый повтор виден через две-три сотни миллисекунд. Раньше
    /// заметили — раньше вылечили.
    ///
    /// Как именно это узнано (повтор `seq` в TCP), домену знать не нужно и вредно: он про то,
    /// что пережил человек, а не про устройство транспорта. Различает КРАЙ.
    Resent { count: u32 },
    /// РАЗГОВОР ОКОНЧЕН — сторона попрощалась, а не оборвала ([`SeenTcp::Rst`]).
    ///
    /// ОТДЕЛЬНО ОТ СБРОСА, и разница доменная: сброс есть беда, прощание — нормальный конец. Слить
    /// их значило бы объявить бедой всякое завершение, а их у здоровой коробки тысячи в час.
    ///
    /// НАПРАВЛЕНИЕ СУЩЕСТВЕННО по тому же принципу, что у [`SeenTcp::AskedToWait`]: «человек
    /// закрыл вкладку» и «цель попрощалась сама» — разные факты. Первое ничего не говорит о цели,
    /// второе говорит, что она дожила до конца.
    ///
    /// ЗАЧЕМ ЭТО ДОМЕНУ (#294). Без прощания наблюдение за флоу не кончается никогда: тики
    /// приходят и мёртвому, и он получает улику в молчании, набранную из пауз ЧУЖОГО трафика.
    /// Оплачено записью, где `example.com` закрылся на 383 мс и получил `Silence 1577 мс`.
    ///
    /// # БУКВА ОБЩАЯ, А ПРОИЗВОДИТЕЛЬ ПОКА ОДИН (#320, названная цена)
    ///
    /// Прощание есть доменный факт «разговор кончился», и он существует на любом транспорте. Но
    /// добывается он сегодня только из `FIN`: у датаграмм прощания нет — разговор кончается
    /// молчанием, а `CONNECTION_CLOSE` у QUIC лежит за шифром. Значит на UDP эта буква не
    /// рождается НИКОГДА, и всё, что ею закрывается (у прибора тишины — `Watch::Ended`), там
    /// недостижимо.
    ///
    /// Оставлена общей намеренно: буква, которой не хватает производителя, честнее буквы,
    /// объявленной чужой. Долг назван — край обязан научиться закрывать датаграммный разговор по
    /// простою, и это первый кандидат в собственный алфавит UDP.
    Closed {
        /// Попрощался КЛИЕНТ. Иначе — цель.
        by_client: bool,
    },
    /// Цель ОТДАЛА байты вниз.
    Received { count: u32 },
    /// ПЕРВЫЕ БАЙТЫ ПОТОКА — то, по чему узнаётся протокол.
    ///
    /// НАПРАВЛЕНИЕ ОБЯЗАТЕЛЬНО, и это вскрылось попыткой заполнить событие с настоящего провода.
    /// Прежде вариант значил сразу две вещи: «голова потока» (для опознания) и «байты вниз» (для
    /// счёта) — `flow` считал его полученным. Но протокол узнаётся по первому пакету КЛИЕНТА:
    /// `ClientHello` у TLS, начальный блок у MTProto. Без направления голова клиента засчиталась
    /// бы целью как отданные ею байты — то есть молчащая цель выглядела бы отвечающей.
    Payload { head: Vec<u8>, from_client: bool },
}

/// СЛОВАРЬ СОЕДИНЕНИЯ — общий алфавит плюс четыре улики, которых у датаграмм нет.
///
/// Рукопожатие, сброс и окно приёма существуют потому, что у TCP есть состояние соединения.
/// У датаграмм его нет: разговор начинается первой датаграммой и кончается молчанием. Это не
/// «пока не поддержано», а свойство транспорта — оттого буквы стоят здесь, а не в [`Seen`].
///
/// Прибор, читающий эти улики, объявляет входом `SeenTcp` и в поток датаграмм НЕ СОБИРАЕТСЯ.
/// Прибор, которому хватает общего, объявляет `Seen` и годится обоим протоколам — сужение даёт
/// [`Reads`](reflex_core::Reads).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SeenTcp {
    /// КЛИЕНТ ПОСТУЧАЛ — `SYN` без `ACK`.
    Syn,
    /// ЦЕЛЬ ОТВЕТИЛА НА СТУК — `SYN+ACK`, то есть рукопожатие СОСТОЯЛОСЬ.
    ///
    /// Отдельным вариантом, а не полем направления в [`SeenTcp::Syn`]: это РАЗНЫЕ события, а не
    /// одно с флагом. Стук говорит о клиенте, ответ на стук — о цели, и предметы у них разные.
    ///
    /// # Чего без него было нельзя
    ///
    /// Различить блокировку ПО АДРЕСУ от блокировки ПО ИМЕНИ. Обе выглядят как «дошёл, не
    /// ответила»: при дропе `SYN` рукопожатия нет вовсе, при немоте по SNI оно состоялось и
    /// оборвалось после `ClientHello`. Прежде оба флага давали один `Syn`, направление терялось,
    /// и земли `syn_drop` и `sni_drop` сливались в одну картину — замерено на фикстурах.
    ///
    /// # Что он объединяет
    ///
    /// Оба типа блокировки суть одно явление, взятое на РАЗНОЙ ГЛУБИНЕ: цензор смотрит либо на
    /// адрес (до имени), либо на имя (после рукопожатия). Это событие и есть граница между двумя
    /// глубинами — то, чем они различаются и что у них общее.
    Handshaken,
    /// СБРОС, И У НЕГО ЕСТЬ АВТОР. Автор — [`ResetBy`], не флаг.
    ///
    /// Без автора детектор обвинял цель за НАШ ЖЕ сброс. Замер живой записи 29.08 (стенд):
    /// 23 сброса, из них **17 наши собственные** — соединение закрывалось после того, как человек
    /// получил своё. Подпись блокировки выглядит иначе: сброс приходит ОТ ЦЕЛИ и ДО того, как она
    /// отдала хоть байт (классический ответ ТСПУ на `ClientHello`).
    ///
    /// У QUIC обрыв зашифрован, и потому эта буква на UDP невыразима — не «не сделано», а нечем.
    Rst {
        /// КТО СБРОСИЛ. Не `bool`: третий случай уже назван (#320, Н10), и булев флаг заставил бы
        /// втискивать его четвёртым полем рядом.
        by: ResetBy,
    },
    /// ОДНА ИЗ СТОРОН ПОПРОСИЛА ПОДОЖДАТЬ — ей некуда принимать, пока не разберёт принятое.
    ///
    /// ЭТО ОБЪЯСНЕНИЕ МЕДЛЕННОСТИ, НЕ ЕЁ ПРИЧИНА В СЕТИ. Весь день мы обходили вопрос «а не сами
    /// ли мы виноваты»: `link` отвечал на него по всему каналу и потому грубо, проба темпа — по
    /// контрольной цели и потому дорого. Здесь ответ приходит даром и про ЭТО САМОЕ соединение:
    /// если притормозил ПОЛУЧАТЕЛЬ, скорость упирается в него, и обвинять цель нельзя.
    ///
    /// # ЗДЕСЬ, А НЕ В ОБЩЕМ АЛФАВИТЕ, и это исправление прежнего решения
    ///
    /// Докстринг гласил: «как это узнано (нулевое окно приёма в TCP), домену знать не нужно».
    /// Для прибора О ЧЕЛОВЕКЕ это верно и сегодня. Но улика ЕСТЬ окно приёма, а окна у датаграмм
    /// нет — то есть стирался не способ узнать, а само существование факта на другом транспорте.
    AskedToWait {
        /// Попросил подождать КЛИЕНТ. Иначе — цель.
        by_client: bool,
    },
    /// ТО, ЧТО ВИДНО НА ЛЮБОМ ТРАНСПОРТЕ — общий алфавит целиком.
    ///
    /// Вложением, а не повтором пяти букв: повтор пришлось бы держать в согласии руками, и первое
    /// же расхождение было бы молчаливым. Отсюда же берётся сужение: `Seen::read(&seen_tcp)`
    /// отдаёт содержимое этого варианта и `None` на четырёх остальных.
    Anywhere(Seen),
}

impl SeenTcp {
    /// Клиент отправил байты. Сокращение для `Anywhere(Seen::Sent { .. })`.
    pub fn sent(count: u32) -> Self {
        Self::Anywhere(Seen::Sent { count })
    }

    /// Клиент повторил просьбу.
    pub fn resent(count: u32) -> Self {
        Self::Anywhere(Seen::Resent { count })
    }

    /// Цель отдала байты.
    pub fn received(count: u32) -> Self {
        Self::Anywhere(Seen::Received { count })
    }

    /// Сторона попрощалась.
    pub fn closed(by_client: bool) -> Self {
        Self::Anywhere(Seen::Closed { by_client })
    }

    /// Голова потока.
    pub fn payload(head: Vec<u8>, from_client: bool) -> Self {
        Self::Anywhere(Seen::Payload { head, from_client })
    }
}

impl From<Seen> for SeenTcp {
    fn from(seen: Seen) -> Self {
        Self::Anywhere(seen)
    }
}

/// СУЖЕНИЕ АЛФАВИТА — частичный морфизм `SeenTcp → Option<Seen>`.
///
/// Четыре буквы соединения на общем алфавите не существуют, и `None` здесь не сбой чтения:
/// сброс TCP для прибора, живущего на любом транспорте, — факт не про него.
impl reflex_core::Reads<SeenTcp> for Seen {
    fn read(wide: &SeenTcp) -> Option<Self> {
        match wide {
            SeenTcp::Anywhere(seen) => Some(seen.clone()),
            SeenTcp::Syn
            | SeenTcp::Handshaken
            | SeenTcp::Rst { .. }
            | SeenTcp::AskedToWait { .. } => None,
        }
    }
}

/// У ПРОТОКОЛА ЕСТЬ СВОЙ СЛОВАРЬ НАБЛЮДЕНИЙ. Связка объекта стека (`reflex`) с алфавитом (здесь).
///
/// # Имя
///
/// Наш коинаж — и это законно: у понятия «словарь наблюдений, снимаемых на протоколе» устоявшегося
/// слова в поле нет, значит и конфликтовать не с чем. Прежде трейт звался `Floor` («этаж»), и это
/// было ЧЕТВЁРТОЕ имя тому, что уже названо: `reflex_core::Protocol` (объект),
/// [`crate::Protocol`] (то же значением), [`crate::Layer`] (уровень OSI). Заодно `Floor` спорил с
/// продуктовым «полом» — VPN-ногой последней надежды из `model/LEXICON.md`.
///
/// # Форма
///
/// Отдельным трейтом, а не полем в [`reflex_core::Protocol`]: `reflex` есть общая библиотека
/// потоков и о наблюдениях невода знать не должен. Направление зависимости сохраняется — объект
/// стека объявлен там, алфавит здесь.
///
/// Отсюда `Wire<P> { seen: P::Seen }`: не «наблюдение с пометкой протокола», а наблюдение, СОСТАВ
/// которого протоколом определён.
///
/// Требования к самому маркеру (`Clone`, `Debug`, `Eq`) — не прихоть: наблюдение выводит их
/// автоматически (`#[derive]` вешает границу на параметр), и без них всякий генерик по протоколу
/// тащил бы за собой четыре лишние границы в подписи.
pub trait Alphabet: reflex_core::Protocol + Clone + core::fmt::Debug + PartialEq + Eq {
    /// Что на этом протоколе вообще бывает видно.
    type Seen: Clone + core::fmt::Debug + PartialEq + Eq;

    /// СУЗИТЬ ДО ОБЩЕГО СЛОВАРЯ. `None` — буква принадлежит протоколу и на общем не существует.
    ///
    /// Отдельным методом, а не границей `Seen: Reads<Self::Seen>` на самом трейте: Rust не
    /// раскрывает where-условия трейта как подразумеваемые, и такая граница переписывалась бы
    /// В КАЖДОЙ подписи, генерик по протоколу. Проверено компилятором, а не предположено: шесть
    /// подписей потребовали её дословно.
    ///
    /// Механизм тот же ([`reflex_core::Reads`]) — здесь у него имя, чтобы им можно было
    /// пользоваться, не таща границу за собой.
    fn anywhere(seen: &Self::Seen) -> Option<Seen>;
}

impl Alphabet for reflex_core::Tcp {
    type Seen = SeenTcp;

    fn anywhere(seen: &SeenTcp) -> Option<Seen> {
        <Seen as reflex_core::Reads<SeenTcp>>::read(seen)
    }
}

/// У ДАТАГРАММ СОБСТВЕННЫХ БУКВ ПОКА НЕТ — алфавит ровно общий.
///
/// Не заводим `SeenUdp` авансом: тип-обёртка без единой своей буквы есть церемония, и она
/// притворяется различением. Первая своя буква (закрытие разговора по простою, см. [`Seen::Closed`])
/// заведёт его сама и сломает ровно тех потребителей, которых обязана сломать.
impl Alphabet for reflex_core::Udp {
    type Seen = Seen;

    fn anywhere(seen: &Seen) -> Option<Seen> {
        Some(seen.clone())
    }
}

/// ПРОТОКОЛ БЕЗРАЗЛИЧЕН — значит и алфавит общий: утверждать про такое наблюдение улику
/// конкретного протокола было бы ложью в типе.
impl Alphabet for reflex_core::AnyProtocol {
    type Seen = Seen;

    fn anywhere(seen: &Seen) -> Option<Seen> {
        Some(seen.clone())
    }
}

/// ПОКАЗАНИЕ С НАЗВАННЫМ ПРОТОКОЛОМ — то, что производитель наблюдений отдаёт потребителю, когда
/// протокол установлен РАЗБОРОМ, а не выбран потребителем заранее.
///
/// # Зачем тип, если алфавит UDP сегодня равен общему
///
/// Затем, что производитель обязан назвать протокол ДО того, как у датаграмм появится первая своя
/// буква. Сигнатура вида `Option<SeenTcp>` — а именно такой она была заведена 03.09 и прожила
/// двадцать минут — фиксирует TCP в самом типе: датаграмму в неё не положить, и вопрос «а как же
/// UDP» приходится задавать человеку, потому что компилятор его не задаст.
///
/// Цена ошибки была бы не в переписи типа, а в том, ЧТО из неё следует: половина живого трафика
/// (QUIC у видео и поиска) молча не имела бы производителя наблюдений, и плоскость выглядела бы
/// исправной — все её тесты зелёные, они про TCP.
///
/// Расщепление алфавитов уже установлено (02.09): четыре буквы TCP на UDP НЕ СУЩЕСТВУЮТ —
/// рукопожатия у датаграмм нет, сброса нет, окна приёма нет. Здесь оно наконец выражено на
/// выходе, а не константами внутри тела.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Reading {
    Tcp(SeenTcp),
    /// У датаграмм алфавит ровно общий — см. `impl Alphabet for Udp` выше. Ветвь названа `Udp`, а
    /// не `Common`, потому что она про ПРОТОКОЛ наблюдения: в день, когда у датаграмм появится
    /// своя буква, меняется содержимое ветви, а не её смысл.
    Udp(Seen),
}

impl Reading {
    /// СУЗИТЬ ДО ОБЩЕГО СЛОВАРЯ — для приборов, которым транспорт безразличен.
    ///
    /// `None` у ветви TCP значит «буква принадлежит транспорту и на общем не существует» (стук,
    /// рукопожатие, сброс, окно), а вовсе не «ничего не наблюдалось».
    pub fn anywhere(&self) -> Option<Seen> {
        match self {
            Reading::Tcp(seen) => <reflex_core::Tcp as Alphabet>::anywhere(seen),
            Reading::Udp(seen) => Some(seen.clone()),
        }
    }
}
