//! Словарь провода — что видно на разговоре, в терминах наблюдения. `Seen` есть наблюдение о мире,
//! а не решение; `Distress`/`Finding`/`Sighting` (беда и намерение) остаются у потребителя.

/// Кто послал сброс. Три явления, лечатся по-разному: булев флаг держал два и молчал, что сброс от
/// цели составной (её отказ И инжект постороннего от её имени).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResetBy {
    /// Человек: закрыл вкладку, оборвал ожидание, переоткрыл.
    Person,
    /// Оборвали мы сами (исполнение `Act::Sever`), не переживание человека. Заведён до нужды:
    /// когда обрыв заработает, наш приказ пришёл бы со стороны клиента и читался бы как уход —
    /// молча.
    Ourselves,
    /// Пришёл со стороны цели — и это всё, что установлено. Не `Target`: чей сброс на самом деле,
    /// не знаем (различитель на проводе есть, не читается — Н10).
    TargetSide,
}

/// Словарь любого транспорта — буквы, существующие и на соединении, и на датаграммах. `Idle` нет:
/// тишина обнаруживается тиком, не выдуманным событием. Имя `Seen` за общим, не за TCP: утверждение
/// о мире верно независимо от транспорта; алфавит TCP — [`SeenTcp`], содержит общий целиком.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Seen {
    /// Клиент отправил байты вверх — человек попросил. Направление существенно: «цель молчит при
    /// живом клиенте» ≠ «молчат обе».
    Sent { count: u32 },
    /// Клиент повторил то же — ответа не было. Отдельно от `Sent`: повтор виден раньше тишины (та
    /// ждёт порога). Как узнано (повтор `seq`), домену знать не нужно — различает край.
    Resent { count: u32 },
    /// Разговор окончен — сторона попрощалась, а не оборвала ([`SeenTcp::Rst`]). Отдельно от
    /// сброса (сброс — беда, прощание — норма). Без прощания наблюдение флоу не кончается никогда
    /// (тик мёртвому набирает улику из чужих пауз). На UDP не рождается (прощания у датаграмм нет).
    Closed {
        /// Попрощался клиент. Иначе — цель.
        by_client: bool,
    },
    /// Цель отдала байты вниз.
    Received { count: u32 },
    /// ЦЕЛЬ ПОВТОРИЛА ТО ЖЕ — её ответ ушёл и до клиента не дошёл. Отдельно от [`Seen::Received`],
    /// и это не симметрия ради симметрии: пока повтор цели схлопывался в «цель отдала», целый КЛАСС
    /// блокировок был неотличим от медленного канала — всякий фильтр «в обратную сторону» выглядит
    /// так, что клиент доволен, цель старается, прогресса нет.
    ///
    /// Замер, которым буква оплачена: запись с дропом ответов после 16-го пакета — цель шлёт один и
    /// тот же сегмент с удваивающимися интервалами (0,5 · 0,9 · 1,8 · 3,4 · 6,7 с — это RTO цели),
    /// потом клиент прощается. Батарея из пяти приборов молчала вся: тишина и захлёбывание не видят
    /// беды, потому что байты ИДУТ; троттлинг видит скорость, а не отсутствие прогресса; повтор
    /// клиента ловит другую сторону; сброса нет вовсе.
    ///
    /// Вариантом, а не полем направления у [`Seen::Resent`], — по оплаченному прецеденту
    /// [`SeenTcp::Rst`]: там автор сброса сделан вариантом, и замер 29.08 показал цену флага —
    /// детектор обвинял цель за наши же сбросы, 17 из 23. Здесь та же развилка и та же цена.
    Restated { count: u32 },
    /// Первые байты потока — по ним узнаётся протокол. Направление обязательно: протокол узнаётся
    /// по первому пакету КЛИЕНТА, иначе голова клиента засчиталась бы отданными целью байтами.
    Payload { head: Vec<u8>, from_client: bool },
}

/// Словарь соединения — общий алфавит плюс четыре улики, которых у датаграмм нет (рукопожатие,
/// сброс, окно приёма существуют от состояния TCP). Прибор на `SeenTcp` в поток датаграмм не
/// собирается; на `Seen` — годится обоим (сужение — [`Reads`](reflex_core::Reads)).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SeenTcp {
    /// Клиент постучал — `SYN` без `ACK`.
    Syn,
    /// Цель ответила на стук — `SYN+ACK`, рукопожатие состоялось. Отдельный вариант, не поле
    /// направления: различает блокировку по адресу (нет рукопожатия) от блокировки по имени
    /// (рукопожатие есть, оборвано после `ClientHello`).
    Handshaken,
    /// Сброс, и у него есть автор [`ResetBy`], не флаг. Без автора детектор обвинял цель за наш же
    /// сброс (замер 29.08: 23 сброса, 17 наши). У QUIC обрыв зашифрован — на UDP невыразимо.
    Rst {
        /// Кто сбросил.
        by: ResetBy,
    },
    /// Одна из сторон попросила подождать (нулевое окно приёма) — объяснение медленности, не её
    /// причина в сети: притормозил получатель — цель винить нельзя. Окна у датаграмм нет, потому
    /// буква здесь, а не в общем.
    AskedToWait {
        /// Попросил подождать клиент. Иначе — цель.
        by_client: bool,
    },
    /// То, что видно на любом транспорте — общий алфавит целиком. Вложением, не повтором пяти букв
    /// (повтор разошёлся бы молча). `Seen::read` отдаёт содержимое, `None` на остальных.
    Anywhere(Seen),
}

impl SeenTcp {
    /// Клиент отправил байты.
    pub fn sent(count: u32) -> Self {
        Self::Anywhere(Seen::Sent { count })
    }

    /// Клиент повторил просьбу.
    pub fn resent(count: u32) -> Self {
        Self::Anywhere(Seen::Resent { count })
    }

    /// Цель отдала байты.
    pub fn received(count: u32) -> Self {
        Self::Anywhere(Seen::Received { count })
    }

    /// Сторона попрощалась.
    pub fn closed(by_client: bool) -> Self {
        Self::Anywhere(Seen::Closed { by_client })
    }

    /// Голова потока.
    pub fn payload(head: Vec<u8>, from_client: bool) -> Self {
        Self::Anywhere(Seen::Payload { head, from_client })
    }
}

impl From<Seen> for SeenTcp {
    fn from(seen: Seen) -> Self {
        Self::Anywhere(seen)
    }
}

/// Сужение алфавита — частичный морфизм `SeenTcp → Option<Seen>`. `None` не сбой: буква соединения
/// для прибора на любом транспорте — факт не про него.
impl reflex_core::Reads<SeenTcp> for Seen {
    fn read(wide: &SeenTcp) -> Option<Self> {
        match wide {
            SeenTcp::Anywhere(seen) => Some(seen.clone()),
            SeenTcp::Syn
            | SeenTcp::Handshaken
            | SeenTcp::Rst { .. }
            | SeenTcp::AskedToWait { .. } => None,
        }
    }
}

/// Из широкого словаря провода в общий: TCP отдаёт своё содержимое, датаграмма — своё. Через это
/// приборы на любом транспорте (тишина, темп) читают свой алфавит, не зная, откуда он пришёл.
impl reflex_core::Reads<Reading> for Seen {
    fn read(wide: &Reading) -> Option<Self> {
        wide.anywhere()
    }
}

/// Из широкого словаря провода в TCP: датаграмма TCP-букв не несёт. Так приборы соединения (сброс,
/// IP-blackhole) читают `SeenTcp` из общего потока.
impl reflex_core::Reads<Reading> for SeenTcp {
    fn read(wide: &Reading) -> Option<Self> {
        match wide {
            Reading::Tcp(seen) => Some(seen.clone()),
            Reading::Udp(_) => None,
        }
    }
}

/// У протокола есть свой словарь наблюдений — связка объекта стека (`reflex`) с алфавитом (здесь).
/// Отдельным трейтом, не полем в `reflex_core::Protocol`: `reflex` о наблюдениях знать не должен.
/// `type Seen` ассоциированным типом: наблюдение, СОСТАВ которого протоколом определён.
pub trait Alphabet: reflex_core::Protocol + Clone + core::fmt::Debug + PartialEq + Eq {
    type Seen: Clone + core::fmt::Debug + PartialEq + Eq;

    /// Сузить до общего словаря. `None` — буква принадлежит протоколу. Отдельным методом, а не
    /// границей `Seen: Reads<Self::Seen>`: Rust не раскрывает where-условия как подразумеваемые.
    fn anywhere(seen: &Self::Seen) -> Option<Seen>;
}

impl Alphabet for reflex_core::Tcp {
    type Seen = SeenTcp;

    fn anywhere(seen: &SeenTcp) -> Option<Seen> {
        <Seen as reflex_core::Reads<SeenTcp>>::read(seen)
    }
}

/// У датаграмм своих букв пока нет — алфавит ровно общий. `SeenUdp` авансом не заводим: обёртка
/// без своей буквы притворяется различением.
impl Alphabet for reflex_core::Udp {
    type Seen = Seen;

    fn anywhere(seen: &Seen) -> Option<Seen> {
        Some(seen.clone())
    }
}

/// Протокол безразличен — алфавит общий: утверждать улику конкретного протокола было бы ложью.
impl Alphabet for reflex_core::AnyProtocol {
    type Seen = Seen;

    fn anywhere(seen: &Seen) -> Option<Seen> {
        Some(seen.clone())
    }
}

/// Показание с названным протоколом — производитель называет протокол, установленный РАЗБОРОМ.
/// Производитель обязан назвать протокол до того, как у датаграмм появится первая своя буква:
/// `Option<SeenTcp>` фиксировал бы TCP в типе, и половина трафика (QUIC) молча не имела бы
/// производителя.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Reading {
    Tcp(SeenTcp),
    /// У датаграмм алфавит общий; ветвь названа `Udp`, не `Common`, — она про ПРОТОКОЛ: появится
    /// своя буква, меняется содержимое, не смысл.
    Udp(Seen),
}

impl Reading {
    /// Сузить до общего словаря — для приборов, которым транспорт безразличен. `None` у ветви TCP —
    /// «буква принадлежит транспорту», не «ничего не наблюдалось».
    pub fn anywhere(&self) -> Option<Seen> {
        match self {
            Reading::Tcp(seen) => <reflex_core::Tcp as Alphabet>::anywhere(seen),
            Reading::Udp(seen) => Some(seen.clone()),
        }
    }
}
