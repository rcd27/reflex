//! ПАСПОРТ ПРИБОРА — проекция `model/law/Instrument.tla` (частица), шов с человеком проверен
//! молекулой `model/molecule/TimelyInstrument.tla`.
//!
//! # Предмет
//!
//! Прибор — не всякий тип, а тот, что даёт СИГНАЛ. Элемент (газоэлемент в газоанализаторе) даёт
//! величину и наружу не высказывается; прибор = элементы + интерпретация. Новый прибор рождается
//! новой интерпретацией над скрещённым элементом, а НЕ сложением приборов: если два прибора
//! приходится складывать, интерпретация у обоих проведена слишком рано.
//!
//! # Приборы о ЧЕЛОВЕКЕ — композиты, и это меняет закон их различения
//!
//! Опыт человека не наблюдается напрямую: он складывается из направления, насыщения, пропуска
//! пакетов и прочего. Проверено на коде: `FlowContribution` — вклад одного разговора в эпизод —
//! несёт `observed: Observed`, то есть ПОКАЗАНИЕ ПРИБОРА О МИРЕ, рядом с величинами (ожидание,
//! объём, пиковый темп). Сводка эпизода есть интерпретация над множеством таких вкладов.
//!
//! **ЗАКОН КОМПОЗИТА: различение(композит) ≤ различению частей, из которых он сложен.**
//!
//! Это тот же `различение(f ∘ g) ≤ различение(g)`, что и у интерпретации, только применённый к
//! целому прибору. Практически: если `Observed` пассивно не отличает `Mirage` от `Good` (а он не
//! отличает — TLS закрыт), то и сводка эпизода не отличит «человек получил своё» от «человек
//! получил заглушку». Слепота ступени поднимается наверх ЦЕЛИКОМ и там уже неисправима.
//!
//! Отсюда практическое следствие для чтения паспортов: у прибора-композита клетка «как он врёт»
//! обязана включать слепоты его частей — иначе паспорт утверждает больше, чем прибор способен.
//! `CellInstrument` признаёт это прямо («не может ошибиться сам, и это не достоинство»).
//!
//! # Четыре множителя, и ноль в любом обнуляет всё
//!
//! Модель установила то, ради чего паспорт существует: прибор, проваливший ЛЮБУЮ ось, остаётся
//! ЧЕСТНЫМ (`NoFalseAlarm` зелёный во всех четырёх красных клетках). То есть по своему выходу
//! он неотличим от исправного, и различить их можно только паспортом.
//!
//! # Что здесь ТИПОМ, а что константой
//!
//! Половина паспорта втащена в тип и потому не разъезжается с телом: решётка, форма выхода,
//! обязанность нести «не знаю». Остальное — предмет, лечение, режимы лжи, покрытие, второй
//! оракул, условие смерти — типом не выражается и живёт константами, которые печатает аудит.
//! Граница та же, что у гейтов: что можно проверить — проверяется, что нельзя — объявляется
//! рядом с телом. Закон слоя: ВЫВЕДЕННОЕ СИЛЬНЕЕ ОБЪЯВЛЕННОГО.

