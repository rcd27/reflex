//! ПРОСАДКА КАНАЛА — прибор о том, что «начало качаться хреново».
//!
//! Переехал из другого крейта при сведении детекции в один дом: ответ на вопрос «что мы видим»
//! обязан быть один, а был свой в каждом из пяти крейтов.

/// ПРОСАДКА КАНАЛА — «начало качаться хреново», а не «скачалось медленно».
///
/// # Почему это ОТДЕЛЬНЫЙ прибор, а не порог у `ThrottledInstrument` (пока у потребителя)
///
/// Тот отвечает на вопрос о ВЕЛИЧИНЕ: «столько байт в секунду против стольких доказанных». Его
/// показание — точка, и точка не различает две вещи, которые человек переживает по-разному:
/// канал, который ВСЕГДА медленный (плохой тариф, дальняя цель, слабый Wi-Fi), и канал, который
/// шёл хорошо и ПРОСЕЛ посреди разговора. Первое человек знает про себя и терпит; второе он
/// чувствует как «сломалось» — и приходит с этим к нам.
///
/// Различает их только РЯД: у просадки есть момент, до которого было хорошо.
///
/// # Три ловушки, каждая замерена на живых записях стенда
///
/// **МАХОВИК.** Первое окно всегда неполное: TCP разгоняется, TLS ещё договаривается. Замер
/// показал 1,1 МБ в нулевой секунде против 1,03 в первой — разница есть, но она не беда.
/// Первое окно из планки исключено, судить по нему нельзя.
///
/// **ХВОСТ.** Последнее окно тоже неполное — файл кончился на середине секунды (183 КБ против
/// 238 в предыдущих). Прибор, судящий последнее окно, объявляет просадку в конце КАЖДОЙ
/// загрузки.
///
/// **ПАЧЕЧНОСТЬ.** Окно короче периода пачки даёт нули между пачками: тот же ряд по полсекунды
/// дал «200 КБ — ноль — 200 КБ», и каждая вторая точка читалась как полный обрыв. Окно обязано
/// быть не меньше секунды, и это свойство ПРОВОДА, а не настройка вкуса.
///
/// # Порог поставлен в разрыве замера
///
/// На фикстуре `sag`: 1,05 МБ/с до и 238 КБ/с после — отношение 4,4. На контроле `steady_slow`
/// канал ровный 238 КБ/с на всём протяжении, и отношение любых двух окон там около единицы.
/// Порог `2` лежит в этом разрыве, а не подогнан к одному из краёв.
pub struct SagInstrument;

/// ЧТО ИМЕННО ПРОСЕЛО — и когда. Не `bool`: «просадка есть» без момента и величины не даёт ни
/// назвать беду человеку, ни сверить её с землёй.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Sag {
    /// Номер окна, на котором темп упал. Это и есть «когда начало качаться хреново».
    pub at_window: usize,
    /// Байт в секунду ДО просадки — планка, которую цель уже доказала.
    pub before_bps: u64,
    /// Байт в секунду ПОСЛЕ. Разность с планкой и есть мера того, что потерял человек.
    pub after_bps: u64,
}

/// СКАЗАНО РАЗГОВОРУ: просадка есть его собственное свойство — у неё момент ВНУТРИ него, до
/// которого было хорошо.
impl reflex_core::word::Word for Sag {
    type Of = reflex_core::word::Conversation;
}

impl SagInstrument {
    fn read(&self, observation: &Vec<u64>, _now_ms: u64) -> Option<Sag> {
        // ХВОСТ И МАХОВИК ОТБРАСЫВАЮТСЯ ДО ВСЯКОГО СЧЁТА. Оба неполны по построению, и участие
        // любого из них в планке или в сравнении даёт ложную тревогу на исправной загрузке.
        let windows: &[u64] = match observation.len() {
            0..=3 => return None,
            length => &observation[1..length - 1],
        };

        // ПЛАНКА — ПЕРВОЕ ОКНО ПОСЛЕ МАХОВИКА. Не среднее по всему ряду: среднее уже включает
        // просадку и потому занижает планку тем сильнее, чем дольше человек терпел.
        let baseline = match windows.first() {
            None => return None,
            Some(&first) => first,
        };

        // ДВА ОКНА ПОДРЯД, А НЕ ОДНО. Одиночный провал бывает от чего угодно — переключение
        // маршрута, чужой трафик, пауза приложения. Требование двух подряд оплачено ложными
        // тревогами на записях, где провалившееся окно было ровно одно.
        windows
            .windows(2)
            .enumerate()
            .find(|(_, pair)| pair.iter().all(|&bps| bps * 2 < baseline))
            .map(|(index, pair)| Sag {
                // `+1` возвращает номер окна в ИСХОДНОМ ряду: маховик мы отбросили, а человек
                // считает секунды от начала загрузки, а не от начала нашей выборки.
                at_window: index + 1,
                before_bps: baseline,
                after_bps: pair[0],
            })
    }
}

impl reflex_core::mealy::Mealy for SagInstrument {
    /// НАБЛЮДЕНИЕ, которое подают прибору.
    type In = reflex_core::DetectorEvent<Vec<u64>>;

    /// СЛОВО. Отсутствие слова сигналом не является: прибор высказывается, когда есть что
    /// сказать, и «ничего не случилось» не занимает места в ленте.
    type Out = smallvec::SmallVec<[Sag; 2]>;

    /// Показаний этот прибор не заводит: он говорит, что увидел, и не говорит, чем мерил.
    type Log = ();

    fn step(self, event: Self::In) -> (Self, Self::Out, ()) {
        match event {
            reflex_core::DetectorEvent::Packet { input, .. } => {
                let reading = self.read(&input, 0);
                (self, reading.into_iter().collect(), ())
            }
            reflex_core::DetectorEvent::Tick { .. } => (self, smallvec::SmallVec::new(), ()),
            // Прибор мерит РАЗОБРАННЫЙ домен; непонятое им не является и молчит так же, как тик.
            reflex_core::DetectorEvent::Opaque { .. } => (self, smallvec::SmallVec::new(), ()),
        }
    }
}

impl crate::Instrument for SagInstrument {
    type Signal = Sag;

    const INSTRUMENT: &'static str = "sag";

    const SUBJECT: crate::Subject = crate::Subject::World;

    /// УРОВЕНЬ: объём во времени считается по байтам, а байты есть на любом транспорте.
    const LAYER: crate::Layer = crate::Layer::Transport;
    /// ТРАНСПОРТЫ: объём во времени считается по байтам, и байты есть у обоих.
    const PROTOCOLS: &'static [crate::Protocol] = &[crate::Protocol::Tcp, crate::Protocol::Udp];
    const RUNG: Option<crate::Rung> = None;

    /// СВОИ ЧАСЫ: окно закрывается временем, а не приходом байта. Иначе прибор молчал бы ровно
    /// тогда, когда байты перестали идти совсем, — то есть в худшем случае для человека.
    const CADENCE: crate::Cadence = crate::Cadence::Own { step_ms: 1_000 };

    /// РЯД, а не величина: показание осмысленно только относительно предыдущих.
    const SHAPE: crate::Shape = crate::Shape::Series;

    /// СЛЕПОТА, А НЕ ПУСТОТА: ряд короче четырёх окон не даёт ответа в принципе — из него после
    /// отбрасывания маховика и хвоста остаётся меньше двух точек. Это `Blind`, и лечится он
    /// более длинной загрузкой, а не другим порогом.
    const SILENCE: Option<crate::Silence> = Some(crate::Silence::Blind);

    const LIES: &'static [&'static str] = &[
        "ПРИЧИНЫ НЕ ЗНАЕТ. Просадка от инфраструктурной фильтрации, от переполненного Wi-Fi и от того, что цель отдаёт \
         остаток файла с диска, дают ОДИН ряд. Прибор говорит «стало хуже вот здесь», и это всё, \
         что он устанавливает.",
        "ПЛАНКА ИЗ НАЧАЛА ЗАГРУЗКИ. Если канал был плох С САМОГО НАЧАЛА, планка запомнит плохое, \
         и просадка от неё не отсчитается никогда — ровно как у соседа по парку (`ThrottledInstrument`, \
         огибающая храповиком). Клетка `steady_slow` показывает это прямо: там прибор МОЛЧИТ, и \
         молчание верно, хотя человеку медленно.",
        "ПРОСАДКА В КОНЦЕ ЗАГРУЗКИ НЕ ВИДНА. Последнее окно отброшено намеренно, и цена названа: \
         беда, случившаяся в последнюю секунду, останется незамеченной. Обратное дало бы тревогу \
         на каждой нормальной загрузке.",
    ];

    const ORACLES: &'static [&'static str] = &["sag(10mbit,2mbit,3)", "throttle(2mbit,0)"];

    /// СМЕРТЬ: прибор ряда научится отличать причину просадки от самой просадки — тогда его
    /// показание перестанет быть «стало хуже» и станет диагнозом.
    const DEATH: &'static str =
        "просадка получила причину: прибор различает наведённую просадку и узкий канал";

    /// ПУБЛИЧНЫЕ ИМЕНА СОБЫТИЙ — реестр, снятый с типа: за границей процесса имя показания не
    /// сторожит компилятор, и `Debug` сменил бы метку молча (#321).
    const EVENTS: &'static [&'static str] = &["sag"];

    fn name(signal: &Self::Signal) -> &'static str {
        let _ = signal;
        "sag"
    }

    fn alarming(signal: &Self::Signal) -> bool {
        let _ = signal;
        true
    }
}
