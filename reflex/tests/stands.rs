//! СТОРОЖ ПРАВИЛА 10.10: стенд, который ИЗМЕНЯЕТ мир, обязан снимать контроль.
//!
//! Правило записано в каноне (§10.1, Правило 10.10) и до этого сторожа держалось тем, что о нём
//! помнили. Между тем оно рождено из четырёх улик поля за один вечер, и каждая — про замер, который
//! мерил не мир, а самого меряющего: изменение применялось по одному признаку, а контроль строился
//! по другому; изменение действовало на исходящую сторону, а беда приходила с обратной; бюджет
//! ожидания упирался в собственный таймаут; и наш собственный стенд обрыва не имел контроля вовсе —
//! он сравнивал замер с числом, запомненным в прошлом.
//!
//! ПРИЗНАК, А НЕ ИМЯ (§10.9). Стенд ищется не по названию примера и не по списку, а по тому, что
//! его код ЗОВЁТ действие: `.act(` в коде, не в докблоке. Заведётся завтра новый пример с
//! действием — сторож потребует контроль и с него, никому не напоминая.
//!
//! ЧЕГО СТОРОЖ НЕ ПРОВЕРЯЕТ, и это названо, чтобы он не выглядел сильнее, чем есть: частей (а) и
//! (б) правила — совпадения признака и покрытия стороны — он не видит. Они суть свойства
//! постановки замера, а не текста скрипта; типом невыразимы так же, как обязанность ослепнуть
//! (Опр. 7.4), и проверяются мутацией да головой. Сторож держит то, что механически проверяемо:
//! контроль ЕСТЬ и он ВЛИЯЕТ на вердикт.

use std::path::{Path, PathBuf};

/// Корень дерева: сторож читает соседние крейты и примеры, а не свой.
fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("у крейта фасада есть родитель")
        .to_path_buf()
}

/// Все файлы с этим расширением под каталогом, рекурсивно.
fn under(dir: &Path, ext: &str) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let Ok(entries) = std::fs::read_dir(dir) else {
        return found;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        match path.is_dir() {
            true => found.extend(under(&path, ext)),
            false if path.extension().is_some_and(|it| it == ext) => found.push(path),
            false => (),
        }
    }
    found
}

/// ЗОВЁТ ЛИ КОД ДЕЙСТВИЕ. Строки докблоков и комментариев не считаются: `replay-recording`
/// объясняет в шапке, почему `.act(…)` с записью НЕ СОБЕРЁТСЯ, — и попал бы в действующие, читай мы
/// файл целиком. Признак обязан отличать употребление от объяснения.
fn acts(source: &str) -> bool {
    source.lines().any(|line| {
        let code = line.trim_start();
        !code.starts_with("//") && (code.contains(".act(") || code.contains("Act::sever"))
    })
}

/// ПРЕДМЕТ: пример, который действует на мир, обязан иметь стенд с контролем, и контроль обязан
/// РЕШАТЬ, а не украшать вывод.
///
/// Две проверки, потому что контроль, который печатают и не используют, — худший вид отсутствия: он
/// виден человеку и не виден вердикту. Вторая проверка спрашивает исход `НЕДЕЙСТВИТЕЛЕН` — клетку,
/// которая бывает только тогда, когда контроль читают.
#[test]
fn a_stand_that_changes_the_world_measures_a_control() {
    let examples = root().join("examples");
    let mut acting: Vec<(String, PathBuf)> = Vec::new();

    for entry in std::fs::read_dir(&examples)
        .expect("каталог примеров читается")
        .flatten()
    {
        let dir = entry.path();
        if !dir.is_dir() {
            continue;
        }
        let name = dir
            .file_name()
            .expect("у каталога есть имя")
            .to_string_lossy()
            .to_string();
        let acting_here = under(&dir.join("src"), "rs")
            .iter()
            .filter_map(|path| std::fs::read_to_string(path).ok())
            .any(|source| acts(&source));
        if acting_here {
            acting.push((name, dir));
        }
    }

    assert!(
        !acting.is_empty(),
        "ни один пример не действует на мир — сторож ослеп к своему классу и проверяет пустоту \
         (Следствие 10.9)"
    );

    let mut naked: Vec<String> = Vec::new();
    for (name, dir) in &acting {
        let stands = under(&dir.join("lab"), "sh");
        // Стенда нет вовсе — правило неприменимо: замера, который мог бы соврать, не существует.
        if stands.is_empty() {
            continue;
        }
        let text: String = stands
            .iter()
            .filter_map(|path| std::fs::read_to_string(path).ok())
            .collect::<Vec<_>>()
            .join("\n");
        if !text.contains("[контроль]") {
            naked.push(format!("{name}: стенд не снимает контроля"));
        } else if !text.contains("НЕДЕЙСТВИТЕЛЕН") {
            naked.push(format!(
                "{name}: контроль снимается, но на вердикт не влияет — нет исхода \
                 «НЕДЕЙСТВИТЕЛЕН»"
            ));
        }
    }

    assert!(
        naked.is_empty(),
        "стенды, меряющие мир, который сами изменяют, без контроля (Правило 10.10): {naked:?}"
    );
}
