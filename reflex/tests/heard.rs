//! ПОКАЗАНИЯ ЗНАЧЕНИЕМ — третья дверь наблюдения (`.heard()`), и закон о том, что она НЕ ВТОРОЙ
//! ЦИКЛ.
//!
//! Опасность здесь ровно одна и уже сбывалась в этом дереве: у действия когда-то завёлся свой
//! ведущий цикл, он молча разошёлся с наблюдательским (слова узлов выбрасывал, дыры не знал вовсе),
//! и сборка при этом была зелена. Потому главный тест файла сверяет не «итератор что-то отдал», а
//! «отдал ДОСЛОВНО то же, что услышало замыкание на том же сценарии».

mod paper;

use std::time::Duration;

use paper::{request, Crier, Paper};
use reflex::*;

/// Сценарий строится дважды — двум прогонам нужен свой носитель каждому (носитель линеен: его
/// съедает открытие). Одна функция, а не две копии: разошедшийся сценарий сверял бы разные ленты и
/// молчал бы об этом.
fn scenario() -> Paper {
    Paper::new()
        .then_packet(request(40001))
        .then_packet_after(Duration::from_secs(1), request(40002))
        .then_stop()
}

/// ОДИН ЦИКЛ, ДВА ПОТРЕБИТЕЛЯ. Показания, вытянутые итератором, дословно равны показаниям,
/// пришедшим в замыкание, — вместе с АДРЕСОМ, а не только со словом.
///
/// Сверка непустого обязательна отдельной строкой: два молчания тоже равны, и закон, довольный
/// равенством, был бы зелен на цепочке, не говорящей ничего.
#[test]
fn показания_значением_дословно_равны_показаниям_замыканием() {
    let mut through_closure: Vec<(String, Flow, Distress)> = Vec::new();
    engine(scenario())
        .from(Tcp)
        .extract(Sni)
        .detect(Crier::always())
        .on_addressed(|whom, word| through_closure.push((whom.target.to_string(), whom.flow, word)))
        .run();

    let through_value: Vec<(String, Flow, Distress)> = engine(scenario())
        .from(Tcp)
        .extract(Sni)
        .detect(Crier::always())
        .heard()
        .expect("бумажный носитель открывается")
        .map(|note| (note.target.to_string(), note.flow, note.word))
        .collect();

    assert_eq!(
        through_value, through_closure,
        "итератор и замыкание слушают ОДИН цикл: разойтись им негде"
    );
    assert_eq!(
        through_value.len(),
        2,
        "два пакета — два показания; пустое совпадение не есть совпадение"
    );
    assert_ne!(
        through_value[0].1, through_value[1].1,
        "адрес доехал значением: разные разговоры различимы, а не слиты именем цели"
    );
}

/// НЕСОСТОЯВШИЙСЯ ЗАПУСК ПРИХОДИТ ЗНАЧЕНИЕМ, А НЕ ПУСТЫМ ИТЕРАТОРОМ (§7).
///
/// «Не смотрели» и «смотрели и кончилось» — разные исходы, и слить их в `None` значило бы отдать
/// потребителю пустоту вместо причины. Пустой итератор молчит; `Err(Report)` называет.
#[test]
fn носитель_не_открылся_и_это_слышно_причиной() {
    let refused = engine(Paper::new().shut("бумага кончилась"))
        .from(Tcp)
        .extract(Sni)
        .detect(Crier::always())
        .heard();

    match refused {
        Ok(_) => panic!("носитель, который не открывается, не смеет отдать итератор"),
        Err(report) => assert_eq!(
            report.why(),
            Some("бумага кончилась"),
            "причина доехала значением, а не потерялась в пустоте"
        ),
    }
}

/// КОНЕЦ ЛЕНТЫ — `None`, и он наступает. Закон о том, что итератор не крутится вечно на носителе,
/// сказавшем «работы больше не будет»: `.then_stop()` в сценарии не украшение.
#[test]
fn исчерпанный_носитель_кончает_итератор() {
    let mut notes = engine(scenario())
        .from(Tcp)
        .extract(Sni)
        .detect(Crier::always())
        .heard()
        .expect("бумажный носитель открывается");

    assert!(notes.next().is_some());
    assert!(notes.next().is_some());
    assert!(
        notes.next().is_none(),
        "носитель сказал, что работы больше не будет, — итератор обязан кончиться"
    );
}
