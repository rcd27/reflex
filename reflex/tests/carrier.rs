//! Дверь отдаёт НОСИТЕЛЯ, а не число очереди: предпосылки носителя — дело носителя.

use reflex::*;

/// Раскладка приходит от носителя, а не от цепочки: у очереди 15 наших бит среди чужих, и кто
/// делит машину с соседом, говорит это здесь.
#[test]
fn the_layout_comes_from_the_carrier() {
    let default = Nfqueue::queue(200);
    assert_eq!(default.layout().mask(), 0x0FFF_E000);

    let shared = Nfqueue::queue(200)
        .marking(0x0000_7FFF, 0b011)
        .expect("15 бит, ненулевой тег");
    assert_eq!(shared.layout().mask(), 0x0000_7FFF);
}

/// Имя носителя — то, чем `Report` назовёт несостоявшийся запуск. Число очереди больше не
/// единственная форма: у WinDivert его нет вовсе.
#[test]
fn the_carrier_names_itself_for_the_report() {
    assert_eq!(Nfqueue::queue(200).name(), "очередь 200");
}

/// Носитель без ядерного учёта — законный носитель, а не костыль для теста: на машине без
/// `nf_conntrack_acct` фасад сегодня не поднимается вовсе (`TimeoutBase::read()` = `None`).
/// Раскладка марки — умолчание [`Nfqueue::queue`], НЕ вся 32-битная ячейка: `Layout::new` по
/// построению принимает лишь 15-битное окно с ненулевым тегом (предпосылка кодека `edge.rs`),
/// и местный носитель делит машину с соседом ровно как ядерный.
#[test]
fn a_local_queue_does_not_require_conntrack_accounting() {
    let local = Nfqueue::local(201);
    assert_eq!(local.name(), "очередь 201 (местный край)");
    assert_eq!(local.layout().mask(), 0x0FFF_E000);
}

/// СПОСОБНОСТЬ, КОТОРУЮ ДЕРЖИТ СОКЕТ, ОБЯЗАН ДЕРЖАТЬ И НОСИТЕЛЬ ФАСАДА.
///
/// Замер 11.09.2026: `CanMark` и `CanRewrite` вернулись в `QueueSocket` (потерялись при переезде на
/// свой сокет и были возвращены по правилу «канон объявил — код обязан держать»), а до
/// `NfqueueCarrier` в тот же заход НЕ ДОШЛИ. Способность, которую держит сокет и не предъявляет
/// носитель фасада, недостижима ровно так же, как несуществующая: гейт §9.1 сторожит доступ к
/// тому, чего в цепочке нет.
///
/// Держит это КОМПИЛЯТОР, а не сравнение имён: функция ниже требует от носителя фасада все семь
/// способностей разом, и отсутствие любой — ошибка сборки, не падение теста. Тело пустое нарочно:
/// предмет здесь — сами границы, а не то, что внутри.
#[test]
fn the_facade_carrier_holds_everything_its_socket_holds() {
    fn requires_all<C>()
    where
        C: CanHold + CanRefuse + CanSever + CanInject + CanRemember + CanMark + CanRewrite,
    {
    }

    requires_all::<NfqueueCarrier>();
}

/// МЕТКА ВПРЫСКА ЛЕЖИТ В СВОЕЙ ОБЛАСТИ, и число здесь — не второе объявление того же.
///
/// Константа фасада есть КОПИЯ значения, выведенного из области (`core::mark::injected_word`).
/// Копии расходятся молча, и расхождение этой читалось бы не красным тестом, а поведением сети:
/// правило ядра пропускает одно слово, сокет метит другим — свой впрыск возвращается в свою же
/// очередь и разбирается как чужой трафик.
#[test]
fn inject_mark_lives_in_its_region() {
    assert_eq!(
        INJECT_MARK,
        reflex_core::mark::injected_word(),
        "константа фасада разошлась с областью впрыска"
    );
    assert!(
        reflex_core::mark::injecting().mask() & INJECT_MARK == INJECT_MARK,
        "метка обязана помещаться в свою область целиком"
    );
    assert_ne!(INJECT_MARK, 0, "нулевая метка неотличима от нетронутой марки");
}

/// ДВА ПИСАТЕЛЯ ОДНИХ БИТОВ — ОТКАЗ ЗНАЧЕНИЕМ, и до всяких прав.
///
/// Раскладку приборов задаёт потребитель, и его числа о нашей метке впрыска не знают. Пересекись
/// они — приборы писали бы поверх признака «этот пакет наш», и заметно это стало бы по тому, что
/// движок разбирает собственные инъекции. Проверка стоит ПЕРЕД предпосылками носителя: отказ
/// приходит на машине без всяких прав, потому этот закон и проверяем в общем прогоне.
#[test]
fn a_layout_over_the_inject_mark_is_refused_before_anything_opens() {
    let refused = engine(
        Nfqueue::queue(200)
            .marking(0xFFFE_0000, 0b101)
            .expect("15 бит от бита 17 — связная маска"),
    )
    .from(Tcp)
    .extract(Sni)
    .detect(Silence::after(secs(5)))
    .on(|_target, _distress| {})
    .run();

    let why = refused.why().expect("пересечение обязано стать причиной");
    assert!(
        why.contains("пересекается с областью метки впрыска"),
        "причина названа не та: {why}"
    );
}

/// ВТОРАЯ ПОЛОВИНА: непересекающаяся раскладка этой дверью НЕ отвергается.
///
/// Без неё первая зелена и на проверке, отвергающей всё подряд, — а такая проверка запрещает
/// работать всем, включая умолчание.
#[test]
fn a_layout_beside_the_inject_mark_passes_the_check() {
    let refused = engine(Nfqueue::queue(200))
        .from(Tcp)
        .extract(Sni)
        .detect(Silence::after(secs(5)))
        .on(|_target, _distress| {})
        .run();

    let why = refused.why().unwrap_or("");
    assert!(
        !why.contains("пересекается с областью метки впрыска"),
        "умолчание раскладки не пересекается с меткой впрыска, а отвергнуто им: {why}"
    );
}
