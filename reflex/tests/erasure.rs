//! СТИРАНИЕ ИМЕНИ ДОЕЗЖАЕТ ДО РЕАКЦИИ — дорога целиком: датаграмма → транспорт → прибор → слово.
//!
//! Разговор, который кончается ДО транспорта. Клиент спросил адрес, получил «такого имени нет» и
//! никуда не пошёл: `SYN` не отправлен, рукопожатия нет, транспортным приборам сказать нечего —
//! разговора не было. Человек при этом видит «сайта не существует», то есть ровно тот же исход,
//! что и от сброса или блэкхола.
//!
//! Проверяется ПРОГОНОМ, а не сборкой: прибор и разбор существовали давно, а двери в фасаде не
//! было — цепочка о стёртом имени молчала, и молчание выглядело как «всё в порядке». Механизм без
//! двери неотличим от отсутствующего механизма.

mod paper;

use paper::{dns_answer, dns_denial, dns_query, log, taken, Denial, Paper};
use reflex::*;

/// Сочинить обмен: вопрос клиента и ответ резолвера.
fn exchange(answer: Vec<u8>) -> Paper {
    Paper::new()
        .then_packet(dns_query(40001, "rutracker.org"))
        .then_packet(answer)
        .then_stop()
}

/// Что сказала цепочка на этот обмен.
fn heard_on(answer: Vec<u8>) -> Vec<Resolved> {
    let heard = log::<Resolved>();

    engine(exchange(answer))
        .from(Udp)
        .extract(Sni)
        .detect(Resolve::names())
        .on(move |_target, resolved: Resolved| heard.lock().expect("слышно").push(resolved))
        .run();

    taken(heard)
}

/// ПРЕДМЕТ: поддельный отказ доезжает до реакции словом о СТИРАНИИ имени.
#[test]
fn стёртое_имя_доезжает_до_реакции() {
    assert_eq!(
        heard_on(dns_denial(40001, "rutracker.org", Denial::Forged)),
        vec![Resolved::Erased {
            name: "rutracker.org".to_string(),
            how: Erasure::Denied,
        }],
        "цепочка обязана назвать стирание имени, а не промолчать"
    );
}

/// Вторая половина пары: ЧЕСТНЫЙ отказ (рекурсор авторитетности не присваивает) — молчание.
/// Без неё первый тест зелен и на цепочке, которая кричит на всякий `NXDOMAIN`, а их в поиске по
/// суффиксам приходит по одному на каждое имя.
#[test]
fn обычное_нет_такого_имени_остаётся_молчанием() {
    assert!(
        heard_on(dns_denial(40001, "rutracker.org", Denial::Recursor)).is_empty(),
        "рекурсор, не нашедший имени, беды не составляет"
    );
}

/// ТРЕТЬЯ ТОЧКА, И ОНА БЛИЖЕ ВСЕХ К ПОДДЕЛКЕ: хозяин зоны, спрошенный НАПРЯМУЮ, ставит `AA` по
/// праву — от подделки его отличает только исполненный долг, срок отрицания в секции AUTHORITY.
///
/// Пара выше зелена и на цепочке, судящей по ОДНОМУ биту `AA`, — а такая цепочка обвиняет всякого,
/// кто спросил авторитетный сервер сам. Цена эта была названа вслух первой строкой `LIES` прибора
/// и держалась осознанно, пока улика была одна. Здесь она предъявлена на ДОРОГЕ ЦЕЛИКОМ:
/// датаграмма → транспорт → разбор → прибор → слово. Замер вантажа 12.09.2026: пять авторитетных
/// зон из пяти кладут `SOA`, три поддельных отказа из трёх — не кладут.
#[test]
fn хозяин_зоны_спрошенный_напрямую_остаётся_молчанием() {
    assert!(
        heard_on(dns_denial(40001, "rutracker.org", Denial::ZoneOwner)).is_empty(),
        "исполнивший долг хозяина зоны не подделка, сколько бы он ни ставил `AA`"
    );
}

/// ЧЕТВЁРТАЯ ТОЧКА: ответ хозяина зоны НЕ ВЛЕЗ В ДАТАГРАММУ — и от подделки он неотличим ничем,
/// кроме бита `TC`. Роль заявлена по праву (`aa`), секция пуста (AUTHORITY: 0) — то есть обе улики
/// обвинения налицо, и молчит прибор ровно потому, что сообщение объявило себя НЕПОЛНЫМ.
///
/// Замер 12.09.2026, `dig +norec +dnssec +bufsize=512 +ignore`: `a0.org.afilias-nst.info` и
/// `a.dns.ripn.net` — `aa tc`, AUTHORITY: 0, две зоны из двух. Без `+ignore` этого класса не
/// увидеть вовсе: `dig` молча переспрашивает по TCP и показывает уже целый ответ, где `SOA` на
/// месте. Класс нашёлся ПОСЛЕ того, как конъюнкция была признана достаточной, — и это цена того,
/// что мир проверяли не всеми доступными способами сразу.
#[test]
fn усечённый_ответ_хозяина_зоны_остаётся_молчанием() {
    assert!(
        heard_on(dns_denial(40001, "rutracker.org", Denial::Truncated)).is_empty(),
        "секцию срезали по дороге; читать её пустоту как невыполненный долг нельзя"
    );
}

/// Пятая точка: имя разрешилось — слово есть, и оно НЕ тревога. Держит дорогу целой с той
/// стороны, где всё в порядке: цепочка, молчащая всегда, зелена на четырёх точках выше.
#[test]
fn честно_разрешённое_имя_называется_своим_словом() {
    assert_eq!(
        heard_on(dns_answer(40001, "rutracker.org", [195, 82, 146, 214])),
        vec![Resolved::Honest {
            name: "rutracker.org".to_string(),
            addrs: vec![[195, 82, 146, 214]],
        }],
        "честный ответ обязан доехать с адресами — по ним потребитель и лечит цель"
    );
}
