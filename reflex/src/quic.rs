//! ТРАНСПОРТ QUIC — третий рядом с [`crate::Tcp`] и [`crate::Udp`].
//!
//! ```no_run
//! # #[cfg(feature = "quic")] fn main() -> reflex::Report {
//! use reflex::*;
//!
//! engine(Nfqueue::queue(200))
//!     .from(Quic)                      // 443/UDP, имя цели — из `Initial`
//!     .extract(Sni)
//!     .detect(Retransmit::unanswered())
//!     .detect(Silence::after(secs(5)))
//!     .on(|target, distress| report!("{target}: {distress}"))
//!     .run()
//! # }
//! # #[cfg(not(feature = "quic"))] fn main() {}
//! ```
//!
//! # Зачем он понадобился: молчание, неотличимое от «всё хорошо»
//!
//! Замер потребителя на 21 записи лаборатории с известной землёй: три записи (`quic_drop`,
//! `quic_mute`, `quic_sni_drop`) не поверялись ВОВСЕ — батарея молчала. Молчание здесь не слепота
//! прибора, а НЕ ТОТ ВХОД: `.from(Tcp)` слушает TCP, а беда живёт на 443/UDP. `Udp` не закрывает —
//! он объявлен как DNS (`Wire = DnsMessage`, `PORT = 53`), и QUIC через него не проходит по
//! построению.
//!
//! Цена в единице человека замерена там же: видеосервис грузится с двадцати узлов параллельно и
//! идёт по QUIC. Значит прогон у потребителя не видел ни одной его блокировки — не «видел хуже», а НЕ
//! ВИДЕЛ, и это молчание неотличимо от «всё хорошо».
//!
//! Разбор при этом лежал в фундаменте готовым (`reflex_core::quic::sni` — имя из зашифрованного
//! `Initial`). Ровно та же порода, что у парка приборов, четвёртой двери шва и `CanMark`: механизм
//! есть, предъявить его нечем. Дыра ФОРМЫ ПРЕДЪЯВЛЕНИЯ, а не механизма.
//!
//! # Словарь провода — ДАТАГРАММНАЯ ветвь общего, и что из этого следует для приборов
//!
//! `Wire = Reading`, ветвь `Reading::Udp(Seen)`: она про ПРОТОКОЛ, а QUIC и есть UDP. Оттого
//! цепочка с парковыми приборами СОБИРАЕТСЯ — и это проверяется сборкой `reflex/tests/quic.rs`, а
//! не обещанием здесь. `Wire = Seen` не собрал бы её вовсе: все шесть парковых объявлены над
//! `Reading`, и докблочное «приборы встают как есть» над узким словарём — ложь, которую находит
//! компилятор у потребителя.
//!
//! ЧТО СЛЫШНО НА QUIC, а что нет — по предмету прибора, и это не дефект, а природа датаграмм:
//!
//! * `Retransmit` — слышно: повтор открытия выражается (`DCID`, ниже). Момент, однако, чужой:
//!   прибор ждёт, пока клиент повторит, и заперт в ЕГО таймере — первый PTO у QUIC есть
//!   `srtt + 4×rttvar` ≈ 999 мс (RFC 9002), и раньше него слова не будет;
//! * `Silence` — слышно ОБЕИМИ половинами двери, и это разные беды в разные сроки: провод по
//!   СВОИМ часам говорит `NoBytes` («за всё моё наблюдение цель не отдала ни байта») — на
//!   датаграммах слово ему возвращено, ибо независимого свидетеля у отсутствия здесь нет
//!   (канон, Утв. 7.5в; довод целиком — у `Stalling` в `reflex/src/lib.rs`); край по ВОЗРАСТУ
//!   говорит `Blackhole`, но лишь на приходе следующего пакета — ct-вид едет с пакетом, на тике
//!   краевой прибор тождественен. Значит вовремя — только провод;
//! * `SynDrop`, `Rst`, `Choked`, `Throttled` — НЕ слышно, и молчат они законно: их предмет —
//!   `SeenTcp` (стук, рукопожатие, сброс, окно приёма), которого у датаграмм нет. Сужение отдаёт
//!   им `None`, и это «буква принадлежит другому транспорту», а не «ничего не наблюдалось».
//!
//! Читать это стоит буквально: на QUIC сегодня слышны повтор и тишина, и не слышны четыре беды из
//! шести. Прежняя редакция строки числила `SynDrop` слышным «через край» — замер на записи
//! QUIC-дропа (пять сценариев, включая повтор открытия) не дал от него ни одного слова. Сказано
//! здесь затем, чтобы это не выяснялось замером у потребителя.
//!
//! # Чего на QUIC НЕ РОЖДАЕТСЯ, названо прямо
//!
//! * `Seen::Closed` — обрыв в QUIC зашифрован, и наблюдателю невыразим (предел назван в докблоке
//!   `instrument::wire`, здесь он лишь наследуется). Следствие: разговор QUIC не кончается
//!   прощанием никогда, и снимает его только эвикт по простою.
//! * Имя цели — только из КЛИЕНТСКОГО `Initial` версии 1: ни 0-RTT, ни `Retry`, ни ECH (предел
//!   `reflex_core::quic`). Нет имени — цель ключуется адресом, `Unnamed`, и тег не притворяется.
//! * [`crate::Seen::Restated`] — повтор ЦЕЛИ — на QUIC НЕ РОЖДАЕТСЯ. Её пакеты зашифрованы
//!   целиком, номера лежат внутри, и наблюдателю видно лишь то, что байты идут. Повтор КЛИЕНТА
//!   выразим (`DCID` открытым текстом, ниже), повтор цели — нет, и это свойство протокола, а не
//!   «пока не сделано». Следствие названо числом у потребителя: запись с дропом ОТВЕТОВ по QUIC
//!   остаётся неслышной, тогда как та же беда на TCP слышна. Закроет её не этот транспорт, а
//!   краевой признак (счётчики ядра видят, что вниз идёт, а вверх подтверждений нет).
//!
//! # Как узнаётся ПОВТОР, и почему не сравнением байт
//!
//! Клиент, не получивший ответа, шлёт `Initial` заново с ТЕМ ЖЕ `DCID`, но новым номером пакета:
//! байты датаграммы другие, и сравнение «тот же кадр» повтора не увидит. Единственное, что видно
//! наблюдателю и не меняется между попытками, — `DCID` (открытым текстом, RFC 9001 §5.2). У TCP ту
//! же работу делает граница по `seq`; здесь её делает `DCID`.
//!
//! Но `DCID` один и у ПРОДОЛЖЕНИЯ: приветствие с постквантовым ключом в датаграмму не влезает, и
//! вторая его половина уходит через микросекунды с тем же `DCID`. Первая редакция звала её повтором —
//! и каждый разговор QUIC давал `Retransmit { after_ms: 0 }` (замер 14.09.2026: стенд и парк, чистые
//! цели уводились в контур). Потому повтор — `DCID` тот же И датаграмма не несёт НИ ОДНОГО нового
//! байта рукопожатия: её куски `CRYPTO` лежат внутри уже присланного, либо кусков нет вовсе — так
//! выглядит проба клиента (`PING` + `PADDING`), и под настоящим дропом других повторов нет (запись
//! стенда, curl/ngtcp2). Цена названа: `Initial`, который не расшифровался (не версия 1), кусков не
//! отдаёт, и его продолжение прочитается повтором — ровно как до этой правки.
//!
//! Повтор объявляется ТОЛЬКО пока цель не ответила ни разу. Ответила — и второй `Initial` уже не
//! улика: так бывает при миграции соединения, и обвинять цель за неё значило бы врать.

use std::collections::HashMap;

use reflex_core::types::Flow;
use reflex_core::word::TargetKey;

use crate::{Observation, Observed, Read, Reading, Seen, Transport, Unread};

/// Транспорт QUIC: датаграммы на 443, имя цели из `Initial`.
pub struct Quic;

/// Что помнит разбор о разговоре QUIC: чем он открылся и отвечали ли ему.
#[derive(Clone)]
struct Talk {
    /// `DCID` первого клиентского `Initial` — им и различается повтор.
    opened_with: Vec<u8>,
    /// Сколько раз клиент повторил открытие, не получив ответа.
    retries: u32,
    /// Ответила ли цель хоть одной датаграммой. После ответа повтор уликой быть перестаёт.
    answered: bool,
    /// Имя из `Initial`, если оно там было. Копится, потому что в следующих датаграммах его нет.
    named: Option<Box<str>>,
    /// Куски `CRYPTO`, собранные со ВСЕХ клиентских `Initial` этого разговора. Так и надо:
    /// `ClientHello` в QUIC не обязан помещаться в одну датаграмму, и у настоящего клиента он в
    /// неё НЕ ПОМЕЩАЕТСЯ — замер на снятом рукопожатии curl/ngtcp2: имя лежит во ВТОРОЙ датаграмме,
    /// а односоставная `quic::sni` молчит на обеих. Ровно ради этого случая в фундаменте и разведены
    /// `crypto_of` (куски из одной датаграммы) и `sni_of` (имя из склеенных кусков).
    crypto: Vec<(u64, Vec<u8>)>,
    /// Какие байты рукопожатия клиент УЖЕ прислал — слитые отрезки `[от, до)` смещений `CRYPTO`.
    /// Живёт дольше `crypto`: имя найдено, а повтор судится до ответа цели. Отрезков единицы —
    /// приветствие непрерывно, слияние сводит десятки кусков к одному.
    covered: Vec<(u64, u64)>,
}

/// Память разбора QUIC. Своя у транспорта — как `TcpState` у соединений.
#[derive(Default)]
pub struct QuicState {
    talks: HashMap<Flow, Talk>,
}

/// Не несёт ли датаграмма ни одного нового байта рукопожатия — это и есть повтор. Датаграмма БЕЗ
/// кусков тоже повтор: так клиент зовёт молчащую цель пробой (`PING` + `PADDING`). Запись стенда
/// под дропом (curl/ngtcp2): после приветствия — только такие пробы, через 1 и 3 с. Первая редакция
/// звала пустую датаграмму «не повтором» и молчала на настоящей беде.
fn brings_nothing_new(covered: &[(u64, u64)], pieces: &[(u64, Vec<u8>)]) -> bool {
    pieces.iter().all(|(offset, data)| {
        let end = offset.saturating_add(data.len() as u64);
        covered
            .iter()
            .any(|(from, to)| from <= offset && end <= *to)
    })
}

/// Покрытие после датаграммы: старые отрезки плюс её куски, отсортированы и слиты. Слияние
/// обязательно — повтор бывает перепакован иначе, чем оригинал, и его кусок накрывается лишь
/// СОЮЗОМ прежних.
fn widened(covered: &[(u64, u64)], pieces: &[(u64, Vec<u8>)]) -> Vec<(u64, u64)> {
    covered
        .iter()
        .copied()
        .chain(
            pieces
                .iter()
                .map(|(offset, data)| (*offset, offset.saturating_add(data.len() as u64))),
        )
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .fold(
            Vec::new(),
            |spans: Vec<(u64, u64)>, (from, to)| match spans.split_last() {
                Some((&(last_from, last_to), rest)) if from <= last_to => rest
                    .iter()
                    .copied()
                    .chain(std::iter::once((last_from, last_to.max(to))))
                    .collect(),
                Some(_) | None => spans
                    .into_iter()
                    .chain(std::iter::once((from, to)))
                    .collect(),
            },
        )
}

impl Transport for Quic {
    /// ШИРОКОЕ СЛОВО — `Reading`, а не голый `Seen`, и ветвь у QUIC та же, что у датаграмм
    /// (`Reading::Udp`): она про ПРОТОКОЛ, а QUIC и ЕСТЬ UDP. Первая редакция объявляла
    /// `Wire = Seen` и тем обещала, что приборы парка встанут «как есть»; компилятор потребителя
    /// обещания не подтвердил — все шесть объявлены над `Reading`, и цепочка не собиралась вовсе.
    /// Обещание в докблоке, не проверенное прогоном, — ровно тот дефект, который это дерево ловит
    /// у всех остальных.
    type Wire = Reading;
    /// 443/UDP. Тот же порт, что у TCP-двойника цели, и это не совпадение: браузер пробует оба.
    const PORT: u16 = 443;
    type State = QuicState;

    fn observe(state: &mut QuicState, read: Read<'_>) -> Observation<Reading> {
        let datagram = match read {
            Read::Udp(datagram) => datagram,
            // Довод тот же, что у `Tcp`/`Udp`: обрезанный кадр МОГ быть нашей датаграммой и МОГ
            // нести ответ цели — ослепнуть на нём честнее, чем счесть его чужим.
            Read::Truncated => return Observation::Unread(Unread::Truncated),
            Read::Tcp(_) | Read::NotIpv4 | Read::NotOurProtocol | Read::NotOurPort => {
                return Observation::Foreign
            }
        };

        // Сторону называет РАЗБОР (`Dir`), а не сравнение портов у нас: правило сторон живёт в
        // одном месте (`parse::upward`), и второе сравнение здесь разошлось бы с ним молча.
        let from_client = matches!(datagram.dir, reflex_core::types::Dir::Up);
        let payload = datagram.payload;
        let talk = state.talks.entry(datagram.flow).or_insert_with(|| Talk {
            opened_with: Vec::new(),
            retries: 0,
            answered: false,
            named: None,
            crypto: Vec::new(),
            covered: Vec::new(),
        });

        let wire = match from_client {
            // ЦЕЛЬ ОТВЕТИЛА. Пакет вниз снимает подозрение с последующих повторов: после ответа
            // второй `Initial` бывает при миграции соединения, и уликой он уже не является.
            false => {
                talk.answered = true;
                Seen::Received {
                    count: payload.len() as u32,
                }
            }
            true => match reflex_core::quic::initial_dcid(payload) {
                // Не `Initial` — обычная датаграмма разговора вверх.
                None => Seen::Sent {
                    count: payload.len() as u32,
                },
                Some(dcid) => {
                    // Расшифровка нужна двум вопросам — имени и повтору — и зовётся, пока хоть один
                    // открыт: после ответа цели повтор уликой не бывает, после имени оно известно.
                    let pieces = match (talk.named.is_none(), talk.answered) {
                        (false, true) => Vec::new(),
                        (true, _) | (false, false) => reflex_core::quic::crypto_of(payload),
                    };
                    // Имя ищется, пока не найдено: куски копятся по датаграммам, и до последнего
                    // куска склейка честно отдаёт `None`.
                    if talk.named.is_none() {
                        talk.crypto.extend(pieces.iter().cloned());
                        talk.named =
                            reflex_core::quic::sni_of(&talk.crypto).map(String::into_boxed_str);
                        // Имя найдено — куски больше не нужны: держать их значило бы платить
                        // памятью на каждый разговор за то, что уже установлено.
                        if talk.named.is_some() {
                            talk.crypto = Vec::new();
                        }
                    }
                    let repeat = !talk.answered
                        && talk.opened_with == dcid
                        && brings_nothing_new(&talk.covered, &pieces);
                    talk.covered = widened(&talk.covered, &pieces);
                    if talk.opened_with.is_empty() {
                        talk.opened_with = dcid.to_vec();
                    }
                    match repeat {
                        true => {
                            talk.retries = talk.retries.saturating_add(1);
                            Seen::Resent {
                                count: payload.len() as u32,
                                // Место повтора — начало первого куска crypto: у датаграмм
                                // номеров потока нет, а смещение в crypto и есть «какой кусок».
                                from: pieces
                                    .first()
                                    .map(|(offset, _)| *offset as u32)
                                    .unwrap_or(0),
                            }
                        }
                        // Первое открытие: отдаём ГОЛОВУ, чтобы цепочка узнала цель по имени тем
                        // же путём, что и на TLS.
                        false => Seen::Payload {
                            head: payload.to_vec(),
                            from_client: true,
                        },
                    }
                }
            },
        };

        // Ключ цели: имя из `Initial`, если оно было; иначе адрес, и тег `Unnamed` не притворяется
        // именем (§4 — расслоение по ключу, а не по строке).
        let key = match talk.named.as_ref() {
            Some(name) => TargetKey::Named(name.clone()),
            None => TargetKey::Unnamed(datagram.dst),
        };

        Observation::Seen(Observed {
            flow: datagram.flow,
            key,
            wire: Reading::Udp(wire),
        })
    }
    /// У QUIC память разбора СВОЯ и на разговор: куски рукопожатия, счёт повторов, поднятое имя.
    /// Уходит вместе с разговором по тому же зову, что и у соединений, — иначе карта росла бы
    /// числом виденных датаграммных потоков, а потолок таблицы перестал бы что-либо ограничивать.
    fn forget(state: &mut QuicState, flow: &Flow) {
        state.talks.remove(flow);
    }
}
