//! Носитель WinDivert — СВИДЕТЕЛЬ ФОРМЫ фасада на второй ОС, не свидетель работы.
//!
//! **Живьём здесь ничто не побежит.** Ни один тест этого крейта не открывает настоящий хэндл
//! WinDivert и не принимает настоящий пакет — здесь нет Windows, и не будет: эта строка
//! произносится вслух намеренно, чтобы никто не прочёл зелёную сборку как «работает». Что форма
//! ГОДНА для Windows — показывает `cargo check -p reflex-windivert --target
//! x86_64-pc-windows-msvc` (тела FFI-вызовов настоящие, не `unimplemented!()`, докблок
//! `carrier.rs`). Что она РАБОТАЕТ — покажет только Windows.
//!
//! ЛИНЕЙНОСТЬ У WINDIVERT — ВЛАДЕНИЕ, та же, что у очереди ядра netfilter: `WinDivertRecvEx`
//! изымает пакет из стека, `WinDivertSend` возвращает, не послать = уронить. Оттого носитель —
//! [`reflex_core::Serves`], а не `Source`: `Source::packets(&mut self)` держал бы бэкенд
//! заимствованным на весь поток наблюдения, а вердикт просит второй `&mut` на тот же носитель
//! (`E0499`) — тот самый довод, по которому очередь ядра стала `Serves` (`reflex_core::held`).
//! Именно поэтому AF_PACKET на роль свидетеля не годился бы: он копия провода, и носитель, не
//! держащий пакета, заявил бы `CanHold` с константным `Pass` — заглушку, запрещённую §9.1.
//!
//! # Что доказывает `cargo check --target x86_64-pc-windows-msvc`, а что НЕТ
//!
//! Это ЧЕТВЁРТЫЙ обязательный к записи предел (требование контролёра, 10.09.2026) — записан здесь,
//! а не только в отчёте задачи, чтобы никто не прочёл «кросс-проверка зелёная» как «всё готово».
//!
//! **Доказывает:** библиотечный код ЭТОГО крейта (`ffi.rs`, `carrier.rs`) типологически корректен
//! для x86_64-pc-windows-msvc — сигнатуры FFI совпадают с объявленными внешними символами по
//! типам, `#[repr(C)]`-структуры собираются, вызовы Win32/WinDivert API соответствуют своим
//! `extern "system"`-подписям. Это и есть предмет задачи: форма годна для второй ОС.
//!
//! **НЕ доказывает:**
//! 1. **Доктесты.** `cargo check` НЕ компилирует доктесты вовсе, ни на одной платформе — это
//!    замерено экспериментом (скормлен заведомо невалидный doc-комментарий, `cargo check` прошёл
//!    чисто, `cargo test --doc` поймал), а не предположено по документации инструмента. Два
//!    доктеста на РЕАЛЬНОМ типе (`WinDivertHandle`, докблок `carrier.rs`) в этом крейте ОБЪЯВЛЕНЫ
//!    как `ignore` — они не проверены здесь НИЧЕМ, ни `cargo check`, ни `cargo test` (тип и его
//!    зависимости существуют только под Windows, линковщика для которого в этой песочнице нет).
//!    Гейт `CanAsk`, который эти доктесты называют, реально прогнан (`compile_fail` + мутация) на
//!    ЗАМЕСТИТЕЛЕ формы — [`witness`], не на `WinDivertHandle`.
//! 2. **Сборку цепочки потребителя.** `impl IntoCarrier for WinDivert` теперь ЕСТЬ (задача 12¾,
//!    докблок `struct WinDivert` в `carrier.rs`) — `engine(WinDivert::filter(..))` называет ТУ ЖЕ
//!    дверь, что `engine(Nfqueue::queue(200))`. Но что цепочка `.from(Tcp).extract(Sni)...`
//!    СОБЕРЁТСЯ на Windows — этот прогон по-прежнему не показывает: `cargo check` доктестов не
//!    собирает (п.1 выше), а доктест цепочки (докблок `WinDivert::filter` в `carrier.rs`) помечен
//!    `ignore` тем же пределом — кросс-таргетной линковки для запуска доктестов здесь нет.
//! 3. **Линковку.** `cargo check` не линкует (`--emit=metadata`) — реальная линковка с
//!    `WinDivert.dll`/`kernel32.dll` не проверена НИГДЕ в этом прогоне; имена символов и `#[link]`
//!    сверены с `dll/windivert.def` чтением, не линковщиком.
//!
//! # Связано: `IntoCarrier` реализован буквально (задача 12¾)
//!
//! Задача 12 совпала форму (`open`/`layout`/`name` ТОЙ ЖЕ ФОРМОЙ, что и `reflex::IntoCarrier`,
//! `reflex/src/lib.rs:120`) вручную, но `impl IntoCarrier for WinDivert` не писала — назвав причину
//! дословно: дом трейта (крейт `reflex`) сам не проходил кросс-сборку под Windows, 23 ошибки в
//! `nfq-0.2.5` (внешний крейт, тянет его `reflex-linux` под фичей `nfqueue`, которую `reflex`
//! включал безусловно), к WinDivert отношения не имеющие.
//!
//! Задача 12½ эту причину сняла (замерено тем же способом: `cargo check -p reflex --target
//! x86_64-pc-windows-msvc` → `Finished`, ноль ошибок), и задача 12¾ написала связывание — ровно так,
//! как и обещал докблок задачи 12: `impl IntoCarrier for WinDivert` в `carrier.rs`, `type Carrier =
//! Local<WinDivertHandle>`. Ручная форма (три метода без импла трейта) не осталась РЯДОМ с
//! реализацией — она И ЕСТЬ реализация: `open`/`layout`/`name` теперь читаются как тело `impl`, а
//! не как отдельный метод инструмента, совпадающий с трейтом только по счастливой сигнатуре.
//!
//! `reflex-windivert` зависит от `reflex` (`[target.'cfg(windows)'.dependencies]`, `Cargo.toml`) —
//! ПОД `cfg(windows)`, а не безусловно: на Linux крейт остаётся пустым (`#[cfg(windows)] mod
//! carrier;` ниже), и тянуть туда весь фасад (движок, разбор провода, приборы) незачем — `cargo
//! build --workspace` эту зависимость на Linux не видит вовсе. `reflex-core`/`reflex-instrument`
//! остаются прямыми зависимостями (нужны и `ffi.rs`, и `witness.rs`, которые собираются на ОБЕИХ
//! платформах).
//!
//! ЧТО ЭТА ЗАДАЧА НЕ СНИМАЕТ — пределы остаются, названы здесь прямо, а не спрятаны тем, что рядом
//! появился факт связывания:
//!
//! * Живьём под Windows по-прежнему ничто не проверено и отсюда проверено не будет — крейт
//!   остаётся свидетелем ФОРМЫ (раздел выше).
//! * `compile_fail` на РЕАЛЬНОМ типе (`WinDivertHandle`) кросс-таргетом по-прежнему непроверяем:
//!   `cargo check` доктестов не собирает ни на одной платформе (п.1 выше), а исполнить доктест для
//!   Windows-таргета здесь нечем — MSVC-линковщика в этой песочнице нет. Гейт `CanAsk` предъявлен
//!   на типе-заместителе (`witness::GateWitness`), не на `WinDivertHandle`.
//! * Догаданное задачи 12 (МСВ-упаковка битового поля `WINDIVERT_ADDRESS`, направление
//!   синтетических пакетов инъекции) остаётся догаданным — эта задача связала дверь, а не проверила
//!   догадки.
//!
//! # Что выверено чтением источника, а что ДОГАДАНО
//!
//! ВЫВЕРЕНО прямым чтением (координаты — докблок `ffi.rs`, полный разбор источника — отчёт задачи
//! 12): подписи `WinDivertOpen`/`WinDivertRecvEx`/`WinDivertSend`/`WinDivertClose`, раскладка байт
//! `WINDIVERT_ADDRESS`/`WINDIVERT_DATA_NETWORK`, слои и параметры (`include/windivert.h`,
//! `basil00/WinDivert@master`); имя библиотеки для линковки (`dll/windivert.def`); коды ошибок
//! `ERROR_INSUFFICIENT_BUFFER`/`ERROR_NO_DATA` и текст про отсутствие сигнала переполнения очереди
//! драйвера (`doc/windivert.html`); `OVERLAPPED`/`CreateEventW`/`WaitForSingleObject`/коды
//! ожидания/`ERROR_IO_PENDING` (learn.microsoft.com); гарантия `CancelIoEx` («не освобождать
//! `OVERLAPPED` до реального завершения, ждать его `GetOverlappedResult`») — цитатой из
//! `learn.microsoft.com/.../ioapiset/nf-ioapiset-cancelioex`, докблок ветки `WAIT_TIMEOUT` в
//! `carrier.rs::attempt_recv`.
//!
//! ДОГАДАНО (форма, не выверенная прогоном или прямой цитатой источника — оба места отмечены и в
//! коде): (1) МСВ-упаковка битового поля `WINDIVERT_ADDRESS` (какой бит — какое имя внутри `flags`,
//! `ffi.rs`) — раскладка ABI компилятора, не гарантия языка; (2) направление (`Outbound`) для
//! СИНТЕТИЧЕСКОГО адреса инъекции в `WinDivertHandle::emit` (`carrier.rs`) — решение формы для
//! скелета, документация называет лишь, для какого направления `IfIdx`/`SubIfIdx` НЕ обязательны,
//! а не что правильно посылать при отсутствии контекста изъятого пакета.
//!
//! # Три предела шва (задачи, оплатившие их раньше)
//!
//! * **`exhausted()`** не переопределён — умолчание трейта (`false`) и есть ответ: живой носитель
//!   конца не знает, WinDivert `WinDivertShutdown` сам не зовёт.
//! * **Закон срока** («не возвращаться раньше `until`, кроме как с работой») держится ОДНИМ
//!   выходом — докблок `impl Serves for WinDivertHandle` (`carrier.rs`) называет, где именно.
//! * **Часы носителя** — `Instant::now()`, ОДНИ на весь крейт: `millis_until` считает остаток до
//!   `until` теми же часами, которыми штампуется `Held::at`, никакой пары часов не заводится.
//!
//! [`witness`]: crate::witness

