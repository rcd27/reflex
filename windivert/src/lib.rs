//! Второй функтор §9 из морфизма в драйвер: WinDivert. Линейность — ВЛАДЕНИЕ, как у очереди ядра
//! (`WinDivertRecvEx` изымает пакет из стека, не послать = уронить), оттого [`reflex_core::Serves`],
//! а не `Source`: вердикт просит второй `&mut` на тот же носитель (`E0499`). `CanAsk` не заявлен —
//! отсутствием impl, не константным `None` в нём (§9.1, правило 9.5).
//!
//! # Свидетельства о работе здесь нет (§10.7)
//!
//! Windows в этом дереве нет: ни один тест не открывает хэндла и не принимает пакета. Зелёное на
//! Linux не свидетельствует о Windows — по §10.7 оно не считается, пока не показана способность
//! той же проверки дать красный, а прогона, способного покраснеть от неработающего WinDivert,
//! здесь не существует. Предъявлено вместо работы ровно три вещи, каждая — своим прогоном:
//!
//! | что | чем предъявлено | что краснеет |
//! |---|---|---|
//! | форма способностей | [`witness`]: `compile_fail` + положительная пара | добавленный `impl CanAsk` |
//! | типовая годность под чужую платформу | `cargo check -p reflex-windivert --target x86_64-pc-windows-msvc` | расхождение подписи с `extern "system"` |
//! | цепочка потребителя | кросс-сборка `examples/detect-silent-drop/src/bin/windows.rs` | снятый `.extract` — две ошибки |
//!
//! Предел инструмента, замеренный, а не предположенный: `cargo check` не собирает доктестов ни на
//! одной платформе (скормлен заведомо невалидный doc-комментарий — прошёл чисто, поймал
//! `cargo test --doc`) и не линкует (`--emit=metadata`). Поэтому цепочку предъявляет БИНАРЬ: он
//! собирается, доктест бы не собрался.
//!
//! ДОГАДАНО, а не выверено источником — два места, каждое отмечено там, где живёт: упаковка
//! битового поля `WINDIVERT_ADDRESS` (`ffi.rs` — раскладка ABI, не гарантия языка) и направление
//! синтетического адреса инъекции (`carrier.rs::emit` — документация диктует лишь, когда
//! `IfIdx`/`SubIfIdx` не обязательны).
//!
//! [`witness`]: crate::witness

