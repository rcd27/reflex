//! СУЖЕНИЕ ИМЕНИ ДО КЛЮЧА — три исхода, а не строка.
//!
//! # Что здесь чинится, и это замерено, а не предположено
//!
//! `narrow: fn(&str) -> &str` возвращал одну строку на три разных исхода, а
//! `psl::domain_str(host).unwrap_or(host)` сливал их молча. Замер корпуса поля 28.08 (#324, 3434
//! флоу, 327 имён) показал, во что это обходится: у **78 имён (23,9 %) и 698 флоу (20,3 %) ключ
//! равен ПОЛНОМУ имени**, хотя сужать было что.
//!
//! Причина не в фолбэке: `unwrap_or` не сработал НИ РАЗУ, 0 имён из 327. `googleapis.com` числится
//! в ЧАСТНОЙ секции публичного списка суффиксов, поэтому список честно отвечает
//! `Some("android.googleapis.com")` — вырождение прячется внутри УСПЕШНОГО ответа. Это болезнь
//! #146 («каждое имя само себе ключ, знание не сходится никогда»), живущая внутри правила, которое
//! от #146 и лечило.
//!
//! # Почему тип, а не счётчик рядом
//!
//! Различающая способность, потерянная в последнем шаге, ничем не отличается от отсутствующей.
//! Пока исход не выражен в типе, потребитель не обязан его разбирать — и не разбирает: сегодня ни
//! одно место в коде не знает, что ключ выродился.
//!
//! # Почему закон ЗДЕСЬ, в крейте без `alloc`
//!
//! Ключ считается В ТЕМПЕ РУКОПОЖАТИЯ, то есть это величина горячего пути, а жила она в
//! продуктовом крейте. Здесь `no_std` без `alloc`, и это не гигиена, а гарантия: всё, что тип
//! несёт, — заимствованные срезы входа, аллокации нет ни одной, и компилятор это держит. Таблицы
//! (список суффиксов, справочник семейств) остаются выше — они данные с провенансом; сюда
//! приезжает их СЛОВО.
//!
//! # Модельный референт
//!
//! `model/family/FamilyKey.tla`. Образец «частный суффикс, арендаторы ОДНОГО владельца» заведён
//! тем же замером; клетка `FamilyKey.private-own-zone.cfg` красная при `KeyRule = "Suffix"` и
//! зелёная в `tobe` — то есть закон не тождественно ложен, и красный что-то свидетельствует.

/// ЧТО ТАБЛИЦЫ СКАЗАЛИ ОБ ИМЕНИ. Наблюдение, снятое вызывающим, а не вывод.
///
/// Три слова, потому что молчать таблицы умеют по-разному: справочник может не знать сервиса, а
/// список суффиксов — объявить зону частной, и это РАЗНЫЕ факты с разными последствиями. Слить их
/// в `Option<&str>` значило бы повторить `unwrap_or` на уровень выше.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Said<'a> {
    /// Справочник семейств назвал сервис — курируемый ответ о том, кто хозяин.
    Service(&'a str),
    /// Справочник молчит; зона в ICANN-секции списка, регистрируемый домен — вот он.
    Registrable(&'a str),
    /// Справочник молчит; граница проведена в ЧАСТНОЙ секции списка — значение есть АРЕНДАТОР
    /// под чужой зоной (`user.github.io`, `android.googleapis.com`), а не регистрация.
    Tenant(&'a str),
}

/// КЛЮЧ И ТО, ЧТО С ИМЕНЕМ СЛУЧИЛОСЬ.
///
/// Алгебраический, потому что вырождение — ЗАКОННЫЙ исход, а не сбой: справочник покрывает 82,6 %
/// имён поля, а не всё. Ветки «ключа нет» не существует.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Narrowed<'a> {
    /// Имя опознано справочником: знание делится со всеми узлами сервиса.
    Family(&'a str),
    /// Сужено списком суффиксов до регистрируемого домена: за ключом стоит ОДИН регистрант.
    Registrable(&'a str),
    /// Ключ — арендатор под чужой зоной. За соседей по зоне список не отвечает: они могут быть
    /// чужими друг другу (`github.io`) или своими (`googleapis.com`), и различить их он не умеет.
    TenantZone(&'a str),
}

/// КАК ДАЛЕКО ПЕРЕНОСИТСЯ ЗНАНИЕ под этим ключом.
///
/// Ради этого различения тип и заводится: ключ у `Registrable` и `TenantZone` может СОВПАДАТЬ по
/// строке, а хозяин за ним стоит разный — и это ровно то, чего `fn(&str) -> &str` сказать не мог.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Carry {
    /// На все узлы сервиса — хозяина назвал справочник.
    Service,
    /// На поддомены регистрируемого домена: за ним один регистрант.
    Domain,
    /// Не дальше АРЕНДАТОРА. Формой похоже на `Domain`, а посылка другая: список утверждает лишь
    /// границу регистрации и ничего не говорит о соседях по зоне.
    ///
    /// ЦЕНА НАЗВАНА ЗАМЕРОМ. Когда арендатор совпал с полным именем (78 имён и 698 флоу поля,
    /// 20,3 %), ключ вырождается в FQDN и знание не сходится НИКОГДА — болезнь #146 внутри
    /// правила, которое от неё лечило. Снимает это только курируемое опровержение: справочник
    /// назначил семейство всем 78, и настоящих дыр среди них ноль.
    Tenant,
}

/// Тотальная проекция: имя плюс слово таблиц — ключ со значением.
///
/// Тотальна по построению: у каждого слова есть исход, «ключа нет» невыразимо.
pub fn narrow(said: Said<'_>) -> Narrowed<'_> {
    match said {
        Said::Service(family) => Narrowed::Family(family),
        Said::Registrable(domain) => Narrowed::Registrable(domain),
        Said::Tenant(tenant) => Narrowed::TenantZone(tenant),
    }
}

impl<'a> Narrowed<'a> {
    /// Ключ, под которым копится знание.
    pub fn key(self) -> &'a str {
        match self {
            Narrowed::Family(key) => key,
            Narrowed::Registrable(key) => key,
            Narrowed::TenantZone(key) => key,
        }
    }

    /// Куда знание переносится. Единственное место, где три исхода расходятся ПОСЛЕДСТВИЯМИ, а не
    /// названием, — и потому единственное оправдание третьего варианта.
    pub fn carry(self) -> Carry {
        match self {
            Narrowed::Family(_) => Carry::Service,
            Narrowed::Registrable(_) => Carry::Domain,
            Narrowed::TenantZone(_) => Carry::Tenant,
        }
    }

    /// НЕ СУЗИЛОСЬ НИЧЕГО: ключ равен входу, знание не разделит ни один сосед.
    ///
    /// Мера, а не вариант. Ключ, равный входу, законен у имени из двух меток (`example.com`
    /// накрывает свои поддомены) и разорителен под частной зоной — оттого спрашивается вместе с
    /// [`Carry`], а не вместо него. Обезоруживание из приёмки #324 звучит ровно так: «ключ равен
    /// полному имени при имени глубже двух меток», и на корпусе поля это 78 имён из 327.
    pub fn is_whole(self, host: &str) -> bool {
        self.key() == host
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// ОДИНАКОВЫЙ КЛЮЧ ПРИ РАЗНОМ ХОЗЯИНЕ — ради этого случая тип и заведён.
    ///
    /// По строке `Registrable("a.io")` неотличим от `TenantZone("a.io")`, а посылки под ними
    /// противоположны: за первым один регистрант, за вторым — арендатор, о соседях которого
    /// список не знает. `fn(&str) -> &str` эту разницу выразить не мог вовсе.
    #[test]
    fn the_same_key_can_stand_for_different_owners() {
        let registrable = narrow(Said::Registrable("a.io"));
        let tenant = narrow(Said::Tenant("a.io"));
        assert_eq!(registrable.key(), tenant.key());
        assert_ne!(registrable.carry(), tenant.carry());
    }

    /// АРЕНДАТОР, СОВПАВШИЙ С ПОЛНЫМ ИМЕНЕМ, — ТА САМАЯ ЗАМЕРЕННАЯ БЕДА.
    ///
    /// `psl::domain_str("android.googleapis.com")` возвращает `Some` ЭТОГО ЖЕ имени, то есть
    /// прежний код получал вырождение под видом успеха: 78 имён и 698 флоу поля (20,3 %).
    #[test]
    fn a_tenant_equal_to_the_whole_name_is_the_measured_harm() {
        let narrowed = narrow(Said::Tenant("android.googleapis.com"));
        assert_eq!(narrowed.carry(), Carry::Tenant);
        assert!(narrowed.is_whole("android.googleapis.com"));
    }

    /// А ВОТ ИМЯ ИЗ ДВУХ МЕТОК ПОД ОБЫЧНОЙ ЗОНОЙ — НЕ БЕДА, хотя ключ тоже равен входу.
    ///
    /// `example.com` накрывает свои поддомены, знание сходится. Оттого мера `is_whole` и
    /// спрашивается ВМЕСТЕ с `carry`, а не вместо неё: одна строка на два разных факта.
    #[test]
    fn a_whole_key_under_an_icann_zone_is_not_harm() {
        let narrowed = narrow(Said::Registrable("example.com"));
        assert!(narrowed.is_whole("example.com"));
        assert_eq!(narrowed.carry(), Carry::Domain);
    }

    /// СПРАВОЧНИК ОПРОВЕРГАЕТ ЧАСТНЫЙ СУФФИКС: список сказал «арендаторы», куратор знает хозяина.
    ///
    /// Замер 03.09: из 78 таких имён корпуса справочник назначает семейство ВСЕМ 78, настоящих дыр
    /// ноль. То есть решение куратора уже принято и лежит в 4-й колонке реестра.
    #[test]
    fn the_directory_overrules_a_private_suffix() {
        let narrowed = narrow(Said::Service("google"));
        assert_eq!(narrowed.key(), "google");
        assert_eq!(narrowed.carry(), Carry::Service);
        assert!(!narrowed.is_whole("android.googleapis.com"));
    }
}
