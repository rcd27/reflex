//! ВЫПУСК РАЗГОВОРА ИЗ ГОРЯЧЕГО ПУТИ.
//!
//! # Почему это закон, а не настройка
//!
//! Замер `intake-price.sh` (#317): 3,88 мкс на пакет, из них 238 нс ВНУТРИ плоскости. Вердикт
//! стоит 6 %, остальные 94 % — дорога в userspace. Значит платим мы не за решение, а за то, что
//! пакет вообще к нам приехал.
//!
//! А приезжать ему нужно не всегда. Знание о цели — элемент частично упорядоченного множества по
//! информации, и пакет несёт информацию, только если соединение с текущим знанием нетривиально:
//! приветствие называет цель, всё остальное даёт `k ⊔ ⊥ = k`. Сотни пакетов потока суть
//! нейтральный элемент, и платить за них полную цену дороги — не «неоптимально», а следствие
//! неверно выбранной единицы вызова.
//!
//! # Обязательство, названное ДО предиката (#300)
//!
//! **Флоу остаётся под наблюдением, пока его личность в ⊥.** Не «N первых пакетов»: порог по
//! счётчику взят бы из ЦЕНЫ, и то, что он больше длины рукопожатия, было бы совпадением, а не
//! свойством. Выпустить разговор до того, как он назвался, значит сделать снимок решения
//! зависимым от того, что видели МЫ, а не от того, что случилось на проводе, — и две коробки с
//! разными порогами получили бы разные планы на одном трафике.
//!
//! # Чем платим
//!
//! Выпущенный разговор перестаёт давать наблюдения: ответ цели, авторство сброса, миг закрытия.
//! Это названо, а не скрыто: расхождение счётчиков ядра и плоскости меряет `row::Sight`, а клетка,
//! о которой сказать нечего, несёт `row::Told::Blind`. При событийном выпуске `Sight::Partial`
//! становится НОРМОЙ, а не аномалией.

use crate::row::Naming;
use crate::{Act, Mark, Plan, Programme};

/// ПРИЗНАК РЕШЁННОСТИ В МЕТКЕ.
///
/// Отдельным разрядом, а не значением: метка обязана нести И маршрут, И то, что решение принято.
/// Без признака «решено ничего не делать» несло бы нулевую метку, неотличимую от «решения не
/// было», и такой разговор возвращался бы в очередь на каждом пакете — то есть самый частый
/// случай платил бы полную цену.
///
/// Разряд выбран свободным: `0x1000_0000` носит десинк (`executor::DESYNC_MARK`), `0x2000_0000` —
/// база воркеров, младший байт — маршруты ног. Пересечение молча увело бы чужой трафик в чужую
/// очередь.
pub const SETTLED: u32 = 0x4000_0000;

// РАЗРЯДЫ ОТВОДА СНЯТЫ ВМЕСТЕ С ОТВОДОМ (#326): `LEG_MTPROTO`, `LEG_QUICSTEP` и `DIVERT` кодировали
// `Programme::Divert`, которого больше нет. Разряд `0x0800_0000` и младшие два освобождены — при
// возвращении отвода вместе с исполнителем брать надо их же, чтобы не пересечься с десинком
// (`0x1000_0000`), базой воркеров (`0x2000_0000`) и признаком решённости (`0x4000_0000`).

/// ФОРМА ВЫПУСКА УЕХАЛА В ФУНДАМЕНТ (05.09.2026), носитель решения остался здесь.
///
/// [`reflex_core::watch::Watch`] параметризован тем, чем решение уезжает; у нас это метка `nft`.
/// Разряды метки и их деление между десинком, воркерами и маршрутами — устройство ОДНОГО носителя,
/// а не форма выпуска, и потому в фундамент не поехали.
pub type Watch = reflex_core::watch::Watch<Mark>;

fn routed(programme: Programme) -> u32 {
    match programme {
        Programme::Pass => 0,
        Programme::Mark(Mark(route)) => route,
    }
}

/// Программа, применённая К ЭТОМУ пакету. Отличается от плана цели: шаг закона видит ещё и
/// состояние разговора.
fn taken(act: Act) -> Option<Programme> {
    match act {
        // Ни сброшенный, ни оборванный разговор не выпускается: поручать ядру нести то, чего мы
        // решили не пропускать, незачем.
        Act::Drop | Act::Sever => None,
        Act::Pass => Some(Programme::Pass),
        Act::Marked(mark) => Some(Programme::Mark(mark)),
    }
}

/// ОБРАТНОЕ ЧТЕНИЕ МЕТКИ. Ядро хранит её в `ct mark` и возвращает нам; по ней обязано читаться то
/// же решение, что мы приняли. Пара к `watching`, и проверяются они друг через друга — иначе два
/// конца механизма разъедутся молча, как уже разъезжался ключ, добываемый на каждой стороне
/// по-своему.
pub fn released(mark: Mark) -> Option<Programme> {
    match mark.0 & SETTLED == 0 {
        true => None,
        false => match mark.0 & !SETTLED {
            0 => Some(Programme::Pass),
            route => Some(Programme::Mark(Mark(route))),
        },
    }
}

/// Выпуск есть функция трёх величин, и все три знает ОДНА плоскость: личность разговора, вердикт
/// этому пакету и интерес приборов к цели. Оболочка их не сводит и потому не может свести
/// неправильно — читает `Fed::watch`.
pub fn watched<N>(naming: Naming<N>, act: Act, plan: Plan) -> Watch {
    reflex_core::watch::watched(
        naming,
        taken(act).map(|programme| Mark(SETTLED | routed(programme))),
        plan.interest,
    )
}
