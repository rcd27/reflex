//! Выпуск разговора из горячего пути. Замер `intake-price.sh`: 3,88 мкс на пакет, из них 238 нс
//! внутри плоскости — платим не за решение (6 %), а за дорогу в userspace (94 %). Приезжать пакету
//! нужно не всегда: знание о цели — элемент ЧУ по информации, пакет несёт её только если соединение
//! нетривиально (`k ⊔ ⊥ = k`). Обязательство: **флоу под наблюдением, пока личность в ⊥** — не «N
//! пакетов» (порог из цены сделал бы снимок решения зависимым от нас, не от провода). Цена:
//! выпущенный разговор не даёт наблюдений — `Sight::Partial` становится нормой.

use crate::row::Naming;
use crate::{Act, Mark, Plan, Programme};

/// Признак решённости в метке. Отдельным разрядом: метка несёт И маршрут, И «решение принято» —
/// иначе «решено ничего не делать» несло бы нулевую метку, неотличимую от «решения не было», и
/// разговор возвращался бы в очередь на каждом пакете. Разряд свободен: `0x1000_0000` — десинк,
/// `0x2000_0000` — база воркеров, младший байт — маршруты ног.
pub const SETTLED: u32 = 0x4000_0000;

// Разряды отвода сняты вместе с отводом (#326): `LEG_MTPROTO`/`LEG_QUICSTEP`/`DIVERT` кодировали
// `Programme::Divert`, которого больше нет. Разряд `0x0800_0000` и младшие два свободны — при
// возврате отвода брать их же, чтобы не пересечься с десинком/воркерами/`SETTLED`.

/// Форма выпуска уехала в фундамент; носитель решения (метка `nft`) остался здесь.
/// [`reflex_core::watch::Watch`] параметризован тем, чем решение уезжает.
pub type Watch = reflex_core::watch::Watch<Mark>;

fn routed(programme: Programme) -> u32 {
    match programme {
        Programme::Pass => 0,
        Programme::Mark(Mark(route)) => route,
    }
}

/// Программа, применённая к этому пакету (отличается от плана цели: шаг видит и состояние
/// разговора). Сброшенный/оборванный не выпускается: нести ядру то, что решили не пропускать,
/// незачем.
fn taken(act: Act) -> Option<Programme> {
    match act {
        Act::Drop | Act::Sever => None,
        Act::Pass => Some(Programme::Pass),
        Act::Marked(mark) => Some(Programme::Mark(mark)),
    }
}

/// Обратное чтение метки из `ct mark`: по ней обязано читаться то же решение, что приняли. Пара к
/// [`watched`], проверяются друг через друга — иначе два конца механизма разъедутся молча.
pub fn released(mark: Mark) -> Option<Programme> {
    match mark.0 & SETTLED == 0 {
        true => None,
        false => match mark.0 & !SETTLED {
            0 => Some(Programme::Pass),
            route => Some(Programme::Mark(Mark(route))),
        },
    }
}

/// Выпуск — функция трёх величин, все три знает одна плоскость (личность, вердикт пакету, интерес
/// приборов). Оболочка их не сводит и потому не может свести неправильно.
pub fn watched<N>(naming: Naming<N>, act: Act, plan: Plan) -> Watch {
    reflex_core::watch::watched(
        naming,
        taken(act).map(|programme| Mark(SETTLED | routed(programme))),
        plan.interest,
    )
}
