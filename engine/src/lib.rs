/// ЧТО ЭТОТ ПАКЕТ СКАЗАЛ О ЛИЧНОСТИ ЦЕЛИ (#317; алгебра разобрана в #300).
///
/// # Зачем это в ядре, где имён нет
///
/// План разрешался на `Cursor::Fresh`, то есть на SYN — в момент, когда о цели известен ТОЛЬКО
/// адрес. Отсюда и весь круг #317: ключ добывался из того самого пакета, который надо чинить, а
/// применялось знание по адресу — и на общем адресе CDN накрывало 69 посторонних имён (замер
/// `dig` 31.08), тогда как у цели с несколькими адресами не накрывало вовсе («пакетов ногой 0»
/// при исправной петле).
///
/// Разрывается это переносом МОМЕНТА, а не заведением таблицы адрес→имя: такая таблица врёт по
/// построению там, где имён на адресе десятки, а её источник (DNS) вдобавок под контролем
/// противника.
///
/// # Почему тип не свой, а `row::Naming`
///
/// Своих было два — `Names` здесь и `Naming` в `row`, — и оба про одно. Понятие, записанное
/// дважды, расходится молча (оплачено ключом памяти: 1136 флоу из 1136 мимо). Ядру довольно
/// различителя без имени: ключ выбирает вызывающий, ядро знает момент.
pub type Said = row::Naming<()>;

/// ЧТО ЗНАЕТ О ЛИЧНОСТИ ЦЕЛИ РАЗГОВОР ЦЕЛИКОМ — после этого пакета.
///
/// # Это JOIN, а не «правило обновления» (#300, разбор nevod-53)
///
/// Знание о личности есть элемент частично упорядоченного множества по ИНФОРМАЦИИ, где
/// `Awaited` = ⊥, а событие провода — монотонная функция на нём:
///
/// ```text
/// Awaited ⊑ Silent ⊑ Spoken
/// ```
///
/// `Silent` ниже `Spoken` не по важности, а по информации: «приветствие прошло, имени в нём не
/// было» есть наше лучшее прочтение на тот момент, а имя, добытое позже (ретрансмиссия, пересборка
/// разреза), — БОЛЬШЕ сведений, не меньше.
///
/// Отсюда три закона, и каждый покрыт тестом:
///
/// 1. **монотонность** `k ⊑ joined(k, e)` — знание не убывает ни от какого события;
/// 2. **идемпотентность** `joined(joined(k,e), e) = joined(k,e)` — повтор того же приветствия не
///    событие;
/// 3. **независимость от порядка** `joined(joined(⊥,a),b) = joined(joined(⊥,b),a)`.
///
/// Третий закон не украшение: провод переставляет пакеты, а мы вдобавок собираемся выпускать
/// userspace из горячего пути, то есть видеть ПОДМНОЖЕСТВО событий. Движок, чей вердикт зависит от
/// порядка прихода, на таком проводе недетерминирован.
///
/// # Чего этот join НЕ разрешает
///
/// Два РАЗНЫХ имени на одном разговоре дали бы в полной решётке ⊤ («противоречие»). Здесь ⊤ нет
/// намеренно: частота явления не замерена, а тип, заведённый под неизмеренное, потом не снимается.
/// Считается счётчиком (`Plane::name_conflicts`) — и на `Said`, где имени нет, случай невыразим
/// вовсе, потому законы 1–3 тут тотальны.
/// РЕШЁТКА УЕХАЛА В ФУНДАМЕНТ, ЗДЕСЬ ОСТАЛСЯ ВЫБОР ПРАВИЛА. Там расхождение двух значений
/// разрешает вызывающий — иначе слитая пара выглядит как согласие приборов, хотя они разошлись.
/// На `Said` значений нет вовсе, и правило вырождено: выбирать не из чего.
pub fn joined(known: Said, said: Said) -> Said {
    reflex_core::disclosure::joined_with(known, said, |mine, _theirs| mine)
}

/// НА ЧЁМ СТОЯЛ ПЛАН, КОГДА ЕГО ПРИНИМАЛИ — и это ДРУГАЯ величина, а не то же знание.
///
/// # Почему не join
///
/// Знание обязано только расти и не зависеть от порядка. Запись о ПРОШЛОМ РЕШЕНИИ — обязана
/// зависеть: мы действовали тем, что пришло первым, и переставить это задним числом нельзя.
/// Требовать от неё коммутативности значит требовать, чтобы запись о случившемся не зависела от
/// того, что случилось.
///
/// Оттого функция ЗАМОРАЖИВАЕТ: первое непустое слово о личности остаётся навсегда. Разговор, чьё
/// приветствие прошло без имени, закрывает вопрос СРАЗУ — ждать нечего, и позднее имя не двигает
/// страту на середине применения.
///
/// Ось при этом по-прежнему ОДНА (личность): здесь её СНИМОК, а не копия. Незаконное «принято по
/// личности, которой ещё нет» непредставимо — снимок берётся ровно тогда, когда ось покидает ⊥.
pub use reflex_core::disclosure::stood_on;

/// РАССКАЗЫВАЛИ ЛИ УЖЕ — и когда.
///
/// # Почему это состояние, а не флаг
///
/// Флаг «уже сказал» делал предикат устаревания зависимым от ИСТОРИИ: одно и то же состояние
/// давало разный ответ в зависимости от прошлого. В лоссовом по построению канале такая логика
/// ломается насмерть с первой потери — приказ не доехал, а повтора не будет никогда.
///
/// Со временем последнего рассказа предикат снова становится функцией СОСТОЯНИЯ, и потеря
/// вырождается в задержку: следующий пакет за горизонтом расскажет заново.
/// ЧТО ВЕЛЕНО СДЕЛАТЬ С ЭТИМ РАЗГОВОРОМ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ordered {
    /// Ничего сверх плана — обычная жизнь.
    Nothing,
    /// Оборвать при первом же пакете.
    Sever,
}

/// ПЕРЕИМЕНОВАНО ИЗ `Told` (05.09.2026): ОДНО СЛОВО НАЗЫВАЛО ДВА РАЗНЫХ ТИПА В ОДНОМ КРЕЙТЕ.
///
/// Здесь — «рассказывали ли МЫ и когда»; в `row` — `Told<T> { Nothing, Told, Blind }`, то есть
/// «что известно о величине, добываемой событием». Общего у них ровно ничего, кроме написания, и
/// такое совпадение расходится молча: читатель, привыкший к одному, читает другое не глядя.
///
/// Переименован МЕНЬШИЙ: у этого было семь употреблений и все внутри крейта, у того — 85 в восьми
/// файлах четырёх крейтов. Цена выбрана замером, а не вкусом.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Announced {
    /// Ещё ни разу — рассказывать пора.
    Never,
    /// Рассказали в этот момент; повторим не раньше горизонта.
    At(Tick),
}

