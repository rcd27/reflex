//! СТРОКА (ЦЕЛЬ × УЗЕЛ) — закон её сборки.
//!
//! # Почему запись, а не показ
//!
//! Строку на пару «цель × узел» сегодня не собирает никто: `Sighting` растворяется в решении,
//! наружу печатается сводка по всей коробке. Запись обязана быть ОДНА и читаться и решением, и
//! показом: второй путь к правде уже оплачен — ключ, добываемый на каждой стороне своим способом,
//! дал 1136 флоу из 1136 мимо памяти.
//!
//! # Почему параметр типа вместо имени
//!
//! Крейт `no_std` без `alloc`, и `Box<str>` тут невыразим. Но закон группировки и не должен знать,
//! чем представлено имя: он знает лишь, НАЗВАЛАСЬ ли цель. Ширину и представление подставляет
//! оболочка — тем же приёмом, что `narrow: fn(&str) -> &str`.

use crate::{Addr, Cursor, Plan, Said, Span, Tick};

/// СЛЕПОТА УЕХАЛА В ФУНДАМЕНТ (05.09.2026).
///
/// `Counted`, `Sight`, `Told` и обе функции описывали не нашу плоскость, а всякий перехватывающий
/// движок: очередь ядра роняет под нагрузкой, кольцо `AF_PACKET` переполняется, WinDivert теряет
/// по-своему. Движок, не умеющий сказать «я этого не видел», выдаёт своё молчание за молчание
/// сети — и это утверждение о жанре, а не о неводе.
///
/// Реэкспорт: `row::Sight`, `row::Told`, `row::Counted` продолжают резолвиться у всех четырёх
/// потребителей, править никого не пришлось.
pub use reflex_core::sight::{
    added, later, no_counts, sighted, sooner, told, Counted, Sight, Told,
};

/// СКАЗАЛА ЛИ ЦЕЛЬ, КТО ОНА, В ЭТОМ РАЗГОВОРЕ.
///
/// Трёх состояний, а не двух: «о личности не сказано ничего» и «сказано, что имени в приветствии
/// не было» — разные факты, и слить их в `Option` значит потерять знаменатель слепой зоны именного
/// ключа: коннект по IP стал бы неотличим от разговора, у которого `ClientHello` просто впереди.
///
/// # РЕШЁТКА УЕХАЛА В ФУНДАМЕНТ (05.09.2026)
///
/// Псевдоним [`reflex_core::disclosure::Disclosed`]: порядок `Awaited ⊑ Silent ⊑ Spoken` и три его
/// закона — форма всякого сведения, добываемого из разговора (шифр, версия, идентификатор
/// соединения), а не свойство имени. Переименован ТИП, варианты сохранены: `Naming::Spoken`,
/// `Naming::Silent`, `Naming::Awaited` резолвятся через псевдоним, и ни одно из 300 употреблений
/// в 50 файлах не тронуто.
///
/// # Что остаётся НАШИМ предметом
///
/// `Spoken` значит «имя взято из `ClientHello` ЭТОГО разговора». `Silent` — приветствие прошло, а
/// имени в нём не было: не-TLS, коннект по IP, MTProto, ECH, обрезанный или нечитаемый SNI.
///
/// ЗАКРЫТИЕ ВОПРОСА ДЛЯ ПЛАНА держится не типом, а разделением величин: знание растёт join'ом, а
/// снимок «на чём стоял план» замерзает в момент принятия (`reflex_engine::stood_on`). Позднее имя
/// обогащает знание и НЕ двигает страту на середине применения.
pub type Naming<N> = reflex_core::disclosure::Disclosed<N>;

/// ЧЕМ КЛЮЧУЕТСЯ ЦЕЛЬ — и для записи, и для действия.
///
/// Тип ОДИН, а расходятся два его применения не арностью, а ШИРИНОЙ безымянной ветви: строке нужна
/// сеть (человек видит `91.108.56.0/24` одной целью), действию — точный адрес (лечить /24 значило
/// бы применить знание к 256 хозяевам — та же беда, что применение именного знания по общему
/// адресу, только уровнем выше).
///
/// Ширина приходит СНАРУЖИ, ровно как `narrow: fn(&str) -> &str` для имён: молчаливое умолчание
/// завело бы вторую правду о ней. Два ключа с общим типом и названной проекцией между ними — не то
/// же, что два типа: расхождение здесь ловится компилятором.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum TargetKey<N> {
    Named(N),
    Unnamed(Addr),
}

// ЧТО ОСТАЛОСЬ ЗДЕСЬ ОТ УЕХАВШЕЙ СЛЕПОТЫ — ДВА ЗАМЕРА, КОТОРЫЕ ПРО НАС, А НЕ ПРО ЖАНР.
// Сам закон переехал в `reflex_core::sight`; эти две записи привязаны к НАШЕЙ истории и потому
// остаются здесь — в фундаменте они были бы чужим опытом без предмета.
//
// НАПРАВЛЕНИЕ ПРЕЖНЕЙ ОШИБКИ БЫЛО КОНСЕРВАТИВНЫМ (#320, 03.09). До сохранения счёта в `Closed`
// счёт плоскости у завершённого разговора обнулялся, то есть был ЗАНИЖЕН. Значит `Partial`
// выходил чаще правды, и строка говорила «не видели» чаще правды: мы приписывали себе МЕНЬШЕ
// знания, чем имели, а не больше. Ни одно решение не принято на ложной уверенности — мы были
// ложно скромны. Записано потому, что без этой строки читатель предположит худшее, а для эпика
// про «уверены ли мы, что видим то, по чему решаем» направление ошибки есть половина ответа.
//
// НАШ ОФЛАЙН-ВХОД ДАЁТ `Full` ПО ПОСТРОЕНИЮ. У `app::wire::snapshot` счёт ядра
// синтезируется из тех же пакетов, что скормлены плоскости. Замер 03.09 на полевом корпусе дал
// `81 full` из 81 — и это число ничего не говорит о нашей слепоте.

/// ЧТО ОСТАЁТСЯ ОТ РАЗГОВОРА, КОГДА ОН ЗАКРЫЛСЯ.
///
/// # Почему двух полей, а не одного
///
/// Первая редакция сохранила только ответ цели — и строка всё равно приходила слепой. Причина
/// механическая: слепота считается РАСХОЖДЕНИЕМ двух счётов (`sighted(kernel, plane)`), а счёт
/// плоскости у завершённого разговора обнулялся вместе с `Run`. Ядро говорило «13 пакетов», мы —
/// «ноль», и `Sight::Partial{13,2}` перекрывал сохранённый ответ: `told(…, Partial)` даёт `Blind`.
///
/// То есть сохранить надо ровно то, что делает разговор ЗНАКОМЫМ: сколько мы видели и ответила ли
/// цель. План и так известен, момент неинтересен, всё прочее умирает вместе с разговором законно.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Closed {
    pub answered: Answered,
    /// Счёт ПЛОСКОСТИ на момент закрытия — второй оракул слепоты. Без него зрячий разговор
    /// выглядит наполовину пропущенным, и строка теряет право говорить о цели.
    pub counted: Counted,
}

/// ОТВЕТИЛА ЛИ ЦЕЛЬ, И ЧЕРЕЗ СКОЛЬКО ОТ НАЧАЛА РАЗГОВОРА.
///
/// Про НАБЛЮДЁННОЕ плоскостью, и только про него: «не ответила» здесь значит «мы не видели
/// ответа». Отличить это от «ответила, а мы ослепли» — работа `Told`, и делается она снаружи,
/// потому что шаг о своей слепоте знать не может по построению.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Answered {
    NotYet,
    After(Span),
}

/// Наблюдение шага — в клетку строки, где слепота выразима.
pub fn answering(answered: Answered, sight: Sight) -> Told<Span> {
    match answered {
        Answered::After(span) => told(Told::Told(span), sight),
        Answered::NotYet => told(Told::Nothing, sight),
    }
}

/// ШИРИНА ЗАПИСИ: /24. Единственная честная единица накопления для коннекта по IP — у такой цели
/// нет ничего, кроме адреса, а соседние адреса одного хозяина ведут себя одинаково.
pub fn net_of(dst: Addr) -> Addr {
    Addr(dst.0 & 0xFF_FF_FF_00)
}

/// ШИРИНА ДЕЙСТВИЯ: точный адрес. Лечить сеть нельзя — знание применилось бы к чужим хозяевам.
pub fn host_of(dst: Addr) -> Addr {
    dst
}

/// ПРОЕКЦИЯ НАБЛЮДЕНИЯ В КЛЮЧ — тотальная и названная.
///
/// Наблюдение трёхчленно (различать обязано: «имени не будет» есть знаменатель слепой зоны, а
/// «имя впереди» — просто время), ключ двухчленен (сходиться обязан: в момент действия имя либо
/// есть, либо нет). Разная арность на разных слоях законна ровно при условии, что переход между
/// ними — ОДНА функция, а не молчаливое совпадение написаний.
pub fn keyed<N>(naming: Naming<N>, dst: Addr, width: fn(Addr) -> Addr) -> TargetKey<N> {
    match naming {
        Naming::Spoken(name) => TargetKey::Named(name),
        Naming::Silent | Naming::Awaited => TargetKey::Unnamed(width(dst)),
    }
}


/// Ответила ли цель, и через сколько — в единице, у которой слепота выразима.
pub type Spoke = Told<Span>;

/// ЧТО ПЛОСКОСТЬ ЗНАЕТ О РАЗГОВОРЕ, КОТОРЫЙ ЯДРО УЖЕ НАШЛО.
///
/// `Never` — не пограничный случай, а обычный: через очередь идёт не всё, и разговор, до неё не
/// дошедший, существует. Слить его с `Lost` (курсор был и вытеснен) значило бы выдать нашу уборку
/// за чужой трафик.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Watched {
    Never,
    Seen {
        plan: Plan,
        /// НА ЧЁМ СТОИТ НОГА — читается прямо из личности: план принят ⟺ она известна
        /// (`Spoken` либо `Silent`). Прежде здесь стоял отдельный `Standing`, снятый разбором
        /// алгебры (#300) как вторая ось, державшая незаконные клетки представимыми.
        naming: Said,
        counted: Counted,
        answered: Answered,
    },
    /// Разговор закрылся штатно: состояния нет, но оно и не терялось.
    ///
    /// ОТВЕТ ЦЕЛИ ПЕРЕЖИВАЕТ ЗАКРЫТИЕ. Без него всякий завершённый разговор приходил в строку
    /// слепым (`Told::Blind`, «не имеем права судить») — 83 цели из 86 на полевом прогоне, то
    /// есть таблица не видела большинства. Знали мы при этом всё.
    Ended(Closed),
    Lost,
}

/// УЗЕЛ ЦЕЛИ — то, что человек видит подстрокой.
///
/// # ЛИЧНОСТИ ЗДЕСЬ НЕТ, И ЭТО ПРОВЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО (#320, 03.09)
///
/// Поле `target: Naming<N>` тут было заведено и СНЯТО в тот же день — оно не несёт сведений ни в
/// одной из двух ветвей:
///
/// * `Named(k)` — тождественно ключу строки покомпонентно: `keyed` кладёт в ключ тот же `Box<str>`
///   из `naming_of_flow`. Внутри строки `Named(k)` узел с другим именем невыразим по построению.
/// * `Unnamed(net)` — хуже, чем дубль: `Silent` и `Awaited` дают ОДИН ключ (теорема
///   `ozhidanie_imeni_i_ego_otsutstvie_dayut_odnu_stroku`), значит в одной строке законно
///   встречаются оба, а слияние берёт ПЕРВЫЙ — то есть порядок записей conntrack. Десять
///   разговоров, девять без имени и один в пути: окажись он первым, узел скажет `Awaited`.
///   Знаменатель слепой зоны схлопывается очерёдностью ядра.
///
/// Цель узла читается из ключа СТРОКИ, внутри которой он и приходит. Понадобится узел отдельно —
/// дешёвая форма это пара `(&TargetKey<N>, &Node)`, а не поле: пара не заводит второго перехода
/// через границу арности (трёхчленное наблюдение → двухчленный ключ), поле заводит.
///
/// Чего узлу ДЕЙСТВИТЕЛЬНО не хватает и что из строки не восстанавливается — полное имя (ключ
/// сужён `narrow`, сырое SNI выброшено) и распределение личности по адресу (сколько разговоров,
/// из них `silent`/`awaited`). Оба — новые сведения, и ни одно не есть `Naming<N>`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Node {
    pub dst: Addr,
    pub flows: u32,
    /// Счёт ЯДРА: переживает метку, ногу и всякое удешевление горячего пути.
    pub kernel: Counted,
    /// Счёт ПЛОСКОСТИ: столько мы видели сами.
    pub plane: Counted,
    /// Расхождение двух счётов и есть замеренная слепота.
    pub sight: Sight,
    /// КОГДА ПЛОСКОСТЬ ВИДЕЛА ЭТОТ УЗЕЛ В ПОСЛЕДНИЙ РАЗ.
    ///
    /// # Почему счёта мало, и это не запас, а второй род слепоты
    ///
    /// [`Sight`] меряет слепоту В ПАКЕТАХ и ловит случай «до очереди дошло не всё». Второго рода
    /// она не ловит вовсе: счета сошлись, а наблюдения ПРЕКРАТИЛИСЬ — плоскость видела разговор
    /// целиком и молчит про него сорок секунд, пока ядро видит его сейчас. По счёту это
    /// `Sight::Full`, то есть зелено.
    ///
    /// Запись ядра берётся в момент снимка и потому актуальна по построению — значит расхождение
    /// «сейчас» и этого момента и есть та слепота. Живая строка и застывшая перестают выглядеть
    /// одинаково, то есть «прибор молчит» отличается от «прибор мёртв».
    ///
    /// `Blind` — плоскость этого разговора не видела ВОВСЕ (до очереди дошло не всё); `Nothing` —
    /// видела, но момент не сохранён. Третье состояние здесь несёт ту же работу, что и везде:
    /// пустая клетка у зрячего значит одно, у слепого — другое.
    pub plane_seen: Told<Tick>,
    pub watched: Watched,
    pub spoke: Told<Span>,
}

/// ЧТО ПЛОСКОСТЬ ЗНАЕТ О РАЗГОВОРЕ — из её курсора, и только из него.
///
/// # Почему тип и закон живут ЗДЕСЬ, а добыча — в краю (#320, Т4)
///
/// Строка собирается из двух источников: ядро отвечает «сколько», плоскость — «кто, чем и на
/// каком основании». Добыча первого — netfilter, то есть Linux; и пока ТИП строки лежал рядом с
/// добычей, всякий, кому нужно было ЗНАТЬ, КАК ВЫГЛЯДИТ СТРОКА, обязан был зависеть от netfilter.
/// Для standalone-показа это запрет по построению: он собирается и поверяется на машине, где
/// conntrack нет вовсе.
///
/// Предмет при этом был разорван пополам: закон сборки (`Counted`, `Sight`, `Told`, `added`,
/// `sighted`) жил здесь, а тип, к которому он применяется, — за дверью. Половина предмета,
/// доступная только одной операционной системе, есть не граница слоя, а случайность истории.
pub fn watched_of(cursor: Cursor) -> Watched {
    match cursor {
        Cursor::Fresh => Watched::Never,
        Cursor::Ended(closed) => Watched::Ended(closed),
        Cursor::Lost => Watched::Lost,
        Cursor::Running(run) => Watched::Seen {
            plan: run.plan,
            // `Standing` снят как поле (#300): он был второй осью рядом с личностью, и произведение
            // двух осей держало представимым «принято по личности, которой ещё нет». Ось одна, и
            // «на чём стоит нога» читается прямо из неё: принято ⟺ личность известна.
            naming: run.naming,
            counted: Counted {
                up: run.up as u64,
                up_bytes: run.up_bytes,
                down: run.down as u64,
                down_bytes: run.down_bytes,
            },
            answered: run.answered,
        },
    }
}

/// УЗЕЛ ИЗ ДВУХ СЧЁТОВ. Чистая часть сборки: откуда взялся счёт ядра, здесь не спрашивается —
/// именно поэтому узел собирается и там, где ядра нет.
///
/// Личность приходит СНАРУЖИ: её знает плоскость, а не запись ядра. Различитель внутри `Watched`
/// её не заменяет — он про то, что плоскость установила о РАЗГОВОРЕ, а `target` про то, как
/// зовут ЦЕЛЬ, и на общем адресе это разные вопросы.
pub fn node_of(dst: Addr, kernel: Counted, cursor: Cursor, seen: Option<Tick>) -> Node {
    let watched = watched_of(cursor);
    let plane = match watched {
        Watched::Seen { counted, .. } => counted,
        // СЧЁТ ЗАВЕРШЁННОГО РАЗГОВОРА ПЕРЕЖИВАЕТ ЕГО. Обнули его — и `sighted` объявит слепотой
        // разницу с ядром, а сохранённый ответ цели окажется перекрыт: `told(…, Partial)` даёт
        // `Blind`. Так лечение первой половины и не сработало.
        Watched::Ended(closed) => closed.counted,
        Watched::Never | Watched::Lost => no_counts(),
    };
    let sight = sighted(kernel, plane);
    Node {
        dst,
        flows: 1,
        kernel,
        plane,
        sight,
        // МОМЕНТА НЕТ У ТОГО, КОГО НЕ ВИДЕЛИ. `Never` значит «через очередь этот разговор не
        // шёл», и сказать про него «наблюдений не было» было бы правдой о ЦЕЛИ вместо правды о
        // НАС: мы не смотрели.
        plane_seen: match (watched, seen) {
            (Watched::Never, _) => Told::Blind,
            (_, Some(at)) => Told::Told(at),
            (_, None) => Told::Nothing,
        },
        watched,
        spoke: match watched {
            Watched::Seen { answered, .. } => answering(answered, sight),
            // ЗАВЕРШЁННЫЙ РАЗГОВОР НЕ СЛЕП: мы видели его целиком, и ответ цели пережил закрытие.
            // Прежде он попадал в общую ветвь со слепотой, и таблица говорила «не имеем права
            // судить» про то, о чём знала всё.
            Watched::Ended(closed) => answering(closed.answered, sight),
            // Разговора мы не видели вовсе либо забыли его — сказать про ответ цели нечего, и это
            // слепота, а не молчание цели.
            Watched::Never | Watched::Lost => Told::Blind,
        },
    }
}

/// Слияние двух узлов одной цели.
///
/// # НИ ОДНО ПОЛЕ ЗДЕСЬ НЕ ЗАВИСИТ ОТ ПОРЯДКА, и это требование, а не свойство
///
/// Узлы приходят в порядке записей conntrack, то есть в произвольном. Всякое поле, берущееся «у
/// первого», молча становится выборкой из мультимножества — так и погибло поле личности, заведённое
/// и снятое 03.09: `Silent` и `Awaited` дают один ключ, оба законно лежат в одной строке, и узел
/// говорил бы то, что оказалось первым.
///
/// Оттого счета складываются, ответ берётся ранний (`sooner`), наблюдение — позднее (`later`): все
/// три операции коммутативны, и результат от очерёдности ядра не зависит.
pub fn merged(into: Node, plus: Node) -> Node {
    let kernel = added(into.kernel, plus.kernel);
    let plane = added(into.plane, plus.plane);
    Node {
        dst: into.dst,
        // ВИДЕЛИ — ЗНАЧИТ ПОЗЖЕ ИЗ ДВУХ. Узел жив, если жив хоть один его разговор; взять ранний
        // значило бы объявить цель застывшей из-за одного давно закрытого соединения.
        plane_seen: later(into.plane_seen, plus.plane_seen),
        flows: into.flows + plus.flows,
        kernel,
        plane,
        sight: sighted(kernel, plane),
        watched: match (into.watched, plus.watched) {
            (Watched::Never, held) => held,
            (held, _other) => held,
        },
        spoke: sooner(into.spoke, plus.spoke),
    }
}

/// ПАСПОРТ СЛЕПОТЫ — проекция `model/law/Instrument.tla`.
///
/// Единственный прибор парка, чей предмет — МЫ САМИ В МОМЕНТ НАБЛЮДЕНИЯ: он отвечает не «что с
/// целью», а «имеем ли мы право говорить о цели». Третье состояние `Told` и есть весь его смысл:
/// у зрячей плоскости «ничего не приходило» есть факт о ЦЕЛИ, у ослепшей — факт о НАС.
pub struct BlindnessInstrument;

impl BlindnessInstrument {
    fn read(&self, sight: &Sight, _now_ms: u64) -> Told<()> {
        match sight {
            Sight::Full => Told::Nothing,
            Sight::Partial { .. } => Told::Blind,
        }
    }
}

impl reflex_core::step::Step for BlindnessInstrument {
    /// НАБЛЮДЕНИЕ, которое подают прибору.
    type From = reflex_core::DetectorEvent<Sight>;

    /// ПОКАЗАНИЕ. Отсутствие показания сигналом не является — прибор высказывается, когда есть
    /// что сказать.
    type To = smallvec::SmallVec<[Told<()>; 2]>;

    /// Показаний этот прибор не заводит: он говорит, что увидел, и не говорит, чем мерил.
    type Notes = ();

    fn step(self, event: Self::From) -> (Self, Self::To, ()) {
        match event {
            reflex_core::DetectorEvent::Packet { input, .. } => {
                let reading = self.read(&input, 0);
                (self, smallvec::smallvec![reading], ())
            }
            reflex_core::DetectorEvent::Tick { .. } => (self, smallvec::SmallVec::new(), ()),
            // Прибор мерит наше право говорить о цели; непонятое им не является и молчит.
            reflex_core::DetectorEvent::Opaque { .. } => (self, smallvec::SmallVec::new(), ()),
        }
    }
}

