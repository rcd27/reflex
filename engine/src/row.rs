/// ТИП СТРОКИ ЧИТАЕТСЯ БЕЗ NETFILTER — исход требования Т4 (#320), и он проверяется здесь.
///
/// Проверка живёт в `dataplane`, потому что этот крейт netfilter не знает и знать не может: он
/// `no_std` и в его графе нет ни `reflex-linux`, ни conntrack. Собранный узел здесь и есть
/// доказательство — если тип или закон уедут обратно к добыче, файл перестанет компилироваться.
#[cfg(test)]
mod row_needs_no_kernel_tests {
    use super::*;
    use crate::{Basis, Epoch, Interest, Programme, Run};

    fn counted(up: u64, down: u64) -> Counted {
        Counted {
            up,
            up_bytes: up * 100,
            down,
            down_bytes: down * 100,
        }
    }

    fn running(up: u16, down: u16) -> Cursor {
        Cursor::Running(Run {
            plan: Plan {
                programme: Programme::Pass,
                epoch: Epoch(1),
                basis: Basis::Seeded,
                interest: Interest::Idle,
            },
            naming: Naming::Spoken(()),
            up,
            down,
            up_bytes: up as u64 * 100,
            down_bytes: down as u64 * 100,
            began: crate::Tick(0),
            last_up: crate::Tick(0),
            last_down: crate::Tick(0),
            answered: Answered::After(Span(30)),
            announced: crate::Announced::Never,
            ordered: crate::Ordered::Nothing,
        })
    }

    /// УЗЕЛ СОБИРАЕТСЯ ИЗ ДВУХ СЧЁТОВ, и счёт ядра приходит ЗНАЧЕНИЕМ, а не из conntrack.
    ///
    /// Ровно это и требовалось заказчику: чтобы узнать, как выглядит строка, не нужен Linux.
    #[test]
    fn a_node_is_built_from_two_counts_without_asking_the_kernel() {
        let node = node_of(
            Addr(0x0A00_0001),
            counted(10, 10),
            running(10, 10),
            Some(Tick(1_000)),
        );
        assert_eq!(node.flows, 1);
        assert_eq!(
            node.sight,
            Sight::Full,
            "счета сошлись, а слепота объявлена"
        );
        assert!(
            matches!(node.watched, Watched::Seen { .. }),
            "разговор виден плоскостью, а узел говорит обратное"
        );
    }

    /// РАСХОЖДЕНИЕ СЧЁТОВ ЕСТЬ ЗАМЕРЕННАЯ СЛЕПОТА, а не ошибка округления.
    ///
    /// Пара к предыдущему: без неё тест зеленел бы у сборки, всегда объявляющей `Full`, — то есть
    /// у таблицы, которая скажет «чисто» там, где мы просто не смотрели.
    #[test]
    fn counts_that_disagree_are_measured_blindness() {
        let node = node_of(
            Addr(0x0A00_0001),
            counted(100, 100),
            running(10, 10),
            Some(Tick(1_000)),
        );
        assert_ne!(
            node.sight,
            Sight::Full,
            "ядро видело вдесятеро больше плоскости, а узел объявил себя зрячим"
        );
    }

    /// РАЗГОВОР, ДО ОЧЕРЕДИ НЕ ДОШЕДШИЙ, — НЕ ПОТЕРЯННЫЙ.
    ///
    /// `Never` и `Lost` различаются лечением: первое значит «через очередь идёт не всё», второе —
    /// «наша уборка вытеснила курсор». Слить их значило бы выдать свою уборку за чужой трафик, и
    /// про ответ цели тогда сказалось бы `Nothing` вместо `Blind`.
    #[test]
    fn a_conversation_that_never_reached_the_queue_is_not_a_lost_one() {
        let never = node_of(
            Addr(0x0A00_0001),
            counted(5, 5),
            Cursor::Fresh,
            Some(Tick(1_000)),
        );
        let lost = node_of(
            Addr(0x0A00_0001),
            counted(5, 5),
            Cursor::Lost,
            Some(Tick(1_000)),
        );
        assert_eq!(never.watched, Watched::Never);
        assert_eq!(lost.watched, Watched::Lost);
        assert_eq!(
            never.spoke,
            Told::Blind,
            "о цели, которой мы не видели, сказано как о молчащей"
        );
    }

    /// СЛИЯНИЕ НЕ ЗАВИСИТ ОТ ПОРЯДКА — требование, а не наблюдение.
    ///
    /// Узлы приходят в порядке записей conntrack, то есть в произвольном. Поле, берущееся «у
    /// первого», молча становится выборкой из мультимножества: так 03.09 погибло поле личности в
    /// узле — `Silent` и `Awaited` дают ОДИН ключ, оба законно лежат в одной строке, и узел
    /// говорил бы то, что оказалось первым. Проверка стоит здесь, чтобы следующее такое поле
    /// краснело сразу, а не через чтение глазами.
    #[test]
    fn merging_does_not_depend_on_the_order_the_kernel_listed_them() {
        let early = node_of(
            Addr(0x0A00_0001),
            counted(3, 3),
            running(3, 3),
            Some(Tick(1_000)),
        );
        let late = node_of(
            Addr(0x0A00_0001),
            counted(7, 7),
            running(7, 7),
            Some(Tick(9_000)),
        );

        let one = merged(early.clone(), late.clone());
        let other = merged(late, early);

        // ВСЁ, ЧТО ОБЯЗАНО БЫТЬ КОММУТАТИВНЫМ, ПЕРЕЧИСЛЕНО ПОИМЁННО — а не сравнением узлов
        // целиком, потому что одно поле сегодня выборкой ЯВЛЯЕТСЯ, и об этом ниже.
        assert_eq!(
            (
                one.flows,
                one.kernel,
                one.plane,
                one.sight,
                one.plane_seen,
                one.spoke
            ),
            (
                other.flows,
                other.kernel,
                other.plane,
                other.sight,
                other.plane_seen,
                other.spoke
            ),
            "слияние зависит от очерёдности записей ядра — поле стало выборкой"
        );

        // TODO(#320): `watched` — ВЫБОРКА, а не свойство узла, и это найдено этой же проверкой.
        //
        // Узел агрегирует разговоры, а `Watched` описывает ОДИН: при двух наблюдавшихся берётся
        // первый по порядку conntrack, вместе с его `counted` и `answered`. Ровно та болезнь, от
        // которой 03.09 погибло поле личности, — только эта старше и пряталась за тем, что
        // сравнивать узлы целиком было негде.
        //
        // ЦЕНА СЕГОДНЯ: у цели с двумя живыми разговорами колонка состояния показывает случайный
        // из них. Лечится либо агрегатом вместо образца, либо снятием поля из узла в пользу
        // счётчиков по личности (`flows`, из них `silent`/`awaited`) — выбор за постановкой
        // таблицы, а не за этим файлом.
        assert_ne!(
            one.watched, other.watched,
            "выборка перестала быть выборкой — снять `TODO(#320)` и сравнивать узлы целиком"
        );
    }

    /// НАБЛЮДЕНИЕ БЕРЁТСЯ ПОЗДНЕЕ, а ответ цели — ранний, и это не симметрия ради симметрии.
    ///
    /// Узел жив, если жив хоть один его разговор; взять ранний момент значило бы объявить цель
    /// застывшей из-за одного давно закрытого соединения. У ОТВЕТА наоборот: цель ответила, если
    /// ответила хоть раз, и «через сколько» — про первый.
    #[test]
    fn the_node_is_seen_as_late_as_its_liveliest_conversation() {
        assert_eq!(
            later(Told::Told(Tick(1_000)), Told::Told(Tick(9_000))),
            Told::Told(Tick(9_000)),
            "узел объявлен застывшим по самому старому разговору"
        );
        assert_eq!(
            later(Told::Blind, Told::Told(Tick(9_000))),
            Told::Told(Tick(9_000)),
            "слепота одного разговора ослепила узел, который видели"
        );
    }

    /// РАЗГОВОР, ДО ОЧЕРЕДИ НЕ ДОШЕДШИЙ, МОМЕНТА НЕ ИМЕЕТ — и это `Blind`, а не «давно».
    ///
    /// Второй род слепоты, которого `Sight` не ловит вовсе: счета могут сойтись, а наблюдений не
    /// быть. Сказать про такой узел «наблюдений не было» значило бы выдать правду о НАС за правду
    /// о цели.
    #[test]
    fn a_node_the_plane_never_watched_has_no_moment_at_all() {
        let never = node_of(
            Addr(0x0A00_0001),
            counted(5, 5),
            Cursor::Fresh,
            Some(Tick(1_000)),
        );
        assert_eq!(
            never.plane_seen,
            Told::Blind,
            "узлу, которого плоскость не видела, приписан момент наблюдения"
        );
    }

    /// ОТВЕТ ЦЕЛИ БЕРЁТСЯ САМЫЙ РАННИЙ: она ответила, если ответила хоть одному разговору.
    #[test]
    fn merging_nodes_keeps_the_earliest_answer() {
        assert_eq!(
            sooner(Told::Told(Span(70)), Told::Told(Span(30))),
            Told::Told(Span(30)),
            "слияние взяло поздний ответ — цель выглядит медленнее, чем была"
        );
        assert_eq!(
            sooner(Told::Blind, Told::Told(Span(30))),
            Told::Told(Span(30)),
            "слепота одного узла стёрла ответ, который другой узел видел"
        );
    }
}

