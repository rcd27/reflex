//! НАПРАВЛЕНИЕ ПАКЕТА ОТНОСИТЕЛЬНО РАЗГОВОРА.

/// КУДА ИДЁТ ЭТОТ ПАКЕТ — к тому, кто отвечает, или от него.
///
/// # Почему это свойство РАЗГОВОРА, а не пакета
///
/// У кадра на проводе направления нет: есть два адреса и два порта, и оба конца устроены
/// одинаково. Направление появляется только когда названо, кто из концов инициатор, а кто
/// отвечающий, — то есть это факт о РАЗГОВОРЕ, приложенный к пакету, а не наблюдение над кадром.
///
/// Отсюда следствие, которое стоит держать в голове: **направление бывает НЕОПРЕДЕЛИМЫМ**. Правило
/// «сервер тот, у кого известный порт» не разводит стороны, когда оба конца чужие или оба свои.
/// Это отказ ПРАВИЛА, а не отказ разбора, и потому классификатор обязан отвечать `Option`, а не
/// угадывать. Сам тип при этом тотален: неопределённость живёт в том, кто его строит, и не
/// протекает в тех, кто им пользуется.
///
/// # Откуда приехало (05.09.2026)
///
/// Из `dataplane`, где тип был объявлен, а СМЫСЛ его вариантов жил в другом крейте — за правилом
/// порта. Три крейта употребляли `Up`/`Down`, сверяясь с соглашением, которого в самом типе не
/// было записано. Здесь смысл и тип неразделимы.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Dir {
    /// К отвечающему: от инициатора разговора к тому, кто его принял.
    Up,
    /// От отвечающего: обратно инициатору.
    Down,
}
