//! Направление пакета относительно разговора.

/// Куда идёт пакет — к отвечающему или от него. Свойство РАЗГОВОРА, не пакета: у кадра на проводе
/// направления нет (два адреса, два порта, оба конца одинаковы), оно появляется, лишь когда названо,
/// кто инициатор. Следствие: направление бывает НЕОПРЕДЕЛИМЫМ (правило «сервер — известный порт» не
/// разводит стороны, когда оба конца чужие или свои) — отказ ПРАВИЛА, не разбора, потому строящий
/// отвечает `Option`. Сам тип тотален: неопределённость живёт в том, кто его строит.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Dir {
    /// К отвечающему: от инициатора разговора к тому, кто его принял.
    Up,
    /// От отвечающего: обратно инициатору.
    Down,
}
