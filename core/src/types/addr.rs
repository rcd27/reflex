//! Адрес узла. Фундаментный тип: им ключуется область цели (`Base::Fibre`), и потому он обязан
//! жить там же, где области, — иначе ключ области ссылался бы вверх по зависимостям.

/// IPv4-адрес одним словом. IPv6 мимо: ключ цели его пока не несёт (TODO #299 — сперва замер доли).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Addr(pub u32);

/// Адрес словами. Четыре байта, старший первым: `Addr` держит адрес в порядке хоста, `a.b.c.d`
/// берётся из `to_be_bytes` — тем же способом, каким его берёт край. Второй способ печати завёл бы
/// вторую правду о том, какой байт старший.
impl std::fmt::Display for Addr {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let [a, b, c, d] = self.0.to_be_bytes();
        write!(f, "{a}.{b}.{c}.{d}")
    }
}
