//! ОБЛАСТЬ МАРКИ — объявленный кусок битов и значение, которое в нём живёт.
//!
//! Марка есть ресурс МАШИНЫ, а не цепочки: на одной машине её пишут и приборы, и правила ядра, и
//! посторонний процесс, ни о ком из нас не знающий. Пока владение областью подразумевается, оно
//! есть будущее молчаливое расхождение — два писателя затирают друг друга, и заметно это станет по
//! поведению сети, а не по красному тесту.
//!
//! # Чем это НЕ является
//!
//! Это не второй закон о том же, что [`crate::edge`]-раскладка приборов (`instrument::edge::Layout`).
//! Предметы разные, и разница проверяемая: `Layout` спрашивает «помещаются ли ЗДЕСЬ МОИ ПЯТНАДЦАТЬ
//! БИТ полей — тег, фаза, оттиск», то есть знает форму содержимого. [`Region`] о содержимом не знает
//! ничего и спрашивает только «хорошо ли устроена сама область». Оттого чужую область `Layout`
//! отдать нельзя: маска подошла бы, поля — нет.
//!
//! # Три свойства, которые область обязана нести
//!
//! * **Отказ ЗНАЧЕНИЕМ при постройке.** Ни паники, ни тихого обрезания: значение, не помещающееся
//!   в объявленную область, НЕ СТРОИТСЯ. Обрежь мы его молча — решение «нога 5» превратилось бы в
//!   «нога 1», и узналось бы это по маршруту, а не по ошибке.
//! * **Связность маски.** Прерывистая маска — не область, а грабли: данные писались бы мимо дырки
//!   и читались мусором. Проверка при рождении, а не на каждом пакете горячего пути.
//! * **Публичная маска.** Ею и только ею выразимо непересечение двух областей — единственный
//!   способ объявить владение вместо того, чтобы о нём помнить.
//!
//! # УСЛОВНОЕ ВЛАДЕНИЕ НЕ ПОДДЕРЖИВАЕТСЯ, И ЭТО РЕШЕНИЕ, А НЕ ПРОБЕЛ
//!
//! Встречается раскладка, где одни и те же младшие биты принадлежат разным полям в зависимости от
//! старшего тега: «номер слота, если взведён бит A; наша метка, если взведён бит B». Это
//! размеченное объединение внутри марки, и [`Region::overlaps`] его не выразит — две такие области
//! честно пересекаются, и он честно скажет «да», хотя конфликта нет.
//!
//! Поддерживать это мы не будем, и причина названа заранее, чтобы не спорить в тот момент, когда
//! кто-то придёт с такой маркой. Условное владение означает, что прочесть область НЕЛЬЗЯ, не
//! прочитав сперва тег, — то есть у неё нет собственного смысла, есть лишь смысл пары. Тогда и
//! проверять надо пару, а пара — это уже формат, а не область; закон о формате знает содержимое, а
//! [`Region`] заведён ровно затем, чтобы его не знать. Разложить свои поля непересекающимися стоит
//! дешевле: в марке тридцать два бита, и занятых среди них обычно единицы.
//!
//! # Предел, названный вслух
//!
//! Непересечение проверяется между областями, ОБЪЯВЛЕННЫМИ НАМ. Посторонний процесс, пишущий те же
//! биты извне, этой проверкой не покрыт и покрыт быть не может: мы о нём не знаем. Против него есть
//! только обнаружение постфактум (чужой тег читается как чужой), и это разные вещи — не путать.

/// Объявленная область марки: связный кусок битов, о содержимом которого закон не знает ничего.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Region {
    mask: u32,
}

/// Значение, УЖЕ ПРОВЕРЕННОЕ на свою область. Существует только то, что в область поместилось, —
/// потому наложение [`Marked::apply_to`] тотально и обрезать ему нечего.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Marked {
    region: Region,
    /// Значение, уже сдвинутое на место области.
    bits: u32,
}

impl Region {
    /// Единственная дверь. `None` — маска пуста либо прерывиста.
    ///
    /// Связность проверяется так: сдвинутая к нулю маска обязана быть вида `2^n - 1`, а у такого
    /// числа `m & (m + 1) == 0`. Одно выражение вместо цикла по битам.
    ///
    /// Пустая маска отсекается ПЕРВОЙ, и не ради порядка: у нуля `trailing_zeros() == 32`, а сдвиг
    /// `u32` на 32 — переполнение, то есть паника в отладке. Проверка «сначала непусто» здесь не
    /// стилистическая, она держит тотальность двери (нашлось прогоном, не чтением).
    pub fn new(mask: u32) -> Option<Region> {
        if mask == 0 {
            return None;
        }
        let run = mask >> mask.trailing_zeros();
        (run & run.wrapping_add(1) == 0).then_some(Region { mask })
    }

    /// Биты области — ими выражается непересечение ([`Region::overlaps`]) и сохранение чужого.
    pub fn mask(&self) -> u32 {
        self.mask
    }

    /// Сколько бит в области: сколько РАЗЛИЧИМЫХ решений в ней помещается, счётом, а не на глаз.
    pub fn width(&self) -> u32 {
        self.mask.count_ones()
    }

    /// Делят ли две области хоть один бит. Не «равны ли» — пересечения достаточно, чтобы писатели
    /// затирали друг друга.
    pub fn overlaps(&self, other: &Region) -> bool {
        self.mask & other.mask != 0
    }

    /// Значение в этой области — `None`, если не помещается. Именно здесь отказ и обязан случиться:
    /// дальше по пути значение уже проверено, и обрезать нечего.
    pub fn holding(&self, value: u32) -> Option<Marked> {
        let shifted = value.checked_shl(self.mask.trailing_zeros())?;
        (shifted & self.mask == shifted).then_some(Marked {
            region: *self,
            bits: shifted,
        })
    }
}

impl Marked {
    /// Наложить значение на прочитанное слово (read-modify-write): чужие биты вне области целы.
    /// Тот же закон, что у памятки приборов, и записан он ровно один раз на область — иначе две
    /// копии разошлись бы молча.
    pub fn apply_to(&self, word: u32) -> u32 {
        (word & !self.region.mask) | self.bits
    }

    /// Прочесть значение области из слова. Обратная сторона [`Marked::apply_to`]: без неё писатель
    /// не мог бы убедиться, что прочтёт своё.
    pub fn read(region: &Region, word: u32) -> u32 {
        (word & region.mask) >> region.mask.trailing_zeros()
    }

    /// Чья это область — для проверки непересечения у того, кто держит уже готовое значение.
    pub fn region(&self) -> Region {
        self.region
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// ПРЕДМЕТ: прерывистая маска — не область. Дырка означала бы, что часть значения пишется мимо
    /// и читается мусором, и обнаружилось бы это поведением сети, а не ошибкой.
    #[test]
    fn a_mask_with_a_hole_is_not_a_region() {
        assert!(Region::new(0b1011_0000).is_none());
        assert!(Region::new(0).is_none(), "пустая область — тоже не область");
        assert!(Region::new(0b1111_0000).is_some());
        assert!(Region::new(0x8000_0000).is_some(), "старший бит — законная область");
    }

    /// Значение, не влезающее в область, НЕ СТРОИТСЯ. Обрежь его молча — «нога 5» стала бы «ногой
    /// 1», и узналось бы это по маршруту, а не по отказу.
    #[test]
    fn a_value_too_wide_for_its_region_is_refused_not_trimmed() {
        let region = Region::new(0b1100_0000).expect("два бита");
        assert_eq!(region.width(), 2);

        assert!(region.holding(3).is_some(), "три в два бита влезает");
        assert!(region.holding(4).is_none(), "четыре — нет, и это отказ, а не 0");
    }

    /// Наложение сохраняет ЧУЖИЕ биты: на одной машине марку пишут многие, и затереть соседа
    /// значило бы сломать то, о чём мы не знаем.
    #[test]
    fn applying_a_value_keeps_every_bit_outside_the_region() {
        let region = Region::new(0x0000_0F00).expect("четыре бита");
        let value = region.holding(0b1010).expect("влезает");

        // Чужое слово: биты и ниже, и выше нашей области.
        let word = 0xFFFF_F0FF;
        let after = value.apply_to(word);

        assert_eq!(after & !region.mask(), word & !region.mask(), "чужое цело");
        assert_eq!(Marked::read(&region, after), 0b1010, "своё читается обратно");
    }

    /// Непересечение — единственный способ ОБЪЯВИТЬ владение вместо того, чтобы о нём помнить.
    #[test]
    fn two_regions_that_share_a_bit_are_seen_to_overlap() {
        let ours = Region::new(0x0000_0F00).expect("область");
        let theirs = Region::new(0x0000_F000).expect("область");
        let creeping = Region::new(0x0000_1F00).expect("область");

        assert!(!ours.overlaps(&theirs), "соседние области не пересекаются");
        assert!(ours.overlaps(&creeping), "один общий бит — уже пересечение");
        assert!(creeping.overlaps(&ours), "и отношение симметрично");
    }
}
