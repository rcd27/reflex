//! ФУНКТОР FRONTEND → BACKEND (#295, срез 4).
//!
//! # Что было
//!
//! Четыре бэкенда — `AfPacketBackend`, `TcAfPacketBackend`, `NfqueueBackend`,
//! `NfqAfPacketBackend` — не были связаны НИ ОДНИМ общим трейтом с методами. Совпадали только
//! имена inherent-функций (`open` / `packets` / `inject`) и тип ошибки. Смена бэкенда была
//! правкой кода потребителя, а не подстановкой типа; портируемость цепочек, обещанная §3.2,
//! структурно не поддерживалась.
//!
//! А пять маркерных трейтов (`CanObserve`, `CanInject`, `CanHold`, `CanModify`, `CanDrop`) были
//! объявлены и реализованы — **14 вхождений, из них 11 `impl`, 3 комментария и НОЛЬ ограничений**.
//! То есть цепочка, требующая вердикта, спокойно собиралась над наблюдательным бэкендом. Открытый
//! вопрос §7.1 был не то что не решён — он не был поставлен в типах.
//!
//! # Что здесь
//!
//! Два трейта — [`Source`] (откуда пакеты) и [`Sink`] (куда команды), — и морфизмы категории,
//! требующие СПОСОБНОСТИ, а не веры:
//!
//! * начать цепочку из бэкенда можно, только если он умеет наблюдать (`CanObserve`) — это держит
//!   [`observing`];
//! * закончить инъекцией — только если умеет вводить (`CanInject`). ЭТО ОБЕЩАНИЕ СЕЙЧАС НИЧЕМ НЕ
//!   ДЕРЖИТСЯ: конструкция, требовавшая `CanInject` на выходе цепочки, снесена вместе со стадийной
//!   категорией 06.09.2026, а `CanInject` остался баундом только внутри законов (`certify`).
//!   Возвращается свидетелем движка в плане алфавита (спека §4), где `e.pass()` и `e.sever(…)`
//!   существуют ровно при заявленной способности.
//!
//! Маркер перестал быть пометкой и стал ограничением. Разница проверяемая: пометку можно не
//! заметить, ограничение — нельзя.

use futures::Stream;

/// ОТКУДА БЕРУТСЯ ПАКЕТЫ.
///
/// Заимствующий `packets(&mut self)` — не уступка, а форма настоящих бэкендов: кольцо `mmap` и
/// очередь ядра принадлежат бэкенду, а поток лишь читает их. Требовать `self` значило бы
/// заставить каждый бэкенд отдать своё устройство наружу.
pub trait Source {
    type Packet;
    type Packets<'a>: Stream<Item = Self::Packet>
    where
        Self: 'a;

    fn packets(&mut self) -> Self::Packets<'_>;
}

/// КУДА УХОДЯТ КОМАНДЫ.
///
/// Ошибка — ассоциированный тип, а не общий `String`: у очереди ядра и у сырого сокета беды
/// разные, и сводить их к строке значило бы терять то единственное, по чему их различают.
pub trait Sink {
    type Command;
    type Error;

    fn emit(&mut self, command: Self::Command) -> Result<(), Self::Error>;
}

/// ДВЕРЬ К НАБЛЮДЕНИЯМ ЭТОГО БЭКЕНДА — И ЕДИНСТВЕННАЯ.
///
/// # Что этим чинится
///
/// Дверей было две: `category::from_source` и `certify::observation::watching`. Обе брали
/// `packets()` и обе требовали [`CanObserve`](crate::capability::CanObserve) — одна идея,
/// записанная дважды. Такие записи расходятся молча, и репа за это платила ключом, добываемым на
/// каждой стороне по-своему: 1136 флоу из 1136 мимо.
///
/// # Функция ничего не делает сверх `packets()`, и в этом её смысл
///
/// Она требует ЗАЯВЛЕННОЙ способности. Поток не подсунуть от типа, который наблюдать не заявлял;
/// а раз `CanObserve` требует [`Source`], заявить его пустым тоже нельзя.
///
/// # Потолка потока здесь нет — ВЫБОР, а не свойство
///
/// У живого бэкенда поток бесконечен, и обрезать его умеет только тот, у кого есть часы.
/// Альтернатива — принимать предел аргументом — отвергнута: предел принадлежит ведущему циклу и
/// меняется без ведома двери, а дверь с пределом мерила бы время вместо способности.
pub fn observing<B>(backend: &mut B) -> B::Packets<'_>
where
    B: Source + crate::capability::CanObserve,
{
    backend.packets()
}
