//! Что видно на уровне приложения — типизированно, а не байтами. Здесь, а не в модуле очереди: тип
//! не знает ни про очередь, ни про Linux, а опирается на [`Sni`] — разбор TLS, живущий тут же, в
//! ядре. В модуле носителя он уехал бы вместе с носителем, хотя нужен всякому, кто читает
//! приветствие, — носитель тут ни при чём.

use crate::tls::Sni;

/// Типизированное L7-содержимое поддержанного пакета. SNI живёт ТОЛЬКО в [`L7::TlsClientHello`] — для
/// прочих видов структурно непредставим, «взяли имя не оттуда» не собирается.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum L7 {
    /// TLS ClientHello. `sni` опционален (SNI — опциональное расширение), но КОГДА он есть, имя и
    /// диапазон неразделимы ([`Sni`]), рассинхрон между ними непредставим.
    TlsClientHello { sni: Option<Sni> },
    /// Ответ сервера: ChangeCipherSpec, Alert, Handshake или прикладные данные.
    ServerResp,
    /// Прочий или неразобранный уровень приложения.
    Other,
}
