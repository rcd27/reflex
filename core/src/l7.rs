//! ЧТО ВИДНО НА УРОВНЕ ПРИЛОЖЕНИЯ — типизированно, а не байтами.
//!
//! # Почему здесь, а не в модуле очереди
//!
//! До 05.09.2026 [`L7`] жил в `reflex-linux::nfqueue::typed` — вместе с разбором пакетов, снятых
//! с NFQUEUE. Место было неверным: тип не знает ни про очередь, ни про Linux, а опирается на
//! [`Sni`] — то есть на разбор TLS, который живёт здесь же, в ядре.
//!
//! Вскрылось это сносом: модуль очереди чистили от обвязки мёртвого потребителя, и `L7` уехал бы
//! вместе с ней, хотя нужен живому крейту (`zond`). Сборка сказала об этом сразу, и хорошо —
//! замер, сделанный по четырём именам из пяти, промолчал.

use crate::tls::Sni;

/// ТИПИЗИРОВАННЫЙ L7-СОДЕРЖИМОЕ ПОДДЕРЖАННОГО ПАКЕТА.
///
/// SNI живёт ТОЛЬКО в [`L7::TlsClientHello`] — для прочих видов он структурно непредставим, и
/// «взяли имя не оттуда» не собирается.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum L7 {
    /// TLS ClientHello. `sni` опционален (SNI — опциональное расширение TLS), но КОГДА он есть,
    /// имя и диапазон неразделимы ([`Sni`]), и рассинхрон между ними непредставим.
    TlsClientHello { sni: Option<Sni> },
    /// Ответ сервера: ChangeCipherSpec, Alert, Handshake или прикладные данные.
    ServerResp,
    /// Прочий или неразобранный уровень приложения.
    Other,
}
