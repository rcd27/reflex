//! Что драйвер обязан сделать с миром сверх ответа носителю (канон §9).
//!
//! Эффект — КОМАНДА, а не действие: функтор акта её возвращает, петля исполняет. Разделение
//! несущее, и держит оно переигровку (§10): в живом прогоне петля команду исполняет, в переигровке
//! — глушит, а сам перевод акта в команду остаётся одним и тем же чистым шагом. Сделай функтор
//! эффектным — и режим пришлось бы протаскивать внутрь него, то есть внутрь чистой части.
//!
//! Список расширяется по мере актов: обрыв даёт инъекцию, вопрос к контуру даст свой эффект.
//! Расширяется ИМЕННО список, а не форма возврата, — потому акт и отдаёт `SmallVec` эффектов, а не
//! «слово либо слово-с-пакетом»: второму акту пришлось бы перекраивать тип.

/// Команда миру, сопровождающая ответ носителю. Равенства не выводит: пакет к инъекции его не
/// имеет, и фабриковать равенство того, чья личность не наша, мы не станем — сравнивают команды по
/// породе, а не побайтно.
#[derive(Debug, Clone)]
pub enum Effect {
    /// Отправить пакет в провод. Строит его способность (`CanSever::notice` — чистая таблица
    /// `наблюдение → пакет`), отправляет драйвер: эффект принадлежит драйверу, не таблице.
    Inject(crate::command::InjectablePacket),
}
