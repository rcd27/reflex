//! СКЛЕЙКА КУСКОВ ПО СДВИГАМ — один закон на все протоколы, у которых приветствие не помещается в
//! один пакет.
//!
//! Предмет общий и встречается дважды по разным причинам: у QUIC `ClientHello` разложен по фреймам
//! `CRYPTO` и по нескольким `Initial`; у TLS поверх TCP — по нескольким сегментам, потому что
//! браузерное приветствие давно не влезает в один (GREASE, ALPN, `key_share`, десяток расширений —
//! полторы тысячи байт против пятисот у `curl`).
//!
//! # Дыра ОСТАНАВЛИВАЕТ склейку, а не заполняется
//!
//! Неполное приветствие лучше склеенного неверно, и разница не стилистическая: из неполного имя
//! просто не достанется, а из неверно склеенного достанется ЧУЖОЕ — цель будет опознана как другая.
//! Цена такой ошибки замерена в поле: продукт лечит по цели, и помеченный не тот адрес уводит в
//! обход посторонние разговоры, о которых не знает ничего.
//!
//! # Почему закон здесь, а не у каждого протокола свой
//!
//! Он и был у каждого свой: у QUIC — приватная склейка внутри модуля, у TLS поверх TCP — никакой,
//! оттого имя с живого браузерного трафика не поднималось ВОВСЕ. Две копии одного закона
//! расходятся молча; одна копия и два зовущих — нет.

/// Склеить куски по сдвигам, оборвав на первой дыре.
///
/// Сдвиг — адрес первого байта куска в потоке, от нуля. Куски могут прийти в любом порядке и
/// повторяться: порядок задаёт СДВИГ, а не приход, и повтор кладётся туда же, откуда пришёл
/// первый (то же место — те же байты).
pub fn by_offset(pieces: &[(u64, Vec<u8>)]) -> Vec<u8> {
    let ordered: std::collections::BTreeMap<u64, &Vec<u8>> =
        pieces.iter().map(|(at, data)| (*at, data)).collect();
    ordered
        .into_iter()
        .fold(Vec::new(), |acc, (offset, data)| match offset as usize == acc.len() {
            true => acc.into_iter().chain(data.iter().copied()).collect(),
            // Кусок не встык — дальше склеивать нельзя.
            false => acc,
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Куски клеятся по СДВИГАМ, а не в порядке прихода: в сети порядок не обещан никем.
    #[test]
    fn pieces_are_glued_by_offset_not_by_arrival() {
        let backwards = vec![(6u64, b"second".to_vec()), (0u64, b"first-".to_vec())];
        assert_eq!(by_offset(&backwards), b"first-second".to_vec());
    }

    /// Дыра ОСТАНАВЛИВАЕТ склейку. Из неполного имя не достанется; из склеенного через дыру
    /// достанется ЧУЖОЕ — и это хуже, чем не знать имени вовсе.
    #[test]
    fn a_gap_stops_the_assembly() {
        let with_hole = vec![(0u64, b"aaa".to_vec()), (10u64, b"bbb".to_vec())];
        assert_eq!(by_offset(&with_hole), b"aaa".to_vec());
    }

    /// Повтор куска не удваивает поток: сдвиг тот же — место то же.
    #[test]
    fn a_repeated_piece_lands_where_it_belongs() {
        let twice = vec![
            (0u64, b"head".to_vec()),
            (0u64, b"head".to_vec()),
            (4u64, b"tail".to_vec()),
        ];
        assert_eq!(by_offset(&twice), b"headtail".to_vec());
    }

    /// Пустой вход — пустой выход, без паники: куски приходят с провода, и «ещё ничего» есть
    /// обычное состояние, а не ошибка.
    #[test]
    fn nothing_glued_is_nothing() {
        assert!(by_offset(&[]).is_empty());
    }
}
