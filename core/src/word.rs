//! АДРЕСНОСТЬ: КОМУ СКАЗАНО.
//!
//! # Что отличает слово от показания
//!
//! Слово адресовано ОБЛАСТИ и потребляется соседом; показание не адресовано никому и не
//! потребляется никем — оно копится. Различает их адрес, а НЕ наклонение: суждение «этот разговор
//! в беде» ничего не велит, но говорит о разговоре, и потому у него есть область, срок и право
//! быть словом.
//!
//! # Зачем область типом
//!
//! Из области берётся срок, из срока — отложимость. Ядро держит пакет, пока цепочка не ответила;
//! значит ожидание на пакетной цепочке невыразимо, а не нежелательно. Живи область в списке трёх
//! слов, всякая новая область требовала бы правки фундамента — а строят на фундаменте другие.

/// ОБЛАСТЬ — то, чему адресуется слово.
///
/// Пустой трейт намеренно: область есть ИМЯ адресата, и всё, что о ней известно фундаменту, —
/// терпит ли она ожидание ([`CanDefer`]).
pub trait Region {}

/// СЛОВО — значение, объявившее свою область.
pub trait Word {
    /// Кому это сказано.
    type Of: Region;
}

/// ОБЛАСТЬ, РЕШЕНИЕ О КОТОРОЙ МОЖНО ОТЛОЖИТЬ.
///
/// Маркер, а не градация: градация нужна там, где запретов несколько и они разной силы. Пока
/// запрет один по существу — ждать нельзя там, где ждать нельзя физически, — маркер выражает его
/// полностью, а градация добавила бы клетки, которым нечего называть.
pub trait CanDefer: Region {}

/// ПАКЕТ В РУКАХ ЯДРА. Ждать нельзя: очередь держит его до ответа.
pub struct Packet;
/// РАЗГОВОР. Живёт до своего конца и ожидание терпит.
pub struct Conversation;
/// ЦЕЛЬ. Живёт до смены плана; откладывать можно свободно.
pub struct Target;

/// НИКОМУ — адресат пустого слова; ПРЯМОГО ИМЕНИ СНАРУЖИ НЕТ.
///
/// Область живёт в закрытом модуле без публичного пути: имя есть, дороги к нему нет. Но саму
/// область это не запирает — `<() as Word>::Of` нормализуема, пока `impl Word for ()` публичен
/// (а его требует спека), и обход баунда `To: Word` этим путём СОБИРАЕТСЯ:
/// `impl Word for Tally { type Of = <() as Word>::Of; }`. Замок здесь не запор, а лежачий
/// полицейский: он не делает обход невозможным, он делает его ЗАМЕТНЫМ. `Of = Nobody` читалось
/// бы как обычное объявление области; `Of = <() as Word>::Of` — строка, которую видно на ревью и
/// ловит греп. Запрет держится не типом, а заметностью.
///
/// РЕЗИДУУМ ОТ ЭТОГО ЗАКОНЕН и предъявлен самой спекой: `Told<()>`, `Option<()>`,
/// `SmallVec<[(); 2]>` — слова с адресом «никому», получившие его по структурным законам
/// (`Of = T::Of` при `T = ()`). Это не дефект ветки: позиция слова для безадресного значения
/// открыта и без прямого именования области.
mod nobody {
    /// Адресат пустого слова.
    pub struct Nobody;
}

pub(crate) use nobody::Nobody;

impl Region for Packet {}
impl Region for Conversation {}
impl Region for Target {}
impl Region for Nobody {}

impl CanDefer for Conversation {}
impl CanDefer for Target {}
/// Сказать нечего — значит некому и держать: ждать можно сколько угодно.
impl CanDefer for Nobody {}

/// СКАЗАТЬ НЕЧЕГО — терминальный объект категории.
///
/// Область пустого слова остаётся ВЫРАЗИМОЙ: по ней ставятся границы, как по всякой другой.
///
/// ```
/// use reflex_core::word::Word;
/// fn to_nobody<W: Word<Of = <() as Word>::Of>>() {}
/// to_nobody::<()>();
/// to_nobody::<((), ())>();
/// ```
///
/// НЕДОСТУПНО ровно одно — прямое ИМЯ области снаружи: у `Nobody` нет публичного пути, и строка
/// ниже не линкуется.
///
/// ```compile_fail
/// use reflex_core::word::Word;
/// struct Tally(u32);
/// // Прямого пути к имени области нет: `Nobody` приватно.
/// impl Word for Tally {
///     type Of = reflex_core::word::Nobody;
/// }
/// ```
///
/// Саму область это не запирает: `<() as Word>::Of` нормализуема и подставляется явно — тогда
/// обход виден на ревью и ловится грепом (см. докблок модуля, объявляющего `Nobody`, выше).
impl Word for () {
    type Of = Nobody;
}

/// Пачка слов адресована туда же, куда каждое.
impl<A: smallvec::Array> Word for smallvec::SmallVec<A>
where
    A::Item: Word,
{
    type Of = <A::Item as Word>::Of;
}

/// ДВА СЛОВА ОДНОЙ ОБЛАСТИ — одно слово той же области.
///
/// Разным областям слиться нельзя: их слова едут в разные места, и склейка была бы ложью о том,
/// кому сказано.
///
/// ```
/// use reflex_core::word::{Conversation, Word};
/// struct Sever;
/// impl Word for Sever { type Of = Conversation; }
/// struct Ordered;
/// impl Word for Ordered { type Of = Conversation; }
/// fn takes<W: Word>() {}
/// takes::<(Sever, Ordered)>();
/// ```
///
/// ```compile_fail
/// use reflex_core::word::{Conversation, Packet, Word};
/// struct Sever;
/// impl Word for Sever { type Of = Conversation; }
/// struct Verdict;
/// impl Word for Verdict { type Of = Packet; }
/// fn takes<W: Word>() {}
/// // Разным областям слиться нельзя: их слова едут в разные места.
/// takes::<(Sever, Verdict)>();
/// ```
///
/// МОМЕНТ СВОЕЙ ОБЛАСТИ НЕ ОБЪЯВЛЯЕТ: `Instant` в фундаменте — не слово, и слово со штампом
/// названо отдельной структурой ([`crate::detector::Stamped`]), а не парой с ним. Регрессия,
/// возвращающая частный закон `impl<S: Word> Word for (Instant, S)`, ловится здесь же: такой
/// `impl` пересёкся бы с законом пары выше и одновременно сделал бы нижнюю строку годной.
///
/// ```compile_fail
/// fn takes<W: reflex_core::word::Word>() {}
/// takes::<(std::time::Instant, ())>();
/// ```
impl<A: Word, B: Word<Of = A::Of>> Word for (A, B) {
    type Of = A::Of;
}

/// СЛОВО, КОТОРОГО МОЖЕТ НЕ БЫТЬ, АДРЕСОВАНО ТУДА ЖЕ, КУДА СКАЗАННОЕ.
///
/// «Промолчал» есть та же речь к тому же адресату, а не речь к никому: адресат у молчания тот, кто
/// ждал слова. Оттого пустота адреса не меняет.
impl<W: Word> Word for Option<W> {
    type Of = W::Of;
}

/// ЖДАТЬ МОЖНО ТОЛЬКО ТАМ, ГДЕ ОБЛАСТЬ ЭТО ТЕРПИТ.
///
/// Страж существует ради границы, которую нельзя перейти молча: всякий будущий оператор ожидания
/// обязан потребовать этот же баунд, и тогда ожидание на пакетной цепочке не соберётся.
///
/// ```
/// use reflex_core::word::{may_wait, Conversation, Word};
/// struct Sever;
/// impl Word for Sever { type Of = Conversation; }
/// // Разговор ожидание терпит.
/// may_wait::<Sever>();
/// ```
///
/// ```compile_fail
/// use reflex_core::word::{may_wait, Packet, Word};
/// struct Verdict;
/// impl Word for Verdict {
///     type Of = Packet;
/// }
/// // Ядро держит пакет: ожидание здесь невыразимо, а не нежелательно.
/// may_wait::<Verdict>();
/// ```
pub fn may_wait<W: Word>()
where
    W::Of: CanDefer,
{
}
