//!
//! # Что этим лечится
//!
//! Машина Мили была написана в репе шесть раз, в шести несовместимых подписях. Замер 06.09.2026:
//! `Detector::step`, `Reactor::step`, `step::Step::step`, `engine::step::step`, `Plane::feed`,
//! `NfqHandler::handle`. Шесть диалектов означают, что цепочка из звеньев разных крейтов не
//! собирается вовсе, — и оттого сшивка кончалась императивщиной.
//!
//! ЧИСЛО ЗАМЕРА, А НЕ ЧИСЛО СЕГОДНЯ: `Reactor` снесён в тот же день вместе со своим диалектом, так
//! что диалектов пять. Замер оставлен как был — он датирован, и правка задним числом стёрла бы то
//! единственное, ради чего он записан: размер беды на момент, когда её взялись лечить.
//!
//! Сводить при этом нечего: подпись уже написана ([`crate::step::Step`]). Диалекты входят в неё
//! ДИСЦИПЛИНОЙ НА АЛФАВИТЫ — много выходов есть одно значение, необязательность есть `Option`, —
//! и здесь эта дисциплина применяется.
//!
//! # Почему обёртка, а не blanket-impl
//!
//! `impl<D: Detector> Step for D` выглядит короче и НЕ СКЛАДЫВАЕТСЯ: реактор захотел бы такого же
//! blanket'а, а тип вправе реализовать оба трейта — когерентность разводит их отказом сборки.
//! Обёртка складывается со всем и не трогает ни одной из существующих реализаций: 17 приборов
//! остаются как были.
//!
//! ЦЕНА НАЗВАНА: одно перемещение структуры на шаг. Поле единственное, представление
//! прозрачное — оптимизатор его снимает, но обещать это без замера мы не будем.
//!
//! # ЧТО ЗДЕСЬ ОСТАЛОСЬ ПОСЛЕ ВПИТЫВАНИЯ
//!
//! Обёртка `Reacting` снята вместе с диалектом реактора: обёртка существует ради того, чтобы
//! чужой трейт вошёл в категорию шага, и умирает вместе с трейтом. Свою работу она сделала —
//! предъявила, что носитель общий; доказанное не нуждается в подпорке.
//!
//! Довод про несложимость blanket-impl'ов остаётся верным и относится теперь к одному
//! оставшемуся диалекту.
//!
//! Обёртка-детектор снята следом за `Reacting`: она существовала не ради подъёма, а ради того,
//! что имён было два — трейт `Detector` и трейт `Step` — и блэнкет `impl<D: Detector> Step for
//! D` невозможен как раз по озвученной выше причине (когерентность отказывает конфликтующим
//! `impl`). Прибор, у которого имя одно (реализует `Step` напрямую), входит в цепочку без
//! посредника; см. `core/tests/lifting.rs::detector_enters_the_step_category`.
