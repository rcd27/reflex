//! ВЫПУСК РАЗГОВОРА ИЗ ГОРЯЧЕГО ПУТИ.
//!
//! # Почему это закон, а не настройка
//!
//! Замер невода (#317): 3,88 мкс на пакет, из них 238 нс ВНУТРИ обработчика. Вердикт стоит 6 %,
//! остальные 94 % — дорога в userspace. Значит платим мы не за решение, а за то, что пакет вообще
//! к нам приехал.
//!
//! А приезжать ему нужно не всегда. Знание о разговоре есть элемент решётки по информации
//! ([`crate::disclosure`]), и пакет несёт информацию, только если соединение с текущим знанием
//! нетривиально: приветствие называет цель, всё остальное даёт `k ⊔ ⊥ = k`. Сотни пакетов потока
//! суть нейтральный элемент, и платить за них полную цену дороги — не «неоптимально», а следствие
//! неверно выбранной единицы вызова.
//!
//! # Обязательство названо ДО предиката
//!
//! **Разговор остаётся под наблюдением, пока его знание в ⊥.** Не «N первых пакетов»: порог по
//! счётчику взят бы из ЦЕНЫ, и то, что он больше длины рукопожатия, было бы совпадением, а не
//! свойством. Выпустить разговор до того, как он сказал о себе, значит сделать решение зависимым
//! от того, что видели МЫ, а не от того, что случилось на проводе, — и две коробки с разными
//! порогами получили бы разные планы на одном трафике.
//!
//! Это выражено сигнатурой: [`watched`] принимает [`Disclosed`], а не счётчик. Выпуск по числу
//! пакетов здесь невыразим — не потому, что запрещён, а потому, что нечем.
//!
//! # Чем платим
//!
//! Выпущенный разговор перестаёт давать наблюдения: ответ цели, авторство сброса, миг закрытия.
//! Это названо, а не скрыто, и потому у решения три источника, а не два: [`Interest`] позволяет
//! приборам удержать разговор, которым они заняты.
//!
//! # Откуда приехало (05.09.2026)
//!
//! Из `dataplane` невода. Кодирование решения (разряды метки `nft`, деление битового поля между
//! десинком, воркерами и маршрутами) осталось там: это устройство ОДНОГО носителя, а не форма
//! выпуска. Сюда приехало то, что верно для всякого перехватывающего движка.

use crate::disclosure::Disclosed;

/// НУЖНЫ ЛИ ПО ЭТОМУ РАЗГОВОРУ ПОКАЗАНИЯ ПРИБОРОВ.
///
/// Не `bool`: у двух состояний разная цена и разный смысл, и «истина» здесь ничего не говорит о
/// том, кто чего хочет. `Watching` означает, что кто-то платит полную цену дороги СОЗНАТЕЛЬНО.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Interest {
    /// Наблюдений по этому разговору никто не ждёт — можно выпускать.
    Idle,
    /// Приборы им заняты: знание дороже сэкономленной дороги.
    Watching,
}

/// ОСТАЁТСЯ ЛИ РАЗГОВОР В ГОРЯЧЕМ ПУТИ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Watch<T> {
    /// Смотреть обязаны: знание не полно, решения нет или приборы заняты.
    Hold,
    /// Решение принято и уезжает носителю — дальше разговор идёт мимо нас.
    Release(T),
}

/// ВЫПУСК ЕСТЬ ФУНКЦИЯ ТРЁХ ВЕЛИЧИН, И КАЖДАЯ ОТМЕНЯЕТ ЕГО В ОДИНОЧКУ.
///
/// Три источника сведены здесь, а не у вызывающего, ровно потому, что вызывающий, сводящий их
/// порознь, может свести неправильно: пропустить одну проверку — значит выпустить разговор,
/// который был кому-то нужен, и узнать об этом нечем.
///
/// `decision` — `Option`, а не значение: «мы ещё не решили» и «решили ничего не делать» суть
/// разные состояния, и второе выпускает, а первое нет. Поручать носителю нести то, чего мы не
/// решили, незачем.
pub fn watched<K, T>(
    knowledge: Disclosed<K>,
    decision: Option<T>,
    instruments: Interest,
) -> Watch<T> {
    match (knowledge, decision, instruments) {
        (Disclosed::Awaited, _, _) => Watch::Hold,
        (_, None, _) => Watch::Hold,
        (_, _, Interest::Watching) => Watch::Hold,
        (Disclosed::Spoken(_), Some(decided), Interest::Idle)
        | (Disclosed::Silent, Some(decided), Interest::Idle) => Watch::Release(decided),
    }
}
