//! Выпуск разговора из горячего пути (канон §9). Замер (#317): 3,88 мкс на пакет, из них 238 нс
//! внутри обработчика — вердикт стоит 6 %, остальные 94 % дорога в userspace. Приезжать пакету нужно
//! не всегда: знание о разговоре — элемент полурешётки по информации ([`crate::disclosure`]), пакет
//! несёт информацию, только если соединение с текущим знанием нетривиально (`k ⊔ ⊥ = k` для сотен
//! пакетов потока). Обязательство названо ДО предиката: **разговор под наблюдением, пока знание в
//! ⊥** — не «N пакетов» (порог из ЦЕНЫ сделал бы решение зависимым от нас, не от провода). Выражено
//! сигнатурой: [`watched`] принимает [`Disclosed`], не счётчик — выпуск по числу пакетов невыразим.
//! Цена: выпущенный разговор наблюдений не даёт — оттого у решения три источника, и [`Interest`]
//! позволяет приборам удержать занятый разговор. Кодирование метки — устройство одного носителя,
//! осталось у продукта.

use crate::disclosure::Disclosed;

/// Нужны ли по этому разговору показания приборов. Не `bool`: у двух состояний разная цена и смысл.
/// `Watching` означает, что кто-то платит полную цену дороги СОЗНАТЕЛЬНО.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Interest {
    /// Наблюдений по этому разговору никто не ждёт — можно выпускать.
    Idle,
    /// Приборы им заняты: знание дороже сэкономленной дороги.
    Watching,
}

/// Остаётся ли разговор в горячем пути.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Watch<T> {
    /// Смотреть обязаны: знание не полно, решения нет или приборы заняты.
    Hold,
    /// Решение принято и уезжает носителю — дальше разговор идёт мимо нас.
    Release(T),
}

/// Выпуск есть функция трёх величин, каждая отменяет его в одиночку. Сведены здесь, не у
/// вызывающего: сводящий их порознь может свести неправильно (пропустить проверку — выпустить
/// нужный кому-то разговор). `decision` — `Option`: «ещё не решили» и «решили ничего не делать» —
/// разные состояния, второе выпускает, первое нет.
pub fn watched<K, T>(
    knowledge: Disclosed<K>,
    decision: Option<T>,
    instruments: Interest,
) -> Watch<T> {
    match (knowledge, decision, instruments) {
        (Disclosed::Awaited, _, _) => Watch::Hold,
        (_, None, _) => Watch::Hold,
        (_, _, Interest::Watching) => Watch::Hold,
        (Disclosed::Spoken(_), Some(decided), Interest::Idle)
        | (Disclosed::Silent, Some(decided), Interest::Idle) => Watch::Release(decided),
    }
}
