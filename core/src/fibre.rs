//! Расслоение: политики слоя — его жизнь и его мощность (канон §4). Ключ расслаивает область;
//! неограниченный ключ есть неограниченная память, потому срок жизни слоя и число слоёв —
//! объявляемы, а не подразумеваемы.

use std::time::Duration;

/// Жизнь слоя по ключу.
pub enum Lifetime {
    /// Ключей конечное число — ноги, классы, порты. Состояние живёт до конца потока: расти некуда.
    Bounded,
    /// Ключей неограниченно много — соединения, цели, сессии. Состояние снимается, когда по ключу не
    /// было события дольше срока. Срок берётся заведомо больше окон детекторов, живущих в нём:
    /// снятое раньше теряет беду, о которой детектор ещё не сказал.
    UntilIdle(Duration),
}

/// Мощность расслоения — сколько слоёв держим.
pub enum Keys {
    /// Ключей конечное число. Память ограничена, слои живут до конца потока. Заявление, не молчание.
    Finite,
    /// Ключей неограниченно много — держим не более `n`; при переполнении уходит слой, к которому
    /// дольше всего не обращались. Цена: вытесненный слой теряет накопленное и, вернувшись, начинает
    /// с нуля — честнее роста без границы, у долгоживущего процесса кончающегося падением.
    AtMost(usize),
}
