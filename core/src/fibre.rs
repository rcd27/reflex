//! РАССЛОЕНИЕ: политики слоя — его жизнь и его мощность.
//!
//! Ключ расслаивает область (канон §4); неограниченный ключ есть неограниченная память, потому
//! срок жизни слоя и число слоёв — ОБЪЯВЛЯЕМЫ, а не подразумеваемы.

use std::time::Duration;

/// ЖИЗНЬ СЛОЯ ПО КЛЮЧУ.
pub enum Lifetime {
    /// КЛЮЧЕЙ КОНЕЧНОЕ ЧИСЛО — ноги, классы, порты. Состояние живёт до конца потока: расти ему
    /// некуда.
    Bounded,
    /// КЛЮЧЕЙ НЕОГРАНИЧЕННО МНОГО — соединения, цели, сессии. Состояние снимается, когда по ключу
    /// не было ни одного события дольше срока. Срок берётся заведомо большим, чем окна детекторов,
    /// живущих в нём: снятое раньше времени теряет беду, о которой детектор ещё не сказал.
    UntilIdle(Duration),
}

/// МОЩНОСТЬ РАССЛОЕНИЯ — сколько слоёв держим.
pub enum Keys {
    /// КЛЮЧЕЙ КОНЕЧНОЕ ЧИСЛО. Память ограничена, слои живут до конца потока. Заявление, а не
    /// молчание.
    Finite,
    /// КЛЮЧЕЙ НЕОГРАНИЧЕННО МНОГО — держим не более `n`; при переполнении уходит слой, к которому
    /// дольше всего не обращались. ЦЕНА: вытесненный слой теряет накопленное и, вернувшись,
    /// начинает с нуля — честнее роста без границы, у долгоживущего процесса кончающегося падением.
    AtMost(usize),
}
