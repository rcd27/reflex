//! ЧАСЫ — ЕДИНСТВЕННЫЙ ИСТОЧНИК ВРЕМЕНИ И ЕДИНСТВЕННЫЙ ИСТОЧНИК ТИКА.
//!
//! # Закон уже был записан, только применён к одной половине
//!
//! [`crate::pcap::with_ticks`] говорит про запись дословно: «Живой провод тиков не несёт: молчание
//! есть ОТСУТСТВИЕ событий, а отсутствие событий не порождает элементов потока. Часы добавляет
//! тот, кто читает провод, — и для записи это делать обязан ИСТОЧНИК, иначе всякий потребитель
//! напишет своё, по-разному».
//!
//! Для записи вывод сделали. Для живого провода — нет, и случилось дословно предсказанное: замер
//! 03.09.2026 нашёл СЕМНАДЦАТЬ мест вне тестов, порождающих время самостоятельно, в пяти разных
//! формах — `thread::spawn(loop { sleep })`, `stream::unfold` + `sleep`, `tokio::interval`,
//! `Instant::now()` внутри обработчика, отдельный тред здоровья.
//!
//! # Что от этого сломалось у человека
//!
//! У плоскости невода 2 `Tick` вычисляется ВНУТРИ обработчика пакета. Нет пакетов — время стоит,
//! и всё, что заводилось ради тишины, в тишине не срабатывает: `Freshness::Silent`,
//! `meter::expired`, `Sighting::Stale`, `Sighting::Lost`. У последнего производителя в живом коде
//! нет ВОВСЕ, и это записано в его собственном паспорте. Мёртвая нога умирает ровно тогда, когда
//! трафика нет, — то есть прибор слеп именно к тому случаю, ради которого заведён.
//!
//! Модель это уже доказала: `model/law/Instrument`, клетка `traffic` — `NoFalseAlarm` ЗЕЛЁНЫЙ,
//! `PainNeverSilent` КРАСНЫЙ, и контрпример обязательно идёт через тишину. Прибор, ведомый чужим
//! пакетом, честен и бесполезен.
//!
//! # ЧАСЫ ЗДЕСЬ — ТРЕЙТ, А СИСТЕМНЫЕ ЧАСЫ ЖИВУТ В `reflex-runtime`
//!
//! `reflex-core` не знает рантайма — ни tokio, ни потоков; это его свойство, а не недостача.
//! Спать умеет край, и системные часы живут там же, где остальной IO. Здесь — контракт и
//! [`TestClock`], которому спать не нужно по построению.
//!
//! # ЛОВУШКА ВИРТУАЛЬНЫХ ЧАСОВ НАЗВАНА, ПОТОМУ ЧТО УЖЕ ОПЛАЧЕНА
//!
//! Виртуальное время доказывает «сколько прошло», но НЕ «оператор проснулся»: на этом наступали в
//! #287, где три зелёных теста не поймали потерянный waker. Отсюда правило для всякого
//! потребителя: рядом с проверкой на [`TestClock`] обязан стоять контроль на РЕАЛЬНЫХ часах.
//! Здесь его нет и быть не может — реальных часов в этом крейте нет вовсе.

use core::time::Duration;
use std::time::Instant;

use futures::Stream;

/// ОТКУДА БЕРЁТСЯ ВРЕМЯ И КТО ПОРОЖДАЕТ ЕГО В ТИШИНЕ.
///
/// Два метода, и второй — весь смысл. `now` отвечает на вопрос «который час» тому, у кого уже
/// есть повод спросить; `ticks` порождает повод там, где его не создаёт никто: в молчании.
///
/// Часы отдаются потребителю ЗНАЧЕНИЕМ, а не берутся из глобального `Instant::now()`. Иначе тест
/// не может двигать время, и всё, что живёт во времени, проверяется ожиданием — то есть медленно,
/// хрупко и приблизительно.
pub trait Clock: Clone {
    /// Который час по этим часам.
    fn now(&self) -> Instant;
}

/// ЧАСЫ, БУДЯЩИЕ ПОТОК — для тех, кто живёт в асинхронном рантайме.
///
/// Отдельно от [`Beats`], и это не церемония: ждать можно ровно двумя несовместимыми способами —
/// отдав управление рантайму или заняв поток. Часы, умеющие оба, обязаны тянуть рантайм, а
/// плоскость его не тянет и не должна: она синхронна и performance-first. Один трейт на оба
/// способа заставил бы её платить за то, чем она не пользуется.
pub trait Ticks: Clock {
    /// ПОТОК МОМЕНТОВ С ШАГОМ `every` — время, порождаемое в тишине.
    ///
    /// Поток бесконечен: часы не кончаются оттого, что кончился трафик. Заканчивает его
    /// потребитель, роняя приёмник, — и это единственный способ остановить часы, потому что
    /// единственный, который выражает намерение «мне больше не надо».
    fn ticks(&self, every: Duration) -> impl Stream<Item = Instant> + Unpin;
}

/// ЧАСЫ, БУДЯЩИЕ ПОТОК ИСПОЛНЕНИЯ — для тех, у кого рантайма нет.
///
/// Итератор, а не поток: у синхронного потребителя нет никого, кому отдать управление, и
/// ожидание для него есть занятие собственного потока. Так живёт плоскость — тред, чьё
/// единственное дело двигать время.
pub trait Beats: Clock {
    /// Моменты сетки, приходящие по мере наступления. Бесконечны по той же причине, что и
    /// [`Ticks::ticks`].
    fn beats(&self, every: Duration) -> impl Iterator<Item = Instant>;
}

/// ЧАСЫ, КОТОРЫЕ ДВИГАЕТ ТЕСТ.
///
/// Спать не умеют и не должны: сценарий во времени пишется как сценарий
/// (`сделал → продвинул → проверил`), а не как последовательность ожиданий. Прогон занимает
/// столько, сколько занимает вычисление, и не зависит от того, час в сценарии или сутки.
///
/// # ТИКИ ИДУТ ПО СЕТКЕ, А НЕ ОТ ПОСЛЕДНЕГО ПРОДВИЖЕНИЯ
///
/// То же правило, к которому пришли часы записи ([`crate::pcap::with_ticks`]): сетка отмеряется
/// от начала, а не от предыдущего события. Иначе два продвижения по полшага не дают ни одного
/// тика, хотя шаг прошёл, — и окно не закрывается там, где обязано.
#[derive(Clone)]
pub struct TestClock {
    began: Instant,
    /// Сколько времени продвинуто с начала. Наносекундами: `Duration` не атомарен, а разделяемое
    /// изменяемое состояние здесь неизбежно — тест двигает время, поток его читает.
    passed: std::sync::Arc<std::sync::atomic::AtomicU64>,
}

impl TestClock {
    pub fn new() -> TestClock {
        TestClock {
            began: Instant::now(),
            passed: std::sync::Arc::new(std::sync::atomic::AtomicU64::new(0)),
        }
    }

    /// ПРОДВИНУТЬ ВРЕМЯ. Всё, что должно случиться за `span`, случается.
    pub fn advance(&self, span: Duration) {
        self.passed
            .fetch_add(span.as_nanos() as u64, std::sync::atomic::Ordering::Relaxed);
    }

    /// Сколько прошло с начала.
    fn elapsed(&self) -> Duration {
        Duration::from_nanos(self.passed.load(std::sync::atomic::Ordering::Relaxed))
    }
}

impl Default for TestClock {
    fn default() -> TestClock {
        TestClock::new()
    }
}

impl Clock for TestClock {
    fn now(&self) -> Instant {
        self.began + self.elapsed()
    }
}

impl TestClock {
    /// Сколько тиков сетки уже наступило к этому моменту.
    ///
    /// ЗАКОН СЕТКИ ОБЩИЙ ДЛЯ ВСЕХ ЧАСОВ (05.09.2026) — [`crate::grid`]. Здесь он был написан
    /// своей копией, и копия отвечала на нулевой шаг `u64::MAX` тиков: число, выглядящее как
    /// «очень много» там, где верно «сетки нет».
    fn due(&self, every: Duration) -> u64 {
        crate::grid::due(self.began, self.now(), every)
    }

    /// Момент `n`-го тика сетки. Считается ОТ НАЧАЛА: два тика, выданных одним продвижением,
    /// обязаны иметь разное время, иначе интервал между ними станет нулём.
    fn beat_at(&self, every: Duration, nth: u64) -> Instant {
        crate::grid::node(self.began, every, nth)
    }
}

impl Beats for TestClock {
    /// ТИКИ, УЖЕ НАСТУПИВШИЕ, И НИ ОДНОГО СВЕРХ. Итератор КОНЧАЕТСЯ, когда время догнало сетку, —
    /// и это отличие тестовых часов от системных названо здесь, а не спрятано: системные ждали бы
    /// следующего, тестовым ждать некого. Сценарий от этого не страдает, он и пишется как
    /// «продвинул, потом собрал».
    fn beats(&self, every: Duration) -> impl Iterator<Item = Instant> {
        let clock = self.clone();
        (1..=self.due(every)).map(move |nth| clock.beat_at(every, nth))
    }
}

impl Ticks for TestClock {
    fn ticks(&self, every: Duration) -> impl Stream<Item = Instant> + Unpin {
        Box::pin(futures::stream::unfold(
            (self.clone(), 0u64),
            move |(clock, handed)| async move {
                // СКОЛЬКО ТИКОВ СЕТКИ УЖЕ НАСТУПИЛО. Ждать нечего: время двигает тест, и если
                // очередной тик ещё не наступил, поток обязан отдать управление, а не крутиться.
                let due = crate::grid::due(clock.began, clock.now(), every);
                match due > handed {
                    true => {
                        let at = crate::grid::node(clock.began, every, handed + 1);
                        Some((at, (clock, handed + 1)))
                    }
                    // ВРЕМЯ ЕЩЁ НЕ ПРИШЛО — поток ЗАКАНЧИВАЕТСЯ, а не висит.
                    //
                    // Виснуть здесь было бы честнее по смыслу («тиков пока нет»), но требовало бы
                    // будильника, то есть рантайма, которого у этого крейта нет. Цена названа:
                    // потребитель берёт у тестовых часов ровно те тики, что уже наступили, и
                    // берёт их СНОВА после следующего `advance`. Сценарий от этого не страдает —
                    // он и пишется как «продвинул, потом собрал», — а вот поток, слитый с
                    // событиями раз и навсегда, на тестовых часах кончится раньше событий.
                    false => None,
                }
            },
        ))
    }
}

/// СИСТЕМНЫЕ ЧАСЫ ДЛЯ СИНХРОННОГО ПОТРЕБИТЕЛЯ.
///
/// Живут в ядре, а не в рантайме, потому что `std::thread::sleep` рантайма не требует — требует
/// его только асинхронное пробуждение. Ошибиться здесь легко и дорого: положи их в рантайм, и
/// плоскость, которой нужен один тред со сном, потянула бы tokio целиком.
///
/// Пустой тип намеренно: у системных часов нет состояния, которое имело бы смысл настраивать, и
/// два экземпляра обязаны показывать одно и то же. Значение существует ради того, чтобы часы
/// ПЕРЕДАВАЛИСЬ, а не брались из воздуха вызовом `Instant::now()` посреди чужой логики — только
/// переданные часы подменяются в тесте.
#[derive(Debug, Clone, Copy, Default)]
pub struct OsClock;

impl Clock for OsClock {
    fn now(&self) -> Instant {
        Instant::now()
    }
}

impl Beats for OsClock {
    /// СЕТКА ОТМЕРЯЕТСЯ ОТ НАЧАЛА, А СОН — ДО СЛЕДУЮЩЕГО ЕЁ УЗЛА.
    ///
    /// Спать ровно `every` было бы проще и неверно: работа потребителя добавляется к каждому шагу,
    /// и сетка уезжает тем быстрее, чем он занятее. Прибор, чей шаг зависит от собственной
    /// загрузки, мерит не мир, а себя.
    ///
    /// ОТСТАВШИЕ УЗЛЫ СХЛОПЫВАЮТСЯ, а не выдаются залпом. Залп есть ошибка СОБЫТИЙНАЯ — пачка
    /// закрытий окна с одинаковым смыслом, — и выглядит она как настоящая беда ровно в тот
    /// момент, когда система под нагрузкой. Сдвиг сетки при заминке есть ошибка ВЕЛИЧИНЫ, и она
    /// видна как величина.
    fn beats(&self, every: Duration) -> impl Iterator<Item = Instant> {
        let began = Instant::now();
        // ВЫРОЖДЕННАЯ СЕТКА ПУСТА, а не бесконечна. У шага в ноль узлов нет, и прежняя редакция
        // на таком шаге крутила бы поток без единого сна, выдавая один и тот же момент.
        let nodes = match every.is_zero() {
            true => 1u64..1,
            false => 1u64..u64::MAX,
        };
        nodes.filter_map(move |nth| {
            let due = crate::grid::node(began, every, nth);
            match due.checked_duration_since(Instant::now()) {
                // Узел уже позади — мы отстали; выдаём его без сна, но и без залпа: следующий
                // вызов возьмёт следующий узел, а не все пропущенные разом.
                None => Some(due),
                Some(left) => {
                    std::thread::sleep(left);
                    Some(due)
                }
            }
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use futures::StreamExt;

    /// ЧАСЫ, КОТОРЫЕ НЕ ДВИГАЛИ, НЕ ИДУТ. Иначе тест доказывал бы не «прошло время», а «прошло
    /// время прогона», и сценарий стал бы зависеть от скорости машины.
    #[test]
    fn a_clock_nobody_advanced_does_not_move() {
        let clock = TestClock::new();
        let first = clock.now();
        assert_eq!(clock.now(), first, "время пошло само");
    }

    #[test]
    fn advancing_moves_the_clock_by_exactly_that_much() {
        let clock = TestClock::new();
        let began = clock.now();
        clock.advance(Duration::from_secs(5));
        assert_eq!(clock.now() - began, Duration::from_secs(5));
    }

    /// СИНХРОННЫЙ ПОТРЕБИТЕЛЬ ПОЛУЧАЕТ ТУ ЖЕ СЕТКУ, что и потоковый.
    ///
    /// Два способа ждать — одно время. Разойдись они, и плоскость с лентой мерили бы окна разной
    /// длины, оставаясь каждая по-своему правой: ровно та беда, ради снятия которой часы и стали
    /// примитивом.
    #[test]
    fn the_synchronous_consumer_sees_the_same_grid() {
        let clock = TestClock::new();
        let began = clock.now();
        clock.advance(Duration::from_millis(250));
        assert_eq!(
            clock
                .beats(Duration::from_millis(100))
                .map(|at| at - began)
                .collect::<Vec<Duration>>(),
            vec![Duration::from_millis(100), Duration::from_millis(200)],
            "синхронные удары разошлись с потоковыми тиками"
        );
    }

    /// СИСТЕМНЫЕ ЧАСЫ БУДЯТ СИНХРОННЫЙ ПОТОК САМИ — контроль на РЕАЛЬНЫХ часах.
    ///
    /// Без него виртуальное время доказывает «сколько прошло», но не «нас разбудили»: оплачено
    /// #287, где три зелёных теста не поймали потерянный waker. Здесь проверяется, что удары
    /// приходят без единого события извне и что время между ними настоящее.
    #[test]
    fn the_os_clock_wakes_a_thread_by_itself() {
        let began = Instant::now();
        let beats: Vec<Instant> = OsClock.beats(Duration::from_millis(10)).take(3).collect();
        assert_eq!(beats.len(), 3, "часы не разбудили поток сами");
        assert!(
            began.elapsed() >= Duration::from_millis(30),
            "три удара по 10 мс пришли быстрее тридцати — часы не ждали"
        );
    }

    /// ТИКОВ РОВНО СТОЛЬКО, СКОЛЬКО ШАГОВ УЛОЖИЛОСЬ.
    #[tokio::test]
    async fn a_silent_advance_yields_the_ticks_that_fit() {
        let clock = TestClock::new();
        clock.advance(Duration::from_millis(250));
        let ticks: Vec<Instant> = clock.ticks(Duration::from_millis(100)).collect().await;
        assert_eq!(ticks.len(), 2, "тик выдан не за каждый прошедший шаг");
    }

    /// СЕТКА ОТМЕРЯЕТСЯ ОТ НАЧАЛА, А НЕ ОТ ПОСЛЕДНЕГО ПРОДВИЖЕНИЯ.
    ///
    /// Два продвижения по полшага дают ОДИН тик: шаг прошёл. Считай часы от последнего
    /// продвижения — и не дали бы ни одного, а окно, которое обязано закрыться, не закрылось бы.
    /// Ровно та ошибка, что уже была исправлена в часах записи.
    #[tokio::test]
    async fn the_grid_is_measured_from_the_start_not_from_the_last_advance() {
        let clock = TestClock::new();
        clock.advance(Duration::from_millis(60));
        clock.advance(Duration::from_millis(60));
        let ticks: Vec<Instant> = clock.ticks(Duration::from_millis(100)).collect().await;
        assert_eq!(ticks.len(), 1, "полшага плюс полшага не дали шага");
    }

    /// ТИКИ НЕСУТ МОМЕНТ СЕТКИ, А НЕ МОМЕНТ ВЫДАЧИ.
    ///
    /// Иначе окно, закрытое тиком, мерило бы не свою длину: два тика, выданных одним
    /// продвижением, получили бы одно и то же время, и интервал между ними стал бы нулём.
    #[tokio::test]
    async fn every_tick_carries_its_own_moment_on_the_grid() {
        let clock = TestClock::new();
        let began = clock.now();
        clock.advance(Duration::from_millis(250));
        let ticks: Vec<Instant> = clock.ticks(Duration::from_millis(100)).collect().await;
        assert_eq!(
            ticks
                .iter()
                .map(|at| *at - began)
                .collect::<Vec<Duration>>(),
            vec![Duration::from_millis(100), Duration::from_millis(200)],
            "два тика пришли с одним временем — интервал между ними стал нулём"
        );
    }
}
