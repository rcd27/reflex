/// БЭКЕНД УМЕЕТ ЧИТАТЬ КОПИЮ КАЖДОГО ПАКЕТА, НЕ ВМЕШИВАЯСЬ В ЕГО ХОД.
///
/// # Предмет у этой способности — поток, а не метод
///
/// В отличие от [`CanInject`], своего метода здесь нет и не нужно: наблюдение уже выражено
/// [`Source::packets`](crate::backend::Source::packets), и добавлять второй способ отдавать
/// пакеты значило бы держать два ответа на один вопрос. Достаточно супертрейта — он и есть
/// предмет: заявить «умею наблюдать», не отдавая потока, больше нельзя.
///
/// Вторая половина смысла — «не вмешиваясь» — типом не выражается вовсе и остаётся ЗАКОНУ:
/// все N пакетов обязаны доехать до дальнего конца. Наблюдатель, роняющий пакеты, синтаксически
/// неотличим от честного, и это ровно та граница, где тип кончается, а прибор начинается.
///
/// # Заявить, не отдавая потока, нельзя
///
/// ```compile_fail,E0277
/// use reflex_core::capability::CanObserve;
///
/// // Ни одного пакета наружу: `Source` не реализован.
/// struct Blind;
/// impl CanObserve for Blind {}
/// ```
pub trait CanObserve: crate::backend::Source {}

/// БЭКЕНД УМЕЕТ ВВОДИТЬ ПАКЕТЫ В СЕТЬ.
///
/// # Почему у способности есть МЕТОД, а не пустое тело
///
/// Замер 05.09.2026: пять способностей были пустыми маркерами, и на живых бэкендах висело
/// **16 заявлений, ни одно из которых ничем не установлено**. Хуже: у десяти из них не было
/// ПРЕДМЕТА — `NfqueueBackend` заявлял все пять, не реализуя ни [`Source`](crate::backend::Source),
/// ни [`Sink`], а `CanDrop` у `TcAfPacketBackend` было нечем выразить, потому что его сток
/// принимал `Vec<u8>`: в байтах «дропни этот поток» не скажешь.
///
/// Пустой маркер — это заявление, которое нельзя ни подтвердить, ни опровергнуть. Метод убирает
/// ровно это: сказать «умею вводить» можно только назвав, КАК инъекция становится командой
/// ЭТОГО стока. Заявление обретает предмет в момент, когда оно делается.
///
/// Разделение труда: **тип убивает ПУСТОЕ заявление, закон убивает ЛОЖНОЕ** (команда построена, а
/// на провод ничего не вышло), гейт `capability_claim` ловит обход синтаксиса.
///
/// Команда остаётся СВОИМ типом бэкенда, а не общим `Command`: сток, принимающий варианты,
/// которых он не умеет, обязан был бы отвечать ошибкой в рантайме — то есть на месте пустого
/// заявления встала бы тихая мина.
///
/// # Заявить, не построив команду, нельзя
///
/// ```compile_fail,E0046
/// use reflex_core::backend::Sink;
/// use reflex_core::capability::CanInject;
///
/// struct Mute;
/// impl Sink for Mute {
///     type Command = ();
///     type Error = ();
///     fn emit(&mut self, _command: ()) -> Result<(), ()> { Ok(()) }
/// }
///
/// // Пустое заявление: способ построить команду инъекции не назван.
/// impl CanInject for Mute {}
/// ```
pub trait CanInject: crate::backend::Sink {
    /// КАК инъекция становится командой ЭТОГО стока. Ассоциированная функция, а не метод:
    /// построение команды не требует открытого бэкенда, и требовать `&self` значило бы запрещать
    /// собирать команду до того, как калитка открыта.
    fn inject(packet: crate::command::InjectablePacket) -> Self::Command;
}

/// Backend can hold a packet pending a verdict (accept/drop/modify).
pub trait CanHold {}

/// Backend can modify a packet in-place before forwarding.
pub trait CanModify {}

/// Backend can drop a packet, preventing it from reaching its destination.
pub trait CanDrop {}
