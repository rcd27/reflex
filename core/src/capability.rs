/// БЭКЕНД УМЕЕТ ЧИТАТЬ КОПИЮ КАЖДОГО ПАКЕТА, НЕ ВМЕШИВАЯСЬ В ЕГО ХОД.
///
/// # Предмет у этой способности — поток, а не метод
///
/// В отличие от [`CanInject`], своего метода здесь нет и не нужно: наблюдение уже выражено
/// [`Source::packets`](crate::backend::Source::packets), и добавлять второй способ отдавать
/// пакеты значило бы держать два ответа на один вопрос. Достаточно супертрейта — он и есть
/// предмет: заявить «умею наблюдать», не отдавая потока, больше нельзя.
///
/// Вторая половина смысла — «не вмешиваясь» — типом не выражается вовсе и остаётся ЗАКОНУ:
/// все N пакетов обязаны доехать до дальнего конца. Наблюдатель, роняющий пакеты, синтаксически
/// неотличим от честного, и это ровно та граница, где тип кончается, а прибор начинается.
///
/// # Заявить, не отдавая потока, нельзя
///
/// ```compile_fail,E0277
/// use reflex_core::capability::CanObserve;
///
/// // Ни одного пакета наружу: `Source` не реализован.
/// struct Blind;
/// impl CanObserve for Blind {}
/// ```
pub trait CanObserve: crate::backend::Source {}

/// БЭКЕНД УМЕЕТ ВВОДИТЬ ПАКЕТЫ В СЕТЬ.
///
/// # Почему у способности есть МЕТОД, а не пустое тело
///
/// Замер 05.09.2026: пять способностей были пустыми маркерами, и на живых бэкендах висело
/// **16 заявлений, ни одно из которых ничем не установлено**. Хуже: у десяти из них не было
/// ПРЕДМЕТА — `NfqueueBackend` заявлял все пять, не реализуя ни [`Source`](crate::backend::Source),
/// ни [`Sink`], а `CanDrop` у `TcAfPacketBackend` было нечем выразить, потому что его сток
/// принимал `Vec<u8>`: в байтах «дропни этот поток» не скажешь.
///
/// Пустой маркер — это заявление, которое нельзя ни подтвердить, ни опровергнуть. Метод убирает
/// ровно это: сказать «умею вводить» можно только назвав, КАК инъекция становится командой
/// ЭТОГО стока. Заявление обретает предмет в момент, когда оно делается.
///
/// Разделение труда: **тип убивает ПУСТОЕ заявление, закон убивает ЛОЖНОЕ** (команда построена, а
/// на провод ничего не вышло), гейт `capability_claim` ловит обход синтаксиса.
///
/// Команда остаётся СВОИМ типом бэкенда, а не общим `Command`: сток, принимающий варианты,
/// которых он не умеет, обязан был бы отвечать ошибкой в рантайме — то есть на месте пустого
/// заявления встала бы тихая мина.
///
/// # Заявить, не построив команду, нельзя
///
/// ```compile_fail,E0046
/// use reflex_core::backend::Sink;
/// use reflex_core::capability::CanInject;
///
/// struct Mute;
/// impl Sink for Mute {
///     type Command = ();
///     type Error = ();
///     fn emit(&mut self, _command: ()) -> Result<(), ()> { Ok(()) }
/// }
///
/// // Пустое заявление: способ построить команду инъекции не назван.
/// impl CanInject for Mute {}
/// ```
pub trait CanInject: crate::backend::Sink {
    /// КАК инъекция становится командой ЭТОГО стока. Ассоциированная функция, а не метод:
    /// построение команды не требует открытого бэкенда, и требовать `&self` значило бы запрещать
    /// собирать команду до того, как калитка открыта.
    fn inject(packet: crate::command::InjectablePacket) -> Self::Command;
}

/// БЭКЕНД УДЕРЖИВАЕТ ПАКЕТ, ПОКА МЫ РЕШАЕМ.
///
/// # Почему предмет — ОТПУСКАНИЕ, а не удержание
///
/// Удержание не выражается командой, и это не пробел, а его природа: пакет ждёт ровно потому, что
/// мы ЕЩЁ НЕ ОТВЕТИЛИ. Само существование [`Answered`](crate::held::Answered) и значит «в ядре
/// висит пакет», а `#[must_use]` на нём — машинная охрана того, чтобы висел не вечно.
///
/// Отсюда предмет: [`release`](Self::release) — слово, которым удержанный отпускается БЕЗ
/// изменений. Удержание без отпускания есть состояние без выхода, а пакет, который держат вечно,
/// для человека неотличим от дропа — только тише.
///
/// # Почему супертрейт — `Terminal`, а не `Sink`
///
/// Прежняя редакция стояла над [`Sink`] и оперировала [`Flow`](crate::types::Flow) — то есть
/// удержанием ПОТОКА. Это была ошибка адреса, и она обошлась в ноль реализаций: вердикт очереди
/// требует владения ТЕМ САМЫМ сообщением, а `Sink` берёт команду, ничего не зная о носителе.
/// `held.rs` установил это, разведя решение и эффект; способность переехала следом.
///
/// Разница не косметическая. Над `Sink` живут способности, ставящие в ядро ПРАВИЛО (оно действует
/// до снятия — таков [`CanDrop`]); над `Terminal` — отвечающие ОДНОМУ удержанному пакету. Свести
/// их в одно имя значило бы стереть различие между «этот пакет не пойдёт» и «поток не идёт».
///
/// # Заявить, не назвав слова отпускания, нельзя
///
/// ```compile_fail,E0046
/// use reflex_core::capability::CanHold;
/// use reflex_core::held::{Answered, Delivered, Refused, Terminal};
///
/// struct Immediate;
/// impl Terminal for Immediate {
///     type Carrier = ();
///     type Answer = ();
///     type Refusal = ();
///     fn apply(&mut self, answered: Answered<(), ()>)
///         -> Result<Delivered<()>, Refused<(), ()>> {
///         Ok(Delivered { at: answered.at, answer: answered.answer })
///     }
/// }
///
/// impl CanHold for Immediate {}
/// ```
pub trait CanHold: crate::held::Terminal {
    /// КАКИМ СЛОВОМ АЛФАВИТА удержанный отпускается без изменений.
    fn release() -> Self::Answer;
}

/// БЭКЕНД УМЕЕТ НЕ ПРОПУСТИТЬ УДЕРЖАННЫЙ ПАКЕТ.
///
/// Брат [`CanDrop`] по смыслу и не он по адресу: тот ставит в ядро правило на ПОТОК, живущее до
/// снятия, а это — ответ ОДНОМУ пакету, который мы держим. Пакет не дойдёт до адресата, и на
/// следующий это никак не влияет.
///
/// Пары «и как снять обратно» здесь нет намеренно, и это не забывчивость: снимать нечего.
/// Одноразовый ответ не оставляет в мире состояния — тем он и отличается от правила, которое
/// [`CanDrop::clear_flow`] обязан уметь убрать.
///
/// ```compile_fail,E0046
/// use reflex_core::capability::CanRefuse;
/// use reflex_core::held::{Answered, Delivered, Refused, Terminal};
///
/// struct Passing;
/// impl Terminal for Passing {
///     type Carrier = ();
///     type Answer = ();
///     type Refusal = ();
///     fn apply(&mut self, answered: Answered<(), ()>)
///         -> Result<Delivered<()>, Refused<(), ()>> {
///         Ok(Delivered { at: answered.at, answer: answered.answer })
///     }
/// }
///
/// impl CanRefuse for Passing {}
/// ```
pub trait CanRefuse: crate::held::Terminal {
    /// КАКИМ СЛОВОМ АЛФАВИТА выражается «этот пакет дальше не пойдёт».
    fn refuse() -> Self::Answer;
}

/// БЭКЕНД УМЕЕТ ОТПУСТИТЬ УДЕРЖАННЫЙ ПАКЕТ, ПОМЕТИВ ЕГО ДЛЯ ТЕХ, КТО НИЖЕ.
///
/// # Единственная способность, чей эффект НЕ ВИДЕН НА ПРОВОДЕ
///
/// Метка не уезжает в сеть — она живёт внутри ядра и адресована не собеседнику, а правилам,
/// стоящим ниже по обходу. Отсюда и особенность её закона: свидетелем не может быть тот, кто
/// смотрит на провод. Свидетельствовать способен только ЧИТАТЕЛЬ метки — правило со счётчиком,
/// поставленное ниже очереди.
///
/// # Грабля, ради которой закон и заводится
///
/// Пакет продолжает обход С МЕСТА, ГДЕ ЕГО ЗАБРАЛИ. Правило, читающее метку, обязано стоять НИЖЕ
/// правила очереди; поставь его выше — метка встанет и не будет прочитана никем, а прибор покажет
/// «решение принято». Это знание записано в коде (`Answer::Marked`), но до закона его не
/// проверяло ничто: изнутри процесса «метку поставили» и «метку прочитали» неотличимы совершенно.
///
/// ```compile_fail,E0046
/// use reflex_core::capability::CanMark;
/// use reflex_core::held::{Answered, Delivered, Refused, Terminal};
///
/// struct Plain;
/// impl Terminal for Plain {
///     type Carrier = ();
///     type Answer = ();
///     type Refusal = ();
///     fn apply(&mut self, answered: Answered<(), ()>)
///         -> Result<Delivered<()>, Refused<(), ()>> {
///         Ok(Delivered { at: answered.at, answer: answered.answer })
///     }
/// }
///
/// impl CanMark for Plain {}
/// ```
pub trait CanMark: crate::held::Terminal {
    /// КАКИМ СЛОВОМ АЛФАВИТА выражается «пропустить, пометив вот этим для тех, кто ниже».
    fn mark(mark: u32) -> Self::Answer;
}

/// БЭКЕНД УМЕЕТ ОТПУСТИТЬ УДЕРЖАННЫЙ ПАКЕТ С ДРУГИМИ БАЙТАМИ.
///
/// Отличие от [`CanModify`] то же, что у [`CanRefuse`] от [`CanDrop`]: тот описывает изменение
/// через [`Flow`](crate::types::Flow), потому что правило в ядре обязано знать, К ЧЕМУ его
/// применять. Здесь адресат уже в руках — мы держим тот самый пакет, — и `flow` в подписи был бы
/// вторым способом сказать то, что уже сказано носителем.
///
/// ```compile_fail,E0046
/// use reflex_core::capability::CanRewrite;
/// use reflex_core::held::{Answered, Delivered, Refused, Terminal};
///
/// struct Verbatim;
/// impl Terminal for Verbatim {
///     type Carrier = ();
///     type Answer = ();
///     type Refusal = ();
///     fn apply(&mut self, answered: Answered<(), ()>)
///         -> Result<Delivered<()>, Refused<(), ()>> {
///         Ok(Delivered { at: answered.at, answer: answered.answer })
///     }
/// }
///
/// impl CanRewrite for Verbatim {}
/// ```
pub trait CanRewrite: crate::held::Terminal {
    /// КАКИМ СЛОВОМ АЛФАВИТА выражается «пропустить, но вот с такими байтами».
    fn rewrite(bytes: Vec<u8>) -> Self::Answer;
}

/// БЭКЕНД УМЕЕТ ИЗМЕНИТЬ ПАКЕТ НА МЕСТЕ И ПРОПУСТИТЬ ДАЛЬШЕ.
///
/// # Замер 05.09.2026: здесь заявление было НЕПРАВДИВЫМ, а не невыразимым
///
/// Разница с [`CanDrop`] существенна и стоит того, чтобы её записать. Дроп у
/// `TcAfPacketBackend` СУЩЕСТВОВАЛ целиком и лишь не имел значения, которым его сказать.
/// Модификации не существовало вовсе: карты BPF-программы — `ACTION_TABLE`, `STEER_*`,
/// `CLIENT_MACS`, `RETURN_*`, и ни одна не несёт байтов для подмены. Единственная запись в кадр
/// (`bpf_skb_store_bytes`, `linux-ebpf/src/main.rs:550`) вписывает ethernet-заголовок в пути
/// заворота — механика лифта, а не команда пользователя.
///
/// То есть пустой маркер скрывал сразу два РАЗНЫХ состояния, неотличимых снаружи: «умеет, но
/// сказать нечем» и «не умеет». Метод разводит их: первое становится ошибкой сборки у стока,
/// второе — отсутствием реализации.
///
/// Сегодня у этой способности НОЛЬ реализаций, и это честный ответ, а не пробел. Vision §3.1
/// прямо разрешает: фронтенд есть полный словарь домена и не сужается до возможностей самого
/// слабого бэкенда.
///
/// # Заявить, не назвав команду модификации, нельзя
///
/// ```compile_fail,E0046
/// use reflex_core::backend::Sink;
/// use reflex_core::capability::CanModify;
///
/// struct Forwarder;
/// impl Sink for Forwarder {
///     type Command = Vec<u8>;
///     type Error = ();
///     fn emit(&mut self, _command: Vec<u8>) -> Result<(), ()> { Ok(()) }
/// }
///
/// impl CanModify for Forwarder {}
/// ```
pub trait CanModify: crate::backend::Sink {
    /// КАКИМ ЗНАЧЕНИЕМ ЭТОГО СТОКА выражается «пропустить, но вот с такими байтами».
    fn modify(change: crate::command::ModifyPacket) -> Self::Command;
}

/// БЭКЕНД УМЕЕТ РОНЯТЬ ПАКЕТ, НЕ ДАВАЯ ЕМУ ДОЙТИ ДО АДРЕСАТА.
///
/// # Замер, из-за которого у способности появился метод
///
/// `TcAfPacketBackend` заявлял `CanDrop`, и заявление было ПРАВДИВЫМ: в ядре есть
/// `ACTION_TABLE` с `FlowAction::Drop` (`linux-ebpf/src/main.rs:170`), в userspace есть писатель
/// `TcProgram::set_flow_action`, и хеш потока считается совпадающей функцией. Механизм полный.
///
/// Невыразимо было ДРУГОЕ: сток брал `Vec<u8>`, а в байтах «дропни этот поток» не скажешь.
/// Способность существовала и была недостижима — состояние, которое нельзя ни подтвердить, ни
/// опровергнуть, и которое пустой маркер прятал полностью.
///
/// Метод убирает именно это: заявить «умею ронять» можно только назвав, каким значением ЭТОГО
/// стока дроп выражается. Сток, у которого такого значения нет, заявление сделать не сможет.
///
/// # Заявить, не назвав команду дропа, нельзя
///
/// ```compile_fail,E0046
/// use reflex_core::backend::Sink;
/// use reflex_core::capability::CanDrop;
///
/// struct Passthrough;
/// impl Sink for Passthrough {
///     type Command = Vec<u8>;
///     type Error = ();
///     fn emit(&mut self, _command: Vec<u8>) -> Result<(), ()> { Ok(()) }
/// }
///
/// // В байтах дроп не выражается — и заявление не собирается.
/// impl CanDrop for Passthrough {}
/// ```
pub trait CanDrop: crate::backend::Sink {
    /// КАКИМ ЗНАЧЕНИЕМ ЭТОГО СТОКА выражается «поток дальше не идёт».
    fn drop_flow(flow: crate::types::Flow) -> Self::Command;

    /// И как снимается обратно. Без снятия дроп есть состояние без выхода: закон обязан уметь
    /// вернуть мир в исходное, иначе один прогон отравляет все следующие.
    fn clear_flow(flow: crate::types::Flow) -> Self::Command;
}

/// КОМУ АДРЕСОВАНО ИЗВЕЩЕНИЕ ОБ ОБРЫВЕ — в терминах ПАКЕТА, а не разговора.
///
/// # Почему не «клиенту»
///
/// «Клиент» есть свойство РАЗГОВОРА: чтобы назвать им сторону, надо помнить, кто постучал первым.
/// Бэкенд разговоров не помнит — он держит один пакет, — и у пакета объективны ровно две стороны:
/// та, что его послала, и та, кому он адресован.
///
/// Знание «клиент здесь — отправитель» принадлежит ВХОДУ и у каждого входа своё: очередь знает
/// сторону из правила (через неё идёт только серверный порт), запись `tcpdump` — из улики (`SYN`
/// без `ACK`). Втяни мы это знание в способность — оно завелось бы вторым правилом рядом с
/// первым, и две правды о стороне разъехались бы молча. Репа платила за это уже дважды.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Toward {
    /// Тому, кто послал удержанный пакет.
    Sender,
    /// Тому, кому удержанный пакет был адресован.
    Receiver,
}

/// БЭКЕНД УМЕЕТ ОБОРВАТЬ РАЗГОВОР — не пропустить пакет И СКАЗАТЬ ОБ ЭТОМ.
///
/// # Обрыв есть ПАРА, и это не педантизм
///
/// Дроп без извещения — ровно то, чем бьёт ТСПУ на нашем вантаже: клиент не узнаёт, что
/// разговора не будет, ретрансмитит приветствие пять-семь раз и ждёт от двух до двенадцати секунд
/// (замер 04.09.2026). Человек называет это «страница висит» — то есть половина обрыва
/// воспроизводит беду, которую вторая половина лечит.
///
/// Определение это записано в репе типом (`Act::Sever`: «пакет дальше не идёт, клиенту сказано»),
/// а исполнялось по-разному в трёх местах: полностью — в бою, наполовину — в эталонном примере
/// движка, никак — во втором бинаре. Здесь оно становится ОДНИМ предметом, и половину заявить
/// больше нельзя: [`CanRefuse`] даёт слово отказа, `notice` — извещение, и без обоих способность
/// не собирается.
///
/// # Почему извещение строится ЗДЕСЬ, а не приходит параметром
///
/// Та же причина, по которой слово алфавита берётся у способности: закон, которому извещение
/// передают снаружи, проверял бы согласие вызывающего с самим собой. Сборка извещения — знание
/// бэкенда о том, что такое «сказать» на ЕГО проводе.
///
/// # Кто извещение ОТПРАВЛЯЕТ — другой носитель, и это по природе
///
/// Алфавит очереди ядра — четыре слова, и `inject` в него не входит: свой пакет уходит своим
/// сокетом, а не вердиктом на чужой. Поэтому способность только СТРОИТ; отправка — дело
/// [`CanInject`] над [`Sink`](crate::backend::Sink), и закон обрыва спрашивает обоих.
///
/// # Заявить, не назвав извещения, нельзя
///
/// ```compile_fail,E0046
/// use reflex_core::capability::{CanRefuse, CanSever};
/// use reflex_core::held::{Answered, Delivered, Refused, Terminal};
///
/// struct Silent;
/// impl Terminal for Silent {
///     type Carrier = ();
///     type Answer = ();
///     type Refusal = ();
///     fn apply(&mut self, answered: Answered<(), ()>)
///         -> Result<Delivered<()>, Refused<(), ()>> {
///         Ok(Delivered { at: answered.at, answer: answered.answer })
///     }
/// }
/// impl CanRefuse for Silent { fn refuse() {} }
///
/// // Отказывать умеет, а сказать об этом нечем — обрыв не собирается.
/// impl CanSever for Silent {}
/// ```
pub trait CanSever: CanRefuse {
    /// ЧЕМ СКАЗАТЬ НАЗВАННОЙ СТОРОНЕ, что разговора не будет.
    ///
    /// # `None` — это «на ЭТОМ носителе сказать нечем», и оно не пустота
    ///
    /// Извещение строится из удержанного пакета, а построить его можно не из всякого: у обрыва
    /// TCP есть форма (`RST` с номерами, которых ждёт сторона), а у датаграммы её нет вовсе.
    /// Вернуть здесь пустой пакет значило бы отправить ноль байт и получить отказ сокета — то
    /// есть предъявить дефект НОСИТЕЛЯ как беду стенда, перепутав вину.
    ///
    /// Движок обязан узнать «сказать нечем» ДО того, как решит рвать: обрыв без извещения есть
    /// ровно та беда, которую он лечит.
    ///
    /// # Вход — НАБЛЮДЁННЫЕ БАЙТЫ, а не носитель
    ///
    /// Первая редакция брала `&Self::Carrier`, и это выяснилось неверным при первом же
    /// употреблении: носитель очереди (`nfq::Message`) без живого ядра не собрать, то есть всякий
    /// потребитель `notice` терял возможность проверяться таблицей вход→выход на машине без прав.
    /// Способность требовала бы прав ради знания, которое лежит в байтах.
    ///
    /// Привязка к бэкенду от этого не исчезла — она в самом трейте: у очереди извещение об обрыве
    /// есть `RST`, у туннельного носителя оно было бы ICMP, и выбор формы остаётся за тем, кто
    /// знает свой провод.
    fn notice(seen: &[u8], toward: Toward) -> Option<crate::command::InjectablePacket>;
}
