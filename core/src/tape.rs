//! Алфавит ЛЕНТЫ — то, что драйвер сливает в один поток и записывает целиком (канон §8, §10).
//!
//! Букв у ленты две породы, и различие между ними несущее. `Event` — наблюдение ПРОВОДА: пакет,
//! узел сетки, непонятое; это алфавит ПРИБОРА, и он узок (`DetectorEvent`, три буквы). `Answer` —
//! отклик на то, что мы сами спросили; он приходит не с провода, и прибору по умолчанию не
//! адресован.
//!
//! Почему не четвёртый вариант `DetectorEvent`: тогда каждый прибор обязан объявить ветку «не моя
//! буква» — восемнадцать одинаковых веток на восемнадцать приборов, и девятнадцатый напишет ту же,
//! не поняв зачем. Буква, которую все обязаны отвергнуть, адресована не им. Здесь она живёт в
//! алфавите ленты, а до адресата доходит §4-сужением ([`crate::stack::Reads`]) — прибор, который её
//! не читает, её и не получает.
//!
//! Лента при этом ОДНА: порядок замерзает на шве ([`crate::interleave::Interleave`]), общий для
//! обеих пород, и записывается вся — иначе переигровка (§10) видела бы не тот вход, что был.

use std::time::Instant;

use crate::detector::DetectorEvent;

/// Отклик на спрошенное. Содержимое `C` — потребителя: фреймворк несёт конверт, а не смысл ответа.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Answer<C> {
    pub input: C,
    pub at: Instant,
}

/// Буква ленты: наблюдение провода либо отклик. Записывается целиком; прибору достаётся лишь то,
/// что он читает.
///
/// Равенства не выводит: буква провода (`DetectorEvent`) его не имеет — там лежит носитель, чьё
/// равенство не наше дело. Лента сравнивается по моментам и по породе, а не побуквенно.
#[derive(Debug, Clone)]
pub enum TapeLetter<T, C> {
    Event(DetectorEvent<T>),
    Answer(Answer<C>),
}

impl<T, C> TapeLetter<T, C> {
    /// Момент буквы — общий для обеих пород: лента упорядочена временем, чем бы буква ни была.
    pub fn at(&self) -> Instant {
        match self {
            TapeLetter::Event(event) => event.at(),
            TapeLetter::Answer(answer) => answer.at,
        }
    }
}

/// Сужение ленты к алфавиту прибора (§4): прибор читает наблюдения провода и НЕ читает откликов.
/// Отклик роняется здесь — без ветки «не моя буква» у каждого прибора.
impl<T: Clone, C> crate::stack::Reads<TapeLetter<T, C>> for DetectorEvent<T> {
    fn read(wide: &TapeLetter<T, C>) -> Option<DetectorEvent<T>> {
        match wide {
            TapeLetter::Event(event) => Some(event.clone()),
            TapeLetter::Answer(_not_ours) => None,
        }
    }
}
