//! Алфавит ЛЕНТЫ — то, что драйвер сливает в один поток и записывает целиком (канон §8, §10).
//!
//! Букв у ленты две породы, и различие между ними несущее. `Event` — наблюдение ПРОВОДА: пакет,
//! узел сетки, непонятое; это алфавит ПРИБОРА, и он узок (`DetectorEvent`, три буквы). `Answer` —
//! отклик на то, что мы сами спросили; он приходит не с провода, и прибору по умолчанию не
//! адресован.
//!
//! Почему не четвёртый вариант `DetectorEvent`: тогда каждый прибор обязан объявить ветку «не моя
//! буква» — восемнадцать одинаковых веток на восемнадцать приборов, и девятнадцатый напишет ту же,
//! не поняв зачем. Буква, которую все обязаны отвергнуть, адресована не им. Здесь она живёт в
//! алфавите ленты, а до адресата доходит §4-сужением ([`crate::stack::Reads`]) — прибор, который её
//! не читает, её и не получает.
//!
//! Лента при этом ОДНА: порядок замерзает на шве ([`crate::interleave::Interleave`]), общий для
//! обеих пород, и записывается вся — иначе переигровка (§10) видела бы не тот вход, что был.

use std::time::Instant;

use crate::detector::DetectorEvent;

/// Отклик на спрошенное. Содержимое `C` — потребителя: фреймворк несёт конверт, а не смысл ответа.
///
/// `key` — ключ ОБЛАСТИ (§4), и он несущий: отклик приходит позже вопроса и сам по себе не говорит,
/// чей он. Без ключа драйверу осталось бы отдать его «первой попавшейся» машине либо всем — и то и
/// другое сделало бы ответ чужим наблюдением, а машину — держащей два разговора (§4: «машина на
/// двух ключах — две машины»).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Answer<K, C> {
    pub key: K,
    pub input: C,
    pub at: Instant,
}

/// Буква ленты: наблюдение провода либо отклик. Записывается целиком; прибору достаётся лишь то,
/// что он читает.
///
/// Равенства не выводит: буква провода (`DetectorEvent`) его не имеет — там лежит носитель, чьё
/// равенство не наше дело. Лента сравнивается по моментам и по породе, а не побуквенно.
#[derive(Debug, Clone)]
pub enum TapeLetter<T, K, C> {
    Event(DetectorEvent<T>),
    Answer(Answer<K, C>),
}

impl<T, K, C> TapeLetter<T, K, C> {
    /// Момент буквы — общий для обеих пород: лента упорядочена временем, чем бы буква ни была.
    pub fn at(&self) -> Instant {
        match self {
            TapeLetter::Event(event) => event.at(),
            TapeLetter::Answer(answer) => answer.at,
        }
    }
}

impl<T, K: PartialEq, C> TapeLetter<T, K, C> {
    /// Адресована ли буква машине этого ключа. Наблюдение провода адресовано ТОЙ машине, которой
    /// его отдал разбор, — здесь о нём не судят; отклик адресован ровно машине своего ключа.
    ///
    /// Тем корреляция и держится: ответ приходит позже вопроса, и «чей он» знает только ключ. Отдай
    /// драйвер отклик первой попавшейся машине — она получила бы чужое наблюдение и стала бы
    /// машиной на двух ключах, то есть двумя машинами (§4).
    pub fn answers(&self, key: &K) -> bool {
        match self {
            TapeLetter::Event(_wire) => false,
            TapeLetter::Answer(answer) => &answer.key == key,
        }
    }
}

/// В каком прогоне идёт драйвер. Различие не в машине — она одна и та же, — а в том, исполняются ли
/// команды миру (§9, §10).
///
/// `Live` — команды исполняются: инъекция уходит в провод, вопрос к контуру отправляется.
/// `Replay` — команды ГЛУШАТСЯ: лента пере-подаётся, машина шагает те же шаги, но мир не трогается.
/// Иначе переигровка слала бы RST заново и спрашивала контур повторно, то есть не переигрывала бы, а
/// повторяла — и восьмой закон (§12.3) проверял бы не то.
///
/// Режим живёт у ДРАЙВЕРА, не внутри функтора: функтор чист и отдаёт команды, петля решает, слать
/// ли. Протащи режим внутрь функтора — и чистая часть узнала бы о прогоне, то есть перестала бы
/// быть чистой.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Live,
    Replay,
}

impl Mode {
    /// Исполняются ли команды миру в этом прогоне.
    pub fn touches_the_world(&self) -> bool {
        matches!(self, Mode::Live)
    }
}

/// Записанная лента: буквы в порядке слияния, как их видел драйвер.
///
/// Пишется ЦЕЛИКОМ, обе породы букв: переигровка, увидевшая не тот вход, что был, проверяла бы
/// другую машину. Сама лента при этом не сравнивается — сверяются ИСХОДЫ прогонов (§10,
/// бисимуляция), потому и равенства у буквы нет.
#[derive(Debug, Clone)]
pub struct Tape<T, K, C> {
    letters: Vec<TapeLetter<T, K, C>>,
}

impl<T, K, C> Default for Tape<T, K, C> {
    fn default() -> Self {
        Self::new()
    }
}

impl<T, K, C> Tape<T, K, C> {
    pub fn new() -> Self {
        Tape {
            letters: Vec::new(),
        }
    }

    /// Записать буквы, как они вышли из шва — в том же порядке.
    pub fn record(&mut self, letters: impl IntoIterator<Item = TapeLetter<T, K, C>>) {
        self.letters.extend(letters);
    }

    /// Буквы для пере-подачи. Порядок тот же, что при записи: он и есть то, что переигрывается.
    pub fn letters(&self) -> &[TapeLetter<T, K, C>] {
        &self.letters
    }

    pub fn len(&self) -> usize {
        self.letters.len()
    }

    pub fn is_empty(&self) -> bool {
        self.letters.is_empty()
    }
}

/// Сужение ленты к алфавиту прибора (§4): прибор читает наблюдения провода и НЕ читает откликов.
/// Отклик роняется здесь — без ветки «не моя буква» у каждого прибора.
impl<T: Clone, K, C> crate::stack::Reads<TapeLetter<T, K, C>> for DetectorEvent<T> {
    fn read(wide: &TapeLetter<T, K, C>) -> Option<DetectorEvent<T>> {
        match wide {
            TapeLetter::Event(event) => Some(event.clone()),
            TapeLetter::Answer(_not_ours) => None,
        }
    }
}
