//! ЗАКОНЫ КАЛИТКИ — то, что типом невыразимо.
//!
//! # Разделение труда, к которому пришли за день
//!
//! **Тип убивает ПУСТОЕ заявление.** Сказать «умею вводить», не назвав, как инъекция становится
//! командой ЭТОГО стока, больше нельзя: [`CanInject`](crate::capability::CanInject) несёт метод.
//! Замер 05.09.2026: заявлений было шестнадцать и ни одно ничем не установлено; после — пять, и
//! все несут предмет.
//!
//! **Закон убивает ЛОЖНОЕ.** Команда построена, `emit` ответил `Ok`, а на проводе пусто — типами
//! это не ловится по построению, потому что происходит за их границей.
//!
//! **Гейт ловит обход синтаксиса**, и это дверь, а не тип.
//!
//! # Свидетельство выдаёт ДАЛЬНИЙ КОНЕЦ
//!
//! Закон не спрашивает подопытного, отправил ли он: спрашивать доставку у доставляющего — тот
//! самый корень, который репа ловит у себя не первый раз. Спрашивают того, до кого должно было
//! дойти, и устроен он ИНАЧЕ: на живом устройстве это `tshark` на противоположном конце veth плюс
//! счётчик ядра — два прибора, разошедшиеся показания которых сами по себе находка.
//!
//! В памятном мире (тесты этого модуля) дальний конец сертифицирует САМ ЗАКОН, а не продукт: он
//! читает то же, что положил сток. Настоящее свидетельство даёт только живое устройство.
//!
//! # Чего здесь нет
//!
//! Отрицательных законов («незаявленная способность недоступна») и устройства. Первые бесплатны —
//! это тот же замер, прочитанный другим предикатом, — но требуют мира, где виден ВЕСЬ поток;
//! второе есть работа docker-среза.

use crate::backend::Sink;
use crate::capability::CanInject;
use crate::command::InjectablePacket;

/// ЧТО ВИДЕЛ ТОТ, ДО КОГО ДОЛЖНО БЫЛО ДОЙТИ.
///
/// Трейт, а не тип: на живом устройстве это чужой процесс со своим разбором, в памятном мире —
/// список. Закон об их различии не знает и знать не должен.
pub trait FarEnd {
    /// Кадры, дошедшие до дальнего конца с прошлого вопроса.
    fn arrived(&mut self) -> Vec<Vec<u8>>;
}

/// СПИСОК КАДРОВ — ТОЖЕ ДАЛЬНИЙ КОНЕЦ, и это единственный способ иметь его в памятном мире.
///
/// `take` намеренно: вопрос задан «что дошло С ПРОШЛОГО РАЗА», и список, отвечающий одно и то же
/// на каждый вопрос, тихо превратил бы одно наблюдение в сколько угодно.
impl FarEnd for Vec<Vec<u8>> {
    fn arrived(&mut self) -> Vec<Vec<u8>> {
        std::mem::take(self)
    }
}

/// ПОЧЕМУ ЗАКОН НЕ ДЕРЖИТСЯ. Алгебраически, а не строкой: у каждой причины своя починка.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Broken {
    /// Сток честно сказал, что не смог. Это НЕ нарушение способности — это отказ, о котором
    /// сообщили; починка ищется в мире, а не в бэкенде.
    SinkRefused,
    /// Сток ответил `Ok`, а на дальнем конце пусто. Вот это и есть ложное заявление.
    NonceMissing,
}

/// ПОЧЕМУ ВЕРДИКТА НЕТ. Не оттенок нарушения, а его ОТСУТСТВИЕ: закон ничего не установил.
///
/// Прежде недействительность жила ВНЕ закона — в живом устройстве, строкой в `Result<_, String>`.
/// Место было выбрано неверно дважды: строка не разбирается на причины, а сам закон при этом
/// оставался таким, что про недействительность можно было ЗАБЫТЬ, — и второй закон повторил бы
/// упущение копипастой. Теперь `match` по вердикту тотален и спрашивает про неё.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Invalid {
    /// Дальний конец не показал НИ ОДНОГО кадра — ни нашего, ни чужого.
    ///
    /// «Прибор не работал» и «подопытный солгал» дают одинаково пустой результат. Различие ЕСТЬ в
    /// данных (пустой список против непустого без нонса), и до этой правки закон его съедал: оба
    /// случая становились `Broken(NonceMissing)`, то есть поломка стенда предъявлялась как
    /// нарушение способности.
    WitnessSilent,
}

/// ДЕРЖИТСЯ ЛИ ЗАКОН — и установлено ли это вообще.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Verdict {
    Held,
    Broken(Broken),
    /// Вердикта НЕТ. Третье состояние обязано быть в самом законе: иначе всякий его потребитель
    /// изобретает недействительность заново и по-своему.
    Invalid(Invalid),
}

/// ЗАКОН ИНЪЕКЦИИ: ЧТО ОТДАНО В СТОК — НАБЛЮДАЕМО ДАЛЬНИМ КОНЦОМ.
///
/// # Почему нонс, а не «хоть что-нибудь»
///
/// Дальний конец видит и посторонний трафик. Считать по числу кадров значило бы засчитать закон
/// на чужом пакете — беда, которую репа уже ловила: «свидетель проходил ПО СЛУЧАЙНОСТИ, счётчик
/// двигал посторонний трафик». Нонс отвечает на вопрос «дошёл ли ИМЕННО НАШ».
///
/// # Почему `emit`, а не `inject`
///
/// `B::inject` строит команду — это половина заявления. Вторая половина в том, что команда,
/// отданная стоку, доходит до провода; проверять первую без второй значит проверять, что мы умеем
/// заполнять структуру.
/// # Дальний конец НИЧЕГО НЕ ПОЛУЧАЕТ ОТ ЗАКОНА
///
/// Первая редакция передавала ему то, что ДОЛЖНО было дойти, и спрашивала, дошло ли. Такой закон
/// держится всегда — в том числе на стоке, который на провод не кладёт ничего: свидетель
/// пересказывал бы вопрос. Здесь у него спрашивают без подсказки, и наблюдает он подопытного.
pub fn injects<B, F>(dut: &mut B, nonce: InjectablePacket, far_end: &mut F) -> Verdict
where
    B: Sink + CanInject,
    F: FarEnd + ?Sized,
{
    let bytes = nonce.serialize();
    match dut.emit(B::inject(nonce)) {
        Err(_refused) => Verdict::Broken(Broken::SinkRefused),
        // ПУСТОЙ ДАЛЬНИЙ КОНЕЦ — НЕ НАРУШЕНИЕ, А ОТСУТСТВИЕ ВЕРДИКТА. Прибор, не увидевший НИЧЕГО,
        // не увидел и чужого шума, которого в живом сегменте всегда хватает: это его собственная
        // беда, и предъявлять её подопытному значило бы наказывать за поломку стенда.
        Ok(()) => match far_end.arrived().as_slice() {
            [] => Verdict::Invalid(Invalid::WitnessSilent),
            seen => match seen.iter().any(|frame| carries(frame, &bytes)) {
                true => Verdict::Held,
                false => Verdict::Broken(Broken::NonceMissing),
            },
        },
    }
}

/// НЕСЁТ ЛИ КАДР НАШ НОНС. Подстрокой, а не равенством.
///
/// Дальний конец видит кадр целиком — с заголовками, которые мог дописать кто угодно по дороге.
/// Требовать равенства значило бы проверять не «дошло ли наше», а «не тронул ли его никто».
///
/// ПУБЛИЧЕН НАМЕРЕННО: живому устройству тот же предикат нужен, чтобы ЖДАТЬ появления нонса в
/// записи, — и будь у него своя копия, ожидание шло бы по одному правилу, а суждение по другому.
/// Такое расхождение репа уже ловила: одно слово значило два разных вопроса в двух реализациях, и
/// снаружи это было не видно.
pub fn carries(frame: &[u8], nonce: &[u8]) -> bool {
    match nonce.len() {
        0 => false,
        len => frame.windows(len).any(|window| window == nonce),
    }
}
