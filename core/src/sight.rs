//! ЧТО ДВИЖОК ВИДЕЛ И ЧЕГО НЕ ВИДЕЛ.
//!
//! # Почему это фундамент, а не свойство одного продукта
//!
//! Перехватывающий движок слепнет: NFQUEUE роняет пакеты при переполнении очереди, кольцо
//! `AF_PACKET` переполняется под нагрузкой, WinDivert теряет по-своему. Слепота — не отказ и не
//! исключение, а нормальный режим, и потому она обязана быть ВЫРАЗИМА, а не обнаруживаться потом.
//!
//! Движок, не умеющий сказать «я этого не видел», выдаёт своё молчание за молчание сети. Это не
//! оборот речи: наблюдение «цель не ответила» и наблюдение «ответ мог быть, а мы его пропустили»
//! приводят потребителя к противоположным решениям, а без третьего состояния они неразличимы.
//!
//! # Слепота ЗАМЕРЯЕТСЯ, а не объявляется
//!
//! [`sighted`] сравнивает два независимых счёта: ядро считает по своему пути, движок по своему.
//! Расхождение и есть величина слепоты. Вывод, у которого один оракул, ещё не вывод.
//!
//! **Чем [`Sight::Full`] НЕ ЯВЛЯЕТСЯ:** свидетельством зрения, если оба счёта пришли из одного
//! источника. У офлайн-входа счёт «ядра» синтезируется из тех же пакетов, что скормлены движку, и
//! `Full` выходит ПО ПОСТРОЕНИЮ, а не по замеру. Второй оракул существует только живьём.
//!
//! # Откуда приехало (05.09.2026)
//!
//! Из `dataplane` невода, где было выражено на своём материале. Общим оказалось не то, что мы
//! ожидали (абстракции плана и политики как раз остались продуктовыми), а знание о том, как
//! движок ВРЁТ.

/// СКОЛЬКО ПРОШЛО В КАЖДУЮ СТОРОНУ.
///
/// Пакеты и байты порознь, и это не избыток: заблокированная цель отвечает на `SYN` и молчит
/// после приветствия — пакеты вниз есть, полезной нагрузки нет. Счёт только пакетов такую цель от
/// живой не отличает.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Counted {
    pub up: u64,
    pub up_bytes: u64,
    pub down: u64,
    pub down_bytes: u64,
}

/// ВИДЕЛ ЛИ ДВИЖОК ВЕСЬ РАЗГОВОР.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Sight {
    Full,
    Partial { missed_up: u64, missed_down: u64 },
}

/// ЧТО ИЗВЕСТНО О ВЕЛИЧИНЕ, ДОБЫВАЕМОЙ СОБЫТИЕМ.
///
/// Третье состояние — весь смысл типа. Пустая клетка значит РАЗНОЕ смотря по тому, могли ли мы
/// вообще увидеть событие: у зрячего движка «ничего не приходило» есть факт о СЕТИ, у ослепшего —
/// факт О НАС.
///
/// # О названии
///
/// `Told::Told` читается неловко, и имя перенесено как есть сознательно: на момент переезда у типа
/// было 85 употреблений в восьми файлах четырёх крейтов, и переименование стоило бы churn'а во
/// всех ради того же смысла. Цена названа, чтобы молчание не читалось как одобрение.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Told<T> {
    /// Канал был открыт, событие не приходило — значит его не было.
    Nothing,
    Told(T),
    /// Движок этих пакетов не видел: событие могло произойти и не дойти.
    Blind,
}

/// Пустой счёт — нейтраль для [`added`].
pub fn no_counts() -> Counted {
    Counted {
        up: 0,
        up_bytes: 0,
        down: 0,
        down_bytes: 0,
    }
}

/// СЛОЖИТЬ ДВА ОТРЕЗКА ОДНОГО РАЗГОВОРА.
///
/// Насыщение, а не перенос: счётчик, ушедший по кругу, соврал бы тише, чем застрявший на потолке.
pub fn added(one: Counted, other: Counted) -> Counted {
    Counted {
        up: one.up.saturating_add(other.up),
        up_bytes: one.up_bytes.saturating_add(other.up_bytes),
        down: one.down.saturating_add(other.down),
        down_bytes: one.down_bytes.saturating_add(other.down_bytes),
    }
}

/// СЛЕПОТА КАК РАСХОЖДЕНИЕ ДВУХ НЕЗАВИСИМЫХ СЧЁТОВ.
///
/// НАСЫЩЕНИЕ В НОЛЬ НЕ КОСМЕТИКА: движок не может видеть больше ядра, и если счётчики так говорят,
/// это расхождение приборов. Отрицательная слепота была бы утверждением сильнее установленного —
/// прибор обязан молчать, когда ему нечего сказать.
pub fn sighted(kernel: Counted, engine: Counted) -> Sight {
    match (
        kernel.up.saturating_sub(engine.up),
        kernel.down.saturating_sub(engine.down),
    ) {
        (0, 0) => Sight::Full,
        (missed_up, missed_down) => Sight::Partial {
            missed_up,
            missed_down,
        },
    }
}

/// РАННЕЕ ИЗ ДВУХ НАБЛЮДЕНИЙ ОДНОГО ПРЕДМЕТА.
///
/// # Почему у слепоты здесь СТАРШИНСТВО НАД ПУСТОТОЙ, а в [`later`] наоборот
///
/// Различие не в знаке сравнения, а в предмете, и его стоит держать в голове, потому что глазами
/// эти две функции читаются как min и max.
///
/// Здесь предмет — величина ОДНОГО разговора (когда отвечающий заговорил). Если часть его мы не
/// видели, утверждать «ничего не было» нельзя: ответ мог быть ровно в пропущенном. Оттого
/// `Blind ⊐ Nothing`.
///
/// # Коммутативна, и это требование, а не свойство
///
/// Наблюдения приходят из разных источников в произвольном порядке. Всякая операция, берущая «то,
/// что пришло первым», молча становится выборкой из мультимножества — то есть результат начинает
/// зависеть от очерёдности, которой мы не управляем.
pub fn sooner<T: Ord>(one: Told<T>, other: Told<T>) -> Told<T> {
    match (one, other) {
        (Told::Told(mine), Told::Told(theirs)) => Told::Told(mine.min(theirs)),
        (Told::Told(value), Told::Nothing)
        | (Told::Told(value), Told::Blind)
        | (Told::Nothing, Told::Told(value))
        | (Told::Blind, Told::Told(value)) => Told::Told(value),
        (Told::Blind, Told::Nothing)
        | (Told::Nothing, Told::Blind)
        | (Told::Blind, Told::Blind) => Told::Blind,
        (Told::Nothing, Told::Nothing) => Told::Nothing,
    }
}

/// ПОЗДНЕЕ ИЗ ДВУХ НАБЛЮДЕНИЙ — зеркало [`sooner`], и разница не в знаке, а в предмете.
///
/// Здесь предмет — наблюдение за УЗЛОМ, склеенное из многих разговоров. Слепота одного разговора
/// не делает слепым узел: если хоть один разговор наблюдался и оказался пуст, это факт об узле.
/// Оттого `Nothing ⊐ Blind` — старшинство ровно обратное [`sooner`].
///
/// Ветки перечислены без `_` намеренно: асимметрия двух функций видна только тогда, когда обе
/// таблицы выписаны целиком и лежат рядом.
pub fn later<T: Ord>(one: Told<T>, other: Told<T>) -> Told<T> {
    match (one, other) {
        (Told::Told(mine), Told::Told(theirs)) => Told::Told(mine.max(theirs)),
        (Told::Told(value), Told::Nothing)
        | (Told::Told(value), Told::Blind)
        | (Told::Nothing, Told::Told(value))
        | (Told::Blind, Told::Told(value)) => Told::Told(value),
        (Told::Nothing, Told::Nothing)
        | (Told::Nothing, Told::Blind)
        | (Told::Blind, Told::Nothing) => Told::Nothing,
        (Told::Blind, Told::Blind) => Told::Blind,
    }
}

/// НАБЛЮДЁННОЕ СЛЕПОТОЙ НЕ ОТМЕНЯЕТСЯ: факт, добытый до того, как мы ослепли, остаётся фактом —
/// иначе действие стирало бы то, что само же и добыло.
pub fn told<T>(seen: Told<T>, sight: Sight) -> Told<T> {
    match (seen, sight) {
        (Told::Nothing, Sight::Partial { .. }) => Told::Blind,
        (Told::Nothing, Sight::Full) => Told::Nothing,
        (Told::Told(value), _any) => Told::Told(value),
        (Told::Blind, _any) => Told::Blind,
    }
}
