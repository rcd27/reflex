//! ЧТО РАЗГОВОР СООБЩИЛ О СЕБЕ — решётка по информации.
//!
//! # Что это за форма
//!
//! Сведение, добываемое из разговора, проходит три состояния: о нём ещё не сказано ничего;
//! событие, которое могло его нести, прошло и не понесло; значение добыто. Имя цели в
//! `ClientHello`, выбранный шифр, версия протокола, идентификатор соединения — у всех эта форма
//! одна, и общее в них не предмет, а ПОРЯДОК.
//!
//! ```text
//! Awaited ⊑ Silent ⊑ Spoken
//! ```
//!
//! Порядок ПО ИНФОРМАЦИИ, а не по важности. `Silent` ниже `Spoken` не потому, что хуже, а потому,
//! что беднее сведениями: «приветствие прошло, имени в нём не было» есть наше лучшее прочтение на
//! тот момент, а значение, добытое позже (ретрансмиссия, пересборка разреза), — БОЛЬШЕ сведений,
//! не меньше.
//!
//! Цепочка законна ровно потому, что каждое состояние есть НАБЛЮДЕНИЕ, а не заключение. Прочти
//! `Silent` как «значения НЕ БУДЕТ» — и это вывод о будущем, со `Spoken` не сравнимый: их
//! соединение было бы ⊤ («противоречие»), и никакого порядка бы не вышло.
//!
//! # Три закона, и третий не украшение
//!
//! 1. **монотонность** `k ⊑ joined(k, e)` — знание не убывает ни от какого события;
//! 2. **идемпотентность** `joined(joined(k,e), e) = joined(k,e)` — повтор того же не событие;
//! 3. **независимость от порядка** `joined(joined(⊥,a),b) = joined(joined(⊥,b),a)`.
//!
//! Третий существен потому, что провод переставляет пакеты, а движок, выпускающий разговоры из
//! горячего пути, видит ПОДМНОЖЕСТВО событий. Вердикт, зависящий от порядка прихода, на таком
//! проводе недетерминирован: две коробки на одном трафике решат по-разному.
//!
//! # Откуда приехало (05.09.2026)
//!
//! Из `dataplane` невода, где называлось `Naming` — имя цели. Тип переименован в общее слово, а
//! варианты сохранены: у продукта 300 употреблений в 50 файлах, и они продолжают работать через
//! псевдоним (`pub type Naming<N> = Disclosed<N>`), потому что варианты доступны через него.

/// ЧТО СООБЩЕНО О ВЕЛИЧИНЕ, КОТОРУЮ НЕСЁТ РАЗГОВОР.
///
/// Трёх состояний, а не двух: «не сказано ничего» и «сказано, что значения нет» — разные факты, и
/// слить их в `Option` значит потерять знаменатель слепой зоны. Разговор, у которого приветствие
/// ещё впереди, стал бы неотличим от разговора, где приветствие прошло пустым.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Disclosed<T> {
    /// Значение добыто из ЭТОГО разговора.
    Spoken(T),
    /// Событие прошло, значения не несло. НАБЛЮДЕНИЕ, а не приговор: значение может прийти
    /// ретрансмиссией или пересборкой разреза, и тогда знание уточнится.
    Silent,
    /// Не сказано ничего: события ещё не было. Низший элемент — ⊥.
    Awaited,
}

impl<T> Disclosed<T> {
    /// СТУПЕНЬ СЛОВОМ — только состояние, без значения.
    ///
    /// Метод, а не `Display`, намеренно. `Display`, печатающий ступень и молчащий о значении, был
    /// бы ловушкой: у `Disclosed<String>` читатель ждёт имени, а получил бы `"spoken"`. Здесь имя
    /// метода говорит, что печатается ступень, и спутать нельзя.
    ///
    /// Нужно там, где значение едет отдельным полем, а от решётки требуется лишь СУДЬБА сведения:
    /// добыто, не понесено, ещё не спрошено. Различие двух последних тут главное — первое есть
    /// окончательное знание, второе его отсутствие.
    pub fn rung(&self) -> &'static str {
        match self {
            Disclosed::Spoken(_) => "spoken",
            Disclosed::Silent => "silent",
            Disclosed::Awaited => "awaited",
        }
    }
}

/// СОЕДИНЕНИЕ ДВУХ СВЕДЕНИЙ ОБ ОДНОЙ ВЕЛИЧИНЕ.
///
/// # Почему расхождение разрешает ВЫЗЫВАЮЩИЙ
///
/// Два разных значения на одном разговоре дали бы в полной решётке ⊤ — «противоречие». Заводить
/// его типом рано: частота явления не замерена, а тип под неизмеренное потом не снимается.
///
/// Но и молчаливый выбор победителя — не отсутствие решения, а НЕЗАПИСАННОЕ решение: слитая пара
/// выглядит как согласие приборов, хотя они разошлись. Поэтому правило приходит аргументом. Не
/// назвав его, слить два разных значения нельзя; а назвав, вызывающий может там же и посчитать,
/// сколько раз расхождение случилось, — то есть замерить то, чего нам не хватает для решения о ⊤.
///
/// Для величин без содержимого (`Disclosed<()>`) выбор вырожден, и правило вызывающего вакуумно.
pub fn joined_with<T>(
    known: Disclosed<T>,
    said: Disclosed<T>,
    settle: impl FnOnce(T, T) -> T,
) -> Disclosed<T> {
    match (known, said) {
        (Disclosed::Spoken(mine), Disclosed::Spoken(theirs)) => {
            Disclosed::Spoken(settle(mine, theirs))
        }
        (Disclosed::Spoken(value), Disclosed::Silent)
        | (Disclosed::Spoken(value), Disclosed::Awaited)
        | (Disclosed::Silent, Disclosed::Spoken(value))
        | (Disclosed::Awaited, Disclosed::Spoken(value)) => Disclosed::Spoken(value),
        (Disclosed::Silent, Disclosed::Silent)
        | (Disclosed::Silent, Disclosed::Awaited)
        | (Disclosed::Awaited, Disclosed::Silent) => Disclosed::Silent,
        (Disclosed::Awaited, Disclosed::Awaited) => Disclosed::Awaited,
    }
}

/// НА ЧЁМ СТОЯЛО РЕШЕНИЕ, КОГДА ЕГО ПРИНИМАЛИ — и это ДРУГАЯ величина, а не то же знание.
///
/// # Почему не соединение
///
/// Знание обязано только расти и не зависеть от порядка. Запись о ПРОШЛОМ РЕШЕНИИ — обязана
/// зависеть: мы действовали тем, что пришло первым, и переставить это задним числом нельзя.
/// Требовать от неё коммутативности значит требовать, чтобы запись о случившемся не зависела от
/// того, что случилось.
///
/// Оттого функция ЗАМОРАЖИВАЕТ: первое непустое слово остаётся навсегда. Разговор, чьё событие
/// прошло без значения, закрывает вопрос СРАЗУ — ждать нечего, и позднее значение не двигает
/// решение на середине применения.
///
/// Ось при этом по-прежнему ОДНА: здесь её СНИМОК, а не копия. Незаконное «принято по значению,
/// которого ещё нет» непредставимо — снимок берётся ровно тогда, когда ось покидает ⊥.
pub fn stood_on<T>(taken: Disclosed<T>, said: Disclosed<T>) -> Disclosed<T> {
    match (taken, said) {
        (Disclosed::Awaited, first_word) => first_word,
        (already, _later) => already,
    }
}
