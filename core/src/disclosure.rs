//! Что разговор сообщил о себе — полурешётка по информации (канон §5). Сведение из разговора
//! проходит три состояния: о нём ещё не сказано ничего; событие, которое могло его нести, прошло и
//! не понесло; значение добыто. Имя цели в `ClientHello`, шифр, версия, id соединения — форма одна,
//! общее в них ПОРЯДОК: `Awaited ⊑ Silent ⊑ Spoken`. По информации, не важности: `Silent` беднее
//! `Spoken` (значение позже — БОЛЬШЕ сведений). Цепочка законна, пока каждое состояние есть
//! наблюдение, а не заключение (прочти `Silent` как «значения не будет» — вывод о будущем, со
//! `Spoken` несравнимый, соединение ⊤). Три закона (под тестом): монотонность `k ⊑ joined(k,e)`,
//! идемпотентность, независимость от порядка (провод переставляет пакеты, движок видит подмножество
//! — вердикт, зависящий от порядка, недетерминирован). Псевдоним `Naming<N> = Disclosed<N>` держит
//! 300 употреблений продукта.

/// Что сообщено о величине, которую несёт разговор. Три состояния, не два: «не сказано ничего» и
/// «сказано, что значения нет» — разные факты; слить в `Option` значит потерять знаменатель слепой
/// зоны (приветствие впереди стало бы неотличимо от прошедшего пустым).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Disclosed<T> {
    /// Значение добыто из ЭТОГО разговора.
    Spoken(T),
    /// Событие прошло, значения не несло. Наблюдение, а не приговор: значение может прийти
    /// ретрансмиссией или пересборкой разреза.
    Silent,
    /// Не сказано ничего: события ещё не было. Низший элемент — ⊥.
    Awaited,
}

impl<T> Disclosed<T> {
    /// Ступень словом — только состояние, без значения. Метод, а не `Display`: `Display`, печатающий
    /// ступень и молчащий о значении, был бы ловушкой у `Disclosed<String>` (читатель ждёт имени).
    /// Различие `Silent`/`Awaited` тут главное — окончательное знание против его отсутствия.
    pub fn rung(&self) -> &'static str {
        match self {
            Disclosed::Spoken(_) => "spoken",
            Disclosed::Silent => "silent",
            Disclosed::Awaited => "awaited",
        }
    }
}

/// Соединение двух сведений об одной величине (join). Расхождение разрешает ВЫЗЫВАЮЩИЙ: два разных
/// значения дали бы ⊤ («противоречие»), заводить его типом рано (частота не замерена, тип под
/// неизмеренное не снимается); молчаливый выбор победителя — незаписанное решение (слитая пара
/// выглядит согласием приборов). Правило приходит аргументом — назвав его, вызывающий там же считает
/// частоту расхождения. Для `Disclosed<()>` выбор вырожден, правило вакуумно.
pub fn joined_with<T>(
    known: Disclosed<T>,
    said: Disclosed<T>,
    settle: impl FnOnce(T, T) -> T,
) -> Disclosed<T> {
    match (known, said) {
        (Disclosed::Spoken(mine), Disclosed::Spoken(theirs)) => {
            Disclosed::Spoken(settle(mine, theirs))
        }
        (Disclosed::Spoken(value), Disclosed::Silent)
        | (Disclosed::Spoken(value), Disclosed::Awaited)
        | (Disclosed::Silent, Disclosed::Spoken(value))
        | (Disclosed::Awaited, Disclosed::Spoken(value)) => Disclosed::Spoken(value),
        (Disclosed::Silent, Disclosed::Silent)
        | (Disclosed::Silent, Disclosed::Awaited)
        | (Disclosed::Awaited, Disclosed::Silent) => Disclosed::Silent,
        (Disclosed::Awaited, Disclosed::Awaited) => Disclosed::Awaited,
    }
}

/// На чём стояло решение при принятии — другая величина, не то же знание. Не соединение: знание
/// обязано расти и не зависеть от порядка, запись о ПРОШЛОМ решении обязана зависеть (действовали
/// пришедшим первым). Функция ЗАМОРАЖИВАЕТ: первое непустое слово остаётся навсегда (событие без
/// значения закрывает вопрос сразу, позднее значение не двигает решение на середине). Ось одна:
/// здесь её снимок, берётся ровно когда ось покидает ⊥ («принято по значению, которого ещё нет»
/// непредставимо).
pub fn stood_on<T>(taken: Disclosed<T>, said: Disclosed<T>) -> Disclosed<T> {
    match (taken, said) {
        (Disclosed::Awaited, first_word) => first_word,
        (already, _later) => already,
    }
}
