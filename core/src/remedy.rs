//! ПОМОГЛО ЛИ ЛЕЧЕНИЕ — вердикт по темпу, а не по факту «байты пошли».
//!
//! # Чем оплачено (канарейка .8, 17.09.2026, #335)
//!
//! Продукт увёл видеоузел ютуба в контур. Свидетель лечения считал его вылеченным, как только
//! уведённый разговор получил хоть один байт, — и четыре разговора к кэшу провайдера, отдавшие по
//! 216 байт за 30 секунд (ссылка подписана под другой адрес, сервер отвечает отказом), читались бы
//! лечением. Тем временем тот же адрес по прямой, по QUIC, нёс 54 МБ за шесть минут, и видео у
//! человека шло именно им. Увод не помогал и не мешал — он просто ничего не значил, а решение
//! жило дальше.
//!
//! # Три исхода, и различает их СОСЕД, а не сам уведённый разговор
//!
//! «Уведённое не несёт» само по себе не повод снимать увод: цель может лежать целиком. Повод —
//! когда прямая к тем же адресам несёт, а уведённое нет. Поэтому вердикт берёт два темпа за одно
//! окно: лечимого пути и прямого.
//!
//! Порог «несёт» — аргумент, а не константа: сколько байт в секунду есть «несёт», знает потребитель
//! и его замер, не фундамент. Сравнение — точной дробью [`Pace`], без деления.

use crate::meter::Pace;

/// Что показало окно свидетельства после решения.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Remedy {
    /// Лечимый путь набрал темп — решение оправдано.
    Carries,
    /// Лечимый путь не несёт, а прямая к тем же адресам несёт — решение ничего не лечит.
    Starved,
    /// Не несёт ни лечимый путь, ни прямая — судить о решении не по чему.
    Nowhere,
}

/// Вердикт окна: темп лечимого пути, темп прямой к тем же адресам и порог «несёт».
pub fn remedy(treated: Pace, direct: Pace, enough: Pace) -> Remedy {
    match (treated >= enough, direct >= enough) {
        (true, _) => Remedy::Carries,
        (false, true) => Remedy::Starved,
        (false, false) => Remedy::Nowhere,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SECOND: u64 = 1_000_000_000;

    fn pace(bytes: u64, seconds: u64) -> Pace {
        Pace {
            bytes,
            over_nanos: seconds * SECOND,
        }
    }

    /// Порог поля: 4 КБ/с. Выбран между 57 Б/с уведённого и 150 КБ/с прямого — не замерен как граница.
    fn enough() -> Pace {
        pace(4_096, 1)
    }

    #[test]
    fn a_trickle_through_the_contour_is_not_a_cure_when_the_direct_path_carries() {
        // .8, 12:44:41: кэш провайдера через контур — 216 байт за 30 с; тот же адрес по прямой QUIC —
        // 54 354 703 байт за 363 с.
        assert_eq!(
            remedy(pace(216, 30), pace(54_354_703, 363), enough()),
            Remedy::Starved
        );
    }

    #[test]
    fn a_single_byte_is_not_a_cure() {
        // Прежний свидетель засчитывал «> 0». Здесь он красный по построению.
        assert_ne!(
            remedy(pace(216, 30), pace(0, 30), enough()),
            Remedy::Carries
        );
    }

    #[test]
    fn nothing_carries_anywhere_is_not_a_reason_to_revoke() {
        // .8, 12:45:06: `n8v7` через контур 6 864 байт за 121 с, по прямой TCP 100 байт — обрыв на приветствии.
        assert_eq!(
            remedy(pace(6_864, 121), pace(100, 1), enough()),
            Remedy::Nowhere
        );
    }

    #[test]
    fn a_real_download_through_the_contour_is_a_cure_whatever_the_direct_path_does() {
        // .8, 12:49:49: разговор через контур — 1 366 451 байт за 10 с.
        assert_eq!(
            remedy(pace(1_366_451, 10), pace(54_354_703, 363), enough()),
            Remedy::Carries
        );
    }

    #[test]
    fn the_threshold_itself_carries() {
        assert_eq!(
            remedy(pace(4_096, 1), pace(0, 1), enough()),
            Remedy::Carries
        );
    }
}
