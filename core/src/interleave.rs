//! ШОВ: ПАКЕТЫ И СЕТКА СХОДЯТСЯ В ОДИН ПОТОК.
//!
//! # Что этим решается
//!
//! Время перестаёт быть сервисом и становится буквой входного алфавита. Потребитель ниже по
//! течению не спрашивает часов вовсе: он читает `Packet | Tick | Opaque`
//! ([`DetectorEvent`](crate::detector::DetectorEvent)) — и этого довольно, чтобы выразить
//! `debounce`, `timeout`, окно, простой и всё прочее, что живёт во времени.
//!
//! Пока трафик идёт, узлы сетки между наблюдениями ВЫЧИСЛЯЮТСЯ, а не выжидаются: [`Interleave::saw`]
//! (разобралось) и [`Interleave::unread`] (не разобралось) чисты и часов не знают — у каждой буквы
//! своя дверь, и обе продвигают сетку одинаково. Будильник нужен ровно там, где событий нет, —
//! [`Interleave::idle`], — и это единственное место всего механизма, которому нужен тот, кто умеет
//! спать.
//!
//! # Почему шов, а не оператор
//!
//! Оператор над потоком (так время выражено в Rx) в тишине бессилен: поток пуст, преобразовывать
//! нечего, и «прошло пять секунд» сказать некому. Оттого там время приходится вносить извне —
//! планировщиком, который заодно решает, ГДЕ считать. Здесь молчание есть законный вход, и
//! способ ожидания перестаёт быть частью оператора: он свойство того, кто ПОРОЖДАЕТ поток.
//!
//! # Монотонность — требование, а не свойство
//!
//! Провод переставляет пакеты, очередь ядра отдаёт их не в порядке съёма, а выпуск разговоров из
//! горячего пути ([`crate::watch`]) означает, что часть событий мы не увидим вовсе. Событие с
//! моментом раньше уже выданного ломает всякий временной оператор ниже по течению — и ломает
//! МОЛЧА, потому что тот вправе считать вход монотонным.
//!
//! Шов это гарантирует и платит названную цену: опоздавшее событие выходит не со своим моментом, а
//! с последним выданным. Мы теряем точность на величину опоздания и НЕ теряем порядок. Обратный
//! выбор — пропускать назад — отдал бы точность тому, кто её всё равно не сможет использовать.

use core::time::Duration;
use std::time::Instant;

use crate::detector::DetectorEvent;

/// СОСТОЯНИЕ ШВА: откуда отмеряется сетка, какой у неё шаг и до какого момента поток уже выдан.
///
/// Шаги чисты и возвращают новое состояние, а не правят своё: результат есть функция входа, и это
/// единственное, что делает шов проверяемым таблицей — без рантайма, без ожидания, за секунды.
#[derive(Debug, Clone, Copy)]
pub struct Interleave {
    start: Instant,
    every: Duration,
    last: Instant,
}

impl Interleave {
    /// Шов, начатый в момент `at`: сетка отмеряется отсюда.
    pub fn started(at: Instant, every: Duration) -> Self {
        Self {
            start: at,
            every,
            last: at,
        }
    }

    /// НАБЛЮДЁН ПАКЕТ — что обязан увидеть потребитель.
    ///
    /// Сперва узлы сетки, которые пакет перешагнул, и лишь потом он сам. Порядок существен:
    /// детектор, увидевший пакет раньше закрытия окна, в которое пакет не попал, отнесёт его байты
    /// не к тому окну.
    pub fn saw<T>(self, input: T, at: Instant) -> (Self, Vec<DetectorEvent<T>>) {
        let at = at.max(self.last);
        let events = self
            .nodes_up_to(at)
            .chain(core::iter::once(DetectorEvent::Packet { input, at }))
            .collect();
        (Self { last: at, ..self }, events)
    }

    /// НАБЛЮДЕНО, НО РАЗОБРАТЬ НЕ СМОГЛИ — дверь для второй буквы, симметричная [`Interleave::saw`].
    ///
    /// Шов не читает содержимое наблюдения — он про МОМЕНТЫ, и непонятое продвигает сетку тем же
    /// способом, что и пакет: сперва узлы, которые оно перешагнуло, и лишь потом оно само. Не будь
    /// этой двери, поток из одних неразобранных пакетов не двигал бы сетку вовсе, и молчание под
    /// таким трафиком было бы неотличимо от «пакетов не было».
    pub fn unread<T>(
        self,
        why: crate::parse::Unread,
        at: Instant,
    ) -> (Self, Vec<DetectorEvent<T>>) {
        let at = at.max(self.last);
        let events = self
            .nodes_up_to(at)
            .chain(core::iter::once(DetectorEvent::Opaque { why, at }))
            .collect();
        (Self { last: at, ..self }, events)
    }

    /// ПРОШЛО ВРЕМЯ БЕЗ ПАКЕТОВ — какие узлы наступили.
    ///
    /// Тишина есть наблюдение, а не отсутствие его: приборы простоя видят свой предмет только
    /// здесь. Зовётся тем, у кого есть будильник ([`crate::clock::Ticks`] отдаёт управление
    /// рантайму, [`crate::clock::Beats`] занимает поток) — сам шов спать не умеет и не должен.
    pub fn idle<T>(self, at: Instant) -> (Self, Vec<DetectorEvent<T>>) {
        let at = at.max(self.last);
        let events = self.nodes_up_to(at).collect();
        (Self { last: at, ..self }, events)
    }

    /// Узлы сетки, наступившие с последнего выданного момента и по `at` включительно.
    ///
    /// Номер узла — [`crate::grid::due`] на его же момент: момент узла попадает на сетку ровно,
    /// так что «сколько узлов наступило к этому моменту» и есть номер этого узла — обратность
    /// [`crate::grid::node`] и [`crate::grid::due`] на ненулевом шаге.
    fn nodes_up_to<T>(&self, at: Instant) -> impl Iterator<Item = DetectorEvent<T>> {
        let start = self.start;
        let every = self.every;
        crate::grid::nodes_between(start, self.last, at, every).map(move |at| DetectorEvent::Tick {
            node: crate::grid::due(start, at, every),
            at,
        })
    }
}
