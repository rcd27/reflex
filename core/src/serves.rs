//! Источник, отдающий владение, а не копию. Канон §9. Очередь ядра не
//! [`Source`](crate::backend::Source): `packets(&mut self)` заимствует бэкенд на весь поток, а
//! ответить удержанному — второй `&mut` (`E0499`). Отсюда [`Serves`]: взять и ответить — один
//! неделимый шаг, носитель наружу не
//! выходит, потому «взял и забыл ответить» непредставимо по построению.
//!
//! КРАЙ — величина НОСИТЕЛЯ (`Serves::Edge`), не сообщения. Первая редакция вешала его на
//! сообщение (`Edging`, `core::held`) и добывала его оттуда фасадом (`held.carrier().edge()`) —
//! довод был верный не по тому вопросу: ГДЕ край вычисляется — величина разговора, а бэкенд видит
//! разговор только через пакет, и это осталось правдой. Но вопрос был другой: КТО ВПРАВЕ КРАЙ
//! ПОДМЕНИТЬ. Декоратор над носителем (`Local`, `core::local`) обязан отдать конвейеру СВОЙ край
//! вместо чужого, а подменить `impl Edging` на ЧУЖОМ типе сообщения (`C::Carrier::Carrier`)
//! декоратору нечем — правило сирот, да и `Edging` даёт РОВНО ОДИН `Edge` на тип. Перенос на
//! `Serves` решает это по построению: `serve` — та самая точка, где декоратор уже стоит между
//! вызывающим и обёрнутым, и вправе подменить решение целиком, включая край. `Edging` не снят —
//! он остаётся ВНУТРЕННИМ помощником носителя, у которого край и правда живёт в сообщении
//! (`QueueSocket::serve` строит `Self::Edge` через него); изменилось не ГДЕ край вычисляется, а
//! КТО его отдаёт наружу.

use crate::edge::EdgeView;
use crate::held::{Delivered, Held, Refused, Terminal};

/// Исход шага обслуживания. Алгебра, не `Option`: «не было работы» и «ждать не на чем» чинятся
/// по-разному.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Served<D, R> {
    /// Пакет взят, решение отдано миру — принято или отказано.
    Answered(Result<D, R>),
    /// Работы не было. Не ошибка: к сроку очередь осталась пуста.
    Idle,
    /// Ждать не на чем — дескриптор не добыт. Со сроком в подписи носитель обязан ПРОСПАТЬ до
    /// него: иначе ведущий цикл сожжёт ядро, а прежде это держалось соглашением с циклом.
    Blind,
    /// Носитель объявил потерю: наблюдения были и до нас не дошли. Клетка отдельная от `Idle` —
    /// «пусто» и «дыра» чинятся по-разному, и сравнивать наблюдения через необъявленную дыру нельзя.
    ///
    /// Момент несёт САМ ИСХОД — как его несёт [`Delivered`]. Иначе владельцев момента у трёх
    /// исходов было бы двое: `Answered` брал бы его у носителя (`Held::at`), а дыра — у часов
    /// зовущего, и носитель с ИНЫМИ часами (записанный провод, стенд, чужая ОС) объявлял бы дыру
    /// не в своей эпохе. Прежде это держал зажим шва (`at.max(last)`), то есть совпадение, а не
    /// закон.
    ///
    /// Это момент ОБНАРУЖЕНИЯ, а не потери: ядро выбросило сообщения раньше, чем мы позвали приём,
    /// и когда именно — не знает никто (`ENOBUFS` не несёт ни числа потерянных, ни времени).
    Torn(std::time::Instant),
}

/// Бэкенд, у которого взять пакет и ответить — один шаг. Носителя наружу не вынести — это держит
/// лайфтайм, не `#[must_use]`:
///
/// ```compile_fail
/// use reflex_core::held::Held;
/// use reflex_core::Serves;
///
/// fn steals<T: Serves>(queue: &mut T) -> Option<&Held<T::Carrier>>
/// where
///     T::Answer: Default,
/// {
///     let mut stolen = None;
///     queue.serve(std::time::Instant::now(), |held, _edge| {
///         stolen = Some(held);
///         T::Answer::default()
///     });
///     stolen
/// }
/// ```
pub trait Serves: Terminal {
    /// Что этот носитель ведёт о разговоре, которому принадлежит взятый пакет. `None` в исходе —
    /// обитаемая клетка (§7): «не считали», не «цель не ответила». Носитель без дома (очередь без
    /// conntrack) вправе объявить `Edge` любым типом закона и всегда отдавать `None` — сигнатура
    /// при этом честная: тип называет, ЧЕМ БЫ он считал, если бы считал, а `None` говорит, что не
    /// считает.
    type Edge: EdgeView;

    /// Взять пакет, решить, отдать решение — неделимо. **Не возвращается раньше `until`, кроме
    /// как с работой**: ждать умеет только владелец дескриптора, знать сколько — только владелец
    /// часов (§8). Пока эти двое не могли договориться, ведущий цикл заводил ожидание мимо шва.
    ///
    /// Сторож: `пустой_носитель_держит_срок`, `работа_возвращается_сразу`,
    /// `ошибка_приёма_тоже_держит_срок` (`core/tests/serves.rs`).
    ///
    /// Край — ВТОРОЙ довод решения, не поле сообщения: носитель строит его сам (внутри `serve`, где
    /// бэкенд занят ровно одним наблюдением) и отдаёт РЕШЕНИЮ, а не прячет за проекцией через
    /// сообщение. Декоратор (`Local`) отсюда и подменяет край — он стоит между вызывающим и
    /// обёрнутым `serve` и волен передать `decide` СВОЙ `Option<Self::Edge>` вместо того, что
    /// вернул обёрнутый носитель.
    fn serve<F>(
        &mut self,
        until: std::time::Instant,
        decide: F,
    ) -> Served<Delivered<Self::Answer>, Refused<Self::Answer, Self::Refusal>>
    where
        F: FnOnce(&Held<Self::Carrier>, Option<Self::Edge>) -> Self::Answer;

    /// Больше работы не будет НИКОГДА — источник кончился. У живой очереди всегда `false`: ядро
    /// конца не обещает. Значение по умолчанию не удобство, а закон — живой носитель конца не
    /// знает, и требовать от каждого написать ответ значило бы требовать ответа на вопрос, которого
    /// у него нет.
    ///
    /// Признак НОСИТЕЛЯ, не флаг фасада: знает о конце тот, у кого источник.
    ///
    /// ГРАНИЦА, названная нарочно: узлы сетки, наступившие после последней буквы, наружу не
    /// выходят. Выдавать их некому — машина, которой они адресованы, больше не получит ни одного
    /// пакета; а момент, в который зовущему случилось спросить о конце, наблюдением не является и
    /// в сценарии носителя не значится. Записано здесь, чтобы следующий не написал тест на счёт
    /// узлов и не досчитался.
    ///
    /// ТРЕБОВАНИЕ К РЕАЛИЗАТОРУ, НЕ ВЫВОДИМОЕ ИЗ ИМЕНИ: вопрос о конце ведущий цикл задаёт В НАЧАЛЕ
    /// оборота, ДО просьбы о работе (`reflex/src/lib.rs`, `drive`) — иначе честно выдержанная тишина
    /// потеряла бы свой последний узел. Отсюда `true` обязан значить не только «источник больше
    /// ничего не пришлёт», но и «в БУФЕРЕ носителя пусто ПРЯМО СЕЙЧАС»: носитель, копящий пачку
    /// внутри себя (`pending`-подобное поле) и вернувший `true`, пока пачка не вычитана, потеряет
    /// её МОЛЧА — цикл вернётся на этом же обороте, не позвав `serve` ни разу. Сегодня это
    /// недостижимо (переопределений одно, `QueueSocket`, и без внутреннего буфера ответа на
    /// `exhausted` вовсе нет — у живой очереди `false` по построению), но требование не про
    /// сегодняшний код, а про следующего реализатора: у него буфер будет.
    fn exhausted(&self) -> bool {
        false
    }
}
