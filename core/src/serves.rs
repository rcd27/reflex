//! ИСТОЧНИК, ОТДАЮЩИЙ ВЛАДЕНИЕ, А НЕ КОПИЮ.
//!
//! # Почему очередь ядра не [`Source`](crate::backend::Source), и это установлено компилятором
//!
//! `Source::packets(&mut self)` заимствует бэкенд на всё время потока, а ответить удержанному
//! пакету можно только через [`Terminal::apply`](crate::held::Terminal::apply) — второй `&mut`.
//! Проба 05.09.2026 дала `E0499` дословно: «cannot borrow `*backend` as mutable more than once».
//!
//! У `AfPacketBackend` того же конфликта нет, потому что у него ДВА устройства — кольцо приёма и
//! инжектор, — и `split()` их разводит. У очереди netlink-сокет ОДИН: делить нечего, и никакой
//! ловкостью это не обходится.
//!
//! # Что из этого следует для категории
//!
//! Не «очередь плохая», а «`Source` описывает не её». `Source` — про НАБЛЮДЕНИЕ: он отдаёт копию,
//! и потому пакетов может быть сколько угодно в полёте. Очередь отдаёт ВЛАДЕНИЕ: пока мы держим
//! носителя, пакет висит в ядре, и второго такого нам не дадут, пока не ответим на первый.
//!
//! Отсюда форма [`Serves`]: взять и ответить — ОДИН неделимый шаг. Носитель наружу не выходит
//! вовсе, поэтому «взял и забыл ответить» становится непредставимым — не по `#[must_use]`,
//! который лишь предупреждает, а по построению: держать носителя негде.
//!
//! Решение при этом остаётся ЧИСТЫМ: `decide` видит наблюдение и возвращает значение, мира не
//! касаясь. Мир случается там же, где и был, — в терминале.

use crate::held::{Delivered, Held, Refused, Terminal};

/// ЧЕМ КОНЧИЛСЯ ШАГ ОБСЛУЖИВАНИЯ. Алгебра, а не `Option`: у «не было работы» и «ждать не на чем»
/// разная починка, и слить их значило бы вернуть беду, за которую уже заплачено (#287 — «обработчик
/// не звали» и «пакета не было» давали один выход, и прибор, чей «ничего не нашёл» неотличим от
/// «не запускался», ввёл в заблуждение на 29 идентификаторах против 17 вызовов).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Served<D, R> {
    /// Пакет взят, решение принято и отдано миру — а мир либо принял его, либо отказал.
    Answered(Result<D, R>),
    /// Работы не было. Это НЕ ошибка: очередь пуста, и это её нормальное состояние.
    Idle,
    /// Ждать не на чем — дескриптор очереди не добыт. Ведущий цикл обязан сам не жечь процессор.
    Blind,
}

/// БЭКЕНД, У КОТОРОГО ВЗЯТЬ ПАКЕТ И ОТВЕТИТЬ — ОДИН ШАГ.
///
/// # Носителя не вынести наружу, и это проверяет компилятор
///
/// ```compile_fail
/// use reflex_core::held::Held;
/// use reflex_core::Serves;
///
/// fn steals<T: Serves>(queue: &mut T) -> Option<&Held<T::Carrier>>
/// where
///     T::Answer: Default,
/// {
///     let mut stolen = None;
///     queue.serve(|held| {
///         stolen = Some(held);
///         T::Answer::default()
///     });
///     stolen
/// }
/// ```
///
/// Забрать носителя себе значило бы оставить пакет висеть в ядре — и никакая пометка вроде
/// `#[must_use]` этого не запрещает, она лишь предупреждает. Здесь запрещает лайфтайм.
pub trait Serves: Terminal {
    /// Взять следующий удержанный пакет, решить и отдать решение — неделимо.
    ///
    /// Исход — [`Served`], а не `Option`: «работы не было» и «ждать не на чем» суть разные
    /// состояния мира с разной починкой, и ведущий цикл вправе считать их по отдельности.
    ///
    /// `decide` получает носителя ПО ССЫЛКЕ: решение читает наблюдение, но распорядиться
    /// носителем не может — распоряжается терминал, и ровно один раз.
    fn serve<F>(
        &mut self,
        decide: F,
    ) -> Served<Delivered<Self::Answer>, Refused<Self::Answer, Self::Refusal>>
    where
        F: FnOnce(&Held<Self::Carrier>) -> Self::Answer;
}
