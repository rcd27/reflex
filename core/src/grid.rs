//! СЕТКА ВРЕМЕНИ — ОДИН ЗАКОН НА ВСЕ ЧАСЫ.
//!
//! # Зачем примитив
//!
//! Замер 05.09.2026: закон был написан ЧЕТЫРЕ раза — в часах записи ([`crate::pcap::with_ticks`]),
//! в тестовых часах, в системных синхронных ([`crate::clock::Beats`]) и в асинхронных. Три
//! считали одинаково; четвёртые, поверх `tokio::interval`, дрейфуют — их док цену называет, но
//! следствие шире, чем цена одной реализации: **детектор, поверенный на тестовых часах, под
//! нагрузкой исполняется по другой сетке**.
//!
//! # Закон один: сетка отмеряется ОТ НАЧАЛА
//!
//! Не от предыдущего события. Иначе на плотном потоке — пакеты каждые 30 мс при окне 300 мс —
//! пауз нужной длины нет ни одной, и часы не идут ВОВСЕ. Приборы, чей предмет виден только при
//! идущем трафике (троттлинг, просадка), молчат на таком потоке всегда, а молчание неотличимо от
//! «беды нет» (#320).
//!
//! # Здесь нет сна, и это главное
//!
//! Функции чисты: они говорят, какие узлы сетки НАСТУПИЛИ между двумя наблюдёнными моментами.
//! Ждать — дело того, у кого есть чем ждать ([`crate::clock::Ticks`] отдаёт управление рантайму,
//! [`crate::clock::Beats`] занимает поток). Пока трафик идёт, ждать не нужно вовсе: узлы между
//! пакетами ВЫЧИСЛЯЮТСЯ, а не выжидаются, и таймер нужен только на настоящую тишину.
//!
//! # Что делать с пропущенными узлами — решает потребитель
//!
//! Функция отдаёт все, что накрыла пауза. Схлопывать их (одно закрытие окна) или выдавать по
//! одному — выбор с разной ценой: залп есть ошибка СОБЫТИЙНАЯ и выглядит как настоящая беда;
//! схлопывание есть ошибка ВЕЛИЧИНЫ и видно как величина. Часы, схлопывающие молча, лишают
//! потребителя этого выбора.

use core::time::Duration;
use std::time::Instant;

/// НАНОСЕКУНДЫ ШАГА, ЕСЛИ СЕТКА СУЩЕСТВУЕТ.
///
/// Нулевой шаг — не «очень частая сетка», а её отсутствие: узлов у неё нет. Прежние часы отвечали
/// на такой шаг `u64::MAX` тиков — число, выглядящее как «очень много» там, где верно «не знаем».
fn step_nanos(every: Duration) -> Option<u64> {
    match u64::try_from(every.as_nanos()) {
        Ok(0) | Err(_) => None,
        Ok(step) => Some(step),
    }
}

/// МОМЕНТ `nth`-ГО УЗЛА СЕТКИ, отсчитанного от `start`.
///
/// Умножение в `u64` наносекунд, а не `Duration * u32`: прежние две копии считали
/// `every * (nth as u32)`, и на миллисекундной сетке `u32` кончается через 49 суток аптайма —
/// сетка завернулась бы в прошлое, то есть все временны́е операторы разом получили бы время,
/// идущее назад. У коробки, живущей месяцами, это не гипотеза.
pub fn node(start: Instant, every: Duration, nth: u64) -> Instant {
    match step_nanos(every) {
        None => start,
        Some(step) => start + Duration::from_nanos(step.saturating_mul(nth)),
    }
}

/// СКОЛЬКО УЗЛОВ СЕТКИ НАСТУПИЛО К МОМЕНТУ `at`.
///
/// Узел в самый момент `start` не считается наступившим: сетка начинается с него, а первый её шаг
/// приходит через `every`.
pub fn due(start: Instant, at: Instant, every: Duration) -> u64 {
    match step_nanos(every) {
        None => 0,
        Some(step) => match u64::try_from(at.saturating_duration_since(start).as_nanos()) {
            Ok(passed) => passed / step,
            Err(_) => u64::MAX,
        },
    }
}

/// УЗЛЫ СЕТКИ, ПОПАВШИЕ В ПОЛУИНТЕРВАЛ `(before, after]`.
///
/// Полуинтервал, а не отрезок: узел, совпавший с левым краем, уже выдан прошлым шагом, и выдать
/// его снова значило бы закрыть одно окно дважды.
pub fn nodes_between(
    start: Instant,
    before: Instant,
    after: Instant,
    every: Duration,
) -> impl Iterator<Item = Instant> {
    let first = due(start, before, every) + 1;
    let last = due(start, after, every);
    (first..=last).map(move |nth| node(start, every, nth))
}
