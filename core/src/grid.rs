//! Сетка времени — один закон на все часы. Замер: закон был написан ЧЕТЫРЕ раза (часы записи,
//! тестовые, синхронные, асинхронные); три считали одинаково, четвёртые поверх `tokio::interval`
//! дрейфуют — детектор, поверенный на тестовых часах, под нагрузкой исполняется по другой сетке.
//! Закон один: сетка отмеряется ОТ НАЧАЛА, не от предыдущего события — иначе на плотном потоке
//! (пакеты каждые 30 мс при окне 300 мс) пауз нужной длины нет, часы не идут вовсе, и приборы
//! троттлинга/просадки молчат всегда (молчание неотличимо от «беды нет», #320). Сна здесь нет:
//! функции чисты, говорят, какие узлы наступили между двумя моментами; ждать — дело того, у кого есть
//! чем. Что делать с пропущенными узлами — решает потребитель (залп есть ошибка событийная,
//! схлопывание — ошибка величины; часы, схлопывающие молча, лишают выбора).

use core::time::Duration;
use std::time::Instant;

/// Наносекунды шага, если сетка существует. Нулевой шаг — не «очень частая сетка», а её отсутствие:
/// узлов нет. Прежние часы отвечали `u64::MAX` тиков — «очень много» там, где верно «не знаем».
fn step_nanos(every: Duration) -> Option<u64> {
    match u64::try_from(every.as_nanos()) {
        Ok(0) | Err(_) => None,
        Ok(step) => Some(step),
    }
}

/// Номер следующего узла сетки после момента `before`. Возвращает `None` при отсутствии сетки
/// (нулевой шаг) — узла не будет, какой бы момент ни спросил. Чистая функция: проходящий момент
/// был бы гарантией «узел наступит», но нулевой шаг отменяет эту гарантию, оставляя только
/// значение — его нет.
pub(crate) fn next_due(start: Instant, before: Instant, every: Duration) -> Option<u64> {
    step_nanos(every).map(|_| due(start, before, every) + 1)
}

/// Момент `nth`-го узла сетки от `start`. Умножение в `u64` наносекунд, не `Duration * u32`: прежние
/// копии считали `every * (nth as u32)`, и на миллисекундной сетке `u32` кончается через 49 суток —
/// сетка завернулась бы в прошлое, все временны́е операторы разом получили бы время назад.
pub fn node(start: Instant, every: Duration, nth: u64) -> Instant {
    match step_nanos(every) {
        None => start,
        Some(step) => start + Duration::from_nanos(step.saturating_mul(nth)),
    }
}

/// Сколько узлов сетки наступило к моменту `at`. Узел в самый `start` не считается наступившим:
/// сетка начинается с него, первый шаг через `every`.
pub fn due(start: Instant, at: Instant, every: Duration) -> u64 {
    match step_nanos(every) {
        None => 0,
        Some(step) => match u64::try_from(at.saturating_duration_since(start).as_nanos()) {
            Ok(passed) => passed / step,
            Err(_) => u64::MAX,
        },
    }
}

/// Узлы сетки в полуинтервале `(before, after]`. Полуинтервал, не отрезок: узел на левом краю уже
/// выдан прошлым шагом, выдать снова значило бы закрыть одно окно дважды.
pub fn nodes_between(
    start: Instant,
    before: Instant,
    after: Instant,
    every: Duration,
) -> impl Iterator<Item = Instant> {
    let last = due(start, after, every);
    let first = next_due(start, before, every).unwrap_or_else(|| last + 1);
    (first..=last).map(move |nth| node(start, every, nth))
}
