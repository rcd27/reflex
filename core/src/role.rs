//! РОЛИ ПЛАГИНОВ (#318) — ПАСПОРТА, а не поведение.
//!
//! # Почему здесь, в reflex, а не у потребителя
//!
//! Правило сирот показало то, что мы и так знали, но откладывали: роль общая. Пока трейт жил у
//! движка, а типы — у плоскости, реализовать одно для другого не мог никто, кроме них самих, и
//! связь пришлось бы гнуть обёртками. Роль про цели и ноги не знает — ей место рядом с
//! [`crate::backend::Source`] и [`crate::backend::Sink`], которые она и обобщает.
//!
//! # Чем отличается от `Sink`
//!
//! `Sink::emit` возвращает `Result`, то есть свидетельствует ОТПРАВКУ. Болезнь живёт в зазоре
//! между отправкой и применением: приказ доехал, был разобран, назван в журнале — и не
//! применился. `Executor` требует свидетельство ПРИМЕНЕНИЯ, и требует его типом.

/// ИСПОЛНИТЕЛЬ — тот, кто применяет решение И МОЖЕТ ЭТО ПОДТВЕРДИТЬ.
///
/// # `Applied` обязателен, и в этом весь смысл роли
///
/// Плагин, которому нечем предъявить свидетельство применения, не «реализует роль плохо» — он её
/// НЕ РЕАЛИЗУЕТ, и это ошибка сборки. Тем самым главная болезнь наших швов — приказ доехал, был
/// разобран, назван в журнале и не применился, а мы отчитались зелёным — превращается из
/// наблюдения задним числом в отказ компилятора.
///
/// Оплачено четырежды: `nfqws2` («закон порядка живёт у исполнителя, виден только его `--debug`»),
/// плоскость («витнес утверждения 1 мерил снятый механизм»), хостлисты («у подписи есть секунда»),
/// лифт («переменная из init субстрата переспорила код»).
///
/// # Свидетельство приходит СВОИМ темпом
///
/// `observed` не связан с `Order` ни возвратом, ни моментом: подтверждение вправе опоздать,
/// прийти обобщённым за много приказов сразу или не прийти вовсе. Связать их значило бы завести
/// запрос-ответ там, где его нет, и выдать задержку за отказ.
///
/// # Отсутствие свидетельства — НЕ ноль
///
/// `None` значит «спросить не у кого»: плагин мёртв, правило снято, канал закрыт. Нулевое
/// свидетельство — совсем другое утверждение: «применялось ноль раз, и это установлено». Первое
/// лечится починкой связи, второе — поиском причины, по которой работа идёт мимо.
///
/// # Исполнитель без свидетельства не собирается
///
/// Витнес того же рода, что `compile_fail` у `reflex_core::backend`: пометку можно не заметить,
/// ограничение — нельзя.
///
/// ```compile_fail
/// use reflex_core::role::Executor;
///
/// struct Nfqws2;
///
/// // Умеет принять наряд — и только. Чем подтвердит применение, сказать нечем.
/// impl Executor for Nfqws2 {
///     type Order = String;
/// }
/// ```
pub trait Executor {
    /// Что этот исполнитель способен принять.
    type Order;

    /// Чем свидетельствуется ПРИМЕНЕНИЕ. Не доставка: «приказ ушёл» у нас никогда не ломалось.
    type Applied;

    /// Спросить свидетельство. Дёшево и без побочных действий: зовётся в темпе решений, а не
    /// в темпе трафика.
    fn observed(&self) -> Option<Self::Applied>;
}
