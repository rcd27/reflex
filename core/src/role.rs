//! Роли плагинов (#318) — паспорта, а не поведение. Роль общая: пока трейт жил у движка, а типы у
//! плоскости, реализовать одно для другого не мог никто — ей место рядом с [`crate::backend::Source`]
//! и [`crate::backend::Sink`], которые она обобщает. Отличие от `Sink`: `Sink::emit` свидетельствует
//! ОТПРАВКУ, а болезнь живёт в зазоре между отправкой и применением (приказ доехал, разобран, назван
//! в журнале — и не применился). `Executor` требует свидетельство ПРИМЕНЕНИЯ, и требует его типом.

/// Исполнитель — тот, кто применяет решение И может это подтвердить. `Applied` обязателен, в этом
/// весь смысл роли: плагин, которому нечем предъявить свидетельство, роль НЕ реализует (ошибка
/// сборки) — главная болезнь швов (не применилось, а отчитались зелёным) становится отказом
/// компилятора. Оплачено четырежды (`nfqws2`, плоскость, хостлисты, лифт). Свидетельство приходит
/// своим темпом: `observed` не связан с `Order` ни возвратом, ни моментом (подтверждение вправе
/// опоздать, прийти обобщённым, не прийти). `None` — «спросить не у кого» (плагин мёртв, правило
/// снято), не нулевое свидетельство («применялось ноль раз, установлено»): первое лечится починкой
/// связи, второе — поиском причины. Исполнитель без свидетельства не собирается:
///
/// ```compile_fail
/// use reflex_core::role::Executor;
///
/// struct Nfqws2;
///
/// // Умеет принять наряд — и только. Чем подтвердит применение, сказать нечем.
/// impl Executor for Nfqws2 {
///     type Order = String;
/// }
/// ```
pub trait Executor {
    /// Что этот исполнитель способен принять.
    type Order;

    /// Чем свидетельствуется ПРИМЕНЕНИЕ. Не доставка: «приказ ушёл» у нас никогда не ломалось.
    type Applied;

    /// Спросить свидетельство. Дёшево и без побочных действий: зовётся в темпе решений, не трафика.
    fn observed(&self) -> Option<Self::Applied>;
}
