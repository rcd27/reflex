//! ЗАКОН НАБЛЮДЕНИЯ: ЧТО ПОРОДИЛ МИР — ВИДНО НАБЛЮДАТЕЛЮ, И ПРИТОМ ВСЁ.
//!
//! # Роли перевёрнуты, и вместе с ними — недействительность
//!
//! В [`injection`](super::injection) подопытный отправлял, а свидетельствовал тот, до кого должно
//! было дойти. Здесь подопытный НАБЛЮДАЕТ, а свидетельствует [`Origin`] — тот, кто породил трафик.
//! Соответственно и молчание значит другое: там молчал прибор, здесь молчит мир.
//!
//! # Почему закон СЧИТАЕТ, а не проверяет наличие
//!
//! `CanObserve` требует [`Source`](crate::backend::Source): заявить «умею наблюдать», не отдавая
//! потока, нельзя. Но вторая половина смысла — «НЕ ВМЕШИВАЯСЬ» — типом не выражается вовсе.
//! Наблюдатель, роняющий каждый второй пакет, синтаксически неотличим от честного, и увидеть это
//! можно только счётом. Отсюда же требование к [`Origin`]: он обязан знать, сколько кадров ушло, и
//! знать это НЕ от подопытного.
//!
//! # Кто ограничивает поток
//!
//! Не закон. `Source` отдаёт поток, который у живого бэкенда бесконечен, и всякий потолок — это
//! ЧАСЫ, которых у закона нет и быть не должно. Поэтому [`watching`] лишь открывает дверь
//! (требуя заявленной способности), обрезает поток устройство — там, где часы известны, — а закон
//! читает то, что ему дали, до конца.

use std::cmp::Ordering;

use futures::{Stream, StreamExt};

use super::{carries, Verdict};
use crate::backend::Source;
use crate::capability::CanObserve;
use crate::held::Observed;

/// КТО ПОРОДИЛ ТРАФИК И СКОЛЬКО ЕГО УШЛО.
///
/// Число берётся НЕ у подопытного: спрашивать наблюдателя, сколько было пакетов, значит принимать
/// его же показания за меру его же точности. В памятном мире это заданное число, на живом
/// устройстве — разность счётчиков ядра до и после отправки, то есть прибор иной природы, чем и
/// наблюдатель, и libpcap.
pub trait Origin {
    /// Породить трафик, несущий нонс, и ответить, сколько кадров ушло НА САМОМ ДЕЛЕ.
    fn emit(&mut self, nonce: &[u8]) -> usize;
}

/// ПОЧЕМУ ЗАКОН НЕ ДЕРЖИТСЯ. Потеря и дубль — не оттенки друг друга.
///
/// Первая лечится в приёме (кольцо мало, читатель не успевает), второй — в разметке (один кадр
/// снят дважды, например с двух точек съёма). Свести их к «число не сошлось» значило бы отнять у
/// читателя ровно то, по чему они различаются.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Broken {
    /// Наблюдатель увидел МЕНЬШЕ, чем ушло: он вмешивается в ход, роняя пакеты.
    Lost { sent: usize, seen: usize },
    /// Наблюдатель увидел БОЛЬШЕ, чем ушло: один кадр посчитан несколько раз.
    Duplicated { sent: usize, seen: usize },
}

/// ПОЧЕМУ ВЕРДИКТА НЕТ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Invalid {
    /// Мир не породил НИ ОДНОГО кадра — наблюдателю нечего было видеть.
    ///
    /// Зеркало [`injection::Invalid::WitnessSilent`](super::injection::Invalid::WitnessSilent):
    /// там молчал прибор, здесь молчит мир, и оба раза беда — стенда, а не подопытного. Предъявить
    /// наблюдателю, что он не увидел ничего, когда ничего и не было, значит наказать за чужое.
    WorldSilent,
}

/// ДВЕРЬ К НАБЛЮДЕНИЯМ ЭТОГО БЭКЕНДА — и единственная.
///
/// Функция ничего не делает сверх `packets()`, и в этом её смысл: она требует ЗАЯВЛЕННОЙ
/// способности. Поток, поданный закону, не подсунуть от типа, который наблюдать не заявлял, —
/// а раз `CanObserve` требует `Source`, заявить его пустым тоже нельзя.
///
/// Ограничение потока сюда НЕ входит намеренно: у живого бэкенда он бесконечен, и обрезать его
/// умеет только тот, у кого есть часы. Закон часов не имеет — иначе он мерил бы время, а не
/// способность.
pub fn watching<B>(dut: &mut B) -> B::Packets<'_>
where
    B: Source + CanObserve,
    B::Packet: Observed,
{
    dut.packets()
}

/// ЗАКОН НАБЛЮДЕНИЯ.
///
/// # Порядок обязателен
///
/// Поток создаётся ДО вызова закона (`watching(&mut dut)` в аргументе), а мир порождает трафик
/// ВНУТРИ. Наоборот было бы проверкой того, успел ли наблюдатель подписаться, — вопрос законный,
/// но другой, и он бы молча подменил предмет.
///
/// # Чужой трафик не засчитывается ни за, ни против
///
/// Наблюдатель видит и посторонние кадры. Считай закон всё подряд — честный наблюдатель в живом
/// сегменте немедленно стал бы «двоящим», и вердикт говорил бы о шуме, а не о способности.
pub async fn observes<P, S, O>(
    origin: &mut O,
    nonce: &[u8],
    observed: S,
) -> Verdict<Broken, Invalid>
where
    P: Observed,
    S: Stream<Item = P>,
    O: Origin,
{
    let sent = origin.emit(nonce);
    let seen = observed
        .filter(|packet| std::future::ready(carries(packet.payload(), nonce)))
        .count()
        .await;

    match sent {
        0 => Verdict::Invalid(Invalid::WorldSilent),
        sent => match seen.cmp(&sent) {
            Ordering::Equal => Verdict::Held,
            Ordering::Less => Verdict::Broken(Broken::Lost { sent, seen }),
            Ordering::Greater => Verdict::Broken(Broken::Duplicated { sent, seen }),
        },
    }
}
