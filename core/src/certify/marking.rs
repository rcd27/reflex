//! ЗАКОН МЕТКИ: ПОМЕТИЛИ — И ТОТ, КТО НИЖЕ, ЭТО ПРОЧИТАЛ.
//!
//! # Единственный закон, чей свидетель не смотрит на провод
//!
//! Метка не уезжает в сеть. Она живёт внутри ядра и адресована не собеседнику, а правилам, стоящим
//! ниже по обходу пакета. Поэтому смотрящий на провод свидетель здесь бесполезен по построению, и
//! свидетельствовать способен только [`Reader`] — тот, ради кого метка ставится.
//!
//! # Грабля, ради которой закон и заведён
//!
//! Пакет продолжает обход С МЕСТА, ГДЕ ЕГО ЗАБРАЛИ. Правило, читающее метку, обязано стоять НИЖЕ
//! правила очереди; поставь его выше — метка встанет и не будет прочитана НИКЕМ, а прибор покажет
//! «решение принято». Знание записано в коде у `Answer::Marked` с 31.08.2026 и до этого закона не
//! проверялось ничем: изнутри процесса «метку поставили» и «метку прочитали» неотличимы совершенно.
//!
//! # Свидетелей ДВОЕ, и это не роскошь
//!
//! Счётчик читателя отвечает, прочитана ли метка. Он же молчит и когда пакет не дошёл вовсе — а
//! это другая беда с другой починкой. Отличить их может только тот, кто смотрит на провод, поэтому
//! закон спрашивает обоих: [`Downstream`] про пакет, [`Reader`] про метку.

use crate::capability::CanMark;
use crate::held::{Held, Observed, Terminal};

use super::{carries, Downstream, Verdict};

/// ТОТ, РАДИ КОГО МЕТКА СТАВИТСЯ.
///
/// В бою — счётчик правила `meta mark`, стоящего ниже очереди; в памятном мире — число. Закон об
/// их различии не знает: он спрашивает «сколько ты прочитал с прошлого раза».
///
/// Метка передаётся параметром намеренно: читатель, отвечающий на любой вопрос одинаково, не
/// отличил бы нашу метку от чужой, и закон засчитал бы посторонний трафик — беда, которую репа уже
/// ловила счётчиком, двигавшимся от чужих пакетов.
pub trait Reader {
    fn read(&mut self, mark: u32) -> usize;
}

/// ПОЧЕМУ ЗАКОН НЕ ДЕРЖИТСЯ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Broken {
    /// Пакет прошёл, а читатель метки её не увидел.
    ///
    /// Либо метка не встала, либо — что вероятнее и что здесь и ловится — читатель стоит ВЫШЕ
    /// правила очереди и остался позади. Снаружи различить эти два случая нечем, и хорошо: чинить
    /// придётся в обоих одно и то же место — порядок правил.
    MarkUnread,
    /// Пометили — и пакет не пошёл. Метка тут ни при чём: беда в том, что отпускания не случилось.
    NotPassed,
}

/// ПОЧЕМУ ВЕРДИКТА НЕТ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Invalid {
    /// Свидетель провода не показал НИ ОДНОГО кадра — ни нашего, ни чужого. Без этой развилки
    /// `NotPassed` предъявлялся бы всякий раз, когда сломался стенд.
    WitnessSilent,
    /// Пакет ушёл ДО нашего ответа: удержания не было, и судить о метке не о чем.
    NotHeld,
    /// Терминал честно сказал, что ответ не принят.
    AnswerNotTaken,
}

/// ЗАКОН МЕТКИ.
///
/// Порядок опроса тот же, что у соседей: сперва убедиться, что пакет ещё у нас, затем ответить,
/// затем спросить мир. Разница в том, что мир здесь отвечает ДВУМЯ голосами, и согласны они не
/// всегда — в несогласии и живёт находка.
pub fn marks<T, D, R>(
    dut: &mut T,
    held: Held<T::Carrier>,
    mark: u32,
    downstream: &mut D,
    reader: &mut R,
) -> Verdict<Broken, Invalid>
where
    T: Terminal + CanMark,
    T::Carrier: Observed,
    D: Downstream + ?Sized,
    R: Reader + ?Sized,
{
    let ours = held.seen().to_vec();

    match downstream.passed().iter().any(|gone| carries(gone, &ours)) {
        true => Verdict::Invalid(Invalid::NotHeld),
        false => match dut.apply(held.answered(T::mark(mark))) {
            Err(_not_taken) => Verdict::Invalid(Invalid::AnswerNotTaken),
            Ok(_delivered) => match downstream.passed().as_slice() {
                [] => Verdict::Invalid(Invalid::WitnessSilent),
                seen => {
                    let passed = seen.iter().any(|gone| carries(gone, &ours));
                    let counted = reader.read(mark) > 0;
                    match (passed, counted) {
                        (true, true) => Verdict::Held,
                        (true, false) => Verdict::Broken(Broken::MarkUnread),
                        // Читатель метку видел, а провод пакета не показал — не беда, а рабочий
                        // случай: метка увела пакет другим маршрутом, мимо нашего свидетеля. Метка
                        // прочитана, то есть ровно то, что закон и утверждает.
                        (false, true) => Verdict::Held,
                        (false, false) => Verdict::Broken(Broken::NotPassed),
                    }
                }
            },
        },
    }
}
