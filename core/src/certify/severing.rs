//! ЗАКОН ОБРЫВА: РАЗГОВОР НЕ СОСТОЯЛСЯ, И ВСТРЕЧНАЯ СТОРОНА ОБ ЭТОМ ЗНАЕТ.
//!
//! # Почему это не сумма отказа и инъекции
//!
//! Прогнать подряд [`refuses`](super::refusal::refuses) и [`injects`](super::injection::injects)
//! значит установить, что бэкенд умеет отказывать и умеет вводить. Обрыв — не эта конъюнкция: у
//! него есть АДРЕСАТ, и вся разница между лечением и бедой лежит в нём.
//!
//! Перепутать стороны — правка одной строки в вычислении концов. Закон отказа при этом увидит,
//! что исходное не прошло; закон инъекции — что наш кадр где-то наблюдаем. Оба скажут
//! «держится», а на проводе будет наш RST, уехавший ЦЕЛИ: разговор клиента цел, зато цель
//! извещена о том, что её ведут.
//!
//! # Две границы — два свидетеля
//!
//! [`Downstream`] стоит по пути к цели, [`NearEnd`] — на стороне, породившей разговор. Один
//! свидетель на обе границы не различал бы «дошло клиенту» и «дошло цели», то есть был бы нем
//! ровно на предмете закона.
//!
//! # Что этим НЕ проверяется, и это названо, а не забыто
//!
//! ПОРЯДОК. «Извещение дошло до клиента раньше, чем цель успела ответить мёртвому сокету» —
//! требование живое и записанное в продукте словами, но здесь невыразимое: у пакета, которого
//! нет, нет и метки времени, а сравнивать приход извещения не с чем. Чтобы порядок стал
//! наблюдаем, дальнему концу нужна ЭХО-роль — он должен отвечать. Долг помечен `TODO(#326)` в
//! устройстве стенда, а не оставлен подразумеваемым.

use crate::backend::Sink;
use crate::capability::{CanInject, CanSever, Toward};
use crate::held::{Held, Observed, Terminal};

use super::{carries, Downstream, Verdict};

/// СВИДЕТЕЛЬ НА СТОРОНЕ, ПОРОДИВШЕЙ РАЗГОВОР.
///
/// Отдельный трейт, а не второй [`Downstream`], и различие несёт ИМЯ: спрашивают их об одном и
/// том же — «что пришло с прошлого вопроса», — но стоят они на разных границах, и перепутать их
/// местами значит перевернуть вердикт закона в противоположный. Тип, у которого две роли названы
/// одним словом, приглашает именно к такой ошибке.
pub trait NearEnd {
    /// ЧТО ПРИШЛО НА ЭТУ СТОРОНУ С ПРОШЛОГО ВОПРОСА.
    fn arrived(&mut self) -> Vec<Vec<u8>>;
}

/// ПОЧЕМУ ЗАКОН НЕ ДЕРЖИТСЯ. Четыре беды, и лечатся они в четырёх разных местах.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Broken {
    /// Ответили «не пропускать», а пакет пошёл дальше.
    ///
    /// Самое опасное: движок уверен, что оборвал, а разговор идёт. Если при этом клиент получил
    /// извещение — он закрыл сокет по живому соединению, то есть вмешательство сделало хуже, чем
    /// бездействие.
    PassedAnyway,
    /// Пакет удержан, а сказать об этом забыли.
    ///
    /// Ровно то, чем бьёт ТСПУ: клиент ретрансмитит и ждёт, человек видит «страница висит». Это
    /// НЕ безобидная неполнота — это воспроизведение той самой беды, которую обрыв лечит.
    NoticeMissed,
    /// Извещение уехало ЦЕЛИ вместо породившей стороны.
    ///
    /// Стороны перепутаны. Клиент по-прежнему ждёт, а цель получила наш кадр — то есть мы
    /// вдобавок показали ей, что разговор ведут.
    NoticeToTarget,
    /// Ни отказа, ни извещения: решение не исполнено целиком.
    ///
    /// Отдельно от [`Broken::PassedAnyway`] намеренно. Там сломана одна половина, и чинить надо
    /// исполнение вердикта; здесь не сработало ничто, и чинить надо путь решения до носителей.
    NeitherHappened,
    /// Извещение не из чего построить: способность заявлена, а на ЭТОМ носителе сказать нечем.
    ///
    /// Не беда стенда: стенд исправен, отвечает подопытный. Заявив [`CanSever`], бэкенд обещал
    /// обрыв целиком — и обязан отвечать за вход, на котором обещание пусто.
    NoticeUnbuildable,
}

/// ПОЧЕМУ ВЕРДИКТА НЕТ. Беды СТЕНДА, а не подопытного.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Invalid {
    /// Пакет ушёл ДО нашего ответа: удержания не было, и судить об обрыве нечего.
    ///
    /// Предмет [`holds`](super::holding::holds), и у него свой вердикт.
    NotHeld,
    /// Терминал честно сказал, что ответ не принят.
    AnswerNotTaken,
    /// Сток честно отказался отправлять извещение.
    SinkRefused,
    /// Дальний свидетель не показал НИ ОДНОГО кадра — ни нашего, ни чужого.
    DownstreamMute,
    /// Ближний свидетель не показал НИ ОДНОГО кадра.
    ///
    /// Различать эту немоту с [`Invalid::DownstreamMute`] обязательно: приборы стоят в разных
    /// местах и ломаются по разным причинам, а «оба молчат» есть не удвоенная беда, а другая.
    NearEndMute,
}

/// ЗАКОН ОБРЫВА.
///
/// Слова берутся у самих способностей — отказ у [`CanSever`] через супертрейт, извещение у
/// [`CanSever::notice`]. Закон, которому их передают снаружи, проверял бы согласие вызывающего с
/// самим собой.
///
/// `toward` приходит параметром, и это не исключение из правила выше: кто из двух концов пакета
/// есть клиент — знание ВХОДА, а не бэкенда (у очереди оно из правила, у записи — из улики).
/// Втяни его сюда — и рядом с первым правилом завелось бы второе.
pub fn severs<T, B, D, N>(
    dut: &mut T,
    wire: &mut B,
    held: Held<T::Carrier>,
    toward: Toward,
    downstream: &mut D,
    near: &mut N,
) -> Verdict<Broken, Invalid>
where
    T: Terminal + CanSever,
    T::Carrier: Observed,
    B: Sink + CanInject,
    D: Downstream + ?Sized,
    N: NearEnd + ?Sized,
{
    let ours = held.seen().to_vec();

    // «СКАЗАТЬ НЕЧЕМ» РАЗБИРАЕТСЯ ДО ВСЯКОГО ДЕЙСТВИЯ. Отказать, а потом обнаружить, что
    // извещения нет, значило бы ОБОРВАТЬ МОЛЧА — то есть исполнить ровно ту беду, которую закон
    // стережёт, и предъявить её же как находку. Прогон, портящий мир, хуже отсутствующего.
    match T::notice(held.seen(), toward) {
        None => Verdict::Broken(Broken::NoticeUnbuildable),
        Some(notice) => sever_and_judge(dut, wire, held, notice, &ours, downstream, near),
    }
}

/// ВТОРАЯ ПОЛОВИНА ЗАКОНА — когда сказать ЕСТЬ чем.
///
/// Отдельной функцией, а не веткой: иначе тело закона ушло бы вправо на три уровня, и решётка
/// исходов перестала бы читаться — а она здесь главное.
fn sever_and_judge<T, B, D, N>(
    dut: &mut T,
    wire: &mut B,
    held: Held<T::Carrier>,
    notice: crate::command::InjectablePacket,
    ours: &[u8],
    downstream: &mut D,
    near: &mut N,
) -> Verdict<Broken, Invalid>
where
    T: Terminal + CanSever,
    T::Carrier: Observed,
    B: Sink + CanInject,
    D: Downstream + ?Sized,
    N: NearEnd + ?Sized,
{
    // ОТПЕЧАТОК СНИМАЕТСЯ ДО ОТПРАВКИ и снимается IP-ФОРМОЙ, а не канальной.
    //
    // Носители заворачивают извещение по-разному: `AfPacketBackend` кладёт на провод кадр с
    // ethernet-заголовком, `RawSender` — голый IP. Возьми закон канальную форму — он держался бы
    // на одном носителе и молча ослеп на другом, потому что искомого просто нет в записи.
    //
    // IP-форма же есть ПОДСТРОКА канальной, и потому вопрос «дошло ли НАШЕ» задаётся одинаково
    // обоим. Ровно та же мысль, по которой [`carries`] ищет подстроку, а не равенство: заголовки
    // по дороге дописывает кто угодно, и требовать равенства значило бы проверять «не тронул ли
    // его никто» вместо «дошло ли».
    let stamp = notice.serialize_ip();

    match downstream.passed().iter().any(|gone| carries(gone, ours)) {
        true => Verdict::Invalid(Invalid::NotHeld),
        false => match dut.apply(held.answered(T::refuse())) {
            Err(_not_taken) => Verdict::Invalid(Invalid::AnswerNotTaken),
            // ОТКАЗ ПЕРВЫМ, ИЗВЕЩЕНИЕ ВТОРЫМ — тот же порядок, что у продукта, и по той же
            // причине: отдай мы пакет цели раньше, чем оборвали, она успела бы ответить, и на
            // проводе появился бы второй, чужой RST.
            Ok(_delivered) => match wire.emit(B::inject(notice)) {
                Err(_refused) => Verdict::Invalid(Invalid::SinkRefused),
                Ok(()) => judge(downstream.passed(), near.arrived(), ours, &stamp),
            },
        },
    }
}

/// СВЕСТИ ДВА ПОКАЗАНИЯ В ОДИН ВЕРДИКТ.
///
/// Отдельной функцией, потому что здесь решётка, а не последовательность: восемь исходов трёх
/// наблюдений, и каждый назван. Спрятать их в цепочку `if` значило бы получить дыры, которых
/// компилятор не покажет.
fn judge(
    beyond: Vec<Vec<u8>>,
    behind: Vec<Vec<u8>>,
    ours: &[u8],
    stamp: &[u8],
) -> Verdict<Broken, Invalid> {
    // НЕМОТА ПРИБОРА РАЗБИРАЕТСЯ ПЕРВОЙ. Пустой ответ неотличим от «ничего не прошло», и всякий
    // вердикт по нему был бы вердиктом о неизвестном.
    match (beyond.as_slice(), behind.as_slice()) {
        ([], _) => Verdict::Invalid(Invalid::DownstreamMute),
        (_, []) => Verdict::Invalid(Invalid::NearEndMute),
        (seen_beyond, seen_behind) => {
            let passed = seen_beyond.iter().any(|frame| carries(frame, ours));
            let at_target = seen_beyond.iter().any(|frame| carries(frame, stamp));
            let at_client = seen_behind.iter().any(|frame| carries(frame, stamp));

            // ВОСЕМЬ ИСХОДОВ ЯВНО. Приоритет бед: прошедший пакет страшнее промаха адресации, а
            // промах адресации страшнее молчания — потому что уводит наш кадр к противнику.
            match (passed, at_target, at_client) {
                (false, false, true) => Verdict::Held,
                (false, false, false) => Verdict::Broken(Broken::NoticeMissed),
                (false, true, true) => Verdict::Broken(Broken::NoticeToTarget),
                (false, true, false) => Verdict::Broken(Broken::NoticeToTarget),
                (true, false, true) => Verdict::Broken(Broken::PassedAnyway),
                (true, false, false) => Verdict::Broken(Broken::NeitherHappened),
                (true, true, true) => Verdict::Broken(Broken::PassedAnyway),
                (true, true, false) => Verdict::Broken(Broken::PassedAnyway),
            }
        }
    }
}
