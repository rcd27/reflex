//! Восьмой закон эталона: **решение восстановимо** (канон §10, §12.3).
//!
//! Семь остальных законов свидетельствуют ЭФФЕКТ — «мир принял?». Этот отвечает на второй конец:
//! пере-подай записанную ленту той же машине из того же семени — и она обязана сказать то же самое.
//! Согласие двух прогонов есть детерминированность морфизма по объявленному алфавиту, то есть
//! определённость его образа в финальной коалгебре; сверка — бисимуляция.
//!
//! Свидетель здесь особый: ему не нужны ни стенд, ни root, ни ядро, ни сеть — только запись. Оттого
//! закон и годится в CI, в отличие от семи прочих.
//!
//! **Сверяются ИСХОДЫ, а не входы.** Лента пере-подаётся та же — сравнивать её с самой собой
//! бессмысленно; сравнению подлежит то, что машина СКАЗАЛА. Потому у буквы ленты и нет равенства:
//! фабриковать его для носителя, чья личность не наша, значило бы проверять не тот предмет.
//!
//! Расхождение прогонов называет свою породу. `Unstable` — недетерминизм ВНУТРИ: машина читает то,
//! чего нет в её алфавите (часы, глобальное знание, чужую память), и это не придирка к чистоте, а
//! приговор всей записи: происхождение перестаёт восстанавливаться, а вместе с ним и разбор боя.

use crate::tape::{Mode, Tape, TapeLetter};

/// Держится ли восьмой закон.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Replayed {
    /// Два прогона одной ленты согласны: решение восстановимо.
    Reproduced,
    /// Прогоны разошлись на букве номер `at`. Внутри машины есть вход, которого нет в её алфавите.
    Unstable { at: usize },
    /// Судить не о чем: ленты нет. Беда стенда, не подопытного — как `Invalid` у прочих законов.
    NoTape,
    /// Лента есть, но машине нечего было сказать: оба прогона молчали. Формально они согласны —
    /// молчание равно молчанию, — а свидетельства нет.
    ///
    /// Отдельный ответ, не `Reproduced`, и это оплачено ошибкой: закон, предъявленный на окне из
    /// одних узлов сетки без единой живой машины, отвечал «воспроизведено» и выглядел исправным.
    /// Под ним прошла мутация «переигровка читает часы» — стенд остался зелёным. Свидетель, зелёный
    /// на пустоте, хуже отсутствующего: он внушает уверенность, которой не заслужил.
    Silent,
}

/// Пере-подать ленту дважды и сверить сказанное.
///
/// `run` — прогон машины по ленте: даёт то, что она сказала. Зовётся ДВАЖДЫ с одной лентой и одним
/// режимом ([`Mode::Replay`] — мир не трогается), и разойтись ему нечем, кроме скрытого входа.
///
/// Сравнение по `Out` требует от него равенства — и это единственное равенство, которое закон
/// просит: слово адресовано нам, его личность наша.
pub fn replays<T, K, C, Out, F>(tape: &Tape<T, K, C>, mut run: F) -> Replayed
where
    F: FnMut(Mode, &[TapeLetter<T, K, C>]) -> Vec<Out>,
    Out: PartialEq,
{
    match tape.is_empty() {
        true => Replayed::NoTape,
        false => {
            let first = run(Mode::Replay, tape.letters());
            let second = run(Mode::Replay, tape.letters());
            match first
                .iter()
                .zip(second.iter())
                .position(|(said, again)| said != again)
            {
                Some(at) => Replayed::Unstable { at },
                // Разная ДЛИНА сказанного — тоже расхождение, и место у него первое из лишних:
                // машина, замолчавшая на переигровке, разошлась там, где перестала говорить.
                None if first.len() != second.len() => Replayed::Unstable {
                    at: first.len().min(second.len()),
                },
                // Согласие двух молчаний — не свидетельство: сверять было нечего.
                None if first.is_empty() => Replayed::Silent,
                None => Replayed::Reproduced,
            }
        }
    }
}
