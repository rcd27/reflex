//! ЗАКОН УДЕРЖАНИЯ: ПОКА МЫ НЕ ОТВЕТИЛИ — ПАКЕТ НЕ ИДЁТ ДАЛЬШЕ.
//!
//! # Почему это главный закон боевого бэкенда
//!
//! Продукт стоит на NFQUEUE, и всё, что он делает, опирается на одну посылку: ядро ЖДЁТ нашего
//! решения. Посылка ложна, если правило очереди стоит не в той цепочке, — и тогда движок не
//! решает, а КОММЕНТИРУЕТ вдогонку уже ушедшему пакету.
//!
//! Снаружи эти два состояния неотличимы совершенно: счётчики движутся, вердикты выносятся, спаны
//! пишутся, трафик идёт мимо. Репа платила за родственную беду и записала её у `Answer::Marked`:
//! правило, читающее метку, обязано стоять НИЖЕ правила очереди, иначе метка встанет и не будет
//! прочитана никем, «а прибор покажет — решение принято».
//!
//! # Третья форма свидетеля
//!
//! У инъекции свидетельствовал тот, до кого должно было дойти; у наблюдения — тот, кто породил.
//! Здесь свидетель — [`Downstream`], то, что стоит НИЖЕ по стеку: он отвечает не «сколько», а
//! «прошло ли уже», и спрашивают его ДВАЖДЫ — до ответа и после. Одного вопроса тут мало по
//! построению: закон не о количестве, а о ПОРЯДКЕ.

use crate::capability::CanHold;
use crate::held::{Held, Observed, Terminal};

use super::{carries, Downstream, Verdict};

/// ПОЧЕМУ ЗАКОН НЕ ДЕРЖИТСЯ. Две беды, и они противоположны по знаку.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Broken {
    /// Пакет ушёл ДО того, как у нас спросили решение. Удержания нет вовсе, и всё, что движок
    /// сделает дальше, — комментарий к случившемуся.
    PassedBeforeAnswer,
    /// Отпустили — а пакет так и не пошёл. Для человека это неотличимо от дропа, только тише:
    /// приложение ждёт таймаута вместо отказа.
    NeverPassed,
}

/// ПОЧЕМУ ВЕРДИКТА НЕТ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Invalid {
    /// Дальний конец не показал НИ ОДНОГО кадра — ни нашего, ни чужого.
    ///
    /// «Не прошло» и «свидетель не смотрел» дают одинаково пустой ответ. Найдено ЖИВЬЁМ
    /// 05.09.2026: остановленный `dumpcap` — и честная очередь была бы объявлена не отпускающей.
    ///
    /// Урок был выучен утром того же дня в законе инъекции и НЕ перенёсся сюда сам собой:
    /// правило, живущее в другом файле, компилятор не читает. На живом устройстве пустоту
    /// разгоняет МАЯК — кадр, который строит ядро, а не проверяемый бэкенд.
    WitnessSilent,
    /// Терминал честно сказал, что ответ не принят. Беда мира, о которой СООБЩИЛИ; предъявлять её
    /// как ложное заявление значило бы наказывать за честность — та же развилка, что у
    /// `SinkRefused` в законе инъекции.
    AnswerNotTaken,
}

/// ЗАКОН УДЕРЖАНИЯ.
///
/// # Порядок вопросов и есть предмет
///
/// 1. Спросить дальний конец ДО ответа: нашего там быть не должно.
/// 2. Отпустить носителя словом [`CanHold::release`].
/// 3. Спросить снова: теперь наше обязано быть.
///
/// Слово берётся у самой способности, а не приходит параметром: закон, которому ответ передают
/// снаружи, проверял бы согласие вызывающего с самим собой. Так же и здесь нельзя подменить
/// бэкенд — `CanHold` требует `Terminal`, а `Terminal` требует носителя, которого без очереди
/// взять негде.
///
/// # Чужой трафик не обвиняет
///
/// Мимо дальнего конца всё время идёт посторонний трафик. Считай закон всякое движение утечкой —
/// честная очередь в живом стеке была бы объявлена текущей немедленно; ищется ИМЕННО НАШ, по
/// байтам удержанного.
pub fn holds<T, D>(
    dut: &mut T,
    held: Held<T::Carrier>,
    downstream: &mut D,
) -> Verdict<Broken, Invalid>
where
    T: Terminal + CanHold,
    T::Carrier: Observed,
    D: Downstream + ?Sized,
{
    let ours = held.seen().to_vec();

    // ВОПРОС ПЕРВЫЙ — пока мы ещё ничего не ответили.
    match downstream.passed().iter().any(|gone| carries(gone, &ours)) {
        true => Verdict::Broken(Broken::PassedBeforeAnswer),
        false => match dut.apply(held.answered(T::release())) {
            Err(_not_taken) => Verdict::Invalid(Invalid::AnswerNotTaken),
            // ВОПРОС ВТОРОЙ — после того, как отпустили.
            Ok(_delivered) => match downstream.passed().as_slice() {
                // ПУСТОЙ ОТВЕТ — НЕ ОБВИНЕНИЕ, А ОТСУТСТВИЕ ВЕРДИКТА.
                [] => Verdict::Invalid(Invalid::WitnessSilent),
                seen => match seen.iter().any(|gone| carries(gone, &ours)) {
                    true => Verdict::Held,
                    false => Verdict::Broken(Broken::NeverPassed),
                },
            },
        },
    }
}
