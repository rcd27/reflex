//! ЗАКОНЫ КАЛИТКИ — то, что типом невыразимо.
//!
//! # Разделение труда, к которому пришли за день
//!
//! **Тип убивает ПУСТОЕ заявление.** Сказать «умею вводить», не назвав, как инъекция становится
//! командой ЭТОГО стока, больше нельзя: [`CanInject`](crate::capability::CanInject) несёт метод.
//! Замер 05.09.2026: заявлений было шестнадцать и ни одно ничем не установлено; после — пять, и
//! все несут предмет.
//!
//! **Закон убивает ЛОЖНОЕ.** Команда построена, `emit` ответил `Ok`, а на проводе пусто — типами
//! это не ловится по построению, потому что происходит за их границей.
//!
//! **Гейт ловит обход синтаксиса**, и это дверь, а не тип.
//!
//! # Свидетельство выдаёт НЕ ТОТ, КОГО ПРОВЕРЯЮТ
//!
//! Закон не спрашивает подопытного, сделал ли он: спрашивать доставку у доставляющего — тот самый
//! корень, который репа ловит у себя не первый раз. Спрашивают того, кто устроен ИНАЧЕ, и у
//! каждого закона это КТО-ТО СВОЙ:
//!
//! * [`injection`] — подопытный отправляет, свидетельствует [`injection::FarEnd`], тот, до кого
//!   должно было дойти;
//! * [`observation`] — подопытный НАБЛЮДАЕТ, а свидетельствует [`observation::Origin`], тот, кто
//!   породил трафик и знает от независимого прибора, сколько его ушло;
//! * [`holding`] — подопытный ДЕРЖИТ пакет, а свидетельствует [`holding::Downstream`], то, что
//!   стоит ниже по стеку, и спрашивают его ДВАЖДЫ: закон здесь не о количестве, а о ПОРЯДКЕ.
//!
//! Роли меняются местами, и вместе с ними меняется то, что делает прогон недействительным: у
//! инъекции — молчащий прибор, у наблюдения — молчащий мир.
//!
//! # Почему вердикт ОБОБЩЁН, а причины у каждого закона свои
//!
//! Общий алфавит причин на все законы был бы произведением осей вместо суммы: потребитель
//! инъекции разбирал бы ветки про потерянные наблюдения, которых в его законе не бывает. Форма
//! ответа при этом одна на всех — [`Verdict`], — и она-то и позволяет устройству печатать все
//! законы одинаково.

pub mod holding;
pub mod injection;
pub mod observation;

pub use holding::holds;
pub use injection::injects;
pub use observation::observes;

/// ДЕРЖИТСЯ ЛИ ЗАКОН — и установлено ли это вообще.
///
/// Три состояния, а не два. `Invalid` — не оттенок нарушения, а его ОТСУТСТВИЕ: закон ничего не
/// установил, потому что не выполнилась предпосылка СО СТОРОНЫ СТЕНДА. Прежде недействительность
/// жила вне закона — строкой в `Result<_, String>` живого устройства, — и место было выбрано
/// неверно дважды: строка не разбирается на причины, а сам закон оставался таким, что про
/// недействительность можно было ЗАБЫТЬ. Второй закон повторил бы упущение копипастой.
///
/// `B` — почему не держится (вина подопытного), `I` — почему не установлено (беда стенда).
/// Разделять их обязательно: предъявлять поломку прибора как нарушение способности значит
/// наказывать подопытного за чужое.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Verdict<B, I> {
    Held,
    Broken(B),
    Invalid(I),
}

/// НЕСЁТ ЛИ КАДР НАШ НОНС. Подстрокой, а не равенством.
///
/// Наблюдатель видит кадр целиком — с заголовками, которые мог дописать кто угодно по дороге.
/// Требовать равенства значило бы проверять не «дошло ли наше», а «не тронул ли его никто».
///
/// ПУБЛИЧЕН НАМЕРЕННО: живому устройству тот же предикат нужен, чтобы ЖДАТЬ появления нонса в
/// записи, — и будь у него своя копия, ожидание шло бы по одному правилу, а суждение по другому.
/// Такое расхождение репа уже ловила: одно слово значило два разных вопроса в двух реализациях, и
/// снаружи это было не видно.
pub fn carries(frame: &[u8], nonce: &[u8]) -> bool {
    match nonce.len() {
        0 => false,
        len => frame.windows(len).any(|window| window == nonce),
    }
}
