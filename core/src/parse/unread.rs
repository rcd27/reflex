//! Почему наблюдение не состоялось. Причина, а не флаг: «не наш протокол» есть законное и вечное
//! свойство трафика, «обрезан» есть потеря, чинимая настройкой съёма — слитые в один счётчик, они
//! дают величину, по которой не решить ничего. В фундаменте, а не у бэкенда: причина едет буквой
//! входного алфавита, а алфавит один на всех бэкендов. Сам разбор остаётся у бэкенда — сюда
//! приезжает только исход.

/// Что помешало прочесть наблюдение. Перечисление закрыто: полноту сторожит компилятор, новый вид
/// непонимания не появится молча.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Unread {
    /// Не IPv4. Ни адреса, ни протокола выше взять неоткуда.
    NotIpv4,
    /// IPv4, но ни TCP, ни UDP: ICMP, SCTP, что угодно ещё. Разбирать нечем и гадать нельзя.
    NotOurProtocol,
    /// Обрезан: заголовок не поместился целиком. ПОТЕРЯ, а не свойство трафика.
    Truncated,
}
