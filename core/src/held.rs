//! НАБЛЮДЕНИЕ, НЕСУЩЕЕ ПРАВО ОТВЕТИТЬ.
//!
//! # Чем этот носитель отличается от пары `Source`/`Sink`
//!
//! [`crate::step`] установил: у очереди ядра вердикт требует владения ТЕМ САМЫМ сообщением, и
//! потому «наблюдай и вбрасывай» ей структурно не подходит — заимствование источника и передача
//! стока по значению не уживаются на одной очереди.
//!
//! Здесь третий ответ, и он не отменяет вчерашнего, а снимает его посылку: **право ответить несёт
//! само наблюдение**. Отдельного стока для вердикта не нужно, а значит и сталкиваться нечему.
//!
//! # Что этим ЗАПРЕЩЕНО, и это главное
//!
//! Невод 1 отстрелил здесь ногу дважды, и обе беды одного рода — сведения покидали значение:
//!
//! 1. **Вердикт был ВЫЗОВОМ**, а не значением (`accept_marked(msg, mark)`). Вызов нельзя ни
//!    записать, ни сравнить, ни развернуть назад; расследование по нему невозможно, потому что
//!    после него не остаётся ничего.
//! 2. **След уезжал спанами OTLP**, и без переменной среды «спаны молча гасятся» — дословно из
//!    его собственного дока. Запись расследования жила вне значения и исчезала бесшумно.
//!
//! [`Held`] не даёт ни того, ни другого: наблюдение читается сколько угодно раз и не съедается,
//! ответ ОСТАВЛЯЕТ [`Answered`] — значение, в котором целы и предмет, и момент, и сам ответ.
//!
//! # Забытый вердикт невозможен, но и не бесшумен
//!
//! Уронить [`Held`], не ответив, можно — и тогда деструктор отвечает пропуском. Семантика та же,
//! что у [`crate::guard::TrafficGuard`] («мёртвый страж ⟹ трафик идёт»): непринятое нами решение
//! не должно останавливать чужой трафик.
//!
//! Но слово при этом ДРУГОЕ ([`Unanswered::PASSED_BY_DROP`]), и это не мелочь. «Мы решили
//! пропустить» есть факт о мире, «мы забыли ответить» — факт о НАС; слить их значило бы повторить
//! ошибку, которую `pribor` называет по имени: считать своим знанием своё нетерпение.

use std::time::Instant;

/// НОСИТЕЛЬ ПРАВА ОТВЕТИТЬ.
///
/// В бою это сообщение очереди ядра, которому вердикт отдаётся по владению. Трейт, а не тип, ровно
/// поэтому: ядро в `reflex-core` не тянется, а закон проверяется распиской в тесте.
pub trait Carrier {
    /// Отдать ответ носителю. Берёт `self`: ответить можно один раз, и это по построению.
    fn answer(self, with: &str);
}

/// СЛОВА, КОТОРЫМИ ОТВЕЧАЕТ НЕ РЕШЕНИЕ, А ЕГО ОТСУТСТВИЕ.
pub struct Unanswered;

impl Unanswered {
    /// Пропущено деструктором: решения не было. ФАКТ О НАС — и потому отдельное слово.
    pub const PASSED_BY_DROP: &'static str = "passed:unanswered";
}

/// НАБЛЮДЕНИЕ, У КОТОРОГО ЕЩЁ НЕ СПРОСИЛИ ОТВЕТА.
///
/// Предмет (`seen`) и момент (`at`) читаются сколько угодно раз: ответ не отнимает у дела того, о
/// чём оно.
pub struct Held<M: Carrier> {
    carrier: Option<M>,
    seen: Vec<u8>,
    at: Instant,
}

/// ОТВЕЧЕННОЕ ДЕЛО — значение, в котором цело всё, что было, плюс то, чем ответили.
///
/// Не «остаток» и не «квитанция»: это полное наблюдение, к которому дописан ответ. Развернуть его
/// назад можно потому, что вычитать из него ничего не пришлось.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Answered {
    pub seen: Vec<u8>,
    pub at: Instant,
    pub answer: String,
}

impl<M: Carrier> Held<M> {
    pub fn new(carrier: M, seen: Vec<u8>, at: Instant) -> Self {
        Self {
            carrier: Some(carrier),
            seen,
            at,
        }
    }

    /// ЧТО НАБЛЮДЕНО. Заимствование, а не выдача: читать можно сколько угодно раз.
    pub fn seen(&self) -> &[u8] {
        &self.seen
    }

    /// КОГДА НАБЛЮДЕНО.
    pub fn at(&self) -> Instant {
        self.at
    }

    /// ОТВЕТИТЬ — И ПОЛУЧИТЬ ДЕЛО ЦЕЛИКОМ.
    ///
    /// Берёт `self`: ответ один, и второго не собрать. Возвращает [`Answered`], а не `()`, потому
    /// что ответ есть ШАГ ДЕЛА, а не его конец — то, что вышло, обязано остаться значением.
    pub fn answered(mut self, with: &str) -> Answered {
        match self.carrier.take() {
            None => (),
            Some(carrier) => carrier.answer(with),
        }
        Answered {
            seen: core::mem::take(&mut self.seen),
            at: self.at,
            answer: with.to_string(),
        }
    }
}

impl<M: Carrier> Drop for Held<M> {
    /// НЕОТВЕЧЕННОЕ ПРОПУСКАЕТСЯ — но своим словом.
    fn drop(&mut self) {
        match self.carrier.take() {
            None => (),
            Some(carrier) => carrier.answer(Unanswered::PASSED_BY_DROP),
        }
    }
}
