//! НАБЛЮДЕНИЕ, РЕШЕНИЕ И ДОСТАВКА — три значения и ровно одно место, где случается мир.
//!
//! # Что этим лечится
//!
//! `step.rs` установил: у очереди ядра вердикт требует владения ТЕМ САМЫМ сообщением, и пара
//! `Source`/`Sink` ей структурно не подходит. Посылка, на которой держалось противоречие, — что
//! ответ ОТДАЁТСЯ внутри цепочки. Она снимается: ответ есть ЗНАЧЕНИЕ, а отдаёт его терминальный
//! морфизм, владеющий очередью.
//!
//! ```text
//! Held<M>  ──answered(a)──▶  Answered<M, A>  ──Terminal::apply──▶  Delivered<A> | Refused<A, E>
//!   чисто                        чисто              ЕДИНСТВЕННОЕ `&mut`
//! ```
//!
//! # Две ноги, отстреленные в неводе 1, и обе в одной строке
//!
//! ```text
//! msg.set_verdict(Verdict::Accept);
//! let _ = self.queue.verdict(msg);
//! ```
//!
//! 1. **Вердикт был ВЫЗОВОМ**, а не значением: записать, сравнить и развернуть назад его нельзя,
//!    после него не остаётся ничего.
//! 2. **`let _ =` выбрасывал факт о ДОСТАВКЕ.** Ядро может отказать — и мы не узнаем. Четыре
//!    вердикта, четыре выброшенных свидетельства. Это тот же корень, что у пустых способностей:
//!    свидетельство выдавал объявляющий, а не доставляющий.
//!
//! Здесь их разводят ДВА РАЗНЫХ ТИПА: [`Answered`] значит «мы решили», [`Delivered`] — «мир
//! принял». Слить их в одно значило бы снова выдать намерение за результат.
//!
//! # Почему `&mut` остаётся, и это не поражение
//!
//! Netlink-сокет один, и отправка по нему последовательна ПО ПРИРОДЕ — типами этого не отменить.
//! Но из того, что последователен ЭФФЕКТ, не следует, что императивна ЦЕПОЧКА. `&mut` заперт в
//! [`Terminal::apply`]: выше него значения, ниже — мир. Прежде он был размазан по четырём
//! вердиктам, и потому цепочка касалась мира посередине.
//!
//! # Чего здесь НЕТ и почему
//!
//! Деструктора, отвечающего за нас, больше нет. Первая редакция (`6256035`) звала носителя прямо
//! из `answered`, и `Drop` мог «пропустить, если забыли», — но той ценой, что цепочка трогала мир
//! в середине. Уронить решение по дороге теперь можно, и это ОШИБКА КОМПИЛЯТОРА:
//! [`Answered`] помечен `#[must_use]`. Сильнее в Rust не выразить — заставить потребить значение
//! язык не умеет.

use std::time::Instant;

/// НОСИТЕЛЬ, У КОТОРОГО МОЖНО СПРОСИТЬ, ЧТО НАБЛЮДЕНО.
///
/// Заимствование, а не выдача: байты принадлежат носителю, пока он жив, и копировать их некуда и
/// незачем — [`Held`] лишь показывает их тому, кто разбирает.
pub trait Observed {
    fn payload(&self) -> &[u8];
}

/// НАБЛЮДЕНИЕ, У КОТОРОГО ЕЩЁ НЕ СПРОСИЛИ ОТВЕТА.
///
/// `M` — носитель права ответить: в бою сообщение очереди, в тесте конверт. Ядро о нём ничего не
/// знает и знать не должно, потому он и параметр.
///
/// # Байтов здесь НЕТ, и это закон, а не экономия
///
/// Первая редакция клала `Vec<u8>` в само дело — аллокация на КАЖДЫЙ пакет и копия полезной
/// нагрузки в записи. `Case` продукта отвечает на этот вопрос иначе и раньше: сырьё снимает
/// НЕЗАВИСИМЫЙ прибор (`raw` — путь к записи), а дело помнит УЛИКУ, то есть то, что из наблюдения
/// извлекли. Тащить байты в свидетельство значило бы держать в памяти каждый пакет и при этом
/// дублировать лежащее на диске.
pub struct Held<M> {
    carrier: M,
    at: Instant,
}

/// РЕШЕНИЕ — ЗНАЧЕНИЕ. «Мы решили», и ничего больше: мира это ещё не касалось.
///
/// `#[must_use]` не украшение: решение, не дошедшее до терминала, оставляет ядро ждать пакета, о
/// котором мы уже всё поняли.
///
/// # Забытое решение — ошибка КОМПИЛЯТОРА, а не молчание
///
/// ```compile_fail
/// #![deny(unused_must_use)]
/// use reflex_core::held::Held;
/// use std::time::Instant;
///
/// fn forgets(held: Held<u32>) {
///     held.answered(1u8);
/// }
/// ```
///
/// Сильнее в Rust не выразить — заставить потребить значение язык не умеет. Но «компилятор
/// сказал» и «в доке написано» суть разные вещи, и второе не читают.
#[must_use = "решение — это ещё не эффект: отдайте его терминалу (Terminal::apply), \
              иначе ядро останется ждать пакета, о котором мы уже всё решили"]
pub struct Answered<M, A> {
    /// Носитель права ответа — едет к терминалу, потому что отдать ответ может только он. Он же
    /// и держит байты: до самого терминала наблюдение читаемо, копировать его незачем.
    pub carrier: M,
    pub at: Instant,
    pub answer: A,
}

/// МИР ПРИНЯЛ. Свидетельство выдаёт ДОСТАВЛЯЮЩИЙ, а не решавший.
///
/// Момент и решение — и ничего сверх. Улику извлекает цепочка и кладёт в своё дело; полные байты
/// живут в сырье, снятом независимым прибором.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Delivered<A> {
    pub at: Instant,
    pub answer: A,
}

/// МИР ОТКАЗАЛ — и это тоже ЗНАНИЕ, а не пустота.
///
/// Целы момент и решение; сверх них названа причина. Прежде на этом месте стоял `let _ =`, и отказ
/// исчезал бесследно.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Refused<A, E> {
    pub at: Instant,
    pub answer: A,
    pub why: E,
}

/// ТЕРМИНАЛЬНЫЙ МОРФИЗМ — единственное место, где значение становится эффектом.
///
/// `&mut self` здесь не стиль, а граница: за ней сокет, очередь, ядро. Всё, что выше, — значения.
pub trait Terminal {
    /// Носитель права ответа, который этот терминал умеет отдать.
    type Carrier;
    /// Чем ему можно ответить.
    type Answer;
    /// Чем он отказывает.
    type Refusal;

    fn apply(
        &mut self,
        answered: Answered<Self::Carrier, Self::Answer>,
    ) -> Result<Delivered<Self::Answer>, Refused<Self::Answer, Self::Refusal>>;
}

impl<M> Held<M> {
    pub fn new(carrier: M, at: Instant) -> Self {
        Self { carrier, at }
    }

    /// КОГДА НАБЛЮДЕНО.
    pub fn at(&self) -> Instant {
        self.at
    }

    /// РЕШИТЬ. Чисто: мира это не касается, и потому шаг можно записать, сравнить и повторить.
    pub fn answered<A>(self, answer: A) -> Answered<M, A> {
        Answered {
            carrier: self.carrier,
            at: self.at,
            answer,
        }
    }
}

impl<M: Observed> Held<M> {
    /// ЧТО НАБЛЮДЕНО — у носителя, а не из копии. Читать можно сколько угодно раз.
    pub fn seen(&self) -> &[u8] {
        self.carrier.payload()
    }
}
