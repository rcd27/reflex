//! Наблюдение, решение и доставка — три значения и ровно одно место, где случается мир (канон §9).
//! `step.rs` установил: у очереди ядра вердикт требует владения ТЕМ САМЫМ сообщением, пара
//! `Source`/`Sink` ей не подходит. Ответ есть ЗНАЧЕНИЕ, отдаёт его терминальный морфизм, владеющий
//! очередью:
//!
//! ```text
//! Held<M>  ──answered(a)──▶  Answered<M, A>  ──Terminal::apply──▶  Delivered<A> | Refused<A, E>
//!   чисто                        чисто              ЕДИНСТВЕННОЕ `&mut`
//! ```
//!
//! Две ноги невода 1 в одной строке (`msg.set_verdict(Accept); let _ = self.queue.verdict(msg);`):
//! вердикт был ВЫЗОВОМ, не значением (записать/сравнить/развернуть нельзя); `let _ =` выбрасывал
//! факт о ДОСТАВКЕ (ядро может отказать — не узнаем). Здесь их разводят два типа: [`Answered`] — «мы
//! решили», [`Delivered`] — «мир принял». `&mut` заперт в [`Terminal::apply`] (netlink-сокет один,
//! эффект последователен по природе — но из этого не следует, что императивна ЦЕПОЧКА): выше него
//! значения, ниже мир. Деструктора, отвечающего за нас, нет: уронить решение по дороге теперь ОШИБКА
//! КОМПИЛЯТОРА ([`Answered`] помечен `#[must_use]`).

use std::time::Instant;

/// Носитель, у которого можно спросить, что наблюдено. Заимствование, не выдача: байты принадлежат
/// носителю, пока он жив — [`Held`] лишь показывает их разбирающему.
pub trait Observed {
    fn payload(&self) -> &[u8];
}

/// Голые байты — тоже наблюдение, форма живых бэкендов, не уступка тестам (`Source::Packet` у
/// `AfPacketBackend`/`TcAfPacketBackend` есть `Vec<u8>`). Носителя права ответить в них нет (с сырым
/// сокетом и не бывает), но закон наблюдения права отвечать не требует: он смотрит, ЧТО видно.
impl Observed for Vec<u8> {
    fn payload(&self) -> &[u8] {
        self
    }
}

/// Что край ведёт о РАЗГОВОРЕ, у которого пришёл этот пакет. Пара к [`Observed`]: тот показывает
/// провод, этот — величины края. Спрашивают НОСИТЕЛЯ СООБЩЕНИЯ, а не бэкенд: внутри `serve` бэкенд
/// заимствован, и второго `&mut` не будет.
pub trait Edging {
    type Edge: crate::edge::EdgeView;
    /// `None` — край о разговоре ничего не ведёт (потока ещё нет в его таблице). Клетка §7:
    /// «не считали» обязано отличаться от «не ответила».
    fn edge(&self) -> Option<Self::Edge>;
}

/// Наблюдение, у которого ещё не спросили ответа. `M` — носитель права ответить (в бою сообщение
/// очереди, в тесте конверт); ядро о нём не знает, потому параметр. Байтов здесь нет — закон, не
/// экономия: первая редакция клала `Vec<u8>` в само дело (аллокация на КАЖДЫЙ пакет и копия в
/// записи); сырьё снимает независимый прибор, дело помнит УЛИКУ.
pub struct Held<M> {
    carrier: M,
    at: Instant,
}

/// Решение — ЗНАЧЕНИЕ. «Мы решили», и ничего больше: мира это ещё не касалось. `#[must_use]` не
/// украшение — решение, не дошедшее до терминала, оставляет ядро ждать пакета, о котором мы всё
/// поняли. Забытое решение — ошибка КОМПИЛЯТОРА:
///
/// ```compile_fail
/// #![deny(unused_must_use)]
/// use reflex_core::held::Held;
/// use std::time::Instant;
///
/// fn forgets(held: Held<u32>) {
///     held.answered(1u8);
/// }
/// ```
#[must_use = "решение — это ещё не эффект: отдайте его терминалу (Terminal::apply), \
              иначе ядро останется ждать пакета, о котором мы уже всё решили"]
pub struct Answered<M, A> {
    /// Носитель права ответа — едет к терминалу (отдать ответ может только он) и держит байты: до
    /// терминала наблюдение читаемо, копировать незачем.
    pub carrier: M,
    pub at: Instant,
    pub answer: A,
}

/// Мир принял. Свидетельство выдаёт ДОСТАВЛЯЮЩИЙ, не решавший. Момент и решение — и ничего сверх;
/// улику извлекает цепочка, полные байты живут в сырье независимого прибора.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Delivered<A> {
    pub at: Instant,
    pub answer: A,
}

/// Мир отказал — тоже ЗНАНИЕ, не пустота. Целы момент и решение, сверх них причина. Прежде здесь
/// стоял `let _ =`, и отказ исчезал бесследно.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Refused<A, E> {
    pub at: Instant,
    pub answer: A,
    pub why: E,
}

/// Терминальный морфизм — единственное место, где значение становится эффектом. `&mut self` не
/// стиль, а граница: за ней сокет, очередь, ядро; всё выше — значения.
pub trait Terminal {
    /// Носитель права ответа, который этот терминал умеет отдать.
    type Carrier;
    /// Чем ему можно ответить.
    type Answer;
    /// Чем он отказывает.
    type Refusal;

    fn apply(
        &mut self,
        answered: Answered<Self::Carrier, Self::Answer>,
    ) -> Result<Delivered<Self::Answer>, Refused<Self::Answer, Self::Refusal>>;
}

impl<M> Held<M> {
    pub fn new(carrier: M, at: Instant) -> Self {
        Self { carrier, at }
    }

    /// Когда наблюдено.
    pub fn at(&self) -> Instant {
        self.at
    }

    /// Носитель по ссылке — для того, что знает о пакете он один ([`seen`](Self::seen) отдаёт байты,
    /// но у носителя бывает внеполосное: метка ядра, по которой решают, наш ли пакет). Права ответить
    /// не даёт: ответ требует владения ([`answered`](Self::answered) берёт `self`), здесь заимствование.
    pub fn carrier(&self) -> &M {
        &self.carrier
    }

    /// Решить. Чисто: мира не касается, потому шаг можно записать, сравнить и повторить.
    pub fn answered<A>(self, answer: A) -> Answered<M, A> {
        Answered {
            carrier: self.carrier,
            at: self.at,
            answer,
        }
    }
}

impl<M: Observed> Held<M> {
    /// Что наблюдено — у носителя, не из копии. Читать можно сколько угодно раз.
    pub fn seen(&self) -> &[u8] {
        self.carrier.payload()
    }
}
