//! Извещение об обрыве: чем сказать названной стороне, что разговора не будет.
//!
//! Таблица ВХОД→ВЫХОД, и предмет её — ПРОТОКОЛ, а не носитель. Жила она приваренной к очереди
//! netfilter (`linux/src/nfqueue/terminal.rs`), и пока носитель был один, разницы не было; со
//! вторым (`QueueSocket`) она стала бы копией, а копии расходятся молча — тем более эта, где
//! ошибка в номерах не видна изнутри процесса: `RST` вне окна получатель отбрасывает без звука
//! (RFC 5961), и «сказали» с «услышали» перестают различаться.
//!
//! Прав таблица не требует и мира не касается: на входе наблюдённые байты, на выходе пакет, который
//! КТО-ТО потом отправит. Оттого она и живёт в ядре — способность носителя лишь называет её своим
//! словом (§9.1).

use crate::builder::TcpBuilder;
use crate::capability::Toward;
use crate::command::InjectablePacket;
use crate::parse::parse_tcp_from_ip;
use crate::types::TcpFlags;

/// Построить `RST` названной стороне по наблюдённому кадру. `None` — формы обрыва у этого
/// наблюдения нет (не TCP, обрезан): не ошибка, а «сказать нечем» (§7).
///
/// Два случая, не один: прежде `seq` брался из `ack` удержанного пакета всегда — верно для пакета ОТ
/// клиента (серверный `seq` есть подтверждённое клиентом), неверно для пакета ОТ ЦЕЛИ (извещение от
/// её имени несёт `seq + длину`). Различие видно, лишь когда стороны названы типом ([`Toward`]).
pub fn rst_for(seen: &[u8], toward: Toward) -> Option<InjectablePacket> {
    parse_tcp_from_ip(seen).map(|segment| {
        // Сколько байт занял удержанный пакет в потоке своего отправителя.
        let taken = segment.seq.wrapping_add(segment.payload.len() as u32);

        let (flow, seq, ack) = match toward {
            // Говорим отправителю от имени получателя: концы меняются местами, наш `seq` — то, что
            // отправитель подтвердил, а подтверждаем всё, что он послал.
            Toward::Sender => (segment.flow.reversed(), segment.ack, taken),
            // Говорим получателю от имени отправителя: концы как есть, наш `seq` продолжает поток
            // отправителя, а подтверждаем то, что он подтверждал.
            Toward::Receiver => (segment.flow.clone(), taken, segment.ack),
        };

        InjectablePacket::Tcp(
            TcpBuilder::new()
                .flow(&flow)
                .seq(seq)
                .ack(ack)
                // `RST|ACK`, а не голый `RST`: сброс без подтверждения многие стеки отбрасывают как
                // несогласованный.
                .flags(TcpFlags::RST | TcpFlags::ACK)
                // Окно нулевое: принимать больше нечего, разговор кончен.
                .window(0)
                .build(),
        )
    })
}
