//! ВЫПУСТИТЬ ПОСЛЕДНЕЕ, КОГДА ПОТОК ЗАТИХ — оператор времени БЕЗ ЧАСОВ.
//!
//! # Почему без рантайма
//!
//! Операторы КОНКУРЕНТНОСТИ (`switch_map`, `merge_map_bounded`) на носителе шага невыразимы: они
//! запускают работу, идущую ПАРАЛЛЕЛЬНО потоку, а у шага нет ни второй нити, ни того, кому отдать
//! управление. Операторы ВРЕМЕНИ — другой род: время стало буквой входа ([`crate::interleave`]),
//! и `debounce` — чистая функция `(состояние, событие) → состояние`, которой не нужны ни часы,
//! ни рантайм.
//!
//! # Цена: точность квантуется сеткой
//!
//! `tokio::sleep` будил бы ровно в конце окна. Здесь выпуск случается на ПЕРВОМ узле сетки после
//! конца окна, то есть опаздывает не более чем на шаг сетки. Взамен оператор работает там, где
//! рантайма нет, — в синхронной плоскости, — и на записи идёт со скоростью чтения файла.
//!
//! Второе, что названо: конца потока у детектора нет, и удержанное событие выпускается ТОЛЬКО
//! тиком — досказать придержанное при обрыве источника есть дело потребителя, который один знает,
//! что поток кончился.

use core::time::Duration;
use std::time::Instant;

use smallvec::{smallvec, SmallVec};

use crate::detector::DetectorEvent;
use crate::step::Step;

/// ДЕРЖИТ ПОСЛЕДНЕЕ СОБЫТИЕ И ОТДАЁТ ЕГО, КОГДА ОКНО ТИШИНЫ ПРОШЛО.
#[derive(Debug, Clone)]
pub struct Debounce<T> {
    window: Duration,
    held: Option<(T, Instant)>,
}

impl<T> Debounce<T> {
    /// Окно тишины, после которого удержанное считается окончательным.
    pub fn over(window: Duration) -> Self {
        Self { window, held: None }
    }
}

impl<T> Step for Debounce<T> {
    type From = DetectorEvent<T>;
    type To = SmallVec<[T; 2]>;

    fn step(self, event: Self::From) -> (Self, Self::To) {
        match event {
            // НОВОЕ СОБЫТИЕ ВЫТЕСНЯЕТ УДЕРЖАННОЕ и отодвигает окно. Отсчёт идёт от ПОСЛЕДНЕГО, а
            // не от первого: иначе поток, идущий чуть чаще окна, выпускался бы регулярно, и
            // оператор перестал бы отличать «затих» от «идёт ровно».
            DetectorEvent::Packet { input, at } => (
                Self {
                    held: Some((input, at)),
                    ..self
                },
                smallvec![],
            ),
            DetectorEvent::Tick { at, .. } => match self.held {
                Some((held, since)) if at.saturating_duration_since(since) >= self.window => {
                    (Self { held: None, ..self }, smallvec![held])
                }
                still_waiting => (
                    Self {
                        held: still_waiting,
                        ..self
                    },
                    smallvec![],
                ),
            },
            // НЕПОНЯТОЕ НЕ ЕСТЬ РАЗГОВОР, КОТОРЫЙ ЗАТИХАЕТ: оператор мерит паузу МЕЖДУ
            // разобранными значениями, и байты, которые не удалось прочесть, к ней не
            // относятся — ни отодвигать окно, ни выпускать удержанное они не вправе.
            DetectorEvent::Opaque { .. } => (self, smallvec![]),
        }
    }
}
