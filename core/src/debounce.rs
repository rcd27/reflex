//! ВЫПУСТИТЬ ПОСЛЕДНЕЕ, КОГДА ПОТОК ЗАТИХ — оператор времени БЕЗ ЧАСОВ.
//!
//! # Что этим доказывается
//!
//! [`crate::step`] утверждал: «`with_latest_from`, `debounce`, `switch_map`, `merge_map_bounded`
//! суть операторы времени и конкурентности, и на носителе шага их не существует». Утверждение
//! верно наполовину, и половины стоит развести — они держат разные стены.
//!
//! **Операторы КОНКУРЕНТНОСТИ** (`switch_map`, `merge_map_bounded`) на носителе шага
//! действительно невыразимы: они запускают работу, которая идёт ПАРАЛЛЕЛЬНО потоку, а у шага нет
//! ни второй нити, ни того, кому отдать управление. Эта стена несущая и остаётся.
//!
//! **Операторы ВРЕМЕНИ** — выразимы, как только время стало буквой входа ([`crate::interleave`]).
//! Здесь тому свидетельство: `debounce` есть чистая функция `(состояние, событие) → состояние`,
//! и ни часов, ни рантайма ему не нужно. Прежняя редакция (`DebounceStream` поверх
//! `tokio::time::sleep`) не имела ни одного потребителя, а её тест ради утверждения `vec![1, 2]`
//! поднимал `spawn`, канал, три `yield_now` и `advance`.
//!
//! # Цена: точность квантуется сеткой
//!
//! `tokio::sleep` будил бы ровно в конце окна. Здесь выпуск случается на ПЕРВОМ узле сетки после
//! конца окна, то есть опаздывает не более чем на шаг сетки. Взамен оператор работает там, где
//! рантайма нет, — в синхронной плоскости, — и на записи идёт со скоростью чтения файла.
//!
//! Второе, что названо: конца потока у детектора нет, и удержанное событие выпускается ТОЛЬКО
//! тиком. Прежний потоковый вариант отдавал придержанное при обрыве источника; здесь это дело
//! потребителя, который один и знает, что поток кончился.

use core::time::Duration;
use std::time::Instant;

use smallvec::{smallvec, SmallVec};

use crate::detector::{Detector, DetectorEvent};

/// ДЕРЖИТ ПОСЛЕДНЕЕ СОБЫТИЕ И ОТДАЁТ ЕГО, КОГДА ОКНО ТИШИНЫ ПРОШЛО.
#[derive(Debug, Clone)]
pub struct Debounce<T> {
    window: Duration,
    held: Option<(T, Instant)>,
}

impl<T> Debounce<T> {
    /// Окно тишины, после которого удержанное считается окончательным.
    pub fn over(window: Duration) -> Self {
        Self { window, held: None }
    }
}

impl<T> Detector for Debounce<T> {
    type Input = T;
    type Signal = T;

    fn step(self, event: DetectorEvent<Self::Input>) -> (Self, SmallVec<[Self::Signal; 2]>) {
        match event {
            // НОВОЕ СОБЫТИЕ ВЫТЕСНЯЕТ УДЕРЖАННОЕ и отодвигает окно. Отсчёт идёт от ПОСЛЕДНЕГО, а
            // не от первого: иначе поток, идущий чуть чаще окна, выпускался бы регулярно, и
            // оператор перестал бы отличать «затих» от «идёт ровно».
            DetectorEvent::Packet { input, at } => (
                Self {
                    held: Some((input, at)),
                    ..self
                },
                smallvec![],
            ),
            DetectorEvent::Tick { at } => match self.held {
                Some((held, since)) if at.saturating_duration_since(since) >= self.window => {
                    (Self { held: None, ..self }, smallvec![held])
                }
                still_waiting => (
                    Self {
                        held: still_waiting,
                        ..self
                    },
                    smallvec![],
                ),
            },
        }
    }
}
