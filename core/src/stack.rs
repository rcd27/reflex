//! ПРОТОКОЛ КАК ТИП: наблюдение, снятое не с того протокола, не собирается в цепочку.
//!
//! # Что этим лечится
//!
//! Объявление протокола паспортом (`PROTOCOLS: &[Tcp]`) ничего не запрещает на уровне типов:
//! наблюдение протокола не несёт, и датаграмма, поданная прибору TCP, повисла бы «соединением» и
//! копила молчание.
//!
//! Протокол становится параметром типа НАБЛЮДЕНИЯ: прибор объявляет входом свой алфавит
//! (`DetectorEvent<In>`), сборщик требует равенство `D: Mealy<In = DetectorEvent<In>, …>` вместе
//! с `In: Reads<Widest>` (подробнее — у [`Reads`] ниже), и поток, из которого этот алфавит не
//! читается, в прибор не соберётся. Отдельной оси совместимости не заводится — прибор, чей предмет
//! от протокола не зависит, пишется генериком и годится всякому.
//!
//! # СЛОВАРЬ — КОМЬЮНИТИ, А НЕ НАШ (решение владельца)
//!
//! Всё, что касается сетевого стека, называется словами поля; конфликтующее продуктовое слово
//! меняется, а не наоборот. Оттого здесь `Protocol`, а не «транспорт» и не «этаж»:
//!
//! * **транспорт** — уровень стека (OSI 4), и TCP с UDP там живут, а QUIC — НЕТ: он поверх UDP.
//!   Трейт, названный `Transport`, обязан был бы либо соврать о QUIC, либо его не принять;
//! * **этаж** — наш коинаж, у которого в поле есть слово `layer` (уровень). Второе имя одному
//!   понятию — та самая болезнь, которую этот модуль и лечит, только в комментариях.
//!
//! Уровень (`Layer`) здесь НЕ живёт намеренно: он есть ось переписи парка приборов и полон
//! знанием о том, где какая цензура водится, — то есть принадлежит продукту, а не общей
//! библиотеке потоков.

/// ПРОТОКОЛ, НА КОТОРОМ СНЯТО НАБЛЮДЕНИЕ. Объект стека — тип, а не значение.
pub trait Protocol {
    const NAME: &'static str;
}

/// TCP: рукопожатие, сброс, окно приёма — улики, которых у датаграмм нет.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Tcp;

/// UDP: датаграммы. Всё, что поверх них, — отдельные объекты: у QUIC свои улики, у DNS свои.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Udp;

/// QUIC: поверх UDP. Рукопожатие есть, но объявлено длинным заголовком, а обрыв зашифрован.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Quic;

/// TLS: поверх TCP. Имя цели открытым текстом в `ClientHello`, тревоги клиента — в рукопожатии.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Tls;

/// DNS: обычно поверх UDP. Содержимое открыто, и потому здесь видно то, чего не видно нигде выше.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Dns;

/// HTTP: поверх TCP, голова открыта.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Http;

/// ПРОТОКОЛ БЕЗРАЗЛИЧЕН — предмет наблюдателя существует на любом (объём, ожидание, уход
/// человека). Это не «неизвестно», а утверждение: улика не зависит от протокола.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AnyProtocol;

impl Protocol for Tcp {
    const NAME: &'static str = "tcp";
}

impl Protocol for Udp {
    const NAME: &'static str = "udp";
}

impl Protocol for Quic {
    const NAME: &'static str = "quic";
}

impl Protocol for Tls {
    const NAME: &'static str = "tls";
}

impl Protocol for Dns {
    const NAME: &'static str = "dns";
}

impl Protocol for Http {
    const NAME: &'static str = "http";
}

impl Protocol for AnyProtocol {
    const NAME: &'static str = "любой";
}

/// СПУСК ПО СТЕКУ: всякое наблюдение `Self` есть также наблюдение `Under`.
///
/// Морфизм ТОТАЛЬНЫЙ — это забывание, и оно определено всегда: QUIC-пакет есть датаграмма, чем
/// бы он ни оказался внутри. Оттого у трейта нет ни одного метода: терять нечего, кроме знания
/// о том, что было выше.
///
/// # Отношение не дерево, а решётка
///
/// Один протокол несётся НЕСКОЛЬКИМИ: HTTP идёт и прямо по TCP, и внутри TLS. Оттого параметр, а
/// не ассоциированный тип, — второй `impl` для того же `Self` законен и нужен.
pub trait CarriedIn<Under: Protocol>: Protocol {}

/// ПОДЪЁМ ПО СТЕКУ: наблюдение `Under` МОЖЕТ оказаться наблюдением `Self`.
///
/// Морфизм ЧАСТИЧНЫЙ, и частичность здесь не ошибка, а свойство мира: датаграмма может быть
/// QUIC, а может быть чем угодно ещё. Композиция частичных морфизмов частична — ровно поэтому
/// протокол нельзя носить ЗНАЧЕНИЕМ и передавать дальше как установленный факт.
///
/// # `CarriedIn` — надтрейт, и в этом весь смысл
///
/// Распознать можно лишь то, что этим протоколом вообще несётся. `Tls` не поднимается из `Udp` не
/// потому, что распознаватель не написан, а потому, что там его нет и быть не может, — и ловит
/// это компилятор:
///
/// ```compile_fail
/// use reflex_core::stack::{Dissects, Tls, Udp};
///
/// fn from_datagrams<P: Dissects<Udp>>(_: &[u8]) {}
///
/// // TLS в датаграммах не несётся: поднимать его оттуда нечем.
/// from_datagrams::<Tls>(&[]);
/// ```
///
/// А законный подъём собирается:
///
/// ```
/// use reflex_core::stack::{Dissects, Quic, Udp};
///
/// fn from_datagrams<P: Dissects<Udp>>(payload: &[u8]) -> bool {
///     P::dissect(payload)
/// }
///
/// // Клиентский `Initial`: длинный заголовок и версия 1.
/// assert!(from_datagrams::<Quic>(&[0xc0, 0x00, 0x00, 0x00, 0x01]));
/// assert!(!from_datagrams::<Quic>(b"\x16\x03\x01hello"));
/// ```
///
/// # НЕСОМЫЙ, НО НЕ РАСПОЗНАВАЕМЫЙ — законная клетка, и она занята
///
/// [`CarriedIn`] без `Dissects` есть утверждение «несётся, а увидеть нельзя»: HTTP внутри TLS
/// зашифрован, DNS поверх UDP узнаётся портом, а не содержимым. Слить два трейта в один значило бы
/// объявить эти клетки несуществующими — то есть повторить болезнь, из-за которой у нас `Seen`
/// стал словарём фактов TCP.
pub trait Dissects<Under: Protocol>: CarriedIn<Under> {
    /// Похоже ли содержимое `Under` на этот протокол.
    ///
    /// Улика, а не догадка по номеру порта: порт есть соглашение, и цензор его не спрашивает.
    fn dissect(payload: &[u8]) -> bool;
}

impl CarriedIn<Udp> for Quic {}

impl Dissects<Udp> for Quic {
    /// ДЛИННЫЙ ЗАГОЛОВОК И ИЗВЕСТНАЯ ВЕРСИЯ. Одного признака формы мало: под «старшие два бита
    /// единицы» подходит каждый четвёртый случайный байт.
    ///
    /// Версий две, и обе законны: 1 (RFC 9000) и черновая 29, которой ещё говорят старые клиенты.
    /// Version Negotiation (версия 0) сюда НЕ входит — это ответ сервера «не умею», а не разговор.
    fn dissect(payload: &[u8]) -> bool {
        match payload {
            [first, v0, v1, v2, v3, ..] => {
                first & 0xf0 == 0xc0
                    && matches!(
                        u32::from_be_bytes([*v0, *v1, *v2, *v3]),
                        0x0000_0001 | 0xff00_001d
                    )
            }
            _short => false,
        }
    }
}

impl CarriedIn<Tcp> for Tls {}

impl Dissects<Tcp> for Tls {
    /// ЗАПИСЬ ТИПА `handshake` (0x16) И ВЕРСИЯ 3.x. Версия проверяется не для порядка: один лишь
    /// 0x16 встречается в произвольных данных каждый двести пятьдесят шестой раз.
    fn dissect(payload: &[u8]) -> bool {
        matches!(payload, [0x16, 0x03, minor, ..] if *minor <= 0x04)
    }
}

impl CarriedIn<Tcp> for Http {}

impl Dissects<Tcp> for Http {
    /// МЕТОД ОТКРЫТЫМ ТЕКСТОМ. Список короткий и явный: эвристика «похоже на текст» назвала бы
    /// HTTP-ом всякий читаемый поток.
    fn dissect(payload: &[u8]) -> bool {
        [b"GET ".as_slice(), b"POST ", b"HEAD ", b"PUT ", b"OPTIONS "]
            .iter()
            .any(|method| payload.starts_with(method))
    }
}

/// HTTP ВНУТРИ TLS НЕСЁТСЯ, А РАСПОЗНАЁТСЯ НИЧЕМ: содержимое зашифровано.
///
/// Клетка «несомый без распознавания» занята здесь намеренно и первой — она и есть причина, по
/// которой трейтов два.
impl CarriedIn<Tls> for Http {}

/// DNS НЕСЁТСЯ ДАТАГРАММАМИ, А УЗНАЁТСЯ ПОРТОМ.
///
/// `Dissects` для него НЕ реализован, и это не пробел: содержимое сообщения DNS разбирается
/// (`crate::dns`), но по одному пакету «это DNS» от «это что-то с похожим заголовком» отличается
/// ненадёжно. Пока улика — порт 53, свидетель СЛАБЕЕ, и тип это говорит.
impl CarriedIn<Udp> for Dns {}

/// УЗКИЙ АЛФАВИТ ЧИТАЕТСЯ ИЗ ШИРОКОГО, и не всякая буква читается.
///
/// # Зачем тип, если есть [`lmap`](crate::mealy::MealyExt::lmap)
///
/// `lmap` берёт сужение ЗАМЫКАНИЕМ — то есть на каждой стройке цепочки заново, и всякий раз можно
/// написать другое. Пока сужение живёт в замыкании, «этот прибор читает вот эти буквы» есть
/// свойство ВЫЗОВА, а не прибора: два места соберут один прибор по-разному, и ни одно из них не
/// соврёт компилятору.
///
/// Здесь то же сужение становится свойством ПАРЫ ТИПОВ. Прибор объявляет свой алфавит входом,
/// сборщик требует равенство `D: Mealy<In = DetectorEvent<In>, …>` вместе с `In: Reads<Widest>` —
/// и прибор, чей алфавит из этого потока не читается, в него не встаёт. Не отфильтровывается, а не
/// компилируется.
///
/// # Частичность существенна
///
/// `Option` здесь не признак ошибки: буквы, которых на узком алфавите нет, просто НЕ ЯВЛЯЮТСЯ
/// событиями для его читателя. Сброс TCP для прибора, живущего на любом транспорте, — не сбой
/// чтения, а факт не про него.
///
/// # Тождество даётся даром
///
/// Всякий алфавит читается сам из себя, и потому прибор, объявивший вход широким, годится своему
/// же потоку без единой строки.
///
/// ```
/// use reflex_core::stack::Reads;
///
/// #[derive(Clone, Debug, PartialEq)]
/// enum Wide { Общая(u8), Своя }
/// #[derive(Clone, Debug, PartialEq)]
/// struct Narrow(u8);
///
/// impl Reads<Wide> for Narrow {
///     fn read(wide: &Wide) -> Option<Self> {
///         match wide {
///             Wide::Общая(n) => Some(Narrow(*n)),
///             // «Своя» на узком алфавите не существует — читателю сказать нечего.
///             Wide::Своя => None,
///         }
///     }
/// }
///
/// assert_eq!(Narrow::read(&Wide::Общая(7)), Some(Narrow(7)));
/// assert_eq!(Narrow::read(&Wide::Своя), None);
/// // Тождество — из общей реализации, писать его не нужно.
/// assert_eq!(Wide::read(&Wide::Своя), Some(Wide::Своя));
/// ```
pub trait Reads<Wide>: Sized {
    /// Прочитать своё из широкого. `None` — этой буквы на узком алфавите нет.
    fn read(wide: &Wide) -> Option<Self>;
}

/// ТОЖДЕСТВО: алфавит читается сам из себя целиком.
///
/// Общей реализацией, а не по одной на алфавит: тождественный морфизм есть у КАЖДОГО объекта, и
/// заставлять его выписывать значило бы просить писать очевидное — а забытая строка выглядела бы
/// как «этот прибор своему потоку не годится».
impl<A: Clone> Reads<A> for A {
    fn read(wide: &A) -> Option<A> {
        Some(wide.clone())
    }
}
