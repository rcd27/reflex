//! ЭТАЖ СТЕКА КАК ТИП: детектор, снятый не с того транспорта, не собирается.
//!
//! Паспорт прибора объявляет протокол (`PROTOCOL: Tcp`), но объявление ничего не запрещало:
//! наблюдение транспорта не несло, и датаграмма, поданная прибору TCP, висела «соединением» и
//! копила молчание. Живой прогон 02.09 дал шквал ложных `no_bytes` о DNS-резолвере.
//!
//! Этаж становится параметром типа НАБЛЮДЕНИЯ: прибор объявляет вход `Wire<Tcp>`, и поток
//! датаграмм в него не соберётся. Отдельной оси совместимости не заводится — прибор, чей предмет
//! от транспорта не зависит, пишется генериком по этажу и годится обоим.

/// Транспорт, на котором снято наблюдение.
pub trait Transport {
    const NAME: &'static str;
}

/// TCP: рукопожатие, сброс, окно приёма — улики, которых у датаграмм нет.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Tcp;

/// UDP: датаграммы, включая QUIC, чьё имя лежит за шифром `Initial`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Udp;

/// ЭТАЖ БЕЗРАЗЛИЧЕН — предмет прибора существует на любом транспорте (объём, ожидание, уход
/// человека). Это не «неизвестно», а утверждение: улика не зависит от транспорта.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AnyTransport;

impl Transport for Tcp {
    const NAME: &'static str = "tcp";
}

impl Transport for Udp {
    const NAME: &'static str = "udp";
}

impl Transport for AnyTransport {
    const NAME: &'static str = "любой";
}
