//! Величины КРАЯ — ЗАКОН, носителя не знающий (§ спеки «Закон и его носитель»). Кто ведёт край —
//! conntrack, карта eBPF, чужая ОС — реализует этот трейт; приборы читают его, а не носителя, и
//! потому переносятся на другой край сменой одного `impl`, не строки в парке.
//!
//! Имена величин — КРАЕВЫЕ, не conntrack'овые (`down`/`up`, не `orig`/`reply`): последние — слова
//! ctnetlink, они протащили бы носителя в закон через словарь. `None` — не педантизм: край с
//! выключенным учётом счётчиков не даёт, и это разница между «цель не ответила» и «мы не считали».

use std::time::Duration;

use crate::mark::Bits;

/// Что ведёт край о разговоре, кем бы край ни был.
pub trait EdgeView {
    /// Пакетов от клиента к цели. `None` — учёт на крае выключен (не ноль).
    fn down_packets(&self) -> Option<u64>;
    /// Пакетов от цели к клиенту.
    fn up_packets(&self) -> Option<u64>;
    /// Байт КАДРОВ (L3+L4+нагрузка) от клиента к цели, не нагрузки. Кадры, а не нагрузка, потому
    /// что conntrack нагрузки не знает и знать не может: обещать её значило бы обещать
    /// невыполнимое, а прибор всё равно компенсировал бы заголовки — и компенсация была бы верна
    /// по совпадению с одним носителем, а не по контракту. Отдельно от пакетов не педантизм: тишину
    /// меряют байты (клиент отдал данные — `down_bytes` сверх заголовков), а жизнь цели — пакеты
    /// (ответила хоть `ACK`, пусть и без данных). Слей их — и медленный-но-живой собеседник (шлёт
    /// `ACK` до ответа) станет неотличим от дропнутого (молчит и байтом, и пакетом). `None` — учёт
    /// выключен.
    fn down_bytes(&self) -> Option<u64>;
    /// Байт КАДРОВ (L3+L4+нагрузка) от цели к клиенту, не нагрузки — симметрично `down_bytes`,
    /// той же причиной (conntrack нагрузки не знает). `None` — учёт выключен.
    fn up_bytes(&self) -> Option<u64>;
    /// Сколько прошло с последнего пакета разговора — ГОТОВОЙ величиной. Пересчёт (из таймаута и
    /// остатка у conntrack, из иного у другого края) — знание носителя, ему место в `impl`, не в
    /// приборе: иначе второй край считал бы иначе, и вышло бы два закона об одной величине.
    fn idle(&self) -> Option<Duration>;
    /// ВОЗРАСТ разговора — сколько прошло от его НАЧАЛА. В отличие от `idle`, монотонен: пакет его не
    /// освежает (ядро сбрасывает таймаут на любом пакете, включая повтор клиента, — оттого `idle` у
    /// дропнутого потока близок к нулю и лжёт). Возраст же — единственные честные часы «сколько цель
    /// молчит с открытия»: два наблюдения подряд умещаются в burst рукопожатия ДО ответа, и лишь
    /// возраст отличает «ещё не ответила» от «уже не ответит». Пересчёт — знание носителя (свои часы
    /// минус абсолютное начало ядра), потому здесь, не в приборе.
    fn age(&self) -> Option<Duration>;
    /// Слово состояния, как его хранит край (наша марка под маской-параметром).
    fn mark(&self) -> u32;
    /// Метки разговора ([`Labels`]). Умолчание — `None`: край, меток не ведущий, так и говорит, а
    /// не выдаёт «меток нет».
    fn labels(&self) -> Option<Labels> {
        None
    }
}

/// МЕТКИ РАЗГОВОРА — флаги, которые край держит о разговоре ОТДЕЛЬНО от марки. Марку по пути
/// переписывают правила (слово целиком), метку ставит только тот, кто её ставит, и она доживает до
/// конца разговора: так свидетельство о событии внутри разговора (впрыск, сработавшая нога) не
/// стирается следующим пакетом. Биты сами по себе не значат ничего — номер метки объявляет её
/// потребитель вместе с правилом, которое её ставит.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[cfg_attr(
    feature = "serde",
    derive(serde::Serialize, serde::Deserialize),
    serde(transparent)
)]
pub struct Labels([u64; 2]);

impl Labels {
    /// Двумя словами, а не `u128`: выравнивание `u128` раздуло бы снимок, едущий с каждой буквой.
    pub fn of(bits: u128) -> Labels {
        Labels([bits as u64, (bits >> 64) as u64])
    }

    /// Стоит ли метка `label`. Номер за пределами карты — не стоит.
    pub fn has(self, label: u8) -> bool {
        let Labels(words) = self;
        words
            .get(usize::from(label / 64))
            .is_some_and(|word| word >> (label % 64) & 1 == 1)
    }
}

/// СНИМОК КРАЯ — величины, СНЯТЫЕ в момент наблюдения, отвязанные от того, кто их вёл.
///
/// Зачем он есть: величины края текут через цепочку и их читают приборы, но наружу их не отдавала
/// ни одна дверь — ни `.on`, ни `.act`, ни показания значением. Потребителю, рисующему человеку
/// таблицу «у кого беда, чем ведём, что с байтами», взять их было негде, и он написал бы второй
/// прибор о том же — то есть вторую правду об одних числах.
///
/// Почему СНИМОК, а не сам край: край живёт у носителя и переживает пакет, а показание уезжает к
/// потребителю и живёт дольше буквы. Отдать ссылку значило бы обещать, что носитель не сдвинется.
///
/// Почему не «беда»: край есть СВОЙСТВО РАЗГОВОРА, а не поломка. Объявить его словом бедствия ради
/// доставки — покривить алфавитом: `Distress` описывает, что человек ПОЧУВСТВОВАЛ бы как поломку, а
/// «вниз прошло 40 килобайт» он не чувствует никак.
///
/// Клетка незнания сохраняется целиком: каждое поле — `Option`, и `None` значит «не считали», а не
/// «ноль» (§7). Снимок берётся с любого края одним способом ([`Counted::of`]), потому два края не
/// могут разойтись в том, ЧТО именно снято.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct Counted {
    pub down_packets: Option<u64>,
    pub up_packets: Option<u64>,
    pub down_bytes: Option<u64>,
    pub up_bytes: Option<u64>,
    pub idle: Option<Duration>,
    pub age: Option<Duration>,
    /// Марка разговора. НЕ `u32`, и это главное в снимке.
    ///
    /// Биты сами по себе не значат ничего: область марки хранит размеченное объединение, и прочесть
    /// её нельзя, не зная разметки (см. раздел про условное владение в [`crate::mark`]). Пока поле
    /// было числом, разметку писал КАЖДЫЙ читатель — у потребителя их набралось четыре, законов
    /// тоже четыре, и два из них не пересеклись: целое состояние продукта стало невыразимым при
    /// зелёных приёмках. Над [`Bits`] случайное `mark & 0xFF == …` не собирается вовсе, а смысл
    /// берётся объявленным алфавитом, второго закона о котором язык написать не даёт (E0119).
    pub mark: Bits,
    /// Метки разговора. `None` — край их не ведёт.
    pub labels: Option<Labels>,
}

impl Counted {
    /// ПОД КАКОЙ МАРКОЙ ШЁЛ РАЗГОВОР — в алфавите потребителя, а не битами.
    ///
    /// Разметка объявляется один раз (`impl Meaning for …`), и второй раз её не объявить. Оттого
    /// все читатели снимка судят об одних битах ОДНИМ законом — не по договорённости, а потому что
    /// другого закона не существует.
    pub fn under<M: crate::mark::Meaning>(&self) -> M {
        self.mark.under()
    }
    /// Снять величины с любого края. Один способ на все края — иначе снимки с conntrack и с
    /// местного счёта разошлись бы в том, что считается снятым.
    pub fn of<V: EdgeView + ?Sized>(view: &V) -> Counted {
        Counted {
            down_packets: view.down_packets(),
            up_packets: view.up_packets(),
            down_bytes: view.down_bytes(),
            up_bytes: view.up_bytes(),
            idle: view.idle(),
            age: view.age(),
            // ЕДИНСТВЕННЫЙ ПЕРЕХОД СЫРЬЯ В ТИП: край говорит с ядром битами, снимок едет к
            // потребителю уже маркой. Дальше по пути голого слова нет ни у кого.
            mark: Bits::of(view.mark()),
            labels: view.labels(),
        }
    }
}

/// Снимок сам есть край: прибор, написанный над `EdgeView`, читает его без переделки — и тем
/// доказуемо, что снимок ничего не потерял.
impl EdgeView for Counted {
    fn down_packets(&self) -> Option<u64> {
        self.down_packets
    }
    fn up_packets(&self) -> Option<u64> {
        self.up_packets
    }
    fn down_bytes(&self) -> Option<u64> {
        self.down_bytes
    }
    fn up_bytes(&self) -> Option<u64> {
        self.up_bytes
    }
    fn idle(&self) -> Option<Duration> {
        self.idle
    }
    fn age(&self) -> Option<Duration> {
        self.age
    }
    /// Снимок отдаёт слово целиком тому, кто спрашивает его КАК КРАЙ: разметка приборов
    /// (`instrument::edge::Layout`) читает своё поле сама, и битов ей не заменить ничем.
    fn mark(&self) -> u32 {
        self.mark.word()
    }
    fn labels(&self) -> Option<Labels> {
        self.labels
    }
}
