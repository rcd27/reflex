//! ТИП КАДРА — два закона вместо тринадцати случаев.
//!
//! Та же порода, что у протоколов и флагов TCP: тринадцать случаев суть представители таблицы,
//! выбранные рукой. Здесь значений 65 536 — перебрать все дешевле, чем выбирать, и перебор ловит
//! то, чего выборка не ловит по устройству: код, попавший в две ветки, или именованный тип,
//! отвечающий чужим числом.
//!
//! Тестов на выведенные компилятором `PartialEq` и `Copy` здесь нет: свой тест на `derive` не
//! ловит наших ошибок — он проверяет компилятор.

use reflex_core::types::EtherType;

/// ИМЕНОВАНЫ РОВНО ТРИ КОДА, И РОВНО ТЕ. Числа взяты из реестра IANA напрямую, независимо от
/// реализации: два способа сказать одно, и расхождение между ними — находка.
#[test]
fn exactly_three_codes_are_named_and_the_other_sixty_five_thousand_are_foreign() {
    for code in 0u16..=u16::MAX {
        let named = match code {
            0x0800 => Some(EtherType::Ipv4),
            0x86DD => Some(EtherType::Ipv6),
            0x0806 => Some(EtherType::Arp),
            _ => None,
        };
        let expected = named.unwrap_or(EtherType::Other(code));
        assert_eq!(
            EtherType::from_u16(code),
            expected,
            "код {code:#06x} разобран не тем вариантом"
        );
    }
}

/// КРУГ ЗАМКНУТ НА ВСЕХ КОДАХ. Закон таблицы не «0x0800 даёт IPv4», а «ни один код не теряется и не
/// подменяется по дороге» — ошибка в любой строке краснит его, включая ту, что осталась бы без
/// своего теста.
#[test]
fn the_round_trip_of_codes_closes_on_every_value() {
    for code in 0u16..=u16::MAX {
        assert_eq!(
            EtherType::from_u16(code).to_u16(),
            code,
            "код {code:#06x} не пережил дорогу туда и обратно"
        );
    }
}
