//! Идиома «докблок называет сторожа». Обещание СВОЙСТВА («не раньше `until`, кроме как с работой»,
//! «узлы выходят ПЕРЕД пакетом», «отпустить и запомнить неделимо») пример не доказывает — пример
//! показывает один проход, обещано поведение на всех. Держит его тест, но связь «докблок ↔ тест»
//! нигде не была записана: докблок и тест расходились молча при переписывании, и человек ловил это
//! постфактум (шесть раз за 09–10.09.2026, ни разу не компилятор и не тест).
//!
//! Идиома: докблок, утверждающий поведение, называет тест словом `Сторож:` — построчно, в
//! обратных кавычках, через запятую, если сторожей несколько:
//!
//! ```text
//! /// Не возвращается раньше `until`, кроме как с работой.
//! /// Сторож: `пустой_носитель_держит_срок`.
//! ```
//!
//! Грамматика узко нарочно: одна строка `///` с подстрокой `Сторож:`, дальше — имена в обратных
//! кавычках до конца строки. Не Markdown-ссылка (`[`имя`]`) — сторож это ИМЯ ФУНКЦИИ-ТЕСТА, не
//! путь типа, резолвить его сквозь `pub`/приватность незачем, и `rustdoc` про него ничего не знает.
//!
//! Эта проверка сканирует `.rs`-файлы всего дерева, вынимает все названные сторожа и требует, чтобы
//! каждый существовал как `fn <имя>` — где угодно (тесты живут в других крейтах и файлах, чем
//! исходник докблока, и это нормально: `core/src/serves.rs` называет сторожа из `core/tests/serves.rs`).
//!
//! # Предел (не молчать о нём — часть договора этого файла)
//!
//! Проверка ловит УТЕЧКУ: связь, однажды установленную записью `Сторож: \`имя\``, разорвали молча —
//! тест переименовали, снесли, докблок скопировали в другое место без переноса сторожа. Она красная,
//! если имя названо и не существует.
//!
//! Она НЕ ловит НАКОПЛЕНИЕ: докблок утверждает поведение и НЕ называет сторожа вовсе. Это ровно
//! болезнь, из-за которой писался весь этот механизм — пять из шести дыр 09–10.09.2026 были именно
//! такими, и эта проверка прошла бы их МОЛЧА: назвать сторожа некому, если докблок его не назвал.
//! Накопление лечится чтением (ревью, дописыванием идиомы к новым законам), не машиной — заявлять
//! иное значило бы завести седьмой случай той же болезни в лекарстве от неё.

use std::path::{Path, PathBuf};

/// Каталоги, которых в сканировании нет намеренно: собранные артефакты (`target`), git-метаданные,
/// служебные каталоги инструмента. Всё остальное дерево — исходники крейтов, тесты, примеры —
/// сканируется целиком: сторож обязан находиться, откуда бы докблок его ни звал.
const SKIP_DIRS: &[&str] = &["target", ".git", "node_modules"];

fn workspace_root() -> PathBuf {
    // `CARGO_MANIFEST_DIR` этого крейта — `<root>/core`; воркспейс на уровень выше.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("core лежит прямо в воркспейсе")
        .to_path_buf()
}

fn collect_rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if SKIP_DIRS.contains(&name) || name.starts_with('.') {
                continue;
            }
            collect_rust_files(&path, out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            out.push(path);
        }
    }
}

/// Похоже на имя функции: только буквы (любого алфавита), цифры, `_` — ни пробела, ни дефиса, ни
/// пунктуации. Фильтр нужен, чтобы строки, где `Сторож:` упомянут как ТЕКСТ (этот же докблок его
/// объясняет), не были прочитаны как настоящее объявление сторожа: у прозы внутри обратных кавычек
/// (если она случится) почти всегда есть пробел или тире, у имени функции — никогда.
fn looks_like_guard_name(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c == '_' || c.is_alphanumeric())
}

/// Имена в обратных кавычках, стоящие ПОСЛЕ подстроки `Сторож:` на этой строке.
fn guards_named_on_line(line: &str) -> Vec<String> {
    let Some(after) = line.split("Сторож:").nth(1) else {
        return Vec::new();
    };
    after
        .split('`')
        .skip(1)
        .step_by(2)
        .map(|s| s.to_string())
        .filter(|s| looks_like_guard_name(s))
        .collect()
}

/// Имена функций (`fn <имя>`), объявленных где-либо в тексте — намеренно грубо: тест-инструмент, не
/// парсер Rust. Ложное срабатывание внутрь (нашли лишнюю `fn`) безвредно, интересна только полнота
/// в другую сторону — не пропустить существующего сторожа.
fn fn_names_declared_in(text: &str) -> std::collections::HashSet<String> {
    let mut names = std::collections::HashSet::new();
    let bytes = text.as_bytes();
    let mut i = 0;
    while let Some(rel) = text[i..].find("fn ") {
        let at = i + rel;
        let before_ok = at == 0 || {
            let prev = bytes[at - 1];
            !(prev.is_ascii_alphanumeric() || prev == b'_')
        };
        let mut j = at + 3;
        while j < bytes.len() && (bytes[j] as char).is_whitespace() {
            j += 1;
        }
        let start = j;
        while j < text.len() {
            let c = text[j..].chars().next().unwrap();
            if c == '_' || c.is_alphanumeric() {
                j += c.len_utf8();
            } else {
                break;
            }
        }
        if before_ok && j > start {
            names.insert(text[start..j].to_string());
        }
        i = at + 3;
    }
    names
}

/// Проверяет идиому «докблок называет сторожа»: каждое имя после `Сторож:` в докблоках всего
/// дерева обязано существовать как `fn <имя>` — иначе связь докблок↔тест уже порвана, и никто
/// этого не заметил.
///
/// ПРЕДЕЛ: ловит только УТЕЧКУ (сторож назван и потерян). НЕ ловит НАКОПЛЕНИЕ (закон утверждён,
/// сторож не назван вовсе) — см. докблок модуля, раздел «Предел».
#[test]
fn каждый_названный_сторож_существует() {
    let root = workspace_root();
    let mut files = Vec::new();
    collect_rust_files(&root, &mut files);
    assert!(
        files.len() > 50,
        "сканирование нашло подозрительно мало .rs-файлов ({}) — проверь корень {:?}",
        files.len(),
        root
    );

    let mut declared = std::collections::HashSet::new();
    let mut named_guards: Vec<(String, PathBuf)> = Vec::new();

    for path in &files {
        let Ok(text) = std::fs::read_to_string(path) else {
            continue;
        };
        declared.extend(fn_names_declared_in(&text));
        for line in text.lines() {
            for guard in guards_named_on_line(line) {
                named_guards.push((guard, path.clone()));
            }
        }
    }

    assert!(
        !named_guards.is_empty(),
        "идиома `Сторож:` не найдена нигде в дереве — либо она ещё не применена ни к одному \
         закону, либо сканирование сломано"
    );

    let missing: Vec<String> = named_guards
        .iter()
        .filter(|(name, _)| !declared.contains(name))
        .map(|(name, path)| format!("`{name}` (назван в {})", path.display()))
        .collect();

    assert!(
        missing.is_empty(),
        "докблок называет сторожа, которого нет ни одной `fn` в дереве — связь докблок↔тест \
         порвана молча:\n{}",
        missing.join("\n")
    );
}
