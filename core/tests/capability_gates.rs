//! У КАЖДОЙ СПОСОБНОСТИ ЕСТЬ СВОЙ `compile_fail`-СТОРОЖ — и это проверяется, а не помнится.
//!
//! Докблок `core/src/capability.rs` объявляет идиому: гейт §9.1 («заявить способность, не назвав её
//! предмет, нельзя») каждый трейт доказывает `compile_fail`-доктестом, стоящим прямо над
//! объявлением. Он же честно называет, почему соседняя идиома (`Сторож:` в
//! `core/tests/docblock_guards.rs`) сюда не годится: доктест не `fn`, у него нет имени, которое
//! можно сверить с деревом.
//!
//! Названо — и не закрыто. **Замер 10.09.2026: девять способностей сторожа имели, две — нет.** Обе
//! без сторожа оказались самыми молодыми (`CanAsk`, `CanRemember`, заведены в тот же день). Правило
//! существовало, было записано в докблоке и соблюдалось девять раз подряд — а новая способность его
//! не наследовала, потому что наследовать было нечему: идиома жила в голове пишущего.
//!
//! # Почему НАКОПЛЕНИЕ здесь ловимо, хотя вообще оно не ловится
//!
//! `docblock_guards.rs` называет свой предел прямо: он ловит УТЕЧКУ (связь была и порвалась) и не
//! ловит НАКОПЛЕНИЕ (связи не завели вовсе) — потому что «докблок, утверждающий поведение» списком
//! не выразим, и требовать сторожа у каждого значило бы требовать его у всякой строки прозы.
//!
//! Здесь предмет **конечен и перечислим**: `pub trait Can*` в ОДНОМ файле. Список полон по
//! построению, и «должно быть по одному на каждого» — проверяемое утверждение, а не пожелание.
//! Накопление ловится ровно там, где известно, чего и сколько должно быть.

use std::path::Path;

/// Разметка `capability.rs`, прочитанная построчно: имя способности и был ли `compile_fail` между
/// ней и предыдущим объявлением.
fn declared_with_guard() -> Vec<(String, bool)> {
    let source = std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("src/capability.rs"))
        .expect("исходник способностей читается");

    let mut found: Vec<(String, bool)> = Vec::new();
    let mut guarded = false;
    for line in source.lines() {
        let line = line.trim_start();
        if line.contains("compile_fail") {
            guarded = true;
        }
        if let Some(rest) = line.strip_prefix("pub trait Can") {
            let name = rest
                .split([':', ' ', '{'])
                .next()
                .expect("у объявления есть имя");
            found.push((format!("Can{name}"), guarded));
            // Счётчик сбрасывается на КАЖДОМ объявлении: доктест соседа сверху не годится в
            // сторожа нижнему, иначе один `compile_fail` покрывал бы весь файл.
            guarded = false;
        }
    }
    found
}

/// ГЕЙТ ЗАЯВЛЕНИЯ ПРЕДЪЯВЛЕН У КАЖДОЙ СПОСОБНОСТИ, БЕЗ ИСКЛЮЧЕНИЙ.
///
/// Красен ровно тогда, когда заведена способность без своего `compile_fail`, — то есть когда
/// правило соблюдено не будет. Это тот же род проверки, что `scripts/canon.sh` для канона: не
/// «утверждение верно», а «утверждение вообще предъявлено».
#[test]
fn у_каждой_способности_есть_свой_гейт_заявления() {
    let declared = declared_with_guard();

    let naked: Vec<&str> = declared
        .iter()
        .filter(|(_, guarded)| !guarded)
        .map(|(name, _)| name.as_str())
        .collect();

    assert!(
        naked.is_empty(),
        "способности без `compile_fail`-сторожа: {naked:?}. Заявить способность, не назвав её \
         предмет, обязано быть нельзя — и это обязано быть ПРЕДЪЯВЛЕНО доктестом прямо над \
         объявлением, а не подразумеваться"
    );
}

/// СПИСОК НЕ ПУСТ И НЕ ОБРЕЗАН — иначе первый тест зелен на пустоте.
///
/// Разбор идёт по тексту исходника, и всякая его поломка (переименование, смена оформления,
/// пустой путь) дала бы пустой список, на котором «нет способностей без сторожа» — истина, ничего
/// не значащая. Число сверяется с объявлениями, найденными НЕЗАВИСИМО: по вхождениям `pub trait
/// Can` в том же тексте.
#[test]
fn разбор_нашёл_все_объявления_а_не_молча_ноль() {
    let source = std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("src/capability.rs"))
        .expect("исходник способностей читается");
    let independently = source.matches("pub trait Can").count();

    assert!(independently >= 11, "способностей стало меньше одиннадцати — это событие, а не опечатка");
    assert_eq!(
        declared_with_guard().len(),
        independently,
        "разбор потерял объявления: он и есть предмет первого теста, и слепой разбор сделал бы тот \
         зелёным на пустоте"
    );
}
