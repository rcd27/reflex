//! ОЧЕРЕДЬ ЯДРА КАК ТЕРМИНАЛЬНЫЙ МОРФИЗМ — единственное место, где решение становится эффектом.
//!
//! # Что здесь чинится
//!
//! Прежде вердикт был ВЫЗОВОМ и стоял в четырёх местах:
//!
//! ```text
//! msg.set_verdict(Verdict::Accept);
//! let _ = self.queue.verdict(msg);      // ← и так четырежды
//! ```
//!
//! Две беды в одном выражении, и обе про то, что сведения покидали значение:
//!
//! 1. Вызов нельзя ни записать, ни сравнить, ни развернуть назад — после него не остаётся ничего,
//!    и расследование по такому шагу невозможно.
//! 2. `let _ =` выбрасывал ЕДИНСТВЕННЫЙ факт о доставке. Ядро отказывает — например, когда
//!    сообщение уже протухло по таймауту очереди, — и мы бы не узнали.
//!
//! Здесь решение отделено от эффекта: цепочка порождает
//! [`Answered`](reflex_core::held::Answered), а мира касается ровно [`Terminal::apply`]. Отказ
//! ядра становится значением [`Refused`](reflex_core::held::Refused), а не тишиной.
//!
//! # `&mut` остаётся, и это правильно
//!
//! Netlink-сокет один, отправка по нему последовательна по природе, и край — место для
//! performance-first. Вопрос был не в том, чтобы `&mut` убрать, а в том, чтобы он стоял В ОДНОМ
//! МЕСТЕ: выше него значения, ниже мир.

use nfq::Verdict;
use reflex_core::builder::TcpBuilder;
use reflex_core::capability::Toward;
use reflex_core::command::InjectablePacket;
use reflex_core::held::{Answered, Delivered, Observed, Refused, Terminal};
use reflex_core::parse::parse_tcp_from_ip;
use reflex_core::types::TcpFlags;

use super::backend::NfqueueBackend;

/// СООБЩЕНИЕ ОЧЕРЕДИ КАК НОСИТЕЛЬ ПРАВА ОТВЕТИТЬ.
///
/// # Почему ньютайп, а не `impl` прямо на `nfq::Message`
///
/// Правило сирот: `Observed` живёт в `reflex-core`, `Message` — в чужом крейте, и ни один из них
/// не наш. Запрет здесь не помеха, а подсказка: обёртка и есть то место, где мы говорим, ЧЕМ для
/// нас является чужой тип.
///
/// `#[repr(transparent)]` — гарантия, что изоляция бесплатна: раскладка та же, что у самого
/// сообщения, и никакого косвенного обращения не появляется.
///
/// # Байты живут здесь, пока живо сообщение
///
/// Разбор читает их заимствованием, дело помнит извлечённую улику, а полная запись пакета лежит в
/// сырье независимого прибора. Прежняя редакция клала `Vec<u8>` в само дело: аллокация на каждый
/// пакет и дубликат того, что уже на диске.
#[repr(transparent)]
pub struct Queued(pub nfq::Message);

impl Observed for Queued {
    fn payload(&self) -> &[u8] {
        self.0.get_payload()
    }
}

/// ЧЕМ МОЖНО ОТВЕТИТЬ ОЧЕРЕДИ — её собственный алфавит, а не общий на все носители.
///
/// Ровно четыре слова, потому что ровно столько умеет очередь. Пятого варианта здесь не завести
/// молча: он потребует ветки в [`Terminal::apply`], и компилятор это спросит.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Answer {
    /// Пропустить как есть.
    Pass,
    /// Пропустить, поставив метку. ПАКЕТ ПРОДОЛЖАЕТ ОБХОД С МЕСТА, ГДЕ ЕГО ЗАБРАЛИ: правило,
    /// читающее метку, обязано стоять НИЖЕ по цепочке, чем правило очереди. Поставь его выше —
    /// метка встанет и не будет прочитана никем, а прибор покажет «решение принято».
    Marked(u32),
    /// Не пропускать.
    Stop,
    /// Пропустить с подменёнными байтами.
    Modified(Vec<u8>),
}

/// ПОЧЕМУ ЯДРО НЕ ПРИНЯЛО ОТВЕТ. Отдельный тип, а не строка: у отказа есть причина, и она
/// приходит от операционной системы — терять её значило бы возвращаться к `let _ =`.
#[derive(Debug)]
pub struct NotTaken(pub std::io::Error);

impl Terminal for NfqueueBackend {
    type Carrier = Queued;
    type Answer = Answer;
    type Refusal = NotTaken;

    fn apply(
        &mut self,
        answered: Answered<Queued, Answer>,
    ) -> Result<Delivered<Answer>, Refused<Answer, NotTaken>> {
        let Answered {
            carrier: Queued(mut carrier),
            at,
            answer,
        } = answered;

        match &answer {
            Answer::Pass => carrier.set_verdict(Verdict::Accept),
            Answer::Marked(mark) => {
                carrier.set_nfmark(*mark);
                carrier.set_verdict(Verdict::Accept);
            }
            Answer::Stop => carrier.set_verdict(Verdict::Drop),
            // ЕДИНСТВЕННАЯ КОПИЯ ВО ВСЁМ ПУТИ, и она копирует НЕ НАБЛЮДЕНИЕ, а РЕШЕНИЕ.
            //
            // Наблюдённые байты не копируются нигде: их читают у сообщения заимствованием, а
            // полная запись лежит в сырье независимого прибора. Подменённые же байты — наши, и
            // больше их нет нигде: отдай мы их ядру по владению, `Delivered` перестал бы говорить,
            // ЧЕМ именно ответили, и шаг стал бы невосстановимым.
            //
            // Платит одна ветвь из четырёх, самая редкая. Убрать копию можно разделяемым буфером
            // (`bytes::Bytes` — стандарт экосистемы), и это станет оправданным, когда подмена
            // перестанет быть редкой; сегодня зависимость дороже выигрыша.
            Answer::Modified(bytes) => {
                carrier.set_payload(bytes.clone());
                carrier.set_verdict(Verdict::Accept);
            }
        }

        // ЕДИНСТВЕННОЕ МЕСТО, ГДЕ СЛУЧАЕТСЯ МИР — и единственное, где его отказ ловится.
        match self.send_verdict(carrier) {
            Ok(()) => Ok(Delivered { at, answer }),
            Err(why) => Err(Refused {
                at,
                answer,
                why: NotTaken(why),
            }),
        }
    }
}

// ПЕРВЫЕ ЗАЯВЛЕНИЯ ОЧЕРЕДИ, И У КАЖДОГО ЕСТЬ ПРЕДМЕТ (#326, 05.09.2026).
//
// До этого дня `NfqueueBackend` не заявлял НИ ОДНОЙ способности — а продукт работает именно на
// нём. То есть оба сертифицированных закона проверяли бэкенды, которыми потребитель не
// пользуется, и единственный боевой стоял вне категории.
//
// ЧЕТЫРЕ ЗАЯВЛЕНИЯ НА ЧЕТЫРЕ СЛОВА АЛФАВИТА — покрытие полное.
//
// `Marked` заводилось последним и поначалу было отложено с честной ценой: метка не видна на
// проводе, свидетеля ей нет. Свидетель нашёлся тем же вечером и оказался тем самым, ради кого
// метка и ставится, — правилом-счётчиком НИЖЕ очереди. Закон `certify::marks` ловит им граблю,
// записанную здесь словами с 31.08: читателя, стоящего выше правила очереди.

impl reflex_core::CanHold for NfqueueBackend {
    fn release() -> Answer {
        Answer::Pass
    }
}

impl reflex_core::CanRefuse for NfqueueBackend {
    fn refuse() -> Answer {
        Answer::Stop
    }
}

impl reflex_core::CanRewrite for NfqueueBackend {
    fn rewrite(bytes: Vec<u8>) -> Answer {
        Answer::Modified(bytes)
    }
}

/// ОБРЫВ — ПАРА, И ТЕПЕРЬ ОН ОДИН ПРЕДМЕТ (#326, 05.09.2026).
///
/// # Что переехало сюда и откуда
///
/// Сборка `RST` жила в продукте (`app::petlya::rst_to_client`), и потому определение
/// обрыва существовало в репе трижды: полностью — в бою, наполовину (дроп без извещения) — в
/// эталонном примере движка, никак — во втором бинаре. Три ответа на один вопрос расходятся
/// молча, и дороже всех именно этот: дроп без извещения есть ровно то, чем бьёт молчаливый дроп на пути.
///
/// # ДВА СЛУЧАЯ, А НЕ ОДИН — и это правка, а не перенос
///
/// Прежняя редакция считала номера ОДИНАКОВО для обеих сторон: `seq` брался из `ack` удержанного
/// пакета всегда. Для пакета, идущего ОТ клиента, это верно — серверный `seq` и есть то, что
/// клиент подтвердил. Для пакета, идущего ОТ ЦЕЛИ, это неверно: там `ack` — то, что подтвердила
/// цель, а извещение от её имени обязано нести `seq + длину`. Клиент такой `RST` отбрасывает как
/// пришедший не в окно, и обрыв не случается — молча, при зелёном вердикте.
///
/// Различие видно только когда стороны названы типом ([`Toward`]), и ровно за этим он и заведён.
///
/// # ПОЧЕМУ НОМЕРА ОБЯЗАНЫ БЫТЬ ВЕРНЫ
///
/// `RST` вне окна приёма получатель МОЛЧА отбрасывает (RFC 5961). Ошибись мы в номерах — получим
/// ту же болезнь в новой форме: приказ исполнен, вердикт зелёный, эффекта нет, и не знает никто.
/// Именно это и делает извещение предметом ЗАКОНА, а не только типа: изнутри процесса «сказали» и
/// «услышали» неразличимы совершенно.
///
/// # ЧТО УВИДИТ ЧЕЛОВЕК
///
/// Ядро извещённой стороны закрывает сокет немедленно (`ECONNRESET`) вместо ожидания таймаута.
/// Браузер на идемпотентном запросе, по которому не пришло ни байта, повторяет его на новом
/// соединении — человек теряет доли секунды вместо секунд ожидания.
///
/// Условие законности обрыва при этом НЕ ЗДЕСЬ и здесь быть не может: `RST` по соединению, которое
/// уже несёт байты, есть оборванная докачка и прерванный ролик. Способность умеет СКАЗАТЬ; решает,
/// позволено ли рвать, домен — и у продукта этот предикат есть (`pipe::still_carries`).
impl reflex_core::CanSever for NfqueueBackend {
    fn notice(seen: &[u8], toward: Toward) -> Option<InjectablePacket> {
        parse_tcp_from_ip(seen).map(|segment| {
            // СКОЛЬКО БАЙТ ЗАНЯЛ УДЕРЖАННЫЙ ПАКЕТ В ПОТОКЕ СВОЕГО ОТПРАВИТЕЛЯ.
            let taken = segment.seq.wrapping_add(segment.payload.len() as u32);

            let (flow, seq, ack) = match toward {
                // ГОВОРИМ ОТПРАВИТЕЛЮ ОТ ИМЕНИ ПОЛУЧАТЕЛЯ: концы меняются местами, наш `seq` —
                // это то, что отправитель уже подтвердил, а подтверждаем мы всё, что он послал.
                Toward::Sender => (segment.flow.reversed(), segment.ack, taken),
                // ГОВОРИМ ПОЛУЧАТЕЛЮ ОТ ИМЕНИ ОТПРАВИТЕЛЯ: концы как есть, наш `seq` продолжает
                // поток отправителя, а подтверждаем то, что он подтверждал.
                Toward::Receiver => (segment.flow.clone(), taken, segment.ack),
            };

            InjectablePacket::Tcp(
                TcpBuilder::new()
                    .flow(&flow)
                    .seq(seq)
                    .ack(ack)
                    // `RST|ACK`, а не голый `RST`: сброс без подтверждения многие стеки
                    // отбрасывают как несогласованный.
                    .flags(TcpFlags::RST | TcpFlags::ACK)
                    // ОКНО НУЛЕВОЕ: принимать больше нечего, разговор кончен.
                    .window(0)
                    .build(),
            )
        })
    }
}

/// ЧЕТВЁРТОЕ СЛОВО ОБРЕЛО ПРЕДМЕТ (#326, 05.09.2026).
///
/// До этого дня оно единственное оставалось без способности, и причина была названа честно: метку
/// не видно на проводе, свидетеля ей нет. Свидетель нашёлся — правило-счётчик, стоящее НИЖЕ
/// очереди: оно и есть тот читатель, ради которого метка ставится.
impl reflex_core::CanMark for NfqueueBackend {
    fn mark(mark: u32) -> Answer {
        Answer::Marked(mark)
    }
}

/// ОЧЕРЕДЬ ВОШЛА В КАТЕГОРИЮ — НЕ КАК `Source`, А КАК [`Serves`](reflex_core::serves::Serves) (#326, 05.09.2026).
///
/// `TODO(#326)` в `backend.rs` требовал «подключить очередь как `NfqSource`». Проба показала, что
/// так нельзя: `Source::packets(&mut self)` держит бэкенд заимствованным, пока жив поток, а ответ
/// требует второго `&mut`. Компилятор сказал `E0499` дословно.
///
/// Причина не в неловкости, а в природе: у `AfPacketBackend` два устройства (кольцо и инжектор),
/// и `split()` их разводит; у очереди netlink-сокет один. `Source` описывает НАБЛЮДЕНИЕ — копию,
/// которых может быть сколько угодно в полёте; очередь отдаёт ВЛАДЕНИЕ, и второго носителя не
/// будет, пока не ответим на первый.
///
/// Здесь `serve` берёт и отвечает неделимо. Носитель наружу не выходит, поэтому «взял и забыл
/// ответить» непредставимо по построению — держать его негде.
impl reflex_core::Serves for NfqueueBackend {
    fn serve<F>(
        &mut self,
        decide: F,
    ) -> reflex_core::serves::Served<Delivered<Answer>, Refused<Answer, NotTaken>>
    where
        F: FnOnce(&reflex_core::held::Held<Queued>) -> Answer,
    {
        use reflex_core::serves::Served;
        // НЕ ЖДЁМ ЗДЕСЬ. Ожидание — это часы, а у бэкенда их нет: сколько крутиться на пустой
        // очереди, знает тот, кто ведёт цикл. `wait` остаётся отдельным и добровольным.
        match self.wait(0) {
            super::Waited::Blind => Served::Blind,
            super::Waited::Idle => Served::Idle,
            super::Waited::Ready => match self.recv() {
                // Пусто при готовом дескрипторе — `EAGAIN`: работы не было, ждать есть на чем.
                Err(_nothing) => Served::Idle,
                Ok(message) => {
                    let held =
                        reflex_core::held::Held::new(Queued(message), std::time::Instant::now());
                    let answer = decide(&held);
                    Served::Answered(self.apply(held.answered(answer)))
                }
            },
        }
    }
}
