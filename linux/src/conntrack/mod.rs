//! ЧТЕНИЕ CONNTRACK ЯДРА — счёт пакетов и байт по каждому разговору, в обе стороны.
//!
//! # Зачем примитив
//!
//! Величину, дорогую на горячем пути, берут там, где её уже считают даром. Ядро ведёт этот счёт
//! независимо от того, каким путём пошёл разговор — через очередь, мимо очереди по метке, через
//! ногу, — и потому переживает всякое действие, которым мы себя ослепляем.
//!
//! Читается ДАМПОМ, в темпе показа, а не в темпе пакета: это `pull` третьего канала, а не `push`.

mod dump;
mod wire;

pub use dump::{Dump, DumpError};
pub use wire::{chunk_of, entry_of, Chunk, Counts, Entry, Tuple};
