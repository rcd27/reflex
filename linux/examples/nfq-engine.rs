//! ЭТАЛОН ДВИЖКА — КАК ВЫГЛЯДИТ ОБРАБОТКА СЕТЕВОГО СЕМЕЙСТВА (#326, 05.09.2026).
//!
//! Читается за один экран, и это условие, а не пожелание: рядом лежит `nfq-passthrough.rs`, где
//! тот же предмет написан ручными индексами (`payload[9]`, `& 0x0F`, `from_be_bytes`) — при том
//! что в СОСЕДНЕМ модуле того же крейта лежит `parse_tcp_from_ip`. Продукт скопировал именно
//! тот образец, и оттуда в него приехали 15 `Arc<Mutex>`, 11 `spawn` и 155 печатей. Форму
//! воспроизводит не тот, кто прав, а тот, на кого можно показать пальцем.
//!
//! # Формула, которую этот файл разворачивает
//!
//! ```text
//! main() { detect(TCP).filter(..).inject(X) }   — для каждого сетевого семейства
//! ```
//!
//! Разворачивается она НЕ в цепочку методов на очереди, и это не уступка, а её природа:
//! у очереди ядра алфавит ровно из четырёх слов (`Pass`/`Marked`/`Stop`/`Modified`), и `inject`
//! в него не входит. Инъекция — способность ДРУГОГО бэкенда (`CanInject` над `Sink`), потому что
//! свой пакет уходит своим сокетом, а не вердиктом на чужой. Поэтому здесь:
//!
//! ```text
//! detect   → parse_tcp_from_ip           провод → тип, ни одного индекса руками
//! filter   → sni_of                      наше это семейство или чужое
//! action   → Table::decide               ЧИСТОЕ решение: слово алфавита + что впрыснуть
//! inject   → RawSender + TcpBuilder      эффект, и ровно в одном месте
//! ```
//!
//! # Три закона, по которым он так устроен
//!
//! **1. Синтаксис отдельно от семантики** (алгебраические эффекты и обработчики; van den Berg &
//! Schrijvers, arXiv:2302.01415 — «синтаксис задаётся сигнатурой эффектных операций,
//! закодированной как функтор; семантика задаётся обработчиками»). Здесь сигнатура — это [`Plan`]:
//! чистое значение, говорящее ЧТО решено. Обработчик — единственное замыкание в [`run`], где
//! решение становится эффектом. `plan_for` о сокетах не знает ничего и потому проверяется
//! таблицей вход→выход, без ядра и без прав.
//!
//! **2. Интерфейс между этажами — ТАБЛИЦА, а не вызов** (канон SDN: data plane сверяется с
//! match-action таблицей, control plane её заполняет; ни один из них не вызывает другой). [`Table`]
//! здесь набита статически ради примера, но её место — заполняться снаружи, и движок не меняется
//! от того, кто её заполнил. Ровно так живёт продукт: `Plane::teach_name` кладёт план, `step`
//! его читает.
//!
//! **3. Мир случается в одном месте.** `&mut` заперт в `Terminal::apply` внутри `serve`: выше
//! него значения, ниже — netlink-сокет. Это не стиль, это граница, и она проверена компилятором —
//! носителя из `serve` не вынести (см. `compile_fail` в `reflex_core::serves`).
//!
//! # Чего здесь нет намеренно
//!
//! Ни одного `unwrap`, ни одного `_ =>`, ни одного ручного индекса в байты. Единственный
//! `let mut` — на самом бэкенде: netlink-сокет один, отправка по нему последовательна по природе,
//! и край есть место для performance-first. Убрать его нельзя, а вот держать в ОДНОМ месте —
//! можно, и он там.
//!
//! # Запуск
//!
//! ```sh
//! sudo nft 'add table inet nevod_demo'
//! sudo nft 'add chain inet nevod_demo out { type filter hook output priority -150; }'
//! sudo nft 'add rule inet nevod_demo out tcp dport 443 meta mark != 0xBB queue num 200'
//! cargo run --example nfq-engine --features nfqueue
//! ```

use std::collections::BTreeMap;

use reflex_core::builder::TcpBuilder;
use reflex_core::held::Held;
use reflex_core::parse::parse_tcp_from_ip;
use reflex_core::serves::Served;
use reflex_core::types::{TcpFlags, TcpSegment};
use reflex_core::{tls, CanHold, CanMark, CanRefuse, CanSever, InjectablePacket, Serves, Toward};
use reflex_linux::nfqueue::{Answer, NfqueueBackend, Queued, Waited};
use reflex_linux::rawsend::RawSender;

/// Очередь, за которой стоит этот движок. Правило ставится снаружи — движок правил не ставит:
/// кто их поставил, тот и снимает, иначе уборка расходится с постановкой.
const QUEUE: u16 = 200;

/// НАША МЕТКА НА СВОИХ ИСХОДЯЩИХ. Без неё впрыснутый пакет вернулся бы в ту же очередь, и движок
/// принялся бы разбирать собственный след как чужой трафик.
const OURS: u32 = 0xBB;

/// МЕТКА ОБХОДА — слово, которым движок говорит ядру «этот разговор ведёт нижестоящее правило».
/// Правило, читающее метку, обязано стоять НИЖЕ правила очереди: пакет продолжает обход с места,
/// где его забрали, и метка, поставленная выше читателя, не прочитается никем — а прибор при этом
/// покажет «решение принято».
const BYPASS: u32 = 0xC0;

/// TTL приманки: она обязана умереть по дороге, не дойдя до сервера. Число тут условное — живое
/// берётся замером на вантаже, и это ровно тот случай, когда константа в примере не есть знание.
const DECOY_TTL: u8 = 3;

/// Сколько ждать на пустой очереди. Ожидание принадлежит ведущему циклу, а не бэкенду: сколько
/// крутиться, знает тот, кто ведёт, — у бэкенда часов нет.
const POLL_MS: i32 = 100;

/// ЧТО ДЕЛАТЬ С СЕМЕЙСТВОМ — язык таблицы, и он НЕ алфавит очереди.
///
/// Разделение намеренное: алфавит говорит, ЧЕМ ответить ядру, а это — ЧТО мы решили про цель.
/// Слить их значило бы, что смена транспорта (очередь → tc → tun) переписывает решения, хотя
/// решения от транспорта не зависят.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Action {
    /// Не наше дело — пусть идёт как шло.
    Leave,
    /// Вести обходом: приманка на провод, метка ядру.
    Bypass,
    /// Оборвать: этот разговор не состоится.
    Sever,
}

/// MATCH-ACTION ТАБЛИЦА — интерфейс между этажами.
///
/// Движок её ЧИТАЕТ и никогда не пишет; кто её пишет — движка не касается. Здесь она набита
/// статически ради примера; в продукте её заполняет тот, кто расследовал цель.
struct Table(BTreeMap<&'static str, Action>);

impl Table {
    fn demo() -> Self {
        Table(BTreeMap::from([
            ("rutracker.org", Action::Bypass),
            ("www.youtube.com", Action::Bypass),
            ("example.invalid", Action::Sever),
        ]))
    }

    /// ЧТО ЗНАЕМ ПРО ЭТО ИМЯ. Незнакомое имя — не беда и не ошибка: у движка нет мнения о целях,
    /// которых он не изучал, и выдумывать его здесь значило бы лечить наугад.
    fn action(&self, name: &str) -> Action {
        match self.0.get(name) {
            None => Action::Leave,
            Some(known) => *known,
        }
    }
}

/// ЧТО РЕШЕНО — ЗНАЧЕНИЕ, а не действие.
///
/// Сигнатура эффектов этого движка: слово ядру плюс то, что должно уйти на провод своим сокетом.
/// Ни поля здесь не касаются мира — потому весь `plan_for` и проверяется без ядра.
struct Plan {
    /// Чем ответить удержанному пакету — слово алфавита очереди.
    answer: Answer,
    /// Что впрыснуть своими руками. Пусто у всех решений, кроме обхода.
    inject: Vec<InjectablePacket>,
}

impl Plan {
    /// НЕ НАШЕ — отпустить без изменений. Слово берётся у способности, а не литералом: способность
    /// обязана назвать, каким словом алфавита отпускают, и потому заявление имеет предмет.
    fn leave() -> Plan {
        Plan {
            answer: NfqueueBackend::release(),
            inject: Vec::new(),
        }
    }
}

/// ВЕСЬ ДВИЖОК — одна чистая функция от байтов провода к решению.
///
/// Ни сокета, ни часов, ни печати: её можно прогнать таблицей вход→выход, на машине без прав,
/// в юнит-тесте. Всё, что ниже по файлу, — это доставка её решения в мир.
fn plan_for(ip: &[u8], table: &Table) -> Plan {
    match parse_tcp_from_ip(ip) {
        // Не TCP или обрезок — у нас нет мнения. Молчание здесь честно: движок про UDP этой
        // очереди не спрашивали, и решать за него он не станет.
        None => Plan::leave(),
        Some(segment) => match sni_of(&segment) {
            // TCP, но не приветствие с именем: вести цель нечем, имя — единственный ключ,
            // переживающий смену адреса.
            None => Plan::leave(),
            Some(name) => act(table.action(&name), &segment, ip),
        },
    }
}

/// ЧЬЁ ЭТО СЕМЕЙСТВО — фильтр, выраженный разбором, а не сравнением байтов.
fn sni_of(segment: &TcpSegment) -> Option<String> {
    match tls::is_client_hello(&segment.payload) {
        false => None,
        true => tls::extract_sni(&segment.payload),
    }
}

/// РЕШЕНИЕ ТАБЛИЦЫ → СЛОВО АЛФАВИТА. Перевод, и только он: тут не принимают решений, тут их
/// произносят на языке транспорта.
fn act(action: Action, segment: &TcpSegment, ip: &[u8]) -> Plan {
    match action {
        Action::Leave => Plan::leave(),
        // ПРИМАНКА ИДЁТ ПЕРЕД ОРИГИНАЛОМ, а оригинал — с меткой обхода. Порядок здесь часть
        // решения: приманка, ушедшая после, лечит уже состоявшийся разговор.
        Action::Bypass => Plan {
            answer: NfqueueBackend::mark(BYPASS),
            inject: vec![decoy(segment)],
        },
        // ОБРЫВ ЕСТЬ ПАРА, И ОБЕ ЕГО ПОЛОВИНЫ ЗДЕСЬ (#326, 05.09.2026).
        //
        // Прежняя редакция этого файла отвечала одним отказом (`inject: Vec::new()`), и это была
        // не экономия, а неверное определение обрыва, стоявшее в ЭТАЛОНЕ. Дроп без извещения —
        // ровно то, чем бьёт молчаливый дроп на пути: клиент не узнаёт, что разговора не будет, ретрансмитит
        // приветствие пять-семь раз и ждёт от двух до двенадцати секунд. Человек называет это
        // «страница висит», и следующий движок, написанный по образцу, воспроизвёл бы её снова.
        //
        // Извещение строит СПОСОБНОСТЬ (`CanSever::notice`), а не этот файл: будь оно собрано
        // здесь руками, в репе завелось бы второе определение обрыва — то самое, ради снятия
        // которого способность и заведена.
        //
        // `Toward::Sender`: удержан пакет клиента (приветствие с именем), и сказать надо ему.
        Action::Sever => Plan {
            answer: NfqueueBackend::refuse(),
            // ПУСТО, ЕСЛИ СКАЗАТЬ НЕЧЕМ — и это честный исход, а не молчание: закон обрыва
            // назовёт его `NoticeUnbuildable`, потому что оборвать молча хуже, чем не рвать.
            inject: NfqueueBackend::notice(ip, Toward::Sender)
                .into_iter()
                .collect(),
        },
    }
}

/// ПРИМАНКА — свой пакет, построенный типом, а не склейкой байтов.
///
/// Чексуммы считает билдер; сериализация в IP — его же забота. Ручная сборка здесь была бы вторым
/// ответом на вопрос «что такое TCP-пакет», а двух ответов на один вопрос мы не держим.
fn decoy(segment: &TcpSegment) -> InjectablePacket {
    InjectablePacket::Tcp(
        TcpBuilder::new()
            .flow(&segment.flow)
            .seq(segment.seq)
            .ack(segment.ack)
            .flags(TcpFlags::PSH | TcpFlags::ACK)
            .window(segment.window)
            .ttl(DECOY_TTL)
            .payload(&segment.payload)
            .build(),
    )
}

/// ОБРАБОТЧИК — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ РЕШЕНИЕ СТАНОВИТСЯ ЭФФЕКТОМ.
///
/// Здесь и только здесь чистый [`Plan`] встречается с миром: инъекции уходят своим сокетом, слово
/// алфавита возвращается терминалу. Разнеси это по двум местам — и появится решение, у которого
/// половина исполнилась.
fn handle(held: &Held<Queued>, table: &Table, sender: &RawSender) -> Answer {
    let plan = plan_for(held.seen(), table);

    plan.inject
        .iter()
        .for_each(|packet| match sender.send(&packet.serialize_ip()) {
            Ok(()) => (),
            // ОТКАЗ ПРОВОДА ГРОМКИЙ: «приманка ушла» и «приманка не ушла» лечатся в разных местах,
            // а молчание здесь выдало бы несостоявшееся вмешательство за состоявшееся.
            Err(why) => eprintln!("[приманка] не ушла: {why}"),
        });

    plan.answer
}

/// ВЕДУЩИЙ ЦИКЛ. Всё, что он умеет, — брать по одному и разбирать исход тотально.
///
/// `mut` ровно один и ровно здесь: netlink-сокет один, отправка по нему последовательна по
/// природе. Выше — значения, ниже — ядро.
fn run(mut queue: NfqueueBackend, sender: RawSender, table: Table) {
    // ЖИВЁТ, ПОКА ЖИВ ПРОЦЕСС. Уйти отсюда по своей воле нельзя: правило очереди без слушателя
    // дропает трафик, то есть выход означал бы обрыв сети у человека, а не остановку прибора.
    loop {
        // `Instant::now()` сохраняет прежнее поведение (`wait(0)` внутри шва): цикл ждёт сам,
        // ниже, через `queue.wait(POLL_MS)` на исходе `Served::Idle`.
        match queue.serve(std::time::Instant::now(), |held, _edge| {
            handle(held, &table, &sender)
        }) {
            // ЯДРО ПРИНЯЛО. Молчим о безразличии и говорим о вмешательстве: прибор, печатающий
            // каждый пропущенный пакет, приучает себя не читать.
            Served::Answered(Ok(delivered)) => match delivered.answer {
                Answer::Pass => (),
                Answer::Marked(mark) => eprintln!("[обход] метка {mark:#010x}"),
                Answer::Stop => eprintln!("[обрыв] разговор не состоится"),
                Answer::Modified(bytes) => eprintln!("[подмена] {} байт", bytes.len()),
            },
            // ЯДРО ОТКАЗАЛО — и это знание, а не пустота: сообщение могло протухнуть по таймауту
            // очереди. Прежде на этом месте стоял `let _ =`, и отказ исчезал бесследно.
            Served::Answered(Err(refused)) => {
                eprintln!("[ядро] не приняло {:?}: {:?}", refused.answer, refused.why)
            }
            // РАБОТЫ НЕ БЫЛО — нормальное состояние очереди, а не ошибка. Ждём здесь, а не в
            // бэкенде: часы принадлежат ведущему.
            Served::Idle => match queue.wait(POLL_MS) {
                Waited::Ready | Waited::Idle => (),
                Waited::Blind => eprintln!("[очередь] дескриптор потерян — ждать не на чем"),
            },
            // ЖДАТЬ НЕ НА ЧЕМ. Отдельно от `Idle` намеренно: «пусто» и «прибор ослеп» чинятся
            // по-разному, и слив их, мы получили бы движок, чья тишина неотличима от поломки.
            Served::Blind => eprintln!("[очередь] ослепла: дескриптор не добыт"),
            // Эта очередь клетку не производит (`nfq` глушит `ENOBUFS`), арм — для тотальности
            // матча на всём алфавите `Served`.
            Served::Torn(_at) => eprintln!("[очередь] потеря: наблюдения были и не дошли"),
        }
    }
}

fn main() {
    // ОБА НОСИТЕЛЯ ПОДНИМАЮТСЯ ДО ПЕРВОГО ПАКЕТА, и отказ каждого назван своей причиной:
    // «нет очереди» и «нет сокета для приманки» — разные беды с разной починкой.
    match (NfqueueBackend::open(QUEUE), RawSender::open(OURS)) {
        (Err(why), _) => eprintln!("очередь {QUEUE} не открылась: {why}"),
        (Ok(_queue), Err(why)) => eprintln!("сокет приманки не открылся: {why}"),
        (Ok(queue), Ok(sender)) => {
            eprintln!("[движок] очередь {QUEUE}, своя метка {OURS:#010x}, обход {BYPASS:#010x}");
            run(queue, sender, Table::demo())
        }
    }
}

